                    <p style="margin-bottom:10px;"><strong>Typical ageing buckets:</strong></p>
<ul>
<li><strong>0-30 days:</strong> current dues - healthy and eligible.</li>
<li><strong>31-60 days:</strong> slightly overdue - generally eligible.</li>
