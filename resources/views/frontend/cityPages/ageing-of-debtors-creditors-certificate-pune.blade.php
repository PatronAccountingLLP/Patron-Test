                <h2 class="section-title">What Is an Ageing of Debtors and Creditors Certificate</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>Definition:</strong> It is a certificate issued by a Chartered Accountant presenting an age-wise classification of a business&#39;s sundry debtors and creditors as on a date, grouped by how long each amount has been outstanding.</p>
<p>Receivables and payables are sorted into <strong>age buckets</strong> - commonly 0-30, 31-60, 61-90, and over 90 days, or longer bands such as over six months. For debtors, this shows which customer dues are current and which are overdue or doubtful; for creditors, it shows how long supplier dues have remained unpaid. The CA certificate typically states the total sundry debtors, the age-wise breakup, the eligible versus doubtful amounts, and a declaration that the balances arose from <strong>genuine business transactions</strong>, with an 18-digit UDIN.</p>
<p>The certificate draws on the business&#39;s <a href="https://www.patronaccounting.com/accounting-services">books of account</a> and, for entities, <a href="https://www.patronaccounting.com/statutory-audit">audited financials</a>. It is a core artifact in both financial due diligence and lender working-capital appraisal.</p>

