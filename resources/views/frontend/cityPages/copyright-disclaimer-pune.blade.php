                        <li><strong>Copyright Notice:</strong> Short statement (symbol + year + name) asserting ownership. Minimum form of copyright assertion.</li>
                        <li><strong>Section 79 Safe Harbour:</strong> IT Act protection for platforms with takedown procedures. Without proper copyright policy, platforms lose protection.</li>
