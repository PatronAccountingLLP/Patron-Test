<!-- SECTION 15A: LEGAL FRAMEWORK -->
<section class="content-section">
    <div class="content-container">
        <div class="text-content">
            <h2 class="section-title">Legal Framework for Copyright Disclaimers in India</h2>
            <div class="content-text">
                
                <p><strong>Fair Dealing - Section 52, Copyright Act 1957:</strong></p>
                <ul><li>Section 52(1)(a)(i): Private or personal use, including research</li>
                    <li>Section 52(1)(a)(ii): Criticism or review of that work or any other work</li>
                    <li>Section 52(1)(a)(iii): Reporting of current events and current affairs</li>
                    <li><strong>Important:</strong> Fair dealing is purpose-specific in India (narrower than US fair use)</li></ul>
                <p style="margin-top:16px;"><strong>Infringement and Penalties:</strong></p>
                <ul><li>Section 51: Reproducing, distributing, performing without permission</li>
                    <li>Section 63: Criminal penalty - <strong>6 months to 3 years + Rs 50,000 to Rs 2 lakh fine</strong></li>
                    <li>Section 63A: Enhanced penalty for repeat offences</li>
                    <li>Section 55: Civil remedies - <strong>injunction, damages, accounts of profits</strong></li></ul>
                <p style="margin-top:16px;"><strong>Intermediary Liability:</strong></p>
