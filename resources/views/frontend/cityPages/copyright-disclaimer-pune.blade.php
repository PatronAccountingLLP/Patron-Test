                <h2 class="section-title">What Is a Copyright Disclaimer?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A copyright disclaimer is a legal statement that informs the public about the copyright ownership of a work, specifies conditions of use, and establishes the creator's legal rights. It typically includes the copyright symbol, year of first publication, name of the holder, a reservation of rights statement, and terms governing use. It is placed prominently on the work - website footer, software terms, video description, or document pages.</p>
                    <p>In India, fair dealing (not 'fair use' - a US doctrine) is governed by Section 52 of the Copyright Act 1957. Section 52 permits certain acts including private use, research, criticism, review, and reporting current events. A disclaimer claiming fair dealing does not create those rights - courts determine fair dealing on a case-by-case basis.</p>
                    <p>For Pune businesses, disclaimers serve two functions: (1) for content you own - asserting rights and warning against unauthorised use, and (2) for third-party content used under fair dealing - acknowledging the source and claiming the permitted exception. Patron provides <a href="/copyright-disclaimer">copyright disclaimer drafting</a> with integrated registration and IP advisory.</p>

                </div>
