                <h2 class="section-title">What Is Copyright for a Cinematographic Film?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Copyright for a cinematographic film is the formal registration of copyright in any work of visual recording - including the sound recording accompanying such visual recording - with the Registrar of Copyrights under Section 2(f) read with Section 13(1)(b) of the Copyright Act, 1957, vesting in the producer as author and first owner, for a term of 60 years from the year of publication under Section 26.</p>
                    <p>The definition under Section 2(f) is technology-neutral: "cinematograph film means any work of visual recording and includes a sound recording accompanying such visual recording and cinematograph shall be construed as including any work produced by any process analogous to cinematography including video films." Feature films, documentary films, short films, ad films, OTT series episodes, YouTube productions, animation films, and corporate films all qualify.</p>
                    <p><strong>The critical Section 13(4) distinction:</strong> A cinematographic film is a composite work built on layers of other copyrighted works. Section 13(4) provides that copyright in a cinematograph film shall NOT affect the separate copyright in any underlying work. The Delhi High Court confirmed this in RDB & Co. (HUF) vs HarperCollins Publishers (CS(COMM) 246/2021). Every Delhi film producer must secure specific assignment agreements or NOCs from each underlying rights holder - this is the NOC bundle requirement. After registration, Delhi film producers can also consider <a href="/copyright-assignment">Copyright Assignment</a> services to ensure underlying works are properly transferred.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Copyright for Cinematographic Film in Delhi:</strong></p>
                    <p><strong>Section 2(f) - Cinematograph Film:</strong> "Any work of visual recording and includes a sound recording accompanying such visual recording; and cinematograph shall be construed as including any work produced by any process analogous to cinematography including video films." Covers all digital video productions, OTT content, and animation films.</p>
                    <p><strong>Producer (Section 2(d)(v)):</strong> The person who takes the initiative and responsibility for making the work. The producer is both the author and first owner of copyright under Section 17.</p>
                    <p><strong>NOC Bundle:</strong> No Objection Certificate required from every person who contributed a separate copyrightable work to the film - scriptwriter, lyricist, music composer, performers, playback singers.</p>
                    <p><strong>Section 13(4) - Separate Copyright in Underlying Works:</strong> Film copyright does not affect the separate copyright in any constituent literary, dramatic, musical, or artistic work incorporated in it.</p>
