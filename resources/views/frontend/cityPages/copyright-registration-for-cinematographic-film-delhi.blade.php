<section class="content-section">
    <div class="content-container">
        <div class="text-content">
            <h2 class="section-title">Legal and Compliance Framework for Cinematographic Film Copyright in Delhi</h2>
            <div class="content-text">
                
                <ul>
                    <li><strong>Section 2(f) - Definition of Cinematograph Film:</strong> "Any work of visual recording and includes a sound recording accompanying such visual recording; and cinematograph shall be construed as including any work produced by any process analogous to cinematography including video films." Technology-neutral definition covering all digital video, OTT, YouTube, and animation productions.</li>
                    <li><strong>Section 13(1)(b) - Subsistence of Copyright in Films:</strong> Copyright shall subsist in India in cinematograph films. Section 13(3)(a) provides that copyright shall NOT subsist if a substantial part is an infringement of copyright in another work.</li>
                    <li><strong>Section 13(4) - Separate Copyright in Underlying Works:</strong> Copyright in the film does not affect the separate copyright in any underlying work. Confirmed by the Delhi HC in RDB & Co. (HUF) vs HarperCollins Publishers (CS(COMM) 246/2021).</li>
                    <li><strong>Section 17 - First Owner:</strong> Producer is the first owner. Exception under Section 17(b): where a film is made at the instance of any person for valuable consideration, such person is the first owner unless there is an agreement to the contrary - the Doordarshan/NFDC trap for Delhi producers.</li>
                    <li><strong>Section 14(d) - Rights in Film:</strong> Exclusive right to: (i) make a copy; (ii) sell or hire any copy; (iii) communicate to the public - covering theatrical, OTT streaming, TV broadcasting, and online distribution.</li>
                    <li><strong>Section 19(9) - Inalienable Royalty Right:</strong> Authors of literary/musical works incorporated in a film retain inalienable right to equal share of royalties for use other than cinema hall communication. Cannot be waived contractually.</li>
                    <li><strong>Section 26 - Term:</strong> 60 years from beginning of calendar year next following the year of publication. A film released in 2025 has protection until December 31, 2086.</li>
                    <li><strong>Rule 70(9), Copyright Rules 2013:</strong> Applicant must send by registered post copies of Form XIV to all parties concerned at the time of filing.</li>
                    <li><strong>Delhi HC Dynamic+ Injunction (Dec 18, 2025):</strong> Warner Bros vs Animesugez.to (Justice Tejas Karia) - blocked 47 piracy websites with Dynamic+ mechanism allowing blocking of future mirror sites without new suits. <a href="https://copyright.gov.in" target="_blank" rel="noopener">Copyright Office - copyright.gov.in</a></li>
