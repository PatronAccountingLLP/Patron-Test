                    <p><strong>Key Terms for Film Copyright:</strong></p>
                    <ul>
                        <li><strong>S.2(f) Film:</strong> Any visual recording + sound. Video, web series, docs, ads, animation. Producer = author (S.2(d)(v)).</li>
                        <li><strong>S.13(4) Independence:</strong> Film copyright ≠ underlying works copyright. Script, music, lyrics independently protected.</li>
                        <li><strong>S.17(b) Producer Owns:</strong> Producer is first owner. Director has NO separate copyright. Must secure underlying works via S.18/19.</li>
                        <li><strong>2012 Amendment:</strong> Equal royalty for non-theatrical use (satellite, OTT, digital). Non-waivable. Void if contract says otherwise.</li>
                        <li><strong>S.14(d) Rights:</strong> Make copy, sell/rent, communicate to public. Narrower than literary/artistic work rights.</li>
