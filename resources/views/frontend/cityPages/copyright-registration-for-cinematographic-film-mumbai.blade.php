                <h2 class="section-title">What Is Copyright in a Cinematograph Film?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Copyright in a cinematograph film is the exclusive right of the producer (as author S.2(d)(v) and first owner S.17(b)) to reproduce, sell, rent, and communicate the film to the public (S.14(d)), lasting 60 years from publication (S.26). S.2(f) covers any visual recording including video, web series, documentaries, ads, and animation.</p>
                    <p><strong>Critical - S.13(4):</strong> Film copyright does NOT affect separate copyright in underlying works. Script (literary), music (musical), lyrics (literary), artistic works all retain independent protection. The film is a 'bundle of copyrights' - each underlying work has different ownership, duration, and exploitation rules.</p>
                    <p><strong>2012 Amendment:</strong> Author of literary/musical work in film retains non-waivable equal royalty for non-theatrical use (satellite, OTT, digital, mobile). Affects every Bollywood deal. Learn more at <a href="#">our national film copyright practice</a>.</p>

                </div>
