                <div class="content-text what-is-definition">
                    
                    <p>Section 2(h): dramatic work includes any piece for recitation, choreographic work or entertainment in dumb show (mime), the scenic arrangement or acting form of which is fixed in writing or otherwise - but explicitly does NOT include a cinematograph film.</p>
                    <p>Five sub-types: (1) Recitation pieces (scripts, monologues, comedy). (2) Choreographic works (Bollywood dance, classical, contemporary). (3) Dumb-show/mime. (4) Scenic arrangements (staging, set design). (5) Acting forms (documented direction). Critical: must be FIXED - written or recorded. Improvised unrecorded work is not protectable.</p>
                    <p>S.13(4): screenplay retains independent copyright from film. S.14(a): reproduce, perform, communicate, make film, translate, adapt. S.22: lifetime + 60 years. Learn more at <a href="/copyright-registration-for-dramatic-work">our national dramatic work practice</a>.</p>

                </div>
