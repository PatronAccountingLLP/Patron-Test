                        <li><strong>S.2(h) Fixation:</strong> Must be "fixed in writing or otherwise." Video recording, notation, digital document all qualify. No fixation = no copyright.</li>
                        <li><strong>S.13(4) Independence:</strong> Screenplay copyright is independent of film copyright. Writer retains unless specifically assigned (S.18/19).</li>
                        <li><strong>2012 Amendment:</strong> Screenwriter/playwright gets non-waivable equal royalty for non-theatrical use (OTT, satellite, digital). Void if waived.</li>
                        <li><strong>S.14(a) Rights:</strong> Reproduce, perform, communicate, make film/recording, translate, ADAPT. Adaptation right key for dramatic works.</li>
                        <li><strong>Excludes Film:</strong> Cinematograph film is NOT a dramatic work. But a screenplay FOR a film IS a dramatic work with its own copyright.</li>
