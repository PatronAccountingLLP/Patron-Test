            <h2 class="section-title">Legal Framework for Musical Work Copyright</h2>
            <div class="content-text">
                
                <p><strong>Section 2(p) - Musical Work:</strong></p>
                <ul><li>Work consisting of music including notation. Does NOT include words or actions. Covers melody, harmony, rhythm only.</li></ul>
                <p style="margin-top:16px;"><strong>Section 2(ffa) - Composer:</strong></p>
                <ul><li>Person who composes music regardless of whether they write notation. Melody on voice memo = musical work.</li></ul>
                <p style="margin-top:16px;"><strong>Section 14(a) - Exclusive Rights:</strong></p>
                <ul><li>Reproduce, issue copies, perform, communicate, make film/recording, translate (arrange), adapt.</li></ul>
                <p style="margin-top:16px;"><strong>2012 Amendment (S.18 Provisos):</strong></p>
                <ul><li>Film: non-waivable equal royalty for non-theatrical use. Non-film recording: non-waivable for any use. Both void if waived.</li></ul>
                <p style="margin-top:16px;"><strong>S.31C Cover Version:</strong> Statutory licence. Prior notice + royalties + no alterations. Original copyright unaffected.</p>
                <p style="margin-top:16px;"><strong>S.33 IPRS:</strong> Copyright society for performing royalty collection from radio, streaming, public performance.</p>
                <p style="margin-top:16px;"><strong>Key Cases:</strong> IPRS v. EIMPA (1977 SC). Tips v. Wynk (2019 Bombay HC). IPRS v. Aditya Pandey (2019 - streaming platforms).</p>
