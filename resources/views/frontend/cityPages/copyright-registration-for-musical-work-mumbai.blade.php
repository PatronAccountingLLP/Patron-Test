                <div class="content-text what-is-definition">
                    
                    <p>Section 2(p): musical work means a work consisting of music and includes graphical notation, but does NOT include words or actions intended to be sung, spoken, or performed with the music. This covers ONLY melody, harmony, rhythm - the composition itself.</p>
                    <p>S.2(ffa): composer = person who composes music regardless of whether they write notation. A melody hummed into a phone is a musical work. Four layers in one song: composition (musical S.2(p)), lyrics (literary S.2(o)), recording (sound recording S.13(1)(e)), performance (S.38).</p>
                    <p>S.13(4): film/recording copyright does NOT affect underlying musical work. Composer's rights survive independently. 2012 Amendment: non-waivable royalty for non-theatrical use. Learn more at <a href="/copyright-registration-for-musical-work">our national musical work practice</a>.</p>

