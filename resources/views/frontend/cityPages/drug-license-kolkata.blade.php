                <h2 class="section-title">What Is a Drug License?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A drug license is a mandatory permit under the Drugs and Cosmetics Act, 1940 required by every pharmacy, medical store, wholesale distributor, and hospital pharmacy to sell, stock, or distribute drugs or cosmetics.</p>
<p>Retail license (Form 20/21) for selling to patients. Wholesale license (Form 20B/21B) for selling to retailers, hospitals, and distributors. Filed on WB Drugs Control portal. Senior Drug Inspector conducts premises inspection.</p>
<p>For Kolkata: neighbourhood pharmacies (Gariahat, Salt Lake), hospital pharmacies (EM Bypass), wholesale distributors (Burrabazar), online pharmacies (New Town), and Ayurveda/Homeopathy stores all need specific drug license types.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Drug License:</strong></p>
                    <ul>
<li><strong>Drugs Act, 1940:</strong> Governing Act for drug manufacture, sale, and distribution</li>
<li><strong>Form 20/21:</strong> Retail drug license for selling to end consumers</li>
<li><strong>Form 20B/21B:</strong> Wholesale drug license for supply to retailers/hospitals</li>
<li><strong>Schedule H/H1/X:</strong> Drug categories requiring specific licence coverage</li>
<li><strong>108 sq ft:</strong> Minimum premises area with 8'2" ceiling, separate entrance</li>
<li><strong>WB Pharmacy Council:</strong> Pharmacist registration authority for retail licence</li>
<li><strong>GRIPS:</strong> Government Receipt Portal for fee payment (Rs 3,000)</li>
<li><strong>5-Year Validity:</strong> Renewal before expiry mandatory</li>
</ul>

                </div>
