                <h2 class="section-title">What Is a Digital Signature Certificate (DSC)?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A Digital Signature Certificate is an electronic credential issued by a CCA-licensed Certifying Authority under the Information Technology Act, 2000, that authenticates a person's identity for digitally signing documents and online filings, with the same legal validity as a handwritten signature (Section 5).</p>
                    <p>DSC uses Public Key Infrastructure (PKI) cryptography ensuring authentication (who signed), integrity (document not altered), and non-repudiation (signer cannot deny signing). As of 2026, Class 3 is the only DSC class issued (Class 2 merged in 2021). Available as signing only, encryption only, or both - most government filings require signing and encryption.</p>
                    <p>DSC validity options are 1, 2, or 3 years and must be renewed before expiry. Available as USB token (hardware) or paperless (cloud-based, ideal for Mac/Linux). Patron provides <a href="#">DSC services</a> with integrated portal association for Pune businesses.</p>

