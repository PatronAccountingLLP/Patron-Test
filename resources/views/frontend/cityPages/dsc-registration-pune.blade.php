                        <li><strong>MCA V3 Association:</strong> Mandatory step linking DSC with DIN on MCA portal. Without it, DSC cannot be used for company filings at RoC Pune.</li>
                        <li><strong>Paperless DSC:</strong> Cloud-based certificate working through web browser. No USB hardware needed. Mac/Linux compatible.</li>
                        <li><strong>Section 5 IT Act:</strong> Digital signatures have same legal standing as handwritten signatures for contracts, filings, and communications.</li>
