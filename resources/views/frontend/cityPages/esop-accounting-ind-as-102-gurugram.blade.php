                <h2 class="section-title">What Is Ind AS 102 ESOP Accounting</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Picture a Cyber City enterprise-SaaS company that grants a refreshed pool of options to its sales and engineering org during a Series D raise, exercise price pegged to the latest 409A-style valuation. No cash leaves the company on grant day - yet Ind AS 102 refuses to let it record zero cost. The standard, notified under Section 133 of the Companies Act 2013 read with Rule 4 of the Companies (Indian Accounting Standards) Rules 2015, forces that pool to be fair-valued at grant and charged to Profit and Loss across the vesting period. At unicorn-scale pools the size Zomato, Delhivery or Policybazaar carried while scaling, this is a board-level number, not a footnote.</p>
                    <p>Mechanically the cost is front-loaded onto grant date. An equity-settled ESOP or RSU is fixed once - grant-date fair value - and marched through the P and L over the vesting window against an ESOP Reserve in equity; a cash-settled SAR or phantom unit is remeasured to fair value every reporting date with the credit sitting as a liability. So a Golf Course Road scale-up running graded four-year vesting books a slice of the cost each year, never a single hit at exercise, and the forfeiture true-up keeps that slice honest as people leave.</p>
                    <p>The Gurugram twist is the foreign parent. Because so many Udyog Vihar and Cyber City firms are the Indian subsidiary of a US or Singapore holding issuing mirror grants, the standalone Ind AS 102 charge has to tie back to a group IFRS 2 or US GAAP number - and Ind AS 102 being materially converged with IFRS 2 from the IFRS Foundation is what makes that tie-out possible on one basis. An Indian arm still under the Rs 250 crore threshold applies the ICAI Guidance Note on Accounting for Share-based Payments (September 2020) under the Companies (Accounting Standards) Rules 2006, until a parent trigger or a net-worth trigger pulls it into Ind AS.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for ESOP Accounting:</strong></p>
                    <p><strong>Grant Date:</strong> The date on which both parties (company and employee) agree to the share-based payment arrangement. For schemes requiring shareholder approval, grant date is the date approval is obtained.</p>
                    <p><strong>Vesting Date:</strong> The date on which the employee becomes unconditionally entitled to the equity instrument. For service conditions, this is the end of the service period.</p>
                    <p><strong>Fair Value:</strong> The price at which the option could be sold in an arm's-length transaction, determined using a recognised option pricing model such as Black-Scholes or Binomial.</p>
                    <p><strong>Equity-Settled SBP:</strong> Awards settled by issuing the company's own equity instruments. Expense recognised over vesting period with credit to ESOP Reserve in equity.</p>
                    <p><strong>Cash-Settled SBP:</strong> Awards settled by paying cash based on the value of equity instruments. Expense over vesting period with credit to a liability remeasured every reporting date.</p>
                    <p><strong>Forfeiture Rate:</strong> Estimated percentage of granted options expected to forfeit due to attrition before vesting. Service and non-market performance conditions are trued up to actual outcomes.</p>

