                        <div class="faq-expanded__a"><p>Gurugram enterprise-SaaS plans often tie vesting to ARR milestones, sales quotas or net revenue retention rather than plain time service. Under Ind AS 102 these are non-market performance conditions: they are NOT built into the grant-date fair value, but instead adjust the estimated number of options expected to vest, and the cumulative expense is trued up at each reporting date as the targets are met or missed. This differs from a market condition such as a share-price hurdle, which is baked into the grant-date fair value and never reversed. Patron maps each Gurugram plan's vesting triggers to the correct treatment before booking.</p></div>
