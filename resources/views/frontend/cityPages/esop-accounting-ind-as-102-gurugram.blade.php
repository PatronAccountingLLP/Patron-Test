    <div class="content-container">
        <div class="text-content">
            <h2 class="section-title">Who Must Apply Ind AS 102 for ESOP Accounting</h2>
            <div class="content-text">
                
                <h3>Ind AS Framework (Mandatory)</h3>
                <ul>
                    <li>All listed companies on Indian stock exchanges</li>
                    <li>Unlisted companies with net worth equal to or greater than Rs 250 crore</li>
                    <li>Holding, subsidiary, joint venture or associate companies of the above</li>
                    <li>Voluntary adopters who have notified the choice (the choice is irrevocable)</li>
                </ul>
                <h3>AS Framework with ICAI Guidance Note 2020 (Non-Ind AS Companies)</h3>
                <ul>
                    <li>Unlisted companies with net worth below Rs 250 crore (most Seed and Series A startups)</li>
                    <li>Small companies, One Person Companies and dormant companies</li>
                    <li>Companies following Companies (Accounting Standards) Rules 2006 as amended in 2021</li>
                </ul>
                <p><em>Note: The ICAI Guidance Note on Accounting for Share-based Payments (September 2020) permits both the Fair Value Method and the Intrinsic Value Method (FMV at grant minus exercise price) for AS framework companies. Many Cyber City and Udyog Vihar B2B SaaS companies run a US holding (Delaware flip) with a Gurugram Indian subsidiary issuing mirror grants; once that Indian arm becomes a subsidiary of an Ind AS or foreign-GAAP parent, it is pulled into Ind AS 102 and the Intrinsic Value shortcut closes. Patron determines the correct framework before the first Gurugram grant batch is booked.</em></p>
                <h3>Triggers for an Ind AS 102 Run at a Gurugram SaaS Company</h3>
                <ul>
                    <li>The founding grant batch after scheme approval - opening reserve and first grant-date fair value</li>
                    <li>Every quarterly hiring wave across a scaling Cyber City or Udyog Vihar team, each a new tranche to value</li>
