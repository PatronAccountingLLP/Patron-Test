                <h2 class="section-title">How a Down Round Reaches Your Cap Table</h2>
                <div class="content-text what-is-definition">

                    <p>In a finance-led market like Mumbai, preference-share terms are usually drafted tightly, so the anti-dilution clause is where the real money moves on a down round. That single clause compensates the investor for the lower price, and the cost flows straight onto common stock and the option pool, the equity a BKC fintech or a Lower Parel media platform leans on to hold its senior team.</p>
                    <p><strong>The two anti-dilution formulas decide the size of the hit.</strong> Broad-based weighted average, the version most Mumbai term sheets carry, nudges the investor's conversion ratio and spreads the pain. Full ratchet is the punishing exception: it resets the investor's effective price the whole way down to the new round, dumping outsized dilution on founders and the ESOP.</p>
                    <p><strong>An ESOP carve-out is your protection on the next grant.</strong> Most anti-dilution clauses exclude shares issued under the option pool from triggering an adjustment, so a carefully drafted carve-out lets a Powai SaaS company make post-round retention grants without firing the clause a second time. We read the term sheets, confirm the carve-out, and use it.</p>
                    <p>Identifying which formula your documents carry, and pushing for weighted average plus a clean ESOP carve-out, is the heart of containing the damage.</p>

