        <div class="text-content">
            <h2 class="section-title">Legal and Tax Framework</h2>
            <div class="content-text">

                <p>The law here is national, but the filing desk is local: a Pune company's repricing is governed by the Companies Act and the Income-tax Act, while the forms land with the Registrar of Companies, Pune on MCA21. The four provisions that actually decide your engagement are below.</p>
                <p><strong>Anti-dilution:</strong> anti-dilution rights attach to investor preference shares and, on a down round, readjust the conversion ratio in the investor's favour; broad-based weighted average is the common, moderate form, full ratchet the rare, severe one.</p>
                <p><strong>Repricing and re-grant:</strong> repricing existing options or issuing fresh grants is a variation of the ESOP scheme under Section 62(1)(b) of the Companies Act read with Rule 12, needing a board resolution and a shareholder special resolution.</p>
                <p><strong>Valuation:</strong> the new exercise price is set with a registered-valuer or <a href="/esop-valuation-services/pune">Rule 11UA valuation</a> reflecting the lower post-down-round fair market value.</p>
                <p><strong>Tax:</strong> the perquisite on a future exercise is the spread over the repriced strike, taxed under <a href="/esop-perquisite-tax-section-17-2-vi/pune">Section 17(2)(vi)</a>; the repricing or re-grant also carries accounting effects under the applicable standards.</p>
