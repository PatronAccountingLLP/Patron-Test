                <h2 class="section-title">Anti-Dilution and Preference Shares</h2>
                <div class="content-text what-is-definition">

                    <p>Start with the term sheet, because the anti-dilution clause your earlier investor negotiated decides how much of the down round you absorb personally. The clause exists to protect the investor's entry price: when you raise lower, it improves the rate at which their preference shares convert to equity, handing them additional shares. Those shares come out of the common pool, which is where founders and the option scheme sit, so in practice a Baner-Balewadi startup's anti-dilution clause is a transfer of ownership away from the team and toward the prior fund.</p>
                    <p><strong>The form of the clause is everything.</strong> Broad-based weighted average, the version most Pune term sheets carry, blends the old and new prices and the existing share count, so the adjustment is proportionate and survivable. Full ratchet is the harsh outlier: it resets the investor's effective price all the way down to the new low regardless of how few shares the round raised, which can gut a founder's stake on a small bridge. We read your specific clause before modelling anything, because the gap between these two outcomes is enormous.</p>
                    <p><strong>The ESOP carve-out is your lever.</strong> Most well-drafted clauses exclude option-pool issuances from triggering a fresh adjustment. For a Kharadi product company that needs to re-grant to its lead engineers after the round, a clean carve-out means those retention grants do not set off another round of investor dilution. We confirm the carve-out is present and usable before recommending re-grants, and flag it for negotiation when it is missing.</p>

