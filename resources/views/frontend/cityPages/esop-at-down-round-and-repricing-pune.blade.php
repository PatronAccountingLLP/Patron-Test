            <h2 class="section-title">Underwater Options: The Employee Problem</h2>
            <div class="content-text">

                <p>An option only has value if its exercise price sits below what a share is actually worth. After a down round resets the fair market value lower, any grant struck at the old, higher price is "underwater", and exercising it would mean paying more than the share is worth. A staff engineer in Magarpatta who joined two years ago for a salary discount plus options now holds paper worth zero on exercise, and unlike a founder, they cannot wait years for it to recover before their next move.</p>
                <p>This is where Pune's labour market makes the problem acute rather than academic. A senior backend or ML engineer in the Hinjewadi-Kharadi belt can field a competing offer within weeks, often from a company that is up-and-to-the-right and can hand them in-the-money equity on day one. So the question is not whether options went underwater; it is which underwater grants are attached to people you cannot afford to lose this quarter.</p>
                <p>Crucially, we do not advise repricing everything. A grant a few rupees below water at a company still scaling through Chakan-MIDC manufacturing demand or a strong SaaS renewal book will likely climb back above the strike on its own, and a formal repricing carries cost and quietly tells the team things are bad. The discipline is triage: separate the grants that need intervention now from the ones that are best left alone, person by person.</p>

