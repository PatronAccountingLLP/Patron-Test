                <h2 class="section-title">What Are ESOP Corporate Filings</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Gurugram runs some of India's largest option pools - the enterprise-SaaS and ITES players in Cyber City and Udyog Vihar, and the unicorns clustered along Golf Course Road. For a company at that scale, ESOP corporate filings are the ongoing machinery of MCA forms, board minutes, statutory registers and annual-return disclosures that keep a plan compliant under Section 62(1)(b) of the Companies Act 2013 and Rule 12 of the Companies (Share Capital and Debentures) Rules 2014. A point Gurugram founders often miss: although the company sits in Haryana, it files with the Registrar of Companies, Delhi.</p>
                    <p>The core set is four filings: MGT-14 for special resolutions, PAS-3 for each allotment on exercise, MGT-7 for the annual-return ESOP movement, and the Form SH-6 Register of Employee Stock Options - the last of which, at unicorn scale, can hold hundreds of grantees.</p>
                    <p>A Sohna Road or Cyber City company running its pool through a Trust adds trust-deed registration, trustees minutes and ITR-7. With ESOPs granted across global delivery teams, an exercise by a non-resident employee triggers <a href="/esop-fema-and-rbi-firms-reporting/gurugram">FC-GPR within 30 days under FEMA</a>. And <a href="/esop-services-for-listed-companies/gurugram">once an enterprise-SaaS company lists</a>, Regulation 19 of the SEBI (Share Based Employee Benefits and Sweat Equity) Regulations 2021 governs any Trust-route ESOP.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for ESOP Corporate Filings:</strong></p>
                    <p><strong>MGT-14:</strong> Filing of resolutions and agreements with Registrar under Section 117(2); required within 30 days for special resolution approving ESOP scheme, scheme variation, pool top-up or any agreement requiring RoC filing.</p>
                    <p><strong>PAS-3:</strong> Return of allotment under Section 39(4) read with Rule 12 of Companies (Prospectus and Allotment of Securities) Rules 2014; required within 30 days of share allotment on ESOP exercise.</p>
                    <p><strong>MGT-7:</strong> Annual Return under Section 92; must include ESOP particulars - options outstanding at start and end, granted, vested, exercised, lapsed and forfeited during the year; filed within 60 days of AGM.</p>
                    <p><strong>Form SH-6:</strong> Register of Employee Stock Options under Rule 12(10); maintained at registered office, authenticated by the Company Secretary; details every grant, vesting and exercise.</p>
                    <p><strong>Rule 12(9):</strong> Companies (Share Capital and Debentures) Rules 2014 - mandates 11 specific ESOP disclosures in the Directors' Report covering grants, vesting period, exercise price, options exercised and more.</p>
                    <p><strong>FC-GPR:</strong> FEMA filing required within 30 days when shares are allotted to non-resident employees under the ESOP scheme; coordinated with FDI Compliance team.</p>

