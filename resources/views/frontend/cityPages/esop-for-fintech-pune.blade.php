            <h2 class="section-title">License Milestone Timing for Fintech ESOP</h2>
            <div class="content-text">
                
                <p>For a Pune lending-tech moving from a software-services mindset into a regulated NBFC, timing is the part of ESOP design that catches founders off guard. The IT-park instinct is to grant early and broadly; a fintech has to map every grant batch to its licence stage, because adoption at the wrong moment invites supervisory friction. Sequenced correctly, that risk disappears.</p>
                <ul>
                    <li><strong>Pre-License (Bootstrapping):</strong> Founder grants only under DPIIT 10-year exemption. No Senior Management grants - RBI may view large pre-license grants as a governance red flag during in-principle review.</li>
                    <li><strong>In-Principle Approval:</strong> Broad team grants - engineering, product, compliance; modest pool (10 to 12 percent). Avoid grants in the 60-day RBI conditional response window after in-principle approval.</li>
                    <li><strong>Final License Issued:</strong> CXO, Compliance Head and Risk Head grants. Align to the newly Board-approved Compensation Policy. Policy must be approved BEFORE the first KMP grant.</li>
                    <li><strong>First RBI Inspection (Year 1 to 2):</strong> Avoid fresh grant batches in the inspection window. Defer to post-inspection cycle. Inspector may flag grants as compensation policy default if not aligned.</li>
                    <li><strong>Scale-Based Layer Upgrade (BL to ML):</strong> Immediate Compensation Policy refresh. Align all KMP and Senior Management ESOPs to the new framework. Continuing BL-era compensation structure attracts supervisory action.</li>
                    <li><strong>Pool Top-up at Funding Round:</strong> Standard EGM process. Ensure post-money pool consistent with RBI Comp Guidelines if ML/UL/TL. Investor may require RBI no-objection if foreign FDI involved.</li>
                    <li><strong><a href="/esop-for-pre-ipo/pune">Pre-IPO (Listing Preparation):</a></strong> Transition from RBI-aligned scheme to SEBI SBEB Regulations 2021 regime. Align trustee structure. SEBI SBEB compliance becomes an additional layer.</li>
                </ul>

