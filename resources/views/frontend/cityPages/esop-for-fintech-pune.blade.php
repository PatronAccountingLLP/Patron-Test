                <h2 class="section-title">What Makes Fintech ESOPs Different</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A lending-tech startup running out of a Hinjewadi IT park looks, on paper, like any other <a href="/esop-for-saas-companies/pune">Pune SaaS company</a> - until it picks up an NBFC registration and inherits a compensation rulebook that pure software founders never see. That is the core reason fintech ESOPs in Pune cannot be lifted from a generic startup template: the RBI sits on top of the Companies Act, and a Pune fintech answers to both.</p>
                    <p>The first layer is the <strong>RBI Compensation Guidelines of 29 April 2022.</strong> They impose a structured variable-pay regime on KMPs and Senior Management of Middle, Upper and Top Layer NBFCs - significant deferral, malus and clawback, and a flat bar on ESOPs for Independent Directors. Because SEBI SBEB definitions treat options as 'share-linked instruments', every grant a Kharadi or Baner fintech makes counts as part of variable pay, not a side benefit.</p>
                    <p>The second layer is <strong>ownership-change control.</strong> Under the RBI Master Direction on <a href="/esop-at-acquisition-and-change-of-control/pune">Acquisition and Transfer of Control</a>, any 26 percent shift in shareholding or change in management needs RBI prior approval, filed through Form A. A Pune NBFC whose employee exercises drift past that line has a regulatory filing on its hands, not just a cap-table update.</p>
                    <p>The third layer is <strong>license-milestone timing.</strong> When a scheme is adopted relative to in-principle approval, final license issuance or an RBI inspection materially changes how it is read. For the Viman Nagar and Magarpatta <a href="/esop-for-foreign-parent-indian-subsidiary/pune">fintechs with foreign backers</a>, FEMA NDI Rules 2019 add a sectoral-cap question on top.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Fintech ESOP Design:</strong></p>
                    <p><strong>NBFC SBR Framework:</strong> RBI Scale Based Regulation classifying NBFCs into Base Layer (BL), Middle Layer (ML), Upper Layer (UL) and Top Layer (TL). Compensation Guidelines apply only to ML, UL and TL.</p>
                    <p><strong>RBI Compensation Guidelines (29 April 2022):</strong> Circular DOR.GOV.REC.No.29 prescribing fixed/variable pay structure, mandatory multi-year deferral, malus, clawback and Independent Director ESOP prohibition for ML/UL/TL NBFCs. Effective 1 April 2023.</p>
                    <p><strong>Malus:</strong> Board-discretion right to reduce or cancel UNVESTED deferred remuneration on negative outcomes - misconduct, material risk failure, willful misreporting.</p>
                    <p><strong>Clawback:</strong> Contractual right to recover PREVIOUSLY PAID or VESTED variable pay on misstatement, fraud or serious risk breach.</p>
                    <p><strong>26 Percent Shareholding Trigger:</strong> Under RBI Master Direction on Acquisition and Transfer of Control, any change in NBFC shareholding of 26 percent or more, or change in management, requires RBI prior approval via Form A.</p>
                    <p><strong>Fit and Proper (F&amp;P):</strong> RBI criteria for directors, KMPs, senior management and ESOP Trust trustees covering financial integrity, regulatory history, qualifications, experience and absence of fraud convictions.</p>

