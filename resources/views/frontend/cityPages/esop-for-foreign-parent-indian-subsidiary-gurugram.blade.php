                <h2 class="section-title">What Makes This the Hardest ESOP Scenario</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Gurugram's equity culture is unusually deep - this is the city of Zomato, Delhivery and Policybazaar, where stock-based pay is the norm and an entire Cyber City workforce is comfortable reading a vesting schedule. <a href="/blog/received-esops-from-a-foreign-company">Foreign-parent equity</a> is a different animal from a home-grown unicorn ESOP, though: a Cyber City enterprise-SaaS captive vesting RSUs from a US-listed parent picks up five technical layers that a domestic plan under one statute never has.</p>
                    <p><strong>One - perquisite in the Gurugram entity.</strong> The parent issues the shares; <a href="/esop-perquisite-tax-section-17-2-vi/gurugram">Section 17(2)(vi) still puts the taxable perquisite</a> in the subsidiary's payroll.</p>
                    <p><strong>Two - the Gurugram subsidiary withholds.</strong> Section 192(1) makes the Indian employer the <a href="/esop-tds-section-192-and-form-24q/gurugram">TDS deductor</a> on a non-cash, foreign-currency benefit - at the scale of a thousand-engineer captive, this is a payroll-systems problem, not a spreadsheet one.</p>
                    <p><strong>Three - four schedules in the ITR.</strong> Schedule FA, FSI, TR and Form 67 reconcile per employee.</p>
                    <p><strong>Four - DTAA and Foreign Tax Credit.</strong> Sections 90/91 read with Rule 128 govern recovery of foreign withholding.</p>
                    <p><strong>Five - the transfer pricing recharge.</strong> Section 92 requires the parent's equity cost to be recharged to the Gurugram entity, usually alongside the existing ITES or SaaS-services billing.</p>
                    <p>The home-country overlays (US 409A, UK CSOP/EMI, Singapore IRAS, Israel Section 102 trustee route) sit on top - and given Gurugram's heavy US enterprise-SaaS base, the US W-8BEN and sell-to-cover mechanics dominate day-to-day.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Foreign Parent ESOP and RSU:</strong></p>
                    <p><strong>RSU (Restricted Stock Unit):</strong> Grant of shares that vests over time; no exercise price; full FMV is the perquisite at vesting. Standard for mature MNCs like Microsoft, Adobe, Salesforce, Cisco, Google.</p>
                    <p><strong>ESOP (Employee Stock Option Plan):</strong> Right to buy shares at a predetermined exercise price; perquisite is FMV minus exercise price at exercise. More common at growth-stage and pre-IPO MNCs.</p>
                    <p><strong>ESPP (Employee Stock Purchase Plan):</strong> Periodic purchases of parent stock at discount (typically 5 to 15 percent); discount is taxable perquisite at the purchase date.</p>
                    <p><strong>SAR (Stock Appreciation Right):</strong> Cash-settled right paying the appreciation in parent share price; treated as a cash bonus, fully taxable as salary at payment.</p>
                    <p><strong>Sell-to-Cover:</strong> Default mechanism at vesting where a portion of vested shares is automatically sold by the broker to fund the TDS liability deposited by the Indian subsidiary.</p>
                    <p><strong>Transfer Pricing Recharge:</strong> Cross-border invoice from the foreign parent to the Indian subsidiary for the equity compensation cost attributable to Indian employees; required under Section 92 read with OECD transfer pricing principles.</p>
                    <p><strong>W-8BEN:</strong> US tax form filed by Indian residents with the US broker (e.g. E-Trade, Fidelity, Morgan Stanley StockPlan Connect) to claim DTAA-reduced withholding rates on US dividends and avoid US capital gains withholding.</p>
                    <p><strong>FTC (Foreign Tax Credit):</strong> Credit claimed in Gurugram under Section 90 read with Rule 128 for taxes paid in the foreign country on the same income; claimed via Form 67 plus Schedule TR in ITR.</p>

