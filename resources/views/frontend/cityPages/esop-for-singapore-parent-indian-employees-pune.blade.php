                        <div class="faq-expanded__a"><p>It is an IRAS rule for employees who are not Singapore Citizens and who cease Singapore employment. Their unexercised ESOP or ESOW is deemed to be exercised one month before the cessation of employment, or the grant date if later, and the gain is taxed in Singapore then. It matters for someone who held Singapore-parent options while working in Singapore and then relocates to India, who may face a Singapore charge on departure plus the later Indian tax, with a treaty credit to coordinate.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-5">
                        <h3 class="faq-expanded__q">Who deducts tax on the perquisite?</h3>
                        <div class="faq-expanded__a"><p>The Indian subsidiary, branch or office that employs you deducts TDS on the perquisite when the ESOP is exercised or the RSU vests, and reports it in your Form 16 and Form 12BA, even though the shares come from the Singapore parent. This usually involves a cross-charge between the parent and the subsidiary. We set up the cross-charge and the TDS mechanics so the subsidiary withholds and reports correctly.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-6">
                        <h3 class="faq-expanded__q">Do I disclose Singapore shares under Schedule FA?</h3>
                        <div class="faq-expanded__a"><p>Yes. As an Indian resident, you must disclose your Singapore-parent shares and your foreign brokerage account under Schedule FA in ITR-2 or ITR-3, including the holding and any income, whether or not you have sold. Non-disclosure or misreporting of foreign assets can lead to penalty and prosecution exposure under the Black Money Act, and such holdings are increasingly traceable, so accurate disclosure is essential. We prepare it from your records.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-7">
