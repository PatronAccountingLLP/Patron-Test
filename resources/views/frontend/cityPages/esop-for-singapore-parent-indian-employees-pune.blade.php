                        <div class="faq-expanded__a"><p>For a Pune product engineer in Hinjewadi, Magarpatta, Kharadi or Baner whose firm flipped to a Singapore parent, an RSU is taxed as a perquisite at vesting on the full fair market value, because there is no exercise price, and the Pune subsidiary deducts TDS and reports it in Form 16 and Form 12BA. On sale, the gain over the vesting value is capital gains in India, with no Singapore charge since Singapore has no capital gains tax. We compute the perquisite, handle the cross-charge and TDS, and file your Schedule FA for the Singapore holding.</p></div>
