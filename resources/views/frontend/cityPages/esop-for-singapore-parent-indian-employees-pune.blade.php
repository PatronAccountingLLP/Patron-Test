                <h2 class="section-title">How Singapore-Parent Equity Is Taxed in Pune</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Pune's equity story runs along two tracks. A SaaS engineer at a Hinjewadi or Kharadi product company that flipped to a Singapore holding holds the same grant as an operations lead at a Chakan or MIDC unit whose APAC parent sits in Singapore, and the India tax mechanics are identical for both. Whoever the Pune employer is, the grant terms are written in Singapore but the perquisite, the TDS and the Schedule FA disclosure are an Indian, Pune-side job.</p>
                    <p>The reporting split is worth fixing up front: the individual employee files with their own jurisdictional assessing officer, while the Pune operating company that pays the salary withholds the TDS and reports it; the company's statutory returns sit with RoC Pune under Maharashtra jurisdiction. From there, every foreign grant follows one two-stage model, a perquisite at the first tax point and then capital gains on exit.</p>
                    <p><strong>ESOP (options):</strong> taxed at exercise on FMV minus the exercise price, as a perquisite, with TDS by the Indian subsidiary.</p>
                    <p><strong>RSU (units):</strong> taxed at vesting on the full FMV, as a perquisite, with no strike to offset.</p>
                    <p><strong>On sale:</strong> the gain over the perquisite-taxed value is <a href="/esop-capital-gains-tax-on-sale/pune">capital gains</a>. Singapore shares are foreign and unlisted for Indian purposes, so a holding period over 24 months from exercise or vesting gives long-term capital gains at 12.5 percent; a shorter holding is short-term, taxed at slab rates. The Indian subsidiary deducts TDS on the perquisite under <a href="/esop-perquisite-tax-section-17-2-vi/pune">Section 17(2)(vi)</a>, with fair market value under <a href="/esop-valuation-services/pune">Rule 11UA</a> for unlisted shares.</p>

                </div>
