                <div class="content-text what-is-definition">
                    
                    <p>When a Nasdaq-listed parent grants equity to its BKC or Powai team, the engineer in Mumbai still pays Indian tax in two distinct events, and getting the sequence right matters more than the US paperwork. The two taxing moments are the grant-side perquisite and the eventual sale.</p>
                    <p><strong>At the perquisite stage</strong> the instrument decides the trigger. An option (ESOP) is taxed only when the employee exercises, on the <a href="/esop-perquisite-tax-section-17-2-vi/mumbai">fair market value over the exercise price</a>; a unit (RSU) is taxed the moment it vests, on the whole fair market value with no strike to net off. In both cases the Indian subsidiary withholds TDS on salary.</p>
                    <p><strong>At the sale stage</strong> any rise over the value already taxed as perquisite is a <a href="/esop-capital-gains-tax-on-sale/mumbai">capital gain</a>. Because US-listed stock counts as a foreign, unlisted security in India, the line sits at 24 months from exercise or vesting: hold longer and the gain is long-term at 12.5 percent, sell sooner and it is short-term at slab rates. We model both events and reconcile the withholding so a Lower Parel finance professional is not over-deducted at vesting and under-credited at sale.</p>

