<!-- SECTION 15A: LEGAL FRAMEWORK -->
<section class="content-section">
    <div class="content-container">
        <div class="text-content">
            <h2 class="section-title">Legal and Compliance Framework</h2>
            <div class="content-text">
                
                <p><strong>Governing provision:</strong> Section 178 of the Companies Act 2013 requires every listed public company and prescribed public companies to constitute a Nomination and Remuneration Committee of three or more non-executive directors, at least one-half independent.</p>
                <p><strong>Applicability:</strong> the prescribed thresholds are paid-up capital of Rs 10 crore or more, turnover of Rs 100 crore or more, or aggregate loans, debentures and deposits exceeding Rs 50 crore. Private companies are not mandated, and Section 8 and specified IFSC public companies are exempt.</p>
                <p><strong>Listed entities:</strong> SEBI LODR Regulation 19 requires all directors of the committee to be non-executive, at least half independent, and the committee to be chaired by an independent director.</p>
                <p><strong>Penalty:</strong> under Section 178(8), contravention makes the company liable to a penalty of Rs 5 lakh and every officer in default to Rs 1 lakh.</p>
                <p>Authoritative sources: the <a href="https://www.mca.gov.in" target="_blank" rel="noopener">Ministry of Corporate Affairs</a> (Section 178, committees), the <a href="https://www.indiacode.nic.in" target="_blank" rel="noopener">Companies Act and Rules</a>, <a href="https://www.sebi.gov.in" target="_blank" rel="noopener">SEBI</a> (LODR Regulation 19), and the <a href="https://www.icsi.edu" target="_blank" rel="noopener">ICSI</a> (secretarial standards, governance).</p>

