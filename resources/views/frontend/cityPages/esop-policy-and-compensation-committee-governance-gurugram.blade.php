                <div class="content-text what-is-definition">
                    
                    <p>Gurugram runs on stock options. In the city that produced Policybazaar, Delhivery and Zomato, equity is how an enterprise-SaaS scale-up in Cyber City or a consumer-tech startup on Golf Course Road hires and holds talent, which is exactly why the board layer above those grants matters. Compensation committee governance is that layer: a Section 178 Nomination and Remuneration Committee that owns who approves an ESOP grant, and against what criteria, instead of the cap table moving on a founder's say-so.</p>
                    <p>Three pieces hold the framework together for a Udyog Vihar or Sohna Road board. A charter sets the committee's powers and how it meets. A written ESOP policy fixes the rules for grant, <a href="/esop-vesting-and-forfeiture-tracking/gurugram">vesting, exercise and forfeiture</a>. A decision-rights map then says, for every equity decision, who recommends it, who approves it and who executes it. The NRC sitting over all three formulates the remuneration policy, recommends senior appointments, and keeps fixed and incentive pay in proportion.</p>

