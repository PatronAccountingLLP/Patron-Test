            <h2 class="section-title">Legal Framework</h2>
            <div class="content-text">
                
                <p>There is no Maharashtra-specific ESOP law and no Pune ESOP law; the rules that govern a Hinjewadi SaaS scheme are the same central statutes that govern a company anywhere in India. What is local is only the counter your forms reach, RoC Pune on the MCA21 portal, which processes the MGT-14 and PAS-3 the framework below already demands.</p>
                <p><strong>Authority:</strong> Section 62(1)(b) of the Companies Act, 2013 authorises a company to issue shares to employees under an ESOP scheme approved by a special resolution in a general meeting.</p>
                <p><strong>Rule 12:</strong> Rule 12 of the Companies (Share Capital and Debentures) Rules, 2014 prescribes who is eligible, the disclosures the scheme and notice must carry, the minimum one-year vesting, and the SH-6 register requirement.</p>
                <p><strong>Filings:</strong> MGT-14 must be filed within 30 days of the special resolution, and PAS-3 on allotment of shares after exercise.</p>
                <p><strong>Listed companies:</strong> a listed company's scheme must additionally comply with the SEBI Share Based Employee Benefits and Sweat Equity Regulations, 2021, with their own disclosure and approval requirements.</p>
                <p>Authoritative sources: the <a href="https://www.mca.gov.in" target="_blank" rel="noopener">Ministry of Corporate Affairs</a> (Section 62, Rule 12, MGT-14, PAS-3), the <a href="https://www.indiacode.nic.in" target="_blank" rel="noopener">Companies Act and Share Capital Rules bare text</a>, <a href="https://www.sebi.gov.in" target="_blank" rel="noopener">SEBI</a> (SBEB and Sweat Equity Regulations), and <a href="https://www.startupindia.gov.in" target="_blank" rel="noopener">Startup India / DPIIT</a> (startup ESOP relaxations).</p>

