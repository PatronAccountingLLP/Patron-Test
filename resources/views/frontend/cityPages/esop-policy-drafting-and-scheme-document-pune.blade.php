            <h2 class="section-title">What a Compliant Scheme Document Contains</h2>
            <div class="content-text">
                
                <p>Take a worked example. A Magarpatta-based SaaS firm widening its pool before a Series A and a Chakan MIDC manufacturer carving out options for two plant heads look nothing alike commercially, yet Rule 12 hands both the same checklist. Whatever the design, the scheme and the general-meeting notice must spell out each of the following, and our draft pins down every one:</p>
                <ul>
                    <li><strong>The pool:</strong> the total number of options the scheme authorises, matched to the dilution your board has already approved.</li>
                    <li><strong>Who is eligible:</strong> the classes of employees and directors who can be granted options, drawn wide for a Hinjewadi engineering team or kept tight for a handful of senior staff at a MIDC plant.</li>
                    <li><strong>Vesting:</strong> the vesting conditions, the vesting period and the longest period the scheme permits before options must have vested.</li>
                    <li><strong>The exercise price:</strong> stated directly, or set by the formula the scheme writes down.</li>
                    <li><strong>Exercising:</strong> the window in which a vested option can be exercised and the mechanics of doing so.</li>
                    <li><strong>What ends an option:</strong> the lapse triggers and the <a href="/esop-employee-exit-and-good-leaver-bad-leaver/pune">leaver treatment for someone exiting the company</a>.</li>
                    <li><strong>The ceilings:</strong> the cap on any single grantee and the cap across the entire pool.</li>
                    <li><strong>Valuation and books:</strong> the valuation approach and the express commitment to the applicable accounting standards.</li>
                </ul>
                <p><strong>Three clauses are not optional</strong> for a Viman Nagar startup or a scaled Chakan manufacturer alike: the one-year minimum between grant and vesting, a stated method for how the board fixes the exercise price, and a clear line that option-holders are not shareholders and acquire no such rights until they exercise.</p>

