                    <li><strong>What events trigger the deferred TDS payment?</strong> The TDS falls due on the earliest of expiry of the deferral window, sale of the shares, or the employee's exit from the company.</li>
                    <li><strong>At what rate and by when must the deferred TDS be paid?</strong> It is paid at the allotment-year slab rate and must be remitted within 14 days of the triggering event.</li>
                </ul>

