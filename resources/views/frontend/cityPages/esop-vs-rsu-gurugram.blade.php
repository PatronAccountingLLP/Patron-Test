            <h2 class="section-title">How ESOPs and RSUs Are Taxed</h2>
            <div class="content-text">
                
                <p>For a Gurugram employee, both instruments <a href="/blog/esop-taxation-rules-2026-when-how-stock-options-taxed-rules">trigger tax at two separate moments</a>, first as a salary perquisite and again as capital gains when the shares are sold. What separates them is when that first perquisite charge lands, and getting that timing right matters as much for a Cyber City RSU holder as for a Sohna Road startup's option pool.</p>
                <ul>
                    <li><strong>RSU perquisite at vesting:</strong> because the shares arrive free, the entire FMV on the vesting date is treated as salary in your hands.</li>
                    <li><strong><a href="/esop-perquisite-tax-section-17-2-vi/gurugram">ESOP perquisite at exercise</a>:</strong> only the spread between the FMV on the exercise date and the exercise price you paid is taxed as salary.</li>
                    <li><strong>Capital gains on eventual sale:</strong> for either instrument, the sale price less the FMV already taxed as perquisite is the gain, short or long term by holding period.</li>
                </ul>
                <div class="highlight-box" style="margin-top:16px;">
                    <p><strong>The phantom-tax trap that bites Cyber City RSU holders</strong></p>
                    <p>RSU perquisite tax is locked in at the vesting-date value. Picture a Udyog Vihar engineer whose foreign-parent RSUs vest in a strong quarter, only for the listed share to slide afterwards. The tax was paid on a high value that was never cashed in, a real economic loss that a subsequent capital loss claim recovers only in part.</p>
                </div>
                <p style="margin-top:16px;"><strong>So which route fits which company:</strong> a foreign-headquartered enterprise-SaaS group on Golf Course Road simply mirrors its global RSU plan, structured for Indian compliance and tax; a listed or pre-IPO Cyber City firm leans on ESOP-structured RSUs for steadier, easy-to-explain value; a dilution-averse employer picks a cash-settled SAR or phantom stock that tracks the equity without issuing a single share; and an early-stage Sohna Road startup still favours plain ESOPs for their zero cash cost and future upside.</p>

