            <h2 class="section-title">What Is an RSU</h2>
            <div class="content-text">
                
                <p>Walk into almost any enterprise-SaaS office around DLF Cyber City or Udyog Vihar and the equity letter on the table will say RSU, not ESOP. A Restricted Stock Unit is simply a promise: the company hands over shares free of cost the moment vesting conditions, whether a time period or a performance milestone, are satisfied. The employee never writes a cheque to acquire them, because there is no exercise price.</p>
                <p>That free grant is exactly why RSUs feel safer to Gurugram's listed-multinational and unicorn workforce. A share that costs nothing at vesting almost always carries real value, so the instrument rarely sits worthless the way an underwater option can. The catch is structural: Indian law does not name the RSU as an instrument, so a Cyber City employer typically delivers it either as an ESOP carrying a token exercise price, or as a cash-settled right such as a <a href="/esop-vs-sar/gurugram">stock appreciation right</a>, while a US-headquartered parent on Golf Course Road grants its own listed stock directly.</p>

