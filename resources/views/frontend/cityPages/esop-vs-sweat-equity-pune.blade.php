                <p><strong>Quick Answers</strong></p>
                <ul>
                    <li><strong>Which section governs ESOPs?</strong> ESOPs are issued under Section 62(1)(b) of the Companies Act, 2013.</li>
                    <li><strong>Which section governs sweat equity shares?</strong> Sweat equity shares are issued under Section 54 of the Companies Act, 2013.</li>
                    <li><strong>Can promoters participate in either scheme?</strong> Promoters can receive sweat equity shares, but they cannot be granted ESOPs unless the company is a DPIIT-recognised startup.</li>
                    <li><strong>Is there a mandatory lock-in period?</strong> Sweat equity shares carry a statutory lock-in of 3 years, whereas ESOPs have no statutory lock-in.</li>
                    <li><strong>Which registers record each issue?</strong> ESOP grants are recorded in Form SH-6 (Register of Employee Stock Options), while sweat equity shares are recorded in Form SH-3 (Register of Sweat Equity Shares).</li>
