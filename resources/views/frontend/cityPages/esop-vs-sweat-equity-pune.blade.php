                <div class="content-text what-is-definition">
                    
                    <p>Picture a product-engineering company in the Hinjewadi IT park that has just closed a Series A and needs to keep its senior backend team from being poached by the next SaaS startup across the road. The ESOP is built for exactly this. It hands an employee the right, not the obligation, to buy company shares at a pre-agreed exercise price once they have vested, and that right rests on Section 62(1)(b) of the Companies Act read with Rule 12. Until the engineer actually exercises and the shares are allotted, the cap table does not move at all.</p>
