                <p>Sweat equity inverts every one of those features. Instead of a future option, the company allots real shares now, either at a discount or against non-cash consideration, under Section 54 read with Rule 8. The "non-cash" part is what makes it the founder's instrument: a Chakan auto-component maker in the MIDC belt whose co-founder contributed a proprietary tooling design, or a Kharadi SaaS promoter who personally wrote the product's core engine, can be paid for that contribution in shares rather than salary or cash.</p>
