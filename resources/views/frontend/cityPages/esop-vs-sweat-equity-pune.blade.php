                        <div class="faq-expanded__a"><p>Established product and services companies in the Hinjewadi and Magarpatta IT parks usually run a structured ESOP pool, because the aim is to retain salaried engineers over a 3-to-4 year vesting schedule rather than reward a past contribution. Sweat equity tends to fit the early Kharadi and Baner founder teams instead, where a promoter or a senior hire who brought IP needs real shares now. The recipient and the goal decide it, not the cluster.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-7">
                        <h3 class="faq-expanded__q">Which instrument is better for giving equity to founders?</h3>
                        <div class="faq-expanded__a"><p>If you are not a DPIIT-recognised startup, promoters cannot be granted ESOPs, so sweat equity is the only route. If you are a DPIIT startup, both instruments are available. Sweat equity issues real shares for know-how or value additions, with a 3-year lock-in.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-8">
                        <h3 class="faq-expanded__q">Can a Pune deep-tech co-founder get equity for IP they built?</h3>
                        <div class="faq-expanded__a"><p>Yes, and sweat equity is the usual route. Many Baner-Balewadi and Kharadi deep-tech teams have a technical promoter who built the core algorithm or know-how. Because that person is a promoter, an ordinary ESOP is barred unless the company is a DPIIT-recognised startup. Sweat equity under Section 54 lets the company issue real shares for that non-cash IP contribution, priced by an IBBI-registered valuer and locked in for three years from allotment.</p></div>
