                <div class="content-text what-is-definition">
                    
                    <p>FSSAI State Licence is the food safety licence issued by FDA Maharashtra to medium-scale FBOs with annual turnover between Rs 12 lakh and Rs 20 crore, or meeting specific production capacity criteria, authorising legal food business operation under Section 31 of the FSS Act, 2006.</p>
                    <p>It occupies the middle tier of FSSAI's three-tier system. Below: Basic Registration (up to Rs 12 lakh, Form A). Above: Central Licence (above Rs 20 crore or importers/exporters/multi-state, Form B). State Licence covers the broadest segment - every restaurant generating >Rs 1 lakh/month, every cloud kitchen with orders >Rs 1 lakh/month, every food processor with 100 kg-2 MT/day capacity.</p>
                    <p>Filed through Form B on FoSCoS (foscos.fssai.gov.in). The 14-digit licence number starts with '2' (State) and must be displayed at premises and on all packaging. Operating without correct licence tier is punishable under Sections 58-59 with fine up to Rs 5 lakh. Patron provides <a href="/fssai-state-license">FSSAI state licence</a> with FSMS documentation and FDA Maharashtra coordination.</p>

