                <div class="highlight-box" style="margin-bottom:20px;">
                    <p><strong>&#128204; TL;DR - GST Notice in Delhi Services at a Glance</strong></p>
                    <p>GST notices in Delhi are issued by Delhi SGST officers (Commissioner GNCTD), CGST officers (Commissioner Delhi Zone), or DGGI (anti-evasion) for discrepancies in returns, ITC mismatches, non-filing, registration issues, or suspected tax evasion. The most common notices are ASMT-10 (scrutiny - reply within 30 days in ASMT-11), DRC-01 (show cause notice under Section 73/74 - reply in DRC-06 within 30 days), and REG-17 (registration cancellation - reply within 7 days). From FY 2024-25, Section 74A replaces the dual Sections 73/74 with a unified 42-month demand provision. Ignoring notices leads to ex-parte demand orders (DRC-07), bank account attachment, registration cancellation, and penalties up to 100% of tax. Patron Accounting handles GST notice replies for Delhi businesses from our Rohini office - 500+ notices handled with 95% resolution rate.</p>
