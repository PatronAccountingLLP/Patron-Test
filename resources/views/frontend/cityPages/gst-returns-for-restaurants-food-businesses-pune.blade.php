            <div class="column-content">
                <h2 class="section-title">What Are GST Returns for Restaurants</h2>
                <div class="content-text what-is-definition">
                    
                    <p>GST returns for restaurants are periodic filings on the GST portal (gst.gov.in) where a GST-registered restaurant, cafe, cloud kitchen, or catering business declares its outward supplies (food and beverage sales), inward supplies (raw material and operational purchases), and net GST payable for the filing period under the CGST Act, 2017.</p>
<p>Most standalone restaurants in India - including those in Pune - operate under the <strong>5% GST regime without Input Tax Credit</strong>, as notified under Notification No. 11/2017-Central Tax (Rate). This means a restaurant at Koregaon Park or FC Road charges 5% GST on dine-in, takeaway, and direct delivery orders, but cannot claim ITC on raw materials, rent, equipment, or utilities. Restaurants in hotels where room tariff is Rs 7,500 or more per night fall under the 18% GST bracket with ITC eligibility.</p>
<p><strong>Section 9(5) - Swiggy and Zomato Orders:</strong> Since 1 January 2022, food delivery platforms (ECOs) like Swiggy and Zomato are deemed suppliers for restaurant services delivered through their platform. The ECO collects and deposits 5% GST on behalf of the restaurant. The restaurant does not collect GST on platform orders and must report these supplies separately in <strong>Table 3.1.1(ii) of GSTR-3B</strong>. This is a critical reporting distinction for Pune restaurants listed on Swiggy and Zomato.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for GST Returns for Restaurants in Pune:</strong></p>
                    <p><strong>5% GST (No ITC):</strong> Standard rate for standalone restaurants. SAC 996331. No Input Tax Credit on purchases.</p>
<p><strong>18% GST (With ITC):</strong> For hotel restaurants (room tariff >= Rs 7,500/night) and outdoor catering. SAC 996332. Full ITC available.</p>
