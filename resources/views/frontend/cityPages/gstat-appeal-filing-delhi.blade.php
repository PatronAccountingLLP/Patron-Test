                <h2 class="section-title">Who Needs GSTAT Appeal Filing at Delhi State Bench</h2>
                <p>Any taxpayer in NCT of Delhi who received an unfavourable order from the First Appellate Authority under S.107 or Revisional Authority under S.108 of the CGST/DGST Act can file at the Delhi State Bench under Section 112.</p>
                <p><strong>Principal Bench vs Delhi State Bench - Critical Distinction:</strong> The Delhi State Bench handles <strong>intra-Delhi GST disputes</strong>. The Principal Bench (also in New Delhi) handles inter-state disputes, place-of-supply matters involving multiple states, anti-profiteering, OIDAR services, ISD, and serves as NAAR. Filing at the wrong bench results in procedural rejection.</p>
                <p><strong>Common demand categories:</strong></p>
                <ul>
                    <li>ITC reversal demands targeting Delhi's extensive trading and services businesses</li>
                    <li>Classification disputes on software licences, SaaS, and digital services (Delhi's IT concentration)</li>
                    <li>Fake invoice cases under S.74 in Chandni Chowk, Sadar Bazaar, Karol Bagh trading zones</li>
                    <li>TRAN-1 transitional credit disputes from pre-GST service tax migration</li>
                    <li>Penalty orders for late GSTR-3B filing and e-way bill violations in Delhi-NCR corridor</li>
                    <li>Service tax migration and place-of-supply classification for Delhi services sector</li>
                </ul>
