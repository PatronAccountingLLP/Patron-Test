                <h2 class="section-title" id="what-is-section">What Is GSTAT Appeal Filing in Srinagar</h2>
<div class="highlight-box" style="background:var(--blue-lighter);border-left:4px solid var(--blue);padding:20px 24px;border-radius:var(--radius-md);margin-bottom:24px;">
    <p style="font-weight:600;color:var(--blue);margin-bottom:4px;">Definition</p>
    <p>GSTAT - the Goods and Services Tax Appellate Tribunal - is the statutory forum under Section 109 of the CGST Act for appeals against GST demand orders. The Srinagar bench covers the Union Territories of J&amp;K and Ladakh, with a Jammu circuit. Businesses file appeals here under Section 112.</p>
</div>
<p>The Srinagar bench was constituted under Notification S.O. 3048(E) dated 31 July 2024, with Jammu as circuit bench. J&amp;K became a Union Territory on 31 October 2019 under the J&amp;K Reorganisation Act 2019. Ladakh became a separate Union Territory on the same date. The bench is operational since January 2026 per Office Order 03/2025.</p>
<p>Appeals arise from the Commissioner, CGST, J&amp;K at OB-32, Rail Head Complex, Jammu (with 4 divisions: Jammu-I, Jammu-II, Samba, Srinagar) and the Commissioner, State Taxes Department, J&amp;K. For Ladakh, the UTGST administration issues demand orders. Under Section 112 CGST Act, any aggrieved person may file a second appeal. See <a href="/gstat-appeal-filing">GSTAT appeal filing services in India</a> for the national hub.</p>
