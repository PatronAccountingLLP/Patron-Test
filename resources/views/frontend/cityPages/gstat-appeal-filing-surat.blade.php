<p>Surat's diamond sector generates multi-crore disputes. Pre-deposit of 20% on diamond ITC demands can be a significant financial burden even for large polishing units. Non-payment under S.112(8) results in rejection at admission. See also <a href="/gst-audit">GST audit support</a>.</p>
<h3>Dual CGST Zone Coverage</h3>
<p>The Surat CGST Zone (Surat-I and Surat-II) covers the city, while the Vadodara CGST Zone handles Bharuch and parts of Central Gujarat. Correctly identifying the respondent commissionerate is essential.</p>
