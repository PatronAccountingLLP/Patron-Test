            <div class="column-content">
                <h2 class="section-title">What Is IEC Registration?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>IEC (Import Export Code) registration is the process of obtaining a 10-digit identification number from DGFT under the Foreign Trade Act, 1992 that serves as the primary identity for all import-export transactions - mandatory for customs clearance, bank forex processing, and availing export promotion benefits.</p>
<p>Since 2018, the IEC number equals the entity's PAN. However, IEC must be separately applied for via DGFT. Without IEC: customs will not clear goods, banks will not process foreign exchange, shipping bills cannot be filed, and export incentive schemes cannot be availed. The IEC has lifetime validity but DGFT mandates annual update between April 1 and June 30.</p>
<p>For Hyderabad, IEC is the gateway to global markets. Pharma companies in Genome Valley cannot export APIs without IEC. IT companies cannot claim export incentives without it. Old City pearl dealers cannot ship internationally. Patron ensures IEC is obtained before the first trade transaction.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for IEC Registration:</strong></p>
                    <ul>
<li><strong>IEC:</strong> 10-digit Import Export Code equal to PAN since 2018</li>
<li><strong>DGFT:</strong> Directorate General of Foreign Trade issuing IEC</li>
<li><strong>ANF-2A:</strong> Application form for new IEC on DGFT portal</li>
<li><strong>AD Code:</strong> Authorised Dealer Code linking bank to customs system</li>
<li><strong>ICEGATE:</strong> Indian Customs Electronic Gateway for electronic filing</li>
<li><strong>HS Code:</strong> Harmonised System classification for products</li>
<li><strong>RCMC:</strong> Registration Cum Membership Certificate from Export Promotion Council</li>
<li><strong>GST LUT:</strong> Letter of Undertaking for zero-rated exports without IGST</li>
</ul>

