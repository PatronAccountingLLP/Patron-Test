                <h2 class="section-title">What Is Import Export Code (IEC)?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>The Import Export Code (IEC) is the primary business identification number for international trade in India, issued by the <a href="https://dgft.gov.in/" target="_blank" rel="noopener">Directorate General of Foreign Trade (DGFT)</a> under the Foreign Trade (Development and Regulation) Act 1992. No person or entity can import or export goods without a valid IEC, unless specifically exempted.</p>
                    <p>Post-GST implementation, the IEC number is the same as the PAN of the entity. However, a separate application to DGFT is still required to activate the IEC. The IEC is issued electronically through the DGFT portal (dgft.gov.in) via application form ANF 2A. Once issued, the IEC is valid for the lifetime of the entity - no periodic renewal is needed. However, the DGFT mandates annual updation of the IEC profile on the portal. Failure to update results in deactivation.</p>
                    <p>For Mumbai's trade ecosystem, IEC is the gateway document. Customs authorities at JNPT and Mumbai Port require IEC for clearing import/export shipments. Banks require IEC for processing foreign currency transactions. Companies availing DGFT export promotion schemes (RoDTEP, Advance Authorization, EPCG) need IEC. E-commerce exporters using Amazon Global Selling or direct international shipments from Mumbai need IEC. A CA-managed IEC registration ensures accurate DGFT filing, proper bank certificate formatting, and annual profile updation compliance.</p>

