                    <p><strong>IEC:</strong> Import Export Code - 10-digit number (same as PAN post-GST) issued by DGFT for international trade.</p>
                    <p><strong>DGFT:</strong> Directorate General of Foreign Trade - the authority issuing IEC under Ministry of Commerce.</p>
                    <p><strong>ANF 2A:</strong> Application form on dgft.gov.in for obtaining a new Import Export Code.</p>
                    <p><strong>AD Code:</strong> Authorised Dealer Code linking your bank account to customs for export incentives.</p>
