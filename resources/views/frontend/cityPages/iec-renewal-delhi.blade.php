            <div class="column-content">
                <h2 class="section-title">What Is IEC Renewal: Annual DGFT Update Under Foreign Trade Policy</h2>
                <div class="content-text what-is-definition">
                    
                    <p>IEC renewal is the mandatory annual process of updating or confirming Import Export Code details on the DGFT portal (dgft.gov.in) between April 1 and June 30 each year, as mandated by DGFT Notification No. 58/2015-2020 dated 12 February 2021 and Foreign Trade Policy Paragraph 2.05. The IEC itself has lifetime validity - it does not expire. However, the annual update is non-negotiable: failure to complete it within the April-June window results in automatic deactivation of the IEC.</p>
<p>The renewal process requires the IEC holder to log in to the DGFT portal, review all existing details in Form ANF 2A (General Information, Director/Partner details, Banking Information, and Operation Sectors), make corrections if needed, and authenticate using a Class 3 Digital Signature Certificate (DSC) or Aadhaar-based e-Sign. Even if no changes have occurred in the business details, the annual confirmation must be submitted on the portal.</p>
<p>For Delhi's trading community - from a garment exporter in Okhla who ships via ICD Tughlakabad to a software services company in Connaught Place billing international clients - an active IEC is the foundational trade credential. Without it, customs will not process any Bill of Entry (imports) or Shipping Bill (exports), and banks will not process foreign currency trade remittances. The annual renewal is the single most critical compliance step to maintain uninterrupted trade operations from Delhi.</p>

                </div>
