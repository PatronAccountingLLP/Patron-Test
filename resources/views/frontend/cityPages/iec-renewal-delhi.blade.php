<li><strong>IEC (Import Export Code):</strong> A 10-digit code issued by DGFT, linked to PAN, required for all import/export transactions in India.</li>
<li><strong>DGFT:</strong> Directorate General of Foreign Trade - the governing authority for India's foreign trade policy and IEC management.</li>
<li><strong>ANF 2A:</strong> Application cum Declaration form used for IEC registration, modification, and annual update on the DGFT portal.</li>
<li><strong>DSC (Digital Signature Certificate):</strong> Class 3 digital certificate required for authenticating IEC renewal submissions on the DGFT portal.</li>
<li><strong>IEC Deactivation:</strong> Automatic suspension of IEC when the annual update is not completed by June 30 - prevents all customs clearance.</li>
