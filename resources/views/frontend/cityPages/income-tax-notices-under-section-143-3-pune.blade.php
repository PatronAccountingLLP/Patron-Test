                <h2 class="section-title">How Scrutiny Selection Works (CASS)</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Returns are selected through <strong>CASS (Computer Assisted Scrutiny Selection)</strong> based on risk parameters defined by CBDT. <strong>Limited Scrutiny</strong> is restricted to the specific issue in the notice - AO cannot expand scope without PCIT approval. <strong>Complete Scrutiny</strong> covers the entire return - all income sources, deductions, expenses, and credits.</p>
<p>Common CASS triggers for Pune: <strong>High-value transactions</strong> (SFT/AIR) for Camp traders with Rs 10 lakh+ cash deposits; <strong>Income-AIS mismatch</strong> for Hinjewadi salaried with AIS income higher than ITR; <strong>Large deductions</strong> for Kharadi employees with 80C + 80D + HRA exceeding 40% of salary; <strong>GST-ITR turnover mismatch</strong> for Deccan retailers; <strong>Transfer pricing</strong> for MIDC manufacturers with international transactions > Rs 1 crore.</p>
<p>Receiving a scrutiny notice does <strong>not mean wrongdoing</strong> - it is a verification process. CASS also makes random selections. The key is to respond thoroughly and on time.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for IT Notice Under Section 143(3) in Pune:</strong></p>
                    <p><strong>Section 143(2):</strong> Scrutiny notice. Must be issued within 3 months from end of FY of return filing. Notice beyond this is time-barred and invalid.</p>
<p><strong>Section 143(3):</strong> Final assessment order by AO after examining all evidence. Must be passed within 12 months from end of AY (Section 153).</p>
<p><strong>Section 144B:</strong> Faceless Assessment Scheme. All scrutiny via NFAC - digital, anonymous, DIN-tracked. Never meet AO in person.</p>
<p><strong>Section 144:</strong> Best Judgment Assessment if taxpayer fails to comply. Results in inflated income and high demand.</p>
<p><strong>Appeal Path:</strong> 143(3) order > CIT(A)/JC(A) Form 35 within 30 days > ITAT Pune Bench within 60 days > High Court > Supreme Court. DRP available for TP/non-resident draft orders.</p>

