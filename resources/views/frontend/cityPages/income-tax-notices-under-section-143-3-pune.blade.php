                    <p><strong>&#128204; TL;DR - IT Notice Under Section 143(3) in Pune Services at a Glance</strong></p>
                    <p>A scrutiny assessment under Section 143(3) of the Income Tax Act is a detailed examination of your income tax return by the Assessing Officer. The process begins when your return is selected for scrutiny (via CASS) and a notice is issued under Section 143(2). You must submit documents, explanations, and evidence through e-Proceedings on incometax.gov.in (faceless assessment under Section 144B). The AO passes a final assessment order under Section 143(3), which may accept your return, make additions, disallow deductions, or compute additional tax. If the order results in a demand, a notice under Section 156 is issued. You can appeal to CIT(A) via Form 35 within 30 days.</p>
                </div>
