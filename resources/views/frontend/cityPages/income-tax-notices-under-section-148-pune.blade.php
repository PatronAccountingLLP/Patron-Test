                <h2 class="section-title">Why Section 148 Notices Are Issued</h2>
                <div class="content-text what-is-definition">
                    
                    <p>The AO must have <strong>'information'</strong> (not mere suspicion or change of opinion) suggesting income has escaped assessment. If the AO is merely re-evaluating the same material from the original assessment, the notice may be challenged as a 'change of opinion' - which is not a valid ground for reassessment.</p>
<p>Common Pune triggers: <strong>Property sale not reported</strong> (SFT data from Sub-Registrar); <strong>Cash deposits flagged in SFT</strong> (Camp/Deccan traders); <strong>NRI rental income unreported</strong> (AIS data); <strong>ESOP/RSU income via FATCA/CRS</strong> (Hinjewadi employees); <strong>GST-ITR turnover mismatch</strong> (prior year discrepancies); <strong>ITR not filed for a year</strong> despite taxable income.</p>
<p>Time limits post Finance (No.2) Act 2024: <strong>3 years</strong> (escaped income < Rs 50 lakh) | <strong>5 years</strong> (>= Rs 50 lakh). The earlier 10-year extended limit for non-search cases has been reduced to 5 years.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for IT Notice Under Section 148 in Pune:</strong></p>
                    <p><strong>Section 147:</strong> Charging section authorising reassessment if income has escaped assessment.</p>
<p><strong>Section 148:</strong> Notice requiring taxpayer to file return for relevant AY. Valid only after mandatory 148A procedure.</p>
<p><strong>Section 148A (Finance Act 2021):</strong> Mandatory pre-notice: SCN with material > 7-30 days response > reasoned order 148A(d). Your best defence opportunity.</p>
<p><strong>Section 149:</strong> Time limits: 3 years (< Rs 50L) | 5 years (>= Rs 50L). Time-barred notice is invalid.</p>
<p><strong>Section 151:</strong> Prior approval from Joint Commissioner or PCIT/CIT required before notice issuance.</p>
<p><strong>Challenge Grounds:</strong> Time-barred, 148A not followed, change of opinion, material not shared, no sanction, information already available during original assessment.</p>

