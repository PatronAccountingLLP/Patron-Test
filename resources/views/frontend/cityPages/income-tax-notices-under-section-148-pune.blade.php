                    <p><strong>&#128204; TL;DR - IT Notice Under Section 148 in Pune Services at a Glance</strong></p>
                    <p>An income tax notice under Section 148 initiates reassessment proceedings for a prior assessment year where the AO has information suggesting income has escaped assessment. Since Finance Act 2021, the AO must mandatorily follow Section 148A: issue a Show Cause Notice (SCN) sharing all material, allow 7-30 days to respond, and pass a reasoned order under 148A(d). If the AO proceeds, the Section 148 notice is issued requiring a return within 30 days. The taxpayer's most powerful opportunity is at the 148A SCN stage - a strong response can result in the AO dropping proceedings before the 148 notice is even issued.</p>
                </div>
