                <p>Time limits post Finance (No.2) Act 2024: <strong>3 years</strong> for escaped income < Rs 50 lakh; <strong>5 years</strong> for >= Rs 50 lakh. Proceedings may be faceless (NFAC) or jurisdictional (Aayakar Bhavan, Shivaji Nagar). Writ petitions go to <strong>Bombay High Court</strong>. After resolution, taxpayers benefit from <a href="/income-tax-notice/pune">Income Tax Notice in Pune</a> and <a href="/accounting-services">Accounting Services</a>.</p>
