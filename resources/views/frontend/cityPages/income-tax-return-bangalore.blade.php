            <div class="column-content">
                <h2 class="section-title">What Is ITR Filing?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Income tax return filing is the annual disclosure of income earned, deductions claimed, and tax paid to the Income Tax Department under Section 139 of the IT Act, 1961. Due 31 July 2026 for AY 2026-27.</p>
<p>New regime (Section 115BAC) is default. Tax-free up to Rs 12.75 lakh for salaried. Old regime available if opted via Form 10-IEA before due date. Filing after due date locks into new regime.</p>
<p>For Bangalore: IT salaried (Form 16, ESOP/RSU, HRA), freelancers (44ADA, foreign income), startup founders (capital gains, angel tax), property sellers (Section 54/54EC), and FD holders claiming TDS refunds.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Income Tax Return:</strong></p>
                    <ul>
<li><strong>AIS:</strong> Annual Information Statement - what the IT Dept already knows about your income</li>
<li><strong>Section 115BAC:</strong> New tax regime (default). Lower rates, limited deductions</li>
<li><strong>Form 10-IEA:</strong> Opt-out form for choosing old regime (must file before due date)</li>
<li><strong>ITR-1:</strong> Salaried ≤ Rs 50L | <strong>ITR-2:</strong> Capital gains/foreign | <strong>ITR-3:</strong> Business | <strong>ITR-4:</strong> Presumptive</li>
<li><strong>Section 234F:</strong> Late filing penalty Rs 5,000 (Rs 1,000 if income ≤ Rs 5L)</li>
<li><strong>Schedule FA:</strong> Foreign asset reporting (US brokerage for ESOP/RSU)</li>
<li><strong>CPC Bangalore:</strong> Centralised Processing Centre - processes all e-filed returns</li>
<li><strong>e-Verification:</strong> Must be done within 30 days of filing (Aadhaar OTP, bank, Demat)</li>
</ul>

