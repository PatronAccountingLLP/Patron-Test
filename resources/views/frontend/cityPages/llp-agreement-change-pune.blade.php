<p><strong>Supplementary Agreement:</strong> On non-judicial stamp paper per Maharashtra Stamp Act. Signed by all partners. Witnessed by 2 persons.</p>
<p><strong>Form 4:</strong> Partner addition/removal/designation change. Filed alongside Form 3 within 30 days.</p>
<p><strong>Form 15:</strong> Registered office address change. Accompanied by Form 3.</p>
