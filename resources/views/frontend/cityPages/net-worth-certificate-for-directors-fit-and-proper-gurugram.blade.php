                <h2 class="section-title">What Is a Net Worth Certificate for Directors (Fit and Proper)?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A fit and proper net worth certificate for a director is a financial declaration signed by a practising Chartered Accountant in Gurugram certifying the personal net worth (assets minus liabilities) of an individual director, prepared in INR with the regulator-specific disclosures required under SEBI LODR Regulations 2015 (Schedule II Part D for BSE/NSE listed companies including Maruti Suzuki, Hero MotoCorp, Hyundai Motor India, Bharti Airtel, Zomato, PB Fintech, Medanta, Max Healthcare, Dr Lal PathLabs, IndiGo, Nestle India), RBI Master Direction Scale Based Regulation 2023 Annex XXIII (for NBFC and HFC directors - Sammaan Capital, PNB Housing Finance, BharatPe and other fintech NBFCs), IRDAI Corporate Governance Guidelines, and Companies Act 2013 Sections 149(6) and 184.</p>
<p>On the asset side the director-personal certificate consolidates - cash and bank balances, fixed deposits, mutual fund and demat holdings, equity shares (with substantial-interest flag), residential and commercial property at the HSVP collector rate for the Gurugram sector (with separate market valuation reference for premium DLF sectors), gold and jewellery, vehicles, ESOPs and RSUs (significant for Maruti Suzuki, Hero MotoCorp, Hyundai Motor India, Bharti Airtel, IndiGo executive directors), EPF and PPF balances, and other investments. On the liability side - personal loans, credit card outstandings, loans against property, vehicle loans, and statutory dues. Beyond the standard schedule, the fit-and-proper format requires disclosure of (i) relatives and their interests under Section 2(77) BRA and Companies Act 2013, (ii) substantial interest in companies, (iii) directorships and KMP positions in last 5 years, (iv) defaults to any bank or FI, (v) criminal proceedings, disciplinary actions, regulatory orders, (vi) sources of income for last 3-5 years, (vii) tax disputes pending, and (viii) for MNC subsidiary independent directors - foreign parent company connection and related-party transactions under SEBI LODR.</p>
<p>The certificate must carry an 18-digit UDIN generated at udin.icai.org, mandatory since 1 July 2019. Regulators (SEBI, RBI, IRDAI), stock exchanges (BSE, NSE; plus NASDAQ for entities like Genpact and historically MakeMyTrip), nomination and remuneration committees, and board secretaries verify the UDIN online as a standard step. Issued under ICAI SA 500 (Audit Evidence) and SA 505 (External Confirmations). For recently-listed Gurugram unicorns (Zomato, PB Fintech, Hyundai Motor India, Medanta), nomination committees are often first-time navigators of SEBI LODR Schedule II Part D and benefit from Patron's pre-audit checklist. Annual renewal is required at board re-appointment, AGM, or as the regulator schedules - typically each financial year.</p>

