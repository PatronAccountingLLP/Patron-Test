<p><strong>Fit and Proper:</strong> Regulatory test requiring directors of banks, NBFCs, HFCs, insurers, listed companies and SEBI-regulated intermediaries to demonstrate integrity, financial soundness, qualifications, and absence of disqualifying proceedings.</p>
