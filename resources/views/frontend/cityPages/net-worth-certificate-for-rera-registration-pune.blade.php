                <h2 class="section-title">What Is a Net Worth Certificate for RERA Registration</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>Definition:</strong> It is a certificate issued by a Chartered Accountant stating the promoter&#39;s total assets minus liabilities as on a stated date, drawn from audited financial statements, for submission with a state RERA project registration.</p>
<p>Under the <strong>Real Estate (Regulation and Development) Act, 2016</strong>, a promoter must register a project (in Maharashtra, with <strong>MahaRERA</strong>) before any marketing or sale. The application requires a statement of the promoter&#39;s assets and liabilities showing net worth, the promoter&#39;s audited financial statements for the last three years, and a CA declaration that no advance was taken before registration. Separately, the promoter must open a <strong>separate designated account where 70 percent of allottee receivables are deposited</strong>, under <strong>Section 4(2)(l)(D)</strong>, used only for construction and land cost.</p>
<p>The net worth certificate is one part of a financial-disclosure set that also includes the CA project-cost certificate (Form 3) and the annual audit (Form 5). It draws on the promoter&#39;s <a href="https://www.patronaccounting.com/statutory-audit">audited financial statements</a>, which is why it is regulator-grade rather than a routine certificate.</p>

