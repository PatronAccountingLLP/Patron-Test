                <h2 class="section-title">What Is a Net Worth Certificate for Students?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A net worth certificate for students is a financial statement signed by a practising Chartered Accountant in Gurugram certifying total assets minus total liabilities for the student and the sponsoring parent or guardian, prepared in dual currency for student visa or study permit applications under ICAI norms.</p>
<p>In Gurugram the asset schedule typically captures balances across savings, current, NRE, NRO and FCNR accounts, fixed deposits, vested ESOPs, vested RSU holdings (valued at the latest grant-date or fair market value), mutual fund and demat holdings, immovable property at the HSVP collector rate, vehicles, and gold. The liability schedule captures home loans, personal loans, education loans, and credit-card outstanding. Net worth appears in INR and the destination currency at the RBI reference rate on the certificate date.</p>
<p>The certificate must carry an 18-digit UDIN generated at udin.icai.org, mandatory since 1 July 2019. Embassy officers verify the UDIN online before accepting the document. Issue is governed by ICAI Standards on Auditing SA 500 (Audit Evidence) and SA 505 (External Confirmations) and read against the I-20 (USA), CAS (UK), PAL plus GIC receipt (Canada), CoE (Australia), or Zulassungsbescheid plus Sperrkonto (Germany). FEMA Liberalised Remittance Scheme limit of USD 250,000 per resident per financial year sets the context for sponsor remittance disclosures.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Net Worth Certificate for Students:</strong></p>
                    <p><strong>UDIN:</strong> 18-digit Unique Document Identification Number generated by the issuing CA at udin.icai.org for every certificate, mandatory since 1 July 2019.</p>
<p><strong>ESOP / RSU:</strong> Employee Stock Option Plan and Restricted Stock Unit. Vested portion qualifies as an asset on the parent's balance sheet and is included at fair market value with the latest brokerage statement (Fidelity, Charles Schwab, Etrade, Morgan Stanley) as evidence.</p>
<p><strong>NRE / NRO / FCNR:</strong> Non-Resident External, Non-Resident Ordinary and Foreign Currency Non-Resident accounts. Common where the sponsor is or was a non-resident; balances are included on the asset side with bank statements as evidence.</p>
<p><strong>HSVP Collector Rate:</strong> Minimum land value notified by the Haryana Shahari Vikas Pradhikaran for stamp-duty purposes, used as the defensible floor for Gurugram property valuation in the certificate.</p>
<p><strong>FEMA LRS:</strong> Liberalised Remittance Scheme under FEMA permits a resident to remit up to USD 250,000 per financial year. Relevant for sponsor remittances to a student abroad and noted in the certificate context where applicable.</p>

