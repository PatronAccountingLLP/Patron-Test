                    <p><strong>UDIN:</strong> 18-digit Unique Document Identification Number generated by the issuing CA at udin.icai.org for every certificate, mandatory since 1 July 2019 under ICAI.</p>
<p><strong>Sponsor:</strong> Parent, guardian or close relative who funds the student's education abroad and signs an affidavit of support submitted with the visa file.</p>
<p><strong>Dual Currency Format:</strong> Net worth shown side by side in INR and the destination currency (USD, CAD, GBP, AUD or EUR), converted at the RBI or FBIL reference rate on the certificate date.</p>
<p><strong>GIC:</strong> Guaranteed Investment Certificate of CAD 20,635 held with a Canadian designated financial institution, treated as a student asset on the certificate for Canada Study Permit cases.</p>
<p><strong>COP:</strong> Certificate of Practice issued by ICAI; only a CA holding a valid COP can generate UDIN and sign the net worth certificate.</p>

