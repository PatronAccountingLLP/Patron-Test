                <h2 class="section-title">What Is a Net Worth Certificate for Students?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A net worth certificate for students is a financial statement signed by a practising Chartered Accountant in Mumbai certifying total assets minus total liabilities for the student and the sponsoring parent or guardian, prepared in dual currency for student visa or study permit applications under ICAI norms.</p>
<p>On the asset side it captures bank balances across savings, current, NRE and NRO accounts, fixed deposits, mutual fund and demat holdings, immovable property valuations, vehicles, and gold. On the liability side it captures home loans, personal loans, education loans, and credit-card outstanding. Total assets minus total liabilities equals the certified net worth, presented in both Indian Rupees and the destination currency at the RBI reference rate on the certificate date.</p>
<p>The certificate must carry an 18-digit UDIN generated at udin.icai.org, mandatory since 1 July 2019. Visa officers and embassy staff verify the UDIN online before accepting the document. The certificate is governed by ICAI Standards on Auditing SA 500 (Audit Evidence) and SA 505 (External Confirmations) and is referenced against the I-20 (USA), CAS (UK), PAL plus GIC receipt (Canada), or CoE (Australia).</p>

                </div>
