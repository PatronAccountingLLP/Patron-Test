                <h2 class="section-title">What Is a Partnership Firm?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A partnership firm is a business organisation where two or more persons carry on business together, sharing profits and losses as defined in their deed, governed by the Indian Partnership Act 1932. Key: minimum 2 partners (max 50), NOT a separate legal entity, unlimited liability (personal assets at risk), mutual agency (each partner is agent and principal).</p>
                    <p>Registration is voluntary under Section 58 but practically essential. Section 69: unregistered firm cannot sue third parties, cannot file claims against partners, cannot claim set-off exceeding Rs 100. Lower compliance than company/LLP - no RoC filings, no board meetings, no auditor appointment (unless turnover threshold).</p>
                    <p>In Mumbai, registration is with RoF Maharashtra at Bandra East via Form A on <a href="https://rof.mahaonline.gov.in" target="_blank" rel="noopener">rof.mahaonline.gov.in</a>. Maharashtra requires certified Marathi translation, specific stamp duty, and Rs 5 court-fee stamp forwarding letter. Patron handles complete registration from <a href="/partnership-firm-registration">our national practice</a>.</p>

                </div>
