                    <p><strong>Key Terms for Partnership Registration:</strong></p>
                    <ul>
                        <li><strong>Section 69:</strong> Unregistered firm cannot sue third parties, file claims against partners, or claim set-off above Rs 100.</li>
                        <li><strong>Section 40(b):</strong> Partner remuneration and interest (up to 12% p.a.) deductible within limits. Tax-optimised deed clauses essential.</li>
                        <li><strong>Unlimited Liability:</strong> Partners jointly and severally liable. Personal assets at risk for business debts.</li>
                        <li><strong>Form A:</strong> Maharashtra-specific RoF registration application. Rs 1,600 filing fee. Bandra East office.</li>
                        <li><strong>Marathi Translation:</strong> Certified translation of deed mandatory for RoF Maharashtra. Many national portals miss this.</li>
                        <li><strong>Stamp Duty:</strong> Rs 500 (capital <=Rs 50,000) or 1% capped at Rs 15,000 (capital >Rs 50,000).</li>
