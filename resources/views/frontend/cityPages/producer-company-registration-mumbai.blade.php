                <div class="content-text what-is-definition">
                    
                    <p>A Producer Company is a body corporate formed exclusively by primary producers to advance their mutual interests through collective production, marketing, and processing. Introduced by Companies (Amendment) Act 2002 adding Part IXA (Sections 581A-581ZT) to Companies Act 1956, preserved under Section 465(1) of Companies Act 2013.</p>
                    <p>Key features: only primary producers can be members (farmers, fishermen, artisans, dairy/poultry producers). Democratic governance: one member one vote. Shares transferable only to members. Name format: 'XYZ Producer Company Limited'. Limited liability. Min 5 directors (all must be producer-members). Chief Executive appointed by Board. Board meetings min 4/year. AGM mandatory.</p>
                    <p>Objects must conform to S.581B: production, harvesting, procurement, grading, pooling, marketing, export, processing, manufacturing, education, insurance, credit/finance, welfare. Patron handles <a href="/producer-company-registration">producer company registration</a> with S.581B-compliant objects and FPO scheme enrolment from Marine Lines, Mumbai.</p>

