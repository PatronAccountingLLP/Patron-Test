                <h2 class="section-title">What Is a Public Limited Company?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A Public Limited Company is defined under Section 2(71) of the Companies Act 2013 as a company which is not a private company. It does not restrict share transfer, does not limit membership to 200, and can invite the public to subscribe to its securities. The name must end with 'Limited'. It is governed by the Companies Act 2013 and, if listed, by SEBI Act 1992 and SEBI (LODR) Regulations 2015.</p>
                    <p>A public company requires minimum 7 members (no upper limit) and minimum 3 directors. At least one director must be Indian resident. The minimum paid-up capital is Rs 5 lakh. A mandatory Company Secretary must be appointed under Section 203. A statutory auditor is mandatory under Section 139. At least 4 board meetings per year are required.</p>
