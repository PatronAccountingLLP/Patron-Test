            <div class="column-content">
                <h2 class="section-title">What Is 12A Registration?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>12A registration is the process of obtaining income tax exemption for a charitable or religious organisation by applying to the PCIT/CIT, enabling the NGO's income (donations, grants, fees, interest) to be exempt from income tax under Sections 11 and 12 of the Income Tax Act, provided at least 85% of income is applied for charitable purposes.</p>
<p>Without 12A, any income received by an NGO is treated as normal taxable income subject to 30% for trusts/societies or 25%/22% for Section 8. 12A changes the treatment: income applied for charitable/religious purposes is fully exempt, and up to 15% can be accumulated. The registration is filed on incometax.gov.in via Form 10A (provisional 3-year) or Form 10AB (regular 5/10-year or renewal).</p>
<p>For Hyderabad, 12A is the tax foundation for every NGO structure. The PCIT/CIT (Exemption) with jurisdiction over Hyderabad processes 12A applications for all Telangana-registered NGOs. The order includes a 16-digit URN used for all subsequent tax filings.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for 12A Registration:</strong></p>
                    <ul>
<li><strong>Form 10A:</strong> Provisional 12A application for new entities. 3-year validity</li>
<li><strong>Form 10AB:</strong> Regular/renewal application. 5-year (or 10-year for small trusts)</li>
<li><strong>85% Application Rule:</strong> At least 85% of income must be applied for charitable purposes</li>
<li><strong>URN:</strong> 16-digit Unique Registration Number issued with 12A order</li>
<li><strong>RNPO:</strong> Registered Non-Profit Organisation under IT Act 2025 Section 332</li>
<li><strong>Section 332:</strong> New IT Act 2025 provision replacing 12A/12AB from 01.04.2026</li>
<li><strong>PCIT/CIT (Exemption):</strong> Authority processing 12A applications</li>
<li><strong>ITR-7:</strong> Annual income tax return for 12A-registered NGOs, due 31 October</li>
</ul>

