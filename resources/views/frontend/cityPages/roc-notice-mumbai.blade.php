                        <li><strong>S.164(2):</strong> 3 years non-filing = director disqualified from ALL boards for 5 years. Cascading across active companies. File pending returns to resolve.</li>
                        <li><strong>Rs 100/Day:</strong> Late fee for AOC-4/MGT-7 with NO cap. 3 years = Rs 2 lakh+. Accumulates until filed. Leads to strike-off at 2+ years.</li>
