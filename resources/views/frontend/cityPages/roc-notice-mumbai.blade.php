                    <p><strong>Key Terms for ROC Notice Reply:</strong></p>
                    <ul>
                        <li><strong>STK-7 (S.248):</strong> Strike-off notice. 2+ years non-filing. 30 days to reply. Non-reply = company removed, bank frozen, assets inaccessible. Revival via NCLT S.252.</li>
