                <h2 class="section-title">What Is an ROC Notice?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>An ROC notice is a formal communication from the Registrar of Companies to a company, LLP, or director under the Companies Act, 2013 or LLP Act, 2008, flagging non-compliance and initiating penalty, adjudication, or strike-off proceedings.</p>
                    <p>Notices served electronically on MCA portal and physically to registered office. Must respond within specified timeline (typically 30 days). Non-response results in strike-off, penalties, or disqualification.</p>
                    <p>ROC Mumbai: <a href="https://www.mca.gov.in" target="_blank" rel="noopener">MCA portal</a>. Related: <a href="/private-limited-company-compliance">company compliance</a>, <a href="/director-kyc">director KYC</a>.</p>

