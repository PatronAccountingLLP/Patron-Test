<li><strong>Shop:</strong> Any premises where goods are sold or services rendered, including connected offices, godowns, and workplaces.</li>
<li><strong>Commercial Establishment:</strong> Premises where trade, business, or profession is carried on, including societies, trusts, and banking offices.</li>
<li><strong>Form A:</strong> Online registration form submitted on labourcis.nic.in within 90 days of commencing business.</li>
<li><strong>Chief Inspector:</strong> Chief Inspector of Shops & Establishments under Delhi Labour Department who oversees registration and compliance.</li>
