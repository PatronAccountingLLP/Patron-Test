                <h2 class="section-title">What Is Shop Act Registration: Delhi Shops & Establishments Act 1954</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Shop Act registration in Delhi is the mandatory process of registering a shop, commercial establishment, or place of business with the Delhi Labour Department under Section 5 of the Delhi Shops & Establishments Act, 1954, by submitting Form A within 90 days of commencing operations. The Act regulates working hours, wages, leave, holidays, terms of service, and conditions of work for persons employed in shops and commercial establishments across Delhi.</p>
<p>The Act defines a 'shop' as any premises where goods are sold (retail or wholesale) or services are rendered, including offices, store-rooms, godowns, warehouses, and workplaces connected with the business. A 'commercial establishment' includes any premises where trade, business, or profession is carried on. Factories registered under the Factories Act 1948 are excluded.</p>
<p>For Delhi businesses - whether a garment shop in Chandni Chowk, a CA firm in Connaught Place, a restaurant in Saket, or a tech startup in Nehru Place - the Shop Act registration certificate serves as the primary proof of legal business existence at the state level. It is required for opening bank current accounts, obtaining trade licences, <a href="/fssai-registration">FSSAI registration</a>, and is referenced during ESIC and EPFO inspections.</p>

