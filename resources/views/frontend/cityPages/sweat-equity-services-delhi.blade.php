                        <div class="faq-expanded__a"><p>Sweat equity shares are equity shares a company issues to its directors or employees at a discount, or for consideration other than cash, in return for know-how, intellectual property rights or value additions. They are defined in Section 2(88) and governed by Section 54 of the Companies Act 2013. Unlike ESOPs, the shares are issued now rather than as an option to buy later.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-2">
                        <h3 class="faq-expanded__q">What are the limits on issuing sweat equity?</h3>
                        <div class="faq-expanded__a"><p>In a financial year, a company can issue sweat equity up to 15% of its existing paid-up equity capital or shares worth Rs 5 crore, whichever is higher. The total sweat equity must not exceed 25% of paid-up capital at any time. DPIIT-recognised startups enjoy a relaxation and may issue up to 50% of paid-up capital within ten years of incorporation.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-3">
                        <h3 class="faq-expanded__q">How many years is the lock-in on sweat equity shares?</h3>
                        <div class="faq-expanded__a"><p>Sweat equity shares remain locked in for 3 years from the date of allotment, which means they are non-transferable during that period. The lock-in and its expiry date are stamped on the share certificate. This differs from an ESOP, where the lock-in depends on the scheme.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-4">
                        <h3 class="faq-expanded__q">Do I need to visit RoC Delhi to issue sweat equity?</h3>
                        <div class="faq-expanded__a"><p>No physical visit is needed. Companies with a registered office anywhere in the National Capital Territory file with the Registrar of Companies, Delhi entirely on the MCA portal. We e-file the MGT-14 for your special resolution and the PAS-3 return of allotment online, so a Nehru Place or Saket company can complete the whole sweat equity issue without leaving the office.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-5">
                        <h3 class="faq-expanded__q">Can a Connaught Place or Nehru Place company issue sweat equity to its team?</h3>
                        <div class="faq-expanded__a"><p>Yes. Any private or unlisted company registered with RoC Delhi, whether a finance house off Connaught Place or a tech firm in the Nehru Place market, can issue sweat equity to permanent employees of at least a year and to whole-time or non-executive directors. The fair price and the value of the know-how or IP are fixed by a registered valuer, the issue is approved by special resolution, and the shares carry the standard three-year lock-in stamped on the certificate.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-6">
                        <h3 class="faq-expanded__q">What is the difference between sweat equity and ESOP?</h3>
                        <div class="faq-expanded__a"><p>Sweat equity issues shares now, under Section 54, for know-how, IPR or value additions, with a registered-valuer price and a three-year lock-in, recorded in Form SH-3. ESOP grants an option under Section 62(1)(b) to buy shares later at an exercise price, recorded in Form SH-6. Sweat equity rewards contribution already made; ESOP incentivises future retention.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-7">
                        <h3 class="faq-expanded__q">Which register is maintained for sweat equity?</h3>
                        <div class="faq-expanded__a"><p>For sweat equity, the company maintains the Register of Sweat Equity Shares in Form SH-3 at its registered office, authenticated by the Company Secretary. This is separate from the SH-6 register used for ESOPs. It records the details of the allottee, the shares, the valuation and the lock-in.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-8">
