                <h2 class="section-title">What Are Sweat Equity Shares</h2>
                <div class="content-text what-is-definition">

                    <p>For a Nehru Place trading house or a Saket consumer-tech venture that wants to reward the people who built its brand, supply chain or product IP, sweat equity is the Section 54 route to put real shares in their hands now. These are equity shares a company registered with RoC Delhi issues to its directors or employees at a discount, or for consideration other than cash, in exchange for know-how, intellectual property rights or value additions. The instrument is defined in Section 2(88) and governed by Section 54.</p>
                    <p>The distinction that matters in practice: an ESOP only hands over an option to buy shares at some future date, whereas sweat equity transfers ownership today in recognition of contribution already made or being made. Because Section 54 is the single carve-out from the Section 53 prohibition on issuing shares at a discount, the MCA, whose head office sits in Delhi, keeps the route tightly fenced, a special resolution, a registered-valuer price, statutory caps, a lock-in and a dedicated register all have to line up.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Sweat Equity Services:</strong></p>
