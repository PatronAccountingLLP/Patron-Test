            <div class="column-content">
                <h2 class="section-title">What Is Trademark Formality Check Fail?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Formality check fail ('Formalities Chk Fail' on IP India portal) is a preliminary administrative screening status indicating the Trademark Registry found procedural, documentary, or classificatory deficiencies that must be corrected before substantive examination.</p>
                    <p>It is NOT rejection, NOT an objection under S.9/S.11. The examiner hasn't looked at the substance of your mark yet - just the paperwork. Think of it as a passport application returned because you forgot a photograph - not because your passport was denied.</p>
                    <p>Reply within 30 days via MIS-F. Trademark Registry Mumbai: <a href="https://ipindia.gov.in" target="_blank" rel="noopener">ipindia.gov.in</a>. Antop Hill, Wadala. Learn more at <a href="/trademark-formality-check-fail">our national formality fail practice</a>.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Trademark Formality Check Fail:</strong></p>
                    <ul>
                        <li><strong>NOT Rejection:</strong> Administrative deficiency. Correctable. File MIS-F reply with right documents = Formalities Chk Pass = proceeds to examination.</li>
                        <li><strong>30-Day Deadline:</strong> Strict. Non-reply = ABANDONED. Fees (Rs 4,500-9,000/class) and priority date permanently lost. Must re-file from scratch.</li>
                        <li><strong>MIS-F Reply:</strong> IP India portal > Miscellaneous Reply > Reply to Formality Check. No govt fee. Upload reply + corrected documents.</li>
                        <li><strong>Form TM-M:</strong> If class, description, or applicant details need correction. Rs 900 (individual/startup) / Rs 1,800 (others). Filed separately.</li>
                        <li><strong>12+ Deficiency Types:</strong> Wrong NICE class, missing POA, missing translation, logo mismatch, wrong description, underpaid fees, corrupted uploads, missing affidavit.</li>
                        <li><strong>Different from Objection:</strong> Formality = administrative (pre-exam). Objection = substantive S.9/S.11 (during exam). Different process entirely.</li>
                    </ul>

