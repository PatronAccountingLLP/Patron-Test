                <h2 class="section-title">What Is Trademark Formality Check Fail?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>When you file a trademark application (Form TM-A) on the IP India portal, it first undergoes the 'Formality Check' - administrative screening by the TM Registry Mumbai (for Pune). The Registry checks whether the application meets basic procedural and documentary requirements under the Trade Marks Rules 2017. If deficiencies are found, status updates to 'Formality Chk Fail' and a keep-pending notice is issued.</p>
                    <p>Common deficiencies: wrong NICE class, missing Form TM-48 (Power of Attorney), logo-name mismatch, wrong fee amount, missing translation/transliteration, incomplete goods/services description, corrupted uploads, and missing prior-use affidavit. A formality check fail is NOT a rejection - it is a procedural hiccup that can be corrected.</p>
                    <p>The 1-month response deadline is firm. Missing it means the application is abandoned - you lose the filing date, government fee, and any priority. Patron provides <a href="/trademark-formality-check-fail">formality check fail resolution</a> with full application audit and prosecution takeover for Pune businesses.</p>

                </div>
