                    <ul>
                        <li><strong>Formality Chk Fail:</strong> Administrative deficiency in TM application. NOT a rejection. Fixable within 1-month deadline.</li>
                        <li><strong>Keep-Pending Notice:</strong> TM Registry notice specifying the deficiency. Triggers 1-month response deadline.</li>
                        <li><strong>NICE Classification:</strong> 45 classes for goods (1-34) and services (35-45). Wrong class = most common failure reason.</li>
                        <li><strong>Form TM-48:</strong> Power of Attorney. Required when filing through agent. Missing = formality failure.</li>
                        <li><strong>Abandonment:</strong> If no response within 1 month, application abandoned. Filing date, fee, and priority permanently lost.</li>
