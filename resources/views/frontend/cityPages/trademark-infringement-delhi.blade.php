<li><strong>Ex Parte Injunction:</strong> Court order stopping infringement without hearing the defendant - Delhi HC grants these swiftly in genuine cases.</li>
<li><strong>Anton Piller Order:</strong> Court-supervised search and seizure of infringing goods at the infringer's premises.</li>
<li><strong>Section 103:</strong> Criminal penalty - 6 months to 3 years imprisonment + Rs 50,000-2,00,000 fine for falsifying trademarks.</li>
<li><strong>Passing Off:</strong> Common law remedy for unregistered marks based on goodwill, misrepresentation, and damage.</li>
