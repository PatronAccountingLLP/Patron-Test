                <h2 class="section-title">What Is Trademark Infringement: Section 29 of the Trade Marks Act 1999</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Trademark infringement occurs when a person, without authorisation from the registered proprietor, uses a mark identical or deceptively similar to a registered trademark in the course of trade, in a manner likely to cause consumer confusion. Section 29 of the Trade Marks Act, 1999 defines multiple forms: identical marks for identical goods (S.29(1)), similar marks causing confusion (S.29(2)), well-known marks for dissimilar goods (S.29(4)), trade name use (S.29(5)), labelling/packaging (S.29(7)-(8)), and spoken use (S.29(9)).</p>
<p>For Delhi businesses - whether an FMCG brand discovering counterfeit products in Chandni Chowk, a tech company finding its software brand misused in Nehru Place, a fashion label seeing knock-offs in Sarojini Nagar, or a D2C brand finding identical online listings - trademark infringement requires swift enforcement. The Delhi High Court grants ex parte injunctions, Anton Piller orders, and damages that serve as powerful deterrents.</p>
<p>The Delhi HC IP Division is India's most active trademark court, with landmark judgments including MakeMyTrip v. Booking.com on keyword trademark misuse and numerous FMCG enforcement actions that establish strong precedents for Delhi brand owners.</p>

