            <div class="column-content">
                <h2 class="section-title">What Is Trademark Infringement?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Trademark infringement is the unauthorised use - in the course of trade - of a mark identical or deceptively similar to a registered trademark, as defined under Section 29 of the Trade Marks Act 1999, which covers nine sub-sections of infringement.</p>
                    <p>Infringement (S.29) = statutory remedy for REGISTERED marks (lighter burden, civil + criminal). Passing off = common law remedy for UNREGISTERED marks (heavier burden, civil only). Both can be filed simultaneously at Bombay HC.</p>
                    <p>Bombay HC Original Side = DIRECT HC filing. Ex parte injunction within 48 hours. Anton Piller orders for surprise raids. Learn more at <a href="/trademark-infringement">our national infringement practice</a>.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Trademark Infringement:</strong></p>
                    <ul>
                        <li><strong>S.29 Nine Sub-sections:</strong> Identical mark, similar mark confusion, dilution/free-riding, trade name, labelling, advertising, spoken word, material application, domain names.</li>
                        <li><strong>Anton Piller Order:</strong> Court-appointed local commissioner for surprise search and seizure. Seizes goods, accounts, evidence before infringer can destroy.</li>
                        <li><strong>Bombay HC Original Side:</strong> 1 of only 4 HCs with direct filing. Experienced IP judges. Ex parte injunction 48 hours. Sophisticated enforcement orders.</li>
                        <li><strong>S.103 Criminal:</strong> 6 months-3 years + Rs 50K-2L. Cognizable. FIR via DSP/ACP (S.115(4)). Runs simultaneously with civil.</li>
                        <li><strong>Passing Off:</strong> For unregistered marks. Prove goodwill + misrepresentation + damage. Civil only. Bombay HC grants injunctions with strong goodwill evidence.</li>
                        <li><strong>Customs Recordal:</strong> Record at JNPT/Air Cargo. Officials seize counterfeit imports without court order. Border protection.</li>
