            <h2 class="section-title">Legal and Compliance Framework for Trademark Infringement</h2>
            <div class="content-text">
                
                <p><strong>Governing Act:</strong> Trade Marks Act, 1999 - Sections 27-30 (infringement and passing off), Sections 103-105 (criminal penalties), Sections 134-135 (jurisdiction and remedies).</p>
<p><strong>Section 29:</strong> Defines trademark infringement including identical marks, deceptively similar marks, use as trade name, and advertising misuse. Section 29(4) extends protection to well-known marks against dissimilar goods.</p>
<p><strong>Section 103:</strong> Criminal penalty for applying false trademarks - imprisonment of 6 months to 3 years, fine of Rs 50,000 to Rs 2,00,000.</p>
<p><strong>Section 104:</strong> Penalty for selling goods with false marks - same imprisonment and fine range as Section 103.</p>
<p><strong>Section 105:</strong> Enhanced penalty for repeat offenders - imprisonment of 1 to 3 years, fine of Rs 1,00,000 to Rs 2,00,000.</p>
<p><strong>Section 134:</strong> Jurisdiction for infringement suits - District Court or High Court where plaintiff carries on business. For Pune, this means Pune District Court or Bombay High Court.</p>
<p><strong>Section 135:</strong> Civil remedies including injunctions, damages, and account of profits.</p>
<p><strong>Regulatory Authority:</strong> Controller General of Patents, Designs and Trade Marks (CGPDTM) under the Ministry of Commerce and Industry. Trademark Registry, Mumbai handles Maharashtra. Portal: <a href="https://ipindia.gov.in" target="_blank" rel="noopener">IP India - ipindia.gov.in</a></p>
<p><strong>Recent Development:</strong> The Jan Vishwas (Amendment of Provisions) Act, 2023 decriminalised Section 107 (false representation of registration), converting it to a civil penalty of 0.5% of turnover or Rs 5,00,000, whichever is less. Criminal penalties under Sections 103-105 remain unchanged.</p>
<p><strong>Maharashtra-Specific:</strong> The Bombay High Court has active IP benches handling trademark infringement matters. Recent rulings in 2025 have clarified jurisdiction under Section 134(2), holding that the place of purchase - not the customer's residence - determines territorial jurisdiction.</p>

