<!-- SECTION 15A: LEGAL FRAMEWORK -->
<section class="content-section">
    <div class="content-container">
        <div class="text-content">
            <h2 class="section-title">Legal Framework for Trademark Notice Reply</h2>
            <div class="content-text">
                
                <p><strong>Infringement and Passing Off:</strong></p>
                <ul><li><strong>Section 29:</strong> Infringement of registered TM - identical or deceptively similar mark for same/similar goods without consent.</li>
                    <li><strong>Passing Off (Common Law):</strong> Protects unregistered marks; requires proof of goodwill, misrepresentation, and damage.</li>
                    <li><strong>Section 30:</strong> Defences - honest practices, descriptive use, prior use, bona fide use of own name, geographical name.</li></ul>
                <p style="margin-top:16px;"><strong>Defences Available:</strong></p>
                <ul><li><strong>Prior Use:</strong> Recipient used mark before sender's registration - superior rights.</li>
                    <li><strong>Honest Concurrent Use:</strong> Both using similar marks simultaneously in good faith.</li>
                    <li><strong>Descriptive Fair Use (S30(2)(a)):</strong> Mark describes characteristics of goods/services.</li>
                    <li><strong>TM Invalidity:</strong> Sender's mark descriptive, generic, or obtained in bad faith.</li>
