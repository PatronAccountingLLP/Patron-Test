                <h2 class="section-title">What is Trademark Rectification</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Trademark rectification is the statutory process under Section 57 of the Trade Marks Act, 1999 for correcting, varying, or cancelling any entry in the Trademark Register that is wrongly made, wrongly remaining, or made without sufficient cause. The procedure is governed by Rules 97 to 100 of the Trade Marks Rules, 2017, and applications are filed using Form TM-O before the Trade Marks Registry or the relevant High Court.</p>
<p>Rectification serves two distinct purposes. First, it allows trademark proprietors to correct their own registration errors - wrong address, incorrect class, clerical mistakes in the mark's description - using Form TM-16 under Section 58. Second, and more critically for brand protection, it enables any aggrieved person to challenge a registered mark under Section 57 on grounds including non-use for 5 years and 3 months (Section 47), fraudulent registration, similarity with an earlier mark, or violation of conditions entered in the Register.</p>
<p>For Pune's business ecosystem - where IT startups in Hinjewadi frequently discover that a squatter has registered a confusingly similar SaaS brand name, and MIDC Bhosari manufacturers find dormant marks blocking their product line registrations - rectification is often the only viable path to clearing the Register. The application must be filed at the Trade Marks Registry, Mumbai, which administers all trademark matters for Pune and Maharashtra under the CGPDTM.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Trademark Rectification in Pune:</strong></p>
                    <p><strong>Section 57 Rectification:</strong> Power to cancel or vary any entry wrongly made or wrongly remaining on the Register.</p>
<p><strong>Section 47 Non-Use:</strong> Removal of a trademark not used for a continuous period of 5 years and 3 months.</p>
<p><strong>Section 58 Correction:</strong> Proprietor-initiated correction of clerical errors, address changes, or description mistakes.</p>
<p><strong>Form TM-O:</strong> Application form for aggrieved party rectification or cancellation filed via ipindia.gov.in.</p>
<p><strong>CGPDTM:</strong> Controller General of Patents, Designs and Trade Marks - national authority administering the Trade Marks Act.</p>

