                <h2 class="section-title">What Is Trademark Registration?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Trademark registration legally protects a brand name, logo, slogan, or any distinctive mark under the Trade Marks Act, 1999. The registered owner gets exclusive rights across India for 10 years (renewable) and legal recourse against infringers.</p>
<p>Filed via TM-A on IP India portal. 45 Nice Classification classes (1-34 goods, 35-45 services). Fee per class. TM symbol (™) from Day 1 of filing. R symbol (®) after full registration (12-18 months).</p>
<p>For Kolkata: sweet shop brands (Class 30), IT/SaaS (Class 9/42), D2C apparel (Class 25), restaurants (Class 43), manufacturers, and wholesale distribution brands all need class-specific protection.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Trademark Registration:</strong></p>
                    <ul>
<li><strong>Trade Marks Act, 1999:</strong> Governing law for trademark protection in India</li>
<li><strong>Nice Classification:</strong> 45 classes - goods (1-34) and services (35-45)</li>
<li><strong>TM-A:</strong> Application form filed on IP India e-filing portal</li>
<li><strong>TM (™):</strong> Usable from Day 1 of filing (application pending)</li>
