            <div class="column-content">
                <h2 class="section-title">What Is Trademark Registration</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Trademark registration is the process of legally protecting a distinctive mark - a brand name, logo, slogan, symbol, colour combination, sound, or shape - that identifies and distinguishes the goods or services of one business from another. Registration is granted under the Trade Marks Act 1999 by the Trade Marks Registry through the Controller General of Patents, Designs & Trade Marks (CGPDTM).</p>
                    <p>A registered trademark gives the owner exclusive rights to use the mark in connection with the registered goods or services, the right to use the R symbol (as opposed to the TM symbol for unregistered marks), the legal standing to file infringement suits and claim damages, and the ability to license, franchise, or sell the trademark as a business asset. India follows the NICE Classification system with 45 classes - Classes 1-34 cover goods and Classes 35-45 cover services. Each class requires a separate application and fee payment.</p>
                    <p>For Mumbai's brand-driven economy, trademark registration is a business necessity. A BKC fintech startup without a registered brand name risks losing it to a competitor filing first. A Bollywood production house at Andheri without registered entertainment marks faces dilution and counterfeiting. A D2C brand shipping nationally from Mumbai without trademark protection can be copied in any market. Mumbai exporters at JNPT need registered trademarks for international brand protection via the Madrid Protocol. CA-managed trademark registration ensures the correct NICE class is selected, a thorough search is conducted, and the application is structured for first-time acceptance by the Trade Marks Registry Mumbai examiner.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Trademark Registration in Mumbai:</strong></p>
                    <p><strong>NICE Classification:</strong> International system with 45 classes (1-34 goods, 35-45 services) used to categorise goods and services for trademark registration. Fees are per class.</p>
                    <p><strong>Form TM-A:</strong> Application form for trademark registration filed online via ipindiaonline.gov.in with applicant details, mark representation, and class description.</p>
                    <p><strong>CGPDTM:</strong> Controller General of Patents, Designs & Trade Marks - the authority overseeing trademark registration in India, headquartered at Antop Hill, Mumbai.</p>
                    <p><strong>Madrid Protocol:</strong> International treaty for filing trademark protection in multiple countries through a single application using Indian registration as base.</p>
                    <p><strong>Opposition Period:</strong> 4-month window after Journal publication during which any person can file a notice of opposition against the trademark application.</p>

