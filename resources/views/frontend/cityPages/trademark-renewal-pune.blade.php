                <h2 class="section-title">What is Trademark Renewal</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Trademark renewal is the process of extending a registered trademark's protection for an additional 10 years under Section 25 of the Trade Marks Act, 1999, by filing Form TM-R and paying the prescribed government fee. The application is filed electronically via ipindiaonline.gov.in and processed by the Trade Marks Registry.</p>
<p>A registered trademark in India is valid for 10 years from the date of filing the original application - not from the date of registration or acceptance. The Registrar sends a reminder notice (Form O-3) 6 months before expiry, but the legal responsibility to track and renew lies entirely with the trademark proprietor. Renewal can be filed up to 1 year before the expiry date. If the deadline is missed, a 6-month grace period is available with a surcharge of Rs 4,500 per class. Beyond the grace period, the mark is removed from the Register, and restoration must be applied for within 1 year from expiry at significantly higher cost.</p>
<p>For Pune's business landscape - where IT companies in Hinjewadi hold trademarks across multiple Nice Classification classes (Class 9 for software, Class 42 for IT services, Class 35 for advertising) and MIDC Bhosari manufacturers maintain product marks in goods classes - renewal is a recurring compliance obligation. A single missed deadline can result in loss of brand rights built over a decade.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Trademark Renewal in Pune:</strong></p>
                    <p><strong>Section 25:</strong> Trade Marks Act provision governing duration and renewal of trademark registration - 10-year validity, renewable indefinitely.</p>
<p><strong>Form TM-R:</strong> Prescribed renewal application form filed electronically via ipindiaonline.gov.in.</p>
<p><strong>Rule 57:</strong> Trade Marks Rules 2017 provision prescribing the renewal procedure, timelines, and fee structure.</p>
<p><strong>Grace Period:</strong> 6-month window after expiry during which renewal can still be filed with an additional surcharge of Rs 4,500 per class.</p>
<p><strong>Restoration:</strong> Process to reinstate a removed trademark within 1 year of expiry, requiring Form TM-R plus restoration fee and affidavit (Form TM-18).</p>

