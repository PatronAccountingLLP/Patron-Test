                <div class="content-text what-is-definition">
                    
                    <p>An ageing of debtors and creditors certificate is a Chartered Accountant's certified schedule that classifies a business's trade receivables, the debtors, and trade payables, the creditors, into age buckets based on how long each amount has been outstanding. It shows, at a glance, how much is current and how much is overdue, and for how long.</p>
                    <p>Debtors are amounts customers owe the business, a current asset; creditors are amounts the business owes suppliers, a current liability. The ageing breaks each into bands, such as current, up to 30 days, 31 to 60, 61 to 90, and beyond 90 days or more than six months. The age profile signals collection quality, bad-debt risk, and payment discipline, which is exactly what a lender or an acquirer needs to judge the strength of the working capital.</p>

                </div>
