                    <p><strong>Key Terms for Ageing of Debtors and Creditors Certificate:</strong></p>
                    <ul>
                        <li><strong>Ageing schedule:</strong> outstanding amounts grouped by how long they are overdue.</li>
                        <li><strong>Debtors:</strong> trade receivables, money customers owe the business.</li>
                        <li><strong>Creditors:</strong> trade payables, money the business owes suppliers.</li>
                        <li><strong>Schedule III:</strong> the Companies Act format requiring ageing disclosure.</li>
