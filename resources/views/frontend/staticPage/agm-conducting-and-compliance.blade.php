                    <div class="faq-expanded__item" id="faq-1">
                        <h3 class="faq-expanded__q">What is an annual general meeting under Section 96?</h3>
                        <div class="faq-expanded__a"><p>An annual general meeting under Section 96 of the Companies Act, 2013 is the yearly meeting of a company’s members, at which ordinary business such as adopting the financial statements, declaring dividend and appointing directors and auditors is transacted. Every company other than a One Person Company must hold an AGM each year and specify it as such in the notice.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-2">
                        <h3 class="faq-expanded__q">When must the first AGM be held?</h3>
                        <div class="faq-expanded__a"><p>The first annual general meeting must be held within 9 months from the close of the company’s first financial year. If the first AGM is held within this period, the company does not need to hold an AGM in the year of its incorporation. Unlike subsequent AGMs, the first AGM cannot be extended by the Registrar, so planning the audited accounts in time is important.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-3">
                        <h3 class="faq-expanded__q">When must subsequent AGMs be held?</h3>
                        <div class="faq-expanded__a"><p>A subsequent annual general meeting must be held within 6 months from the close of the financial year, and not more than 15 months may elapse between one AGM and the next. The earlier of these two limits governs the due date in a given year, so both the 6-month and the 15-month rules must be checked when fixing the AGM date.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-4">
                        <h3 class="faq-expanded__q">How much notice is required for an AGM?</h3>
                        <div class="faq-expanded__a"><p>A clear 21 days’ notice must be given to all members, directors and the auditors before the AGM, along with the agenda and the explanatory statement for any special business. A shorter notice can be given if the requisite proportion of members entitled to vote consent to it. The notice must specify that the meeting is the annual general meeting.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-5">
                        <h3 class="faq-expanded__q">Can the AGM date be extended?</h3>
                        <div class="faq-expanded__a"><p>Yes, for a subsequent AGM. The Registrar of Companies may, for a special reason, extend the time within which a subsequent AGM is held by a period not exceeding 3 months, on an application in Form GNL-1 stating the reasons. No extension is available for the first AGM, so the first AGM must be held strictly within its 9-month window.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-6">
                        <h3 class="faq-expanded__q">What happens if a company misses its AGM?</h3>
                        <div class="faq-expanded__a"><p>Missing the AGM is a default under the Companies Act and attracts penalties on the company and its officers in default, with a further daily penalty for a continuing default. Where the audited accounts are delayed, a subsequent AGM can be extended through a GNL-1 application before the due date, which is the right step rather than simply missing the meeting.</p></div>
