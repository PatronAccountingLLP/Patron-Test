                <div class="content-text what-is-definition">
                    
                    <p>An annual general meeting under Section 96 is the yearly meeting of a company’s members, at which the ordinary business of the company, such as adopting the financial statements, declaring dividend, and appointing directors and auditors, is transacted. Every company except an OPC must hold one each year.</p><p>It is a core annual compliance, with fixed timelines, a 21-day notice and prescribed conduct. Holding it on time and recording it correctly keeps the company compliant, while missing it brings penalties on the company and its officers.</p>

