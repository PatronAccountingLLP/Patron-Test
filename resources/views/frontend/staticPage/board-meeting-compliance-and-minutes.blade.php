            <div class="column-content">
                <h2 class="section-title">What Is Board Meeting Compliance?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Board meeting compliance is holding the meetings of a company’s board of directors in the manner Section 173 and Secretarial Standard SS-1 require, with proper notice, quorum, conduct and minutes. It is how the board’s decisions are validly taken and recorded.</p><p>Every company must hold a minimum number of board meetings each year and record them correctly. Missing the frequency, giving short notice or keeping defective minutes can invalidate decisions and attract penalties, which is why ongoing board meeting compliance matters.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Board Meeting Compliance:</strong></p>
                    <ul><li><strong>120-Day Rule:</strong> The maximum gap allowed between two consecutive board meetings.</li><li><strong>Quorum:</strong> The minimum directors needed for a valid meeting, one-third or 2, whichever is higher.</li><li><strong>SS-1:</strong> The ICSI Secretarial Standard governing the conduct and minutes of board meetings.</li><li><strong>Minutes:</strong> The official record of the proceedings and decisions, recorded within the prescribed time.</li><li><strong>Action Tracking:</strong> Following up the decisions taken so they are implemented before the next meeting.</li></ul>

