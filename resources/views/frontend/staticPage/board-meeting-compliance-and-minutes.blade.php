                        <h3 class="faq-expanded__q">How much notice is required for a board meeting?</h3>
                        <div class="faq-expanded__a"><p>At least 7 days’ written notice of a board meeting must be given to every director at their registered address, by hand, post or electronic means. A board meeting can be held at shorter notice to transact urgent business, provided at least one independent director, if any, is present; if none is present, the decisions are final only on ratification by an independent director.</p></div>
