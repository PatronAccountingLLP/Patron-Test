                        <h3 class="faq-expanded__q">How many board meetings must a company hold in a year?</h3>
                        <div class="faq-expanded__a"><p>Under Section 173 of the Companies Act, 2013, every company must hold a minimum of 4 board meetings each year, and the gap between two consecutive meetings must not be more than 120 days. The first board meeting must be held within 30 days of incorporation. An OPC, small company or dormant company has a relaxed requirement of one meeting in each half of the calendar year.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-2">
                        <h3 class="faq-expanded__q">What is the 120-day gap rule for board meetings?</h3>
                        <div class="faq-expanded__a"><p>The 120-day rule means that not more than 120 days may elapse between two consecutive board meetings. Even if a company holds four meetings in a year, it must also ensure no two of them are more than 120 days apart, which in practice means roughly one meeting each quarter. Breaching this gap is a non-compliance under Section 173.</p></div>
                    </div>
