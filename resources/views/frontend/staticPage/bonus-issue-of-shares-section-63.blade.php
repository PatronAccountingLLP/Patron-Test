                    <div class="faq-expanded__item" id="faq-6">
                        <h3 class="faq-expanded__q">Can a bonus issue exceed the authorised capital?</h3>
                        <div class="faq-expanded__a"><p>No. The authorised capital must be sufficient to cover the bonus shares. If it is not, the company must first increase its authorised capital by altering the capital clause of the Memorandum and filing Form SH-7. Only then can the bonus shares be allotted, so this step is planned at the start of the process.</p></div>
                    </div>
