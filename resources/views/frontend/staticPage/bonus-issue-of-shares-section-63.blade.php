                <h2 class="section-title">What Is a Bonus Issue of Shares?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A bonus issue under Section 63 is the allotment of additional fully paid-up shares to existing members, free of cost, by capitalising the company’s reserves. Members receive shares in proportion to their existing holding.</p><p>It converts accumulated reserves into share capital. Because no money changes hands and every member receives shares pro rata, a bonus issue rewards shareholders and signals financial strength without diluting their proportionate stake or draining the company’s cash.</p>

                </div>
