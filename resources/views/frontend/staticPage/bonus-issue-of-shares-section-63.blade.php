                        <h3 class="faq-expanded__q">What is a bonus issue of shares under Section 63?</h3>
                        <div class="faq-expanded__a"><p>A bonus issue under Section 63 of the Companies Act, 2013 is the allotment of additional fully paid-up shares to existing members at no cost, by capitalising the company’s free reserves, securities premium account or capital redemption reserve account. Members receive shares in proportion to their existing holding, with no cash outflow for the company.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-2">
                        <h3 class="faq-expanded__q">Which reserves can fund a bonus issue?</h3>
                        <div class="faq-expanded__a"><p>A bonus issue can be funded only from free reserves, the securities premium account or the capital redemption reserve account. Reserves created by the revaluation of assets cannot be used, because they represent unrealised gains. A bonus issue also cannot be made in lieu of a dividend payment.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-3">
                        <h3 class="faq-expanded__q">What are the conditions for a bonus issue?</h3>
                        <div class="faq-expanded__a"><p>Under Section 63(2), the Articles must authorise the bonus issue, the Board must recommend it and members must authorise it in general meeting. The company must not be in default on deposits or debt securities, or on employee statutory dues such as provident fund, gratuity and bonus, and any partly paid-up shares must first be made fully paid-up.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-4">
                        <h3 class="faq-expanded__q">Does a bonus issue dilute existing shareholders?</h3>
                        <div class="faq-expanded__a"><p>No. Because bonus shares are allotted to existing members in proportion to their current holding, each member’s percentage stake stays the same. A bonus issue increases the number of shares and capitalises reserves, but it does not bring in new shareholders or change the proportionate ownership of existing members.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-5">
                        <h3 class="faq-expanded__q">What forms are filed for a bonus issue?</h3>
