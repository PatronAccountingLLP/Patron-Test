        <div class="two-column">
            <div class="column-content">
                <h2 class="section-title">What Is a Branch Office?</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>A branch office is an extension of a foreign company that is permitted by the RBI to carry on specified activities in India under the parent's name, rather than as a separate Indian company.</strong> It is governed by FEMA and registered with the Registrar of Companies as a foreign company's place of business.</p>
                    <p>A branch can earn income from its permitted activities, but it can only carry out activities <strong>similar to those of the parent</strong> and within the RBI-approved list. It cannot undertake manufacturing or processing in India directly, and it cannot do retail trading.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Branch Office Setup:</strong></p>
                    <ul>
                        <li><strong>Form FNC:</strong> the application to the AD bank and RBI to set up a branch or liaison office.</li>
                        <li><strong>AD Category-I bank:</strong> the authorised bank that channels the application to RBI.</li>
                        <li><strong>UIN:</strong> the Unique Identification Number the RBI allots to each branch office.</li>
                        <li><strong>Form FC-1:</strong> the ROC registration for a foreign company's place of business.</li>
                    </ul>

                </div>
