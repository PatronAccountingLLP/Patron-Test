                <div class="content-text what-is-definition">
                    
                    <p>A capital account certificate is a Chartered Accountant's certification of a capital-account transaction under the Foreign Exchange Management Act, most commonly an External Commercial Borrowing or a foreign-currency loan. The best-known form is the certification of the monthly Form ECB-2 return, in which the CA scrutinises the original documents and certifies that the reported ECB transactions are correct, complete, and in order per RBI guidelines.</p>
                    <p>Capital-account transactions, those that alter assets or liabilities outside India, such as ECB drawdowns, foreign-currency loans, and inbound or outbound investment, are regulated by FEMA and the RBI's master directions, notably the ECB Master Direction. Because money and obligations cross the border, the RBI requires accurate, certified reporting. The CA certification gives the AD bank and the RBI assurance that the transaction and its reporting comply with the framework.</p>

