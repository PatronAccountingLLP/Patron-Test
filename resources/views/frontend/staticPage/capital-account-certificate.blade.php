<!-- SECTION 15A: LEGAL FRAMEWORK -->
<section class="content-section">
    <div class="content-container">
        <div class="text-content">
            <h2 class="section-title">Why ECB Reporting Is Strictly Time-Bound</h2>
            <div class="content-text">
                
                <p>An External Commercial Borrowing is a privilege under FEMA, available on terms the RBI sets: an eligible borrower, a recognised non-resident lender, the automatic or approval route, and norms on minimum average maturity, all-in-cost, and end-use, for instance, ECB proceeds generally cannot fund working capital or repay rupee loans except in defined cases. Before any drawdown, the borrower obtains a Loan Registration Number from the RBI, and from then on every month's actual transactions are reported in Form ECB-2, certified by a CA or CS, and routed through the AD Category-I bank to the RBI's DSIM within seven working days of month-end.</p>
                <p>The reporting is strict because the RBI monitors the country's external debt through it. A late or missing ECB-2, or an unreported change in terms, is a FEMA contravention, which can be regularised through a late-submission fee, INR 5,000, or INR 50,000 or INR 100,000 per year depending on the delay, but only if caught and addressed. This is why a CA-certified, on-time ECB-2 matters, and why borrowers raising foreign funds, often as part of an FDI or company-funding exercise, keep the certification on a disciplined monthly cycle.</p>
                <p>For the governing framework, refer to the <a href="https://www.rbi.org.in" target="_blank" rel="noopener">Reserve Bank of India (rbi.org.in)</a> ECB Master Direction and the FEMA Borrowing and Lending Regulations. The CA certifies the Form ECB-2 and capital-account compliance after scrutinising the original documents; the LRN is allotted by the RBI, and reporting flows through the AD Category-I bank to the RBI's DSIM. The CA does not raise the borrowing or grant approvals.</p>

