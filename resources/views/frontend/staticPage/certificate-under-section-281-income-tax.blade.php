                        <li><strong>NOC / prior permission:</strong> the Assessing Officer's clearance for the transfer.</li>
                        <li><strong>Form 34A:</strong> the application form under Rule 111A.</li>
                        <li><strong>Assessing Officer (AO):</strong> the income tax authority that grants permission.</li>
                        <li><strong>TRO:</strong> the Tax Recovery Officer, who recovers tax dues.</li>
