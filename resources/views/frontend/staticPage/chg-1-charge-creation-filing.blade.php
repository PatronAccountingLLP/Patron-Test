                <h2 class="section-title">What Is Charge Registration?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>A charge is an interest or lien created on a company’s property or assets as security, including a mortgage. Charge registration is the filing of that charge with the ROC in Form CHG-1, so it appears on the public record and is recognised in law.</p><p>It is a duty of the company under Section 77, usually arising when a company borrows against its assets. Registering the charge on time protects the lender’s security and keeps the company compliant, while a failure to register leaves the charge unrecognised against creditors.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
