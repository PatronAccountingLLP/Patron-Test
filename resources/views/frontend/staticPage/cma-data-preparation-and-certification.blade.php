            <h2 class="section-title">How MPBF and the CMA Story Fit Together</h2>
            <div class="content-text">
                
                <p>The technical heart of a CMA report is the Maximum Permissible Bank Finance. MPBF is the ceiling the bank can lend for working capital, computed from the borrower's current assets and liabilities. For larger borrowers, banks typically use the Tandon Committee Second Method, under which the borrower funds a quarter of the working-capital gap from its own resources; for smaller enterprises with limits up to INR 7.5 crore, the Nayak Committee Turnover Method, broadly 20 percent of projected turnover, is common. Although the RBI withdrew mandatory MPBF norms in 1997, banks continue to use these methods.</p>
                <p>Around MPBF sits the rest of the story: the operating statement and projected balance sheets, the fund flow showing how borrowed money will be used, and the ratio analysis, current ratio, often expected at 1.25 or above, debt-equity, and DSCR, that signals financial health. The projections must be realistic and consistent with the historical financial statements, because a banker will test them. A CA-led CMA report ties all of this into a coherent, defensible proposal.</p>
                <p>For the framework on working-capital finance and the Tandon and Nayak committee methods, refer to the <a href="https://www.rbi.org.in" target="_blank" rel="noopener">Reserve Bank of India (rbi.org.in)</a>. CMA data can be generated cheaply by software, but a CA-led, IBA-format report with defensible assumptions, a correct MPBF computation, and a coherent ratio analysis is what banks expect for larger exposures; the requirement itself is set by the bank's credit policy and the size of the facility, not universally mandatory for every loan.</p>

