            <div class="column-content">
                <h2 class="section-title">What Is CMA Data?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>CMA stands for Credit Monitoring Arrangement. CMA data is a standardised financial package, in the format set by the Indian Banks' Association, that presents a borrower's past and projected financial performance for a bank's credit appraisal of a loan, most often a working capital facility or term loan.</p>
                    <p>It is far more than a set of projections. A CMA report combines historical and forecast financials with a working-capital assessment, the Maximum Permissible Bank Finance, a fund flow statement, and detailed ratio analysis, so the bank can judge the borrower's capacity, the amount it can prudently lend, and the use of funds. For larger exposures, commonly above INR 2 crore, banks expect a properly prepared, CA-led CMA report rather than a quick software output.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for CMA Data Preparation and Certification:</strong></p>
                    <ul>
                        <li><strong>CMA:</strong> Credit Monitoring Arrangement, the bank's credit appraisal data package.</li>
                        <li><strong>MPBF:</strong> Maximum Permissible Bank Finance, the ceiling the bank can lend for working capital.</li>
                        <li><strong>IBA format:</strong> the Indian Banks' Association's standard CMA layout.</li>
                        <li><strong>Tandon / Nayak method:</strong> the methods used to compute MPBF.</li>
