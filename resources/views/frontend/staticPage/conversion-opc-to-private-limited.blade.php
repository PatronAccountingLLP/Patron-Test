            <h2 class="section-title">When Should an OPC Convert to a Private Company?</h2>
            <div class="content-text">
                
                <p>Since the 2021 amendment, conversion is voluntary at any time, and a founder converts when the business is ready to grow beyond a single owner.</p><ul><li><strong>Bringing in co-founders:</strong> Adding one or more shareholders, which an OPC cannot have.</li><li><strong>Raising equity:</strong> Taking investment from angels or VCs, which needs a multi-member company.</li><li><strong>Issuing ESOPs:</strong> Granting stock options to employees, which an OPC cannot do.</li><li><strong>Scaling and credibility:</strong> A private company structure suits larger operations and partners.</li><li><strong>No size trigger now:</strong> The former compulsory conversion on crossing 50 lakh capital or 2 crore turnover was removed in 2021, so conversion is a choice, not a compulsion.</li></ul><h3>What Changed in 2021</h3><p>The Companies (Incorporation) Second Amendment Rules, 2021, effective 1 April 2021, simplified OPC conversion in three ways that are widely misreported online.</p><ul><li><strong>No more compulsory conversion on size:</strong> The earlier rule that an OPC had to convert on crossing 50 lakh paid-up capital or 2 crore average turnover was deleted, so an OPC can stay an OPC at any size.</li><li><strong>No two-year wait:</strong> The earlier requirement to wait two years from incorporation before a voluntary conversion was removed, so an OPC can convert at any time.</li><li><strong>INC-5 deleted:</strong> Form INC-5, the intimation that an OPC had ceased to be eligible, was deleted, and Form INC-6 is now the single conversion form.</li></ul><p>If you instead want a fresh private company, see our <a href="https://www.patronaccounting.com/private-limited-company-registration">private limited company registration service</a>.</p>

