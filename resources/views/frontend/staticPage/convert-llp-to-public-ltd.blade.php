                <h2 class="section-title">What Does Converting LLP to Public Ltd Mean?</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>Converting an LLP to a public limited company means registering the LLP as a company under Section 366 of the Companies Act, 2013, with the conversion treated as the registration of a new company rather than a mere change of name.</strong> The LLP's business, assets and liabilities pass to the new public company on conversion.</p>
                    <p>To register as a public company, the LLP must have <strong>7 or more members and at least 3 directors</strong>; with fewer than 7 members it can only register as a private company. The LLP Act, 2008 has no conversion route of its own, so the process runs entirely under the Companies Act and the Authorised to Register Rules.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for LLP to Public Ltd:</strong></p>
                    <ul>
                        <li><strong>Section 366:</strong> the provision allowing an LLP and other entities to register as a company.</li>
                        <li><strong>Form URC-1:</strong> the primary conversion application under the Authorised to Register Rules, now linked to SPICe+.</li>
                        <li><strong>Form URC-2:</strong> the newspaper advertisement inviting objections before conversion.</li>
                        <li><strong>SPICe+:</strong> the MCA incorporation form filed with the MOA and AOA of the new company.</li>
