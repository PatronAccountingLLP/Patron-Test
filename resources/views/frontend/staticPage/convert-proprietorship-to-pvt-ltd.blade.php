                <h2 class="section-title">What Does Converting Proprietorship to Pvt Ltd Mean?</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>Converting a proprietorship to a private limited company means incorporating a new company under the Companies Act, 2013 and transferring the existing business, assets and liabilities into it as a going concern.</strong> Indian law has no direct statutory conversion for a sole proprietorship, so the proprietor becomes a shareholder and director of the new company.</p>
                    <p>The new company is a separate legal entity with limited liability, perpetual succession and the ability to issue shares to investors and employees. The proprietor typically holds the majority of the shares to keep the transfer tax-neutral under <strong>Section 47(xiv)</strong> of the Income Tax Act, 1961.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Proprietorship to Pvt Ltd:</strong></p>
                    <ul>
                        <li><strong>Going concern:</strong> transferring the running business as a whole, including assets and liabilities.</li>
                        <li><strong>SPICe+:</strong> the MCA's integrated company incorporation form (INC-32) with PAN, TAN and GST.</li>
                        <li><strong>Slump sale:</strong> transfer of the business for a lump-sum consideration, used where Section 47(xiv) is not chosen.</li>
                        <li><strong>Section 47(xiv):</strong> the provision that exempts the transfer from capital gains tax when conditions are met.</li>
                    </ul>

