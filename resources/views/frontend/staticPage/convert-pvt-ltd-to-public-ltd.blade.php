                <h2 class="section-title">What Does Converting Pvt Ltd to Public Ltd Mean?</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>Converting a private limited company to a public limited company means altering the company's MoA and AoA under Section 14 of the Companies Act, 2013 to remove the private company restrictions in Section 2(68).</strong> The same legal entity continues with the same CIN; only its class changes from private to public.</p>
                    <p>A public limited company can offer shares to the public, list on a stock exchange, and have unlimited members, but it must meet stricter governance - minimum <strong>3 directors and 7 members</strong>, and additional disclosure and board norms under the Companies Act, 2013.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Private to Public:</strong></p>
                    <ul>
                        <li><strong>Section 14:</strong> the provision allowing alteration of articles to convert a company's class.</li>
                        <li><strong>Special Resolution:</strong> a shareholder resolution passed by at least 75% of votes.</li>
                        <li><strong>MGT-14:</strong> the ROC form for filing the special resolution within 30 days.</li>
                        <li><strong>INC-27:</strong> the ROC form applying for conversion, filed within 15 days under Rule 33.</li>
                    </ul>

                </div>
            </div>
