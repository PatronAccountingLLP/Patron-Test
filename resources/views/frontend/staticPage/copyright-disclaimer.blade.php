                        <h3 class="faq-expanded__q">What is Section 52 of the Copyright Act?</h3>
                        <div class="faq-expanded__a"><p>Section 52 enumerates specific acts that do not constitute infringement - commonly called 'fair dealing' in Indian law. These include: fair dealing for private or personal use including research, criticism or review, and reporting of current events; reproduction for judicial proceedings; and transient storage for electronic transmission. Fair dealing does NOT cover commercial reproduction or wholesale copying.</p></div>
