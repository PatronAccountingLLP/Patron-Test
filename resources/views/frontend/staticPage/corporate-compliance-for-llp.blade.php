            <h2 class="section-title">How LLP Compliance Differs from a Company</h2>
            <div class="content-text">
                
                <p>If you have run a company, the LLP regime will feel lighter in places and different in others.</p><ul><li><strong>Different forms:</strong> Form 11 and Form 8, not AOC-4 and MGT-7.</li><li><strong>No AGM:</strong> An LLP does not hold an annual general meeting.</li><li><strong>No board meetings:</strong> There is no mandatory board meeting requirement, governance follows the LLP agreement.</li><li><strong>Audit only above thresholds:</strong> Audit is required only if turnover exceeds 40 lakh or contribution exceeds 25 lakh, unlike a company, which is always audited.</li><li><strong>Same discipline:</strong> Despite being lighter, the filings are mandatory and the late fees, 100 rupees per day per form with no cap, are the same.</li></ul><h3>The LLP Annual Compliance Map</h3><p>These are the recurring filings every LLP must complete each year.</p><ul><li><strong>Form 11, annual return:</strong> By 30 May, within 60 days of the financial year end, certified by a practising company secretary if turnover exceeds 5 crore or contribution exceeds 50 lakh.</li><li><strong>Form 8, account and solvency:</strong> By 30 October, certified by the auditor if turnover exceeds 40 lakh or contribution exceeds 25 lakh.</li><li><strong>Audit, if applicable:</strong> By a practising chartered accountant where the thresholds are crossed, before the income tax return.</li><li><strong>DIR-3 KYC, partner KYC:</strong> By 30 September, for every designated partner, to keep the DPIN active.</li><li><strong>ITR-5, income tax:</strong> By 31 July if not audited, or 31 October if audited.</li><li><strong>Form 3CEB, if applicable:</strong> By 30 November, for international or specified domestic transactions.</li></ul>

