            <div class="content-text">
                
                <p><strong>Governing law and forms:</strong> A Limited Liability Partnership is governed by the Limited Liability Partnership Act, 2008, and files two annual forms with the Registrar, Form 11, the annual return, within 60 days of the financial year end, by 30 May, and Form 8, the statement of account and solvency, within 30 days of the end of six months of the financial year, by 30 October, with each attracting a penalty of 100 rupees per day per form and no maximum cap if filed late.</p><p><strong>Audit and certification:</strong> An audit of the LLP’s accounts by a practising chartered accountant is mandatory only where its turnover exceeds 40 lakh or its contribution exceeds 25 lakh, in which case Form 8 is certified by the auditor, while Form 11 must be certified by a practising company secretary where turnover exceeds 5 crore or contribution exceeds 50 lakh, and a tax audit under Section 44AB of the Income-tax Act applies where turnover exceeds 1 crore, or 10 crore where at least 95 percent of transactions are digital.</p><p><strong>Income tax and partner KYC:</strong> An LLP files its income tax return in Form ITR-5, by 31 July where no audit is required and by 31 October where it is, and must file even where its income is nil, while every designated partner files DIR-3 KYC by 30 September to keep the designated partner identification number active, failing which the DPIN is deactivated and the partner cannot sign any MCA form.</p><p><strong>No AGM, and inactive LLPs:</strong> An LLP has no requirement to hold an annual general meeting or board meetings, its governance following the LLP agreement, but even an inactive or zero-turnover LLP must file Form 11, Form 8 and its income tax return and maintain books of account, and a failure to file for two or more years can lead the Registrar to strike the LLP off the register.</p><p>Refer to the <a href="https://www.mca.gov.in" target="_blank" rel="noopener">MCA portal</a> for the LLP forms and to <a