            <h2 class="section-title">The Operational Overlay, Layer by Layer</h2>
            <div class="content-text">
                
                <p>Manufacturing compliance is best understood as the company stack plus three operational layers.</p><h3>The Factory and Safety Layer</h3><p>Under the Factories Act, and increasingly the OSH and Working Conditions Code, the factory needs its licence, must keep within working-hour and overtime limits, maintain health, safety and welfare standards, run a safety committee where the worker count requires one, and keep the statutory registers and returns.</p><h3>The Labour and Social Security Layer</h3><p>The workforce brings the Code on Wages, the Industrial Relations Code and the Code on Social Security into play, with the wage definition and the fifty percent rule, PF and ESI, bonus and gratuity, and the management of contract labour, for whom the factory carries residual liability.</p><h3>The Environmental Layer</h3><p>Because it emits and generates waste, the unit needs Consent to Establish and Consent to Operate from the Pollution Control Board under the Water and Air Acts, and must handle hazardous waste under the 2016 rules, renewing the consents as required.</p><h3>Cost Audit for Manufacturers</h3><p>Manufacturing is one of the main triggers for a cost audit. Under Section 148 of the Companies Act, a company in a notified industry that crosses the prescribed turnover thresholds must maintain cost records and have them audited by a cost accountant, with the cost audit report filed with the MCA. Many manufacturing sectors are covered, so a growing manufacturer should check its position early. We assess whether the cost audit applies to your unit and coordinate it where it does, alongside the rest of the compliance.</p>

