                        <h3 class="faq-expanded__q">What compliance must a private limited company do every year?</h3>
                        <div class="faq-expanded__a"><p>Every year, a private limited company must hold at least four board meetings, or two if it is a small company, hold its AGM within six months of the financial year end, get its accounts audited, and file AOC-4 within 30 days and the annual return MGT-7, or MGT-7A for a small company, within 60 days of the AGM. It also completes DIR-3 KYC by 30 September, files DPT-3 by 30 June, the half-yearly MSME-1 where applicable, and its income tax return in ITR-6.</p></div>
