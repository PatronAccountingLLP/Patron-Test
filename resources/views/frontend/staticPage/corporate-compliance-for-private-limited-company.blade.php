                <h3>Annual Filings</h3><p>Every year, regardless of activity, the company files AOC-4, the annual return MGT-7 or MGT-7A, completes director KYC, files DPT-3 and MSME-1 where applicable, and files its income tax return, after holding its AGM and getting its accounts audited.</p><h3>Event-Based Filings</h3><p>Whenever something changes, the company files the matching form, for example a share allotment, a change of directors, the creation of a charge, a significant beneficial owner, or a special resolution, each within its own deadline.</p><h3>Governance and Records</h3><p>Underlying it all, the company holds its board meetings, four a year or two for a small company, holds the AGM, and maintains its statutory registers and minutes, which the filings draw from.</p><h3>The Annual Compliance Map</h3><p>These are the recurring filings every private limited company must complete each year. Each links to its own service.</p><ul><li><strong>AOC-4, financial statements:</strong> Within 30 days of the AGM, with the board’s and auditor’s reports.</li><li><strong>MGT-7 or MGT-7A, annual return:</strong> Within 60 days of the AGM, MGT-7A if a small company.</li><li><strong>ADT-1, auditor:</strong> Within 15 days of the AGM where the auditor is appointed or reappointed.</li><li><strong>DIR-3 KYC, director KYC:</strong> By 30 September, to keep each director’s DIN active.</li><li><strong>DPT-3, deposits:</strong> By 30 June, including loans from directors treated as exempted deposits.</li><li><strong>MSME-1, MSME dues:</strong> Half-yearly, reporting outstanding dues to MSME vendors.</li><li><strong>ITR-6, income tax:</strong> By 31 October, with the audit report.</li></ul>

