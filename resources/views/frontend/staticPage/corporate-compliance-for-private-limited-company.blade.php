                    <div class="faq-expanded__item" id="faq-3">
                        <h3 class="faq-expanded__q">Does a private limited company with no business still file?</h3>
                        <div class="faq-expanded__a"><p>Yes. The compliance obligation arises from the company being registered under the Companies Act, not from whether it does any business. A company with no revenue, no transactions and no employees must still file its AOC-4 with a nil balance sheet, its annual return, DPT-3, and DIR-3 KYC for every director. Treating a dormant or idle company as exempt is a common and expensive mistake, because the penalties accrue regardless.</p></div>
