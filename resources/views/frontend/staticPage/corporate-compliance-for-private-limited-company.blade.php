                        <h3 class="faq-expanded__q">What are AOC-4 and MGT-7?</h3>
                        <div class="faq-expanded__a"><p>AOC-4 is the form used to file a company’s financial statements with the Registrar of Companies, including the balance sheet, profit and loss account, the board’s report and the auditor’s report, and it is due within 30 days of the AGM. MGT-7 is the annual return, giving the shareholding, directors and other details, due within 60 days of the AGM, with the abridged MGT-7A used by small companies and One Person Companies.</p></div>
