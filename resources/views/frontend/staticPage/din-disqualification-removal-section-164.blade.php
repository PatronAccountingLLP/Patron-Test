                        <h3 class="faq-expanded__q">What triggers director disqualification under Section 164(2)?</h3>
                        <div class="faq-expanded__a"><p>A director is disqualified under Section 164(2)(a) when the company fails to file its financial statements or annual returns for any continuous period of three financial years. The disqualification lasts five years from the date of default. It is automatic by operation of law, requires no court order, and deactivates the director’s DIN.</p></div>
