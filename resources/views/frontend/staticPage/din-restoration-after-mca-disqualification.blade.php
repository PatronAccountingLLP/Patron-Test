                        <h3 class="faq-expanded__q">How is a disqualified DIN restored?</h3>
                        <div class="faq-expanded__a"><p>A disqualified DIN is restored by reviving the struck-off company through an NCLT appeal under Section 252, filing INC-28 with the ROC, and then completing DIR-3 KYC. Once the NCLT order is recorded and the company status returns to Active, the MCA removes the disqualification flag and the DIN can be reactivated through the KYC filing.</p></div>
