                        <div class="faq-expanded__a"><p>INC-28 is the form filed with the Registrar to record the NCLT restoration order, on the MCA V3 portal, within 30 days of the order. Once INC-28 is processed, the company’s status is restored to Active and the disqualification flag on the directors’ DINs is removed, paving the way for DIR-3 KYC and reactivation.</p></div>
