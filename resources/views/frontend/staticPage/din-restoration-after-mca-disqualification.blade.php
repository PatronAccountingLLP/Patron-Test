                <h2 class="section-title">What Is DIN Restoration?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>DIN restoration is the process of reactivating a Director Identification Number that the MCA deactivated after the director was disqualified. When the disqualification followed the company being struck off, the DIN cannot be reactivated until the company is revived through the NCLT.</p><p>The restoration is therefore a sequence: an NCLT appeal under Section 252 to revive the company, the filing of INC-28 with the Registrar, removal of the disqualification flag, and finally DIR-3 KYC to make the DIN active and usable again for filings.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for DIN Restoration:</strong></p>
                    <ul><li><strong>DIN Reactivation:</strong> Bringing a deactivated DIN back to active or approved status so the director can file again.</li><li><strong>Section 252 Appeal:</strong> The NCLT appeal to restore a struck-off company, which underpins DIN restoration.</li><li><strong>INC-28:</strong> The form filed with the ROC to record the NCLT order, on the MCA V3 portal.</li><li><strong>CRF:</strong> The Change Request Form ticket the ROC raises on MCA21 to reactivate the DIN after the order.</li><li><strong>DIR-3 KYC:</strong> The final KYC filing that moves the DIN status to approved and fully operational.</li></ul>

