    <div class="content-container">
        <div class="two-column">
            <div class="column-content">
                <h2 class="section-title">What is a Double Currency Networth Format?</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>A Double Currency Networth Format</strong> is a CA-certified net worth statement that presents Total Assets minus Total Liabilities in both Indian Rupees (INR) and a foreign currency using the official FBIL reference rate as on the date of the certificate. It is the standard format for visa financial documentation.</p>
                    <p>The certificate is structured in two parallel columns or two separate statements - one in INR showing the actual asset values, and a second conversion showing the equivalent foreign currency value at the FBIL rate applicable on the date of issue. The CA certifies both sets of values, states the exchange rate used, and generates a UDIN that locks the rate into the certificate record.</p>
                    <p>The format originated as a practical response to embassy requirements - foreign embassies and consulates prefer to see Indian applicants' wealth in a currency they work with daily. While there is no ICAI-mandated format, the double currency presentation has become the de-facto industry standard for all visa-related net worth certificates and is recognized by embassies of all major destination countries.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Double Currency Networth Format:</strong></p>
                    <p><strong>FBIL:</strong> Financial Benchmarks India Pvt Ltd - the official body responsible for computing and disseminating USD/INR and other major currency reference rates in India since 10 July 2018. Rates published daily on <a href="https://www.fbil.org.in" target="_blank" rel="noopener">fbil.org.in</a>.</p>
                    <p><strong>Reference Rate:</strong> The official daily exchange rate set by FBIL for INR against USD, GBP, EUR, JPY, and cross rates for CAD, AUD, SGD, etc.</p>
                    <p><strong>UDIN:</strong> Unique Document Identification Number - 18-digit code generated by the CA on the ICAI portal. The certificate figures including the conversion rate are part of the UDIN-locked record, verifiable at <a href="https://udin.icai.org" target="_blank" rel="noopener">udin.icai.org</a>.</p>
                    <p><strong>Conversion Date:</strong> The rate used is the FBIL rate as on the certificate date. If the certificate is dated on a weekend or bank holiday, the last available FBIL rate is used.</p>
                    <p><strong>Single Currency Format:</strong> Standard net worth certificate in INR only - used for bank loans, DEMAT accounts, tenders. Not suitable for visa applications to non-India countries.</p>

