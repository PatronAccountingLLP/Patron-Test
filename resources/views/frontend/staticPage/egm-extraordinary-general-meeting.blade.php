                <h2 class="section-title">What Is an Extraordinary General Meeting?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>An extraordinary general meeting is any general meeting of a company’s members other than the annual general meeting. It is convened under Section 100 to transact urgent or special business that needs member approval before the next AGM.</p><p>Because it deals only with special business, every item on the EGM agenda is supported by an explanatory statement. It is the meeting through which members approve major decisions, such as altering capital, amending the constitution or removing a director, at the time the decision is needed.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for EGM:</strong></p>
                    <ul><li><strong>Requisition:</strong> A members’ demand, by those holding at least 1/10th of voting rights, that the Board call an EGM.</li><li><strong>Special Business:</strong> All business at an EGM, each item carrying an explanatory statement under Section 102.</li><li><strong>Explanatory Statement:</strong> The statement attached to the notice setting out the material facts of each item.</li><li><strong>Proxy:</strong> A person appointed by a member to attend and vote; need not be a member, not counted for quorum.</li><li><strong>Special Resolution:</strong> The 75 percent majority resolution many EGM matters require.</li></ul>

