                <h2 class="section-title">What Is EOR India for US Companies</h2>
                <div class="content-text what-is-definition">
                    
                    <p>EOR India for US Companies is a third-party employment structure where Patron Accounting acts as the legal employer in India for the US client's hires. Patron issues the Indian employment contract, runs INR payroll, deposits EPF and ESI contributions, withholds TDS under Section 192, files Form 24Q quarterly, manages statutory leave, gratuity provisioning, and exit compliance, and reports periodically to the US client. The US client retains full functional control over the employee's day-to-day work, deliverables, performance management, and intellectual property under a Master Services Agreement that includes IP assignment to the US parent.</p>
<p>This structure is widely used by US Series A through Series D startups, mid-market SaaS companies, and US-listed enterprises piloting India hiring before incorporating a subsidiary. The break-even point against running an Indian Pvt Ltd directly is typically 25 to 30 full-time employees - below that, EOR is more cost-effective than maintaining an India entity with dedicated finance and HR overhead.</p>
<p>The structure is governed by the Indian Companies Act 2013, the Income-tax Act 1961, the four Labour Codes 2019/2020, the EPF and ESI Acts, FEMA 1999, and the <a href="https://incometaxindia.gov.in/" target="_blank" rel="noopener">India-US DTAA</a> (signed 12 September 1989). The US Treasury technical explanation is published by the <a href="https://www.irs.gov/businesses/international-businesses/india-tax-treaty-documents" target="_blank" rel="noopener">IRS</a>.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for EOR India:</strong></p>
                    <p><strong>Employer of Record (EOR) -</strong> A third-party Indian entity (Patron Accounting LLP) that becomes the legal employer for the US client's Indian hires. Patron handles all Indian employment-law obligations; the US client manages the work itself.</p>
<p><strong>Permanent Establishment (PE) -</strong> Under Article 5 of the India-US DTAA, a PE is a fixed place of business through which an enterprise of one state carries on business in the other. A dependent agent who habitually concludes contracts on behalf of the foreign enterprise can also create a PE. An EOR acting as principal employer for its own staff, with arm's-length pricing to the US client, does not by itself create a PE for the US parent.</p>
<p><strong>Section 17(2)(vi) Perquisite Taxation of ESOP / RSU -</strong> When a US parent grants stock options or RSUs to an Indian-resident employee, the difference between Fair Market Value at exercise (or vesting for RSUs) and the exercise price is taxable in India as a salary perquisite under Section 17(2)(vi) read with Rule 3(8) and Rule 3(9) of the Income-tax Rules. TDS under Section 192 is deducted by the Indian employer (Patron, as EOR) at the time of exercise / vesting.</p>
<p><strong>Schedule FA + Form 67 -</strong> Indian residents holding foreign assets (US parent stock from RSUs / ESOPs / ESPP) must disclose them in Schedule FA of the Indian ITR. Form 67 is required for claiming Foreign Tax Credit on US tax withheld on the same income, in line with Article 25 of the India-US DTAA.</p>
<p><strong>FCRA versus FEMA -</strong> The Foreign Contribution Regulation Act 2010 governs foreign donations / grants to Indian non-profits. Section 2(1)(h) of FCRA EXCLUDES amounts received in lieu of goods or services. The US client's payment to Patron for EOR services is a commercial transaction under FEMA 1999, not a foreign contribution. FCRA registration is NOT required.</p>
<p><strong>FEMA Form A2 + RBI Purpose Codes -</strong> Inward remittance from the US client to Patron's Authorised-Dealer Category-I bank account uses Form A2 with the relevant RBI purpose code (P0802 for software / IT services or P1006 for business services). Bank issues a Foreign Inward Remittance Certificate (FIRC) for each receipt.</p>

