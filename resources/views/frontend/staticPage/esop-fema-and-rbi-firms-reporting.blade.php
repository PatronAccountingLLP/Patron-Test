                <h2 class="section-title">The Rules Changed in 2022: What Applies Now</h2>
                <div class="content-text what-is-definition">
                    
                    <p>The framework for reporting foreign-parent ESOPs was overhauled in August 2022, and the old approach no longer applies. Using the pre-2022 method is itself a compliance risk.</p>
                    <p>The earlier annual Form ESOP filed with the RBI is gone. Cross-border employee grants are now reported in Form OPI through the AD bank, under the Foreign Exchange Management (Overseas Investment) Rules, Regulations and Directions, 2022.</p>
                    <p><strong>Note on terminology:</strong> the inbound side, foreign investment into India, runs under the Non-debt Instruments Rules and the RBI FIRMS portal. The outbound side covered here, an Indian resident acquiring shares in a foreign parent, runs under the Overseas Investment Rules, 2022 and is reported in Form OPI. We use the correct regime for your transaction.</p>

