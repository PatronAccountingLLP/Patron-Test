                <p>The first question is what the employee's holding actually is under the OI Rules, because the classification drives the form.</p>
                <ul>
                    <li><strong>Overseas Portfolio Investment (OPI):</strong> a resident employee acquiring shares in the foreign parent under ESOP, RSU or sweat equity, holding below 10 percent of the equity and without control, is OPI under Schedule III. This is the usual case, and it is reported in Form OPI by the Indian entity.</li>
