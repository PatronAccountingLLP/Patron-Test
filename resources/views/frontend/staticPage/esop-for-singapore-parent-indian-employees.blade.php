                        <h3 class="faq-expanded__q">How are Singapore-parent RSUs taxed for an Indian employee?</h3>
                        <div class="faq-expanded__a"><p>A Singapore-parent RSU is taxed in India as a salary perquisite at vesting, on the full fair market value of the shares, because there is no exercise price to offset, and the Indian subsidiary deducts TDS. When you later sell, the gain over the vesting value is taxed in India as capital gains. Singapore itself usually does not tax these gains for a purely India-based employee, and has no capital gains tax on the sale, so the India treatment generally governs.</p></div>
