            <div class="content-text">
                
                <p><strong>India perquisite:</strong> Singapore-parent equity granted to an Indian-subsidiary employee is a salary perquisite under Section 17(2)(vi) of the Income-tax Act, taxed at exercise for options and at vesting for RSUs, with fair market value under Rule 3 and Rule 11UA, and TDS by the Indian subsidiary.</p>
