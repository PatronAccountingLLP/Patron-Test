            <h2 class="section-title">The Singapore Side: IRAS and No Capital Gains Tax</h2>
            <div class="content-text">
                
                <p>Singapore's treatment is what makes this corridor lighter than the US one, and it surprises many founders.</p>
                <ul>
                    <li><strong>IRAS taxes equity gains only on Singapore service:</strong> Singapore taxes ESOP and ESOW gains at exercise or vesting, but only to the extent the award relates to employment exercised in Singapore. For an employee who works in India and never exercised employment in Singapore, the gains attributable to Indian service are generally outside the Singapore charge.</li>
                    <li><strong>No capital gains tax:</strong> Singapore does not tax capital gains, so selling the shares generally attracts no Singapore tax at all, unlike the US, where a sale can be taxable. The Indian capital-gains charge therefore usually stands alone.</li>
                    <li><strong>The result:</strong> for a purely India-based employee, double taxation is often not an issue, so the treaty credit matters far less here than in the US corridor.</li>
                </ul>

