                        <h3 class="faq-expanded__q">Does Singapore tax the sale of the shares?</h3>
                        <div class="faq-expanded__a"><p>No. Singapore does not have a capital gains tax, so selling the shares generally attracts no Singapore tax. This is a key difference from the US corridor, where a sale can be taxable in the US. For a Singapore-parent grant, the capital gain on sale is taxed only in India, as long-term or short-term gains depending on the holding period, with no Singapore charge to credit against it.</p></div>
                    </div>
