        <div class="text-content">
            <h2 class="section-title">What a Compliant Scheme Document Contains</h2>
            <div class="content-text">
                
                <p>Rule 12 sets out the disclosures the scheme and the general-meeting notice must carry. Our drafted document covers all of them:</p>
                <ul>
                    <li><strong>Total options:</strong> the total number of options or the option pool authorised under the scheme.</li>
                    <li><strong>Eligible employees:</strong> the classes of employees and directors who may receive options.</li>
                    <li><strong>Vesting:</strong> vesting requirements, the vesting period and the maximum vesting period.</li>
                    <li><strong>Exercise price:</strong> the exercise price or the formula for arriving at it.</li>
                    <li><strong>Exercise period:</strong> the exercise window and the process to exercise.</li>
                    <li><strong>Lapse and forfeiture:</strong> when options lapse, and the leaver treatment.</li>
                    <li><strong>Limits:</strong> the maximum options per employee and in aggregate.</li>
                    <li><strong>Valuation and accounting:</strong> the valuation method and a statement on the accounting standards.</li>
                </ul>
                <p><strong>Mandatory terms:</strong> the document must build in the minimum one-year gap between grant and vesting, set how the board fixes the exercise price, and confirm that employees gain no shareholder rights until they exercise.</p>

