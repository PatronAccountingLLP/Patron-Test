                <h2 class="section-title">What Is the Form SH-6 Register</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Form SH-6 is the statutory Register of Employee Stock Options that a company must maintain under Rule 12(10) of the Companies (Share Capital and Debentures) Rules 2014. It records every option granted under Section 62(1)(b) and its lifecycle.</p>
                    <p>The register is maintained, not filed: it is kept at the registered office and produced on inspection, audit or due diligence, rather than uploaded to the MCA portal as a routine e-form. Each entry is authenticated by the Company Secretary or an authorised person, and the register is preserved as a permanent governance record.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for SH-6 Register Administration:</strong></p>
                    <ul>
                        <li><strong>Grant:</strong> the award of options to an employee, the first event recorded in SH-6.</li>
                        <li><strong>Vesting:</strong> the point at which options become exercisable, recorded with its date.</li>
                        <li><strong>Forfeiture or lapse:</strong> options lost on exit or non-exercise, recorded with any amount refunded.</li>
                        <li><strong>Authentication:</strong> the Company Secretary or authorised signatory validating each entry.</li>
