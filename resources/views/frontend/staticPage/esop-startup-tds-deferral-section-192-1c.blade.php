    <div class="content-container">
        <div class="two-column">
            <div class="column-content">
                <h2 class="section-title">What Is the Section 192(1C) Deferral</h2>
                <div class="content-text what-is-definition">
                    
                    <p>The Section 192(1C) deferral is a special rule that lets an eligible startup postpone TDS on the ESOP perquisite instead of deducting it at exercise. The perquisite is still computed at exercise, but the tax becomes payable only on the earliest trigger event.</p>
                    <p>Introduced by the Finance Act 2020, it applies only to startups that are DPIIT-recognised and hold an Inter-Ministerial Board certificate under Section 80-IAC. From 1 April 2026, the same relief continues under Section 392(3) read with Section 289(3) of the Income-tax Act 2025, with the window extended to 60 months from the end of the Tax Year of allotment.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for ESOP TDS Deferral:</strong></p>
                    <ul>
                        <li><strong>Eligible startup:</strong> a DPIIT-recognised Pvt Ltd or LLP that also holds an IMB certificate under Section 80-IAC.</li>
                        <li><strong>IMB certificate:</strong> the Inter-Ministerial Board certificate of eligible business, separate from DPIIT recognition.</li>
