        <div class="text-content">
            <h2 class="section-title">How They Are Taxed</h2>
            <div class="content-text">
                
                <p>This is where the contrast is sharpest. A cash reward is simply salary; an ESOP has a two-stage equity tax.</p>
                <ul>
                    <li><strong>Profit-sharing and bonus:</strong> fully taxable as salary income at the employee's slab rate in the year received, with employer TDS; no capital-gains event.</li>
                    <li><strong>ESOP at exercise:</strong> the gap between FMV and the exercise price is taxed as a salary perquisite.</li>
                    <li><strong>ESOP at sale:</strong> the gain over the exercise FMV is taxed as capital gains, often at a lower rate than salary.</li>
                </ul>
                <div class="highlight-box" style="margin-top:16px;">
                    <p><strong>The tax trade-off</strong></p>
                    <p>Cash rewards are simple but fully taxed as salary every year. An ESOP defers part of the value to a capital-gains event on sale, which can be more tax-efficient if the shares are held and the company grows.</p>
                </div>
                <p style="margin-top:16px;"><strong>Current value vs future value:</strong> a bonus rewards what an employee did this year and gives strong short-term motivation; an ESOP rewards what the company becomes and builds retention and an ownership mindset. Family businesses often prefer cash rewards to keep ownership within the family, while high-growth startups often prefer ESOPs to conserve cash and share future upside.</p>

