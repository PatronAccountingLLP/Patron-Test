            <h2 class="section-title">Legal and Tax Framework</h2>
            <div class="content-text">
                
                <p><strong>ESOP:</strong> granted under Section 62(1)(b) of the Companies Act as an option to buy shares, taxed as a perquisite at exercise under Section 17(2)(vi) and as capital gains on sale.</p>
                <p><strong>Statutory bonus:</strong> governed by the Payment of Bonus Act 1965 for establishments with 20 or more employees; eligible employees draw wages up to Rs 21,000 a month, with a bonus of 8.33% to 20% on a calculation ceiling of Rs 7,000 or the minimum wage.</p>
                <p><strong>Profit-sharing and discretionary bonus:</strong> contractual rewards set by the employer above the statutory minimum, not capped by the Act, but fully taxable as salary.</p>
                <p><strong>Taxation:</strong> all cash rewards are taxed as salary income at the slab rate with employer TDS, in the year received, with no capital-gains event, unlike an ESOP.</p>
                <p>Authoritative sources: the <a href="https://labour.gov.in" target="_blank" rel="noopener">Ministry of Labour and Employment</a> (Payment of Bonus Act 1965), the <a href="https://www.incometax.gov.in" target="_blank" rel="noopener">Income Tax Department</a> (salary, TDS), the <a href="https://www.mca.gov.in" target="_blank" rel="noopener">Ministry of Corporate Affairs</a> (Companies Act, Section 62), and the <a href="https://clc.gov.in" target="_blank" rel="noopener">Chief Labour Commissioner</a> (bonus compliance).</p>

