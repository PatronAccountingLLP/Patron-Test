                        <h3 class="faq-expanded__q">What is the difference between an ESOP and a bonus?</h3>
                        <div class="faq-expanded__a"><p>An ESOP gives employees an option to buy company shares at an exercise price, so they gain a future equity stake that dilutes ownership and is taxed at exercise and on sale. A bonus is a cash reward paid on top of salary, fully taxable as salary, with no shares issued and no dilution. An ESOP rewards future value and retention, while a bonus rewards current performance in cash.</p></div>
