        <div class="text-content">
            <h2 class="section-title">Legal and Compliance Framework</h2>
            <div class="content-text">
                
                <p><strong>Entity options:</strong> a foreign company can operate through an Indian company - a wholly-owned subsidiary or joint venture incorporated under the Companies Act, 2013 on the <a href="https://www.mca.gov.in" target="_blank" rel="noopener">MCA portal</a> - or through a branch, liaison or project office of the foreign company, each with different permitted activities and approvals.</p>
                <p><strong>FDI policy and routes:</strong> foreign investment is governed by the FDI policy and FEMA, 1999, under the automatic route (no prior approval, most sectors) or the government route (prior approval for sectors such as defence, media, insurance and banking), subject to sectoral caps and, for land-border countries, prior government approval (see <a href="https://dpiit.gov.in" target="_blank" rel="noopener">DPIIT</a>).</p>
                <p><strong>RBI approval for offices:</strong> branch, liaison and project offices require approval from the <a href="https://www.rbi.org.in" target="_blank" rel="noopener">Reserve Bank of India</a> applied through an Authorised Dealer bank using Form FNC, with branch and liaison offices generally needing a profit and net-worth track record, followed by registration of the office with the Registrar of Companies.</p>
                <p><strong>FEMA reporting:</strong> a foreign-owned company must report the investment to the RBI, including filing FC-GPR on the issue of shares and FC-TRS on a transfer, and documents executed abroad must be notarised and apostilled or consularised; non-compliance attracts FEMA penalties.</p>

