                        <h3 class="faq-expanded__q">How does a foreign company register in India?</h3>
                        <div class="faq-expanded__a"><p>A foreign company enters India by choosing an entry mode and registering accordingly. The most common is a wholly-owned subsidiary, an Indian private limited company 100% owned by the foreign parent, incorporated via the SPICe+ form, with 100% FDI permitted under the automatic route in most sectors. Alternatively, the foreign company can set up a branch, liaison or project office, which are its own offices and require RBI approval through an Authorised Dealer bank. The investment is then reported to the RBI under FEMA.</p></div>
