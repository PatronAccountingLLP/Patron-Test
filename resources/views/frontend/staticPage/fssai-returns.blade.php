<p><strong>FoSCoS:</strong> Food Safety and Compliance System - FSSAI's online portal for all compliance activities including return filing. Mandatory since FY 2020-21.</p>
<p><strong>Licensed Manufacturer:</strong> Any FBO holding State or Central FSSAI License engaged in food production, processing, repacking, relabelling, or labelling.</p>
<p><strong>Location-Specific Filing:</strong> Returns are per license, not per applicant. Multiple food units with separate licenses require separate returns each.</p>

