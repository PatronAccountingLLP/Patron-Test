            <div class="column-content">
                <h2 class="section-title">What Is Form GST RFD-11 LUT?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Form GST RFD-11 is the prescribed form under <strong>Rule 96A of the CGST Rules 2017</strong> for furnishing Letter of Undertaking (LUT) or Bond by a registered exporter or SEZ supplier. The form is filed annually before 31 March of the preceding financial year on the GST Common Portal at <a href="https://www.gst.gov.in" target="_blank" rel="noopener">gst.gov.in</a> under Services > User Services > Furnish Letter of Undertaking. It is a self-declaration that authorises the exporter to make zero-rated supplies under Section 16 of the IGST Act 2017 without payment of IGST.</p>
                    <p>The 3-month export window for goods and 1-year (extendable to 15-month FEMA period per RBI Master Direction) realisation window for services are codified in Rule 96A(1)(a) and Rule 96A(1)(b) respectively.</p>
                    <p><strong>LUT vs Bond - Eligibility Matrix:</strong></p>
                    <div class="table-responsive-wrapper" style="margin-top:12px;margin-bottom:16px;">
                    <table>
                        <thead><tr><th>Type</th><th>Eligibility</th><th>Security</th><th>Common Use</th></tr></thead>
                        <tbody>
                            <tr><td><strong>LUT (Letter of Undertaking)</strong></td><td>All registered exporters and SEZ suppliers except those prosecuted above Rs 2.5 crore in 5 years</td><td>Self-declaration; no monetary security; 2 witnesses with PAN</td><td>Default option for almost all exporters</td></tr>
                            <tr><td><strong>Bond + Bank Guarantee</strong></td><td>Exporters prosecuted for tax evasion above Rs 2.5 crore in past 5 years</td><td>Bond + Bank Guarantee 15 percent of bond amount</td><td>Limited use - only where LUT eligibility lost</td></tr>
                        </tbody>
                    </table>
                    </div>
                    <p><strong>The 3 Undertakings in Form RFD-11:</strong></p>
                    <ol>
                        <li><strong>3-Month Export of Goods (Rule 96A(1)(a)):</strong> Export goods out of India within 3 months from the date of tax invoice (or such further period as Commissioner may allow per Circular 37/11/2018-GST).</li>
                        <li><strong>1-Year/FEMA Period Service Realisation (Rule 96A(1)(b)):</strong> Receive payment for services in convertible foreign exchange or INR (where permitted by RBI) within 1 year from invoice date OR FEMA 15-month period - whichever is later.</li>
                        <li><strong>IGST Plus 18 Percent Interest on Failure (Rule 96A(1) + Section 50(1)):</strong> Pay IGST on the export supply along with interest at 18 percent per annum within 15 days after expiry of 3-month/1-year window if export or realisation does not happen.</li>
                    </ol>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for LUT Filing:</strong></p>
                    <ul style="margin-bottom:0;">
                        <li><strong>Form GST RFD-11:</strong> Online form under Rule 96A for furnishing LUT or Bond - filed annually before 31 March of preceding FY.</li>
                        <li><strong>Letter of Undertaking (LUT):</strong> Self-declaration by exporter binding to export within 3 months and pay IGST plus interest on failure.</li>
                        <li><strong>Bond + Bank Guarantee:</strong> Alternative to LUT for exporters prosecuted above Rs 2.5 crore - includes BG of 15 percent of bond amount.</li>
                        <li><strong>Rule 96A CGST Rules 2017:</strong> Substantive provision for LUT/Bond mechanism.</li>
                        <li><strong>Rule 96A(1)(a):</strong> 3-month export window for goods from invoice date.</li>
                        <li><strong>Rule 96A(1)(b):</strong> 1-year service payment realisation window or FEMA 15-month period whichever is later.</li>
                        <li><strong>Section 16 IGST Act 2017:</strong> Zero-rated supply provision - LUT enables LUT-route under Section 16(3)(a).</li>
                        <li><strong>Notification 37/2017-CT (04.10.2017):</strong> Widened LUT eligibility to all exporters except those prosecuted above Rs 2.5 crore.</li>
                        <li><strong>Circular 40/14/2018-GST (06.04.2018):</strong> Online LUT filing and DEEMED APPROVAL - LUT auto-approved on ARN generation.</li>
                        <li><strong>Deemed Approval:</strong> Automatic approval of LUT on ARN generation - no manual sign-off by Department needed.</li>
                        <li><strong>Witnesses:</strong> Two individuals with PAN and address - sign as witnesses to the LUT undertaking.</li>
                        <li><strong>FEMA Master Direction No.16/2015-16:</strong> RBI direction setting 15-month outer limit for export proceeds realisation.</li>
                    </ul>

