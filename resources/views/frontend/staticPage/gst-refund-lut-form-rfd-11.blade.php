            <h2 class="section-title">Legal and Compliance Framework (India)</h2>
            <div class="content-text">
                
                <p><strong>Rule 96A of CGST Rules 2017:</strong> Any registered person availing the option to supply goods or services for export without payment of integrated tax shall furnish, prior to export, a bond or a Letter of Undertaking in Form GST RFD-11 to the jurisdictional Commissioner, binding himself to pay the tax due along with the interest specified under Section 50(1) within 15 days after expiry of three months from the date of issue of invoice for export (for goods), or one year from the date of invoice for export (for services where payment not received in convertible foreign exchange or INR where permitted by RBI).</p>
                <p><strong>Notification 37/2017-Central Tax dated 04 October 2017:</strong> Foundational widening of LUT eligibility. Any registered person who intends to supply goods or services for export without payment of integrated tax shall be eligible for submission of LUT in place of bond except those who have been prosecuted for any offence under the CGST Act or under any of the existing laws in force in a case where the amount of tax evaded exceeds two hundred and fifty lakh rupees. The five-year look-back applies.</p>
                <p><strong>Circular 8/8/2017-GST dated 04 October 2017:</strong> Master clarification on LUT and Bond mechanics. Sets out conditions for LUT eligibility, Bond format and Bank Guarantee percentage (15 percent of bond amount), filing procedure with jurisdictional Commissioner, witness requirements, and validity period.</p>
                <p><strong>Circular 37/11/2018-GST dated 15 March 2018:</strong> Commissioner can extend the 3-month export window where exports are delayed for genuine reasons. The extension is requested via written representation to the jurisdictional Commissioner with supporting evidence such as shipment delays, regulatory clearance, or force majeure.</p>
                <p><strong>Circular 40/14/2018-GST dated 06 April 2018:</strong> Foundational deemed approval mechanic. The LUT is deemed to be accepted as soon as ARN is generated on online filing. No manual approval signature is required from the Department. The exporter can immediately reference the ARN on export invoices and shipping bills.</p>
                <p><strong>Section 16 of IGST Act 2017:</strong> Zero-rated supply means (a) export of goods or services or both; or (b) supply of goods or services or both to a Special Economic Zone developer or unit. A registered person making zero-rated supply shall be eligible to claim refund either by exporting under LUT/Bond and claiming refund of unutilised ITC OR by paying IGST and claiming refund of tax paid.</p>
                <p><strong>Section 50(1) of CGST Act 2017:</strong> Interest at 18 percent per annum on delayed IGST payment where LUT undertakings are breached.</p>
                <p><strong>FEMA Master Direction No.16/2015-16 (RBI):</strong> RBI direction setting outer realisation period for export of goods and services - currently 15 months from invoice date. Rule 96A(1)(b) reads with this Master Direction to give the longer of 1 year (statutory) or FEMA period as the service realisation window.</p>
                <p><strong>Section 132 of CGST Act 2017:</strong> Prosecution provision - Rs 2.5 crore evasion threshold for LUT eligibility loss per Notification 37/2017-CT carve-out.</p>
                <p><strong>Government references:</strong> <a href="https://www.gst.gov.in" target="_blank" rel="noopener">GST portal</a>, <a href="https://cbic-gst.gov.in" target="_blank" rel="noopener">CBIC GST notifications and circulars</a>, <a href="https://www.rbi.org.in" target="_blank" rel="noopener">RBI FEMA Master Direction</a>, and <a href="https://www.indiacode.nic.in" target="_blank" rel="noopener">indiacode.nic.in (CGST Act 2017 and IGST Act 2017)</a>.</p>

