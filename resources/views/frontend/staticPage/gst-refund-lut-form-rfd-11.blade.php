                <p>Form GST RFD-11 is the gateway to zero-rated GST exports without working capital lock-up. Section 16 of the IGST Act 2017 grants the zero-rated facility for exports and SEZ supplies. Two routes are available - either pay IGST and claim refund (Rule 96 auto-route), or supply under Letter of Undertaking (LUT) or Bond without payment of IGST and claim refund of accumulated ITC (Rule 89 LUT route). The LUT route is structurally faster for working capital because it skips the IGST outflow entirely; the LUT is the instrument that authorises this no-IGST supply.</p>
                <p>Rule 96A of the CGST Rules 2017 is the foundational provision for LUT/Bond. Notification 37/2017-Central Tax dated 04 October 2017 widened eligibility to all exporters except those prosecuted for tax evasion exceeding Rs 2.5 crore in any 5-year period (in which case Bond + Bank Guarantee 15 percent of bond amount is required). Circular 40/14/2018-GST dated 06 April 2018 enabled the online deemed approval mechanic - LUT is approved automatically on ARN generation. Patron Accounting LLP files LUT for 200+ exporters and SEZ suppliers annually with same-day deemed approval and proactive 31 March renewal scheduling.</p>
