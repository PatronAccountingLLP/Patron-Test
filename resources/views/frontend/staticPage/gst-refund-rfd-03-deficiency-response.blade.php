            <h2 class="section-title">Legal and Compliance Framework (India)</h2>
            <div class="content-text">
                
                <p><strong>Rule 90(2) of CGST Rules 2017:</strong> The application for refund, other than claim for refund from electronic cash ledger, shall be forwarded to the proper officer who shall, within a period of fifteen days of filing of the said application, scrutinise the application for its completeness and where the application is found to be complete in terms of sub-rule (2), (3) and (4) of Rule 89, an acknowledgement in Form GST RFD-02 shall be made available to the applicant through the common portal electronically.</p>
                <p><strong>Rule 90(3) of CGST Rules 2017:</strong> Where any deficiencies are noticed, the proper officer shall communicate the deficiencies to the applicant in Form GST RFD-03 through the common portal electronically, requiring him to file a fresh refund application after rectification of such deficiencies.</p>
                <p><strong>Circular 125/44/2019-GST dated 18 November 2019 - Paragraph 9:</strong> It is clarified that either an acknowledgement or a deficiency memo should be issued within the aforesaid period of 15 days starting from the date of generation of ARN. Once an acknowledgement has been issued in relation to a refund application, no deficiency memo, on any grounds, may be subsequently issued for the said application.</p>
                <p><strong>Circular 125/44/2019-GST dated 18 November 2019 - Paragraph 10:</strong> After a deficiency memo has been issued, the refund application would not be further processed and a fresh application would have to be filed. Any amount of input tax credit or cash debited from electronic credit or cash ledger would be re-credited automatically once the deficiency memo has been issued. It may be noted that the re-credit would take place automatically and no order in Form GST PMT-03 is required to be issued. The applicant is required to rectify the deficiencies highlighted in deficiency memo and file fresh refund application electronically in Form GST RFD-01 again for the same period and this application would have a new and distinct ARN.</p>
                <p><strong>Jian International v. Commissioner of Delhi GST (Delhi HC, W.P.(C) 4205/2020):</strong> The Delhi High Court held that Rules 90 and 91 of the CGST/DGST Rules provide a complete code with regard to acknowledgement, scrutiny and grant of refund. The said Rules also provide a strict timeline for carrying out the aforesaid activities. Within fifteen days from the date of filing of the refund application, the respondent has to either point out discrepancy or deficiency in Form GST RFD-03 or acknowledge the refund application in Form GST RFD-02. The respondent has lost the right to point out any deficiency in the petitioner's refund application at this belated stage. Refund along with interest in accordance with law was directed to be paid within two weeks.</p>
                <p><strong>Section 54(1) of CGST Act 2017:</strong> Any person claiming refund of any tax and interest paid on such tax or any other amount paid by him, may make an application before the expiry of two years from the relevant date in such form and manner as may be prescribed. The 2-year cut-off is original and absolute - it does NOT reset upon RFD-03 issuance.</p>
                <p><strong>Section 56 of CGST Act 2017:</strong> Interest on delayed refund - 6 percent per annum default rate; 9 percent for refunds pursuant to appellate orders or court orders. Where RFD-03 was beyond Rule 90(3) window and Jian International applies, Section 56 interest runs from Day 61 of original ARN.</p>
