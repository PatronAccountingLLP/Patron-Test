                    <p>A Non-Resident Taxable Person under Section 2(77) of the CGST Act, 2017 is a person who occasionally undertakes transactions involving the supply of goods or services, or both, whether as principal or agent or in any other capacity, but who has no fixed place of business or residence in India.</p>
                    <p>Two elements set NRTP apart from a Casual Taxable Person. First, no fixed place of business OR residence in India - the supplier does not maintain an office, branch, project office or residential address inside India during normal course. Second, the supplies in India are occasional and temporary - tied to a specific engagement, exhibition, project or contract. Where any one element fails, the foreign supplier may instead need an Indian subsidiary, branch office or a different registration route.</p>
                    <p>Section 24(v) makes NRTP registration compulsory regardless of any aggregate turnover threshold. Section 27(1) requires the certificate of registration before any taxable supply, and Section 27(2) mandates an advance deposit of tax equal to the estimated GST liability for the registration period. Rule 13 of the CGST Rules, 2017 prescribes the procedural mechanics: application in Form GST REG-09 at least 5 days before commencement, self-attested passport copy mandatory, and where the applicant is a business entity incorporated outside India, its foreign Tax Identification Number or unique identification number, or PAN if available, must be furnished.</p>

