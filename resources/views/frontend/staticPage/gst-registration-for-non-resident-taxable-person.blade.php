                    <div class="faq-expanded__item" id="faq-1">
                        <h3 class="faq-expanded__q">Who is a non-resident taxable person under GST?</h3>
                        <div class="faq-expanded__a"><p>A Non-Resident Taxable Person under Section 2(77) of the CGST Act, 2017 is a person who occasionally undertakes transactions involving the supply of goods or services, or both, whether as principal or agent or in any other capacity, but who has no fixed place of business or residence in India. Registration is compulsory under Section 24(v) regardless of any aggregate turnover threshold. Application is filed in Form GST REG-09 under Rule 13 of the CGST Rules, 2017.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-2">
                        <h3 class="faq-expanded__q">What documents are required for NRTP registration?</h3>
                        <div class="faq-expanded__a"><p>Self-attested copy of valid passport of the applicant or its authorised representative; foreign Tax Identification Number or unique identification number certificate from the home country for incorporated entities, or PAN if available; KYC of the Indian authorised signatory (PAN, Aadhaar, photograph) along with the Letter of Authorisation; proof of Indian principal place of business (rent agreement plus NOC plus utility bill, or event venue allotment letter); Indian bank account proof; and advance tax challan acknowledgement.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-3">
                        <h3 class="faq-expanded__q">Why is an Indian authorised signatory needed for NRTP GST?</h3>
                        <div class="faq-expanded__a"><p>Under Rule 13 of the CGST Rules, 2017 read with the General Clauses Act, every application for NRTP registration must be duly signed and verified by an authorised representative holding a PAN in India. The signatory is a resident of India responsible for ongoing GST compliance - filing GSTR-5, responding to notices, and coordinating with the proper officer. The mandate is granted through a Letter of Authorisation or board resolution from the foreign entity, accepted in writing by the signatory.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-4">
                        <h3 class="faq-expanded__q">Can NRTP claim Input Tax Credit on local purchases?</h3>
                        <div class="faq-expanded__a"><p>No. The GST portal FAQ on Form GSTR-5 and Section 17 of the CGST Act, 2017 read with Rule 13 make it clear that NRTPs can avail Input Tax Credit ONLY on goods imported from overseas. ITC is denied on local procurement of goods, on local procurement of services, and on import of services. Hotel stays, venue rental, local transport, and AV equipment hire generate pure GST cost with no credit recovery, which must be built into pricing.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-5">
                        <h3 class="faq-expanded__q">What is the difference between NRTP and OIDAR registration?</h3>
                        <div class="faq-expanded__a"><p>NRTP under Section 27 of the CGST Act covers foreign persons with PHYSICAL operations in India - exhibitions, projects, equipment installation. Uses Form GST REG-09 and files Form GSTR-5 by the 13th. OIDAR under Section 14 of the IGST Act, 2017 covers foreign suppliers of digital services (SaaS, streaming, app stores) to non-taxable Indian consumers. Uses Form GST REG-10 (not REG-09) and files Form GSTR-5A (not GSTR-5) by the 20th, with nil return mandatory. No advance tax under OIDAR; ITC not available.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-6">
                        <h3 class="faq-expanded__q">What is the validity of NRTP GST registration?</h3>
                        <div class="faq-expanded__a"><p>Under Section 27(1) of the CGST Act, 2017, the certificate is valid for the period specified in the application or 90 days from the effective date of registration, whichever is earlier. The proper officer may extend this by a further period not exceeding 90 days through Form GST REG-11 with additional advance tax, taking the total maximum validity to 180 days.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-7">
                        <h3 class="faq-expanded__q">How to file GSTR-5 for non-resident taxable person?</h3>
                        <div class="faq-expanded__a"><p>Form GSTR-5 is filed monthly on the GST common portal by the 13th of the following month under Section 39(5) of the CGST Act, 2017 (the original 20th cut-off was rationalised to the 13th by Budget 2022). The return captures outward supplies, inward supplies (mostly imports of goods), ITC on imported goods only, tax payable and tax paid through electronic cash ledger. The wrap-up GSTR-5 for the last tax period must be filed within 7 days of the validity expiry.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-8">
                        <h3 class="faq-expanded__q">Can NRTP opt for composition scheme?</h3>
                        <div class="faq-expanded__a"><p>No. Section 10 of the CGST Act, 2017 expressly excludes Non-Resident Taxable Persons from the composition scheme. NRTPs must register and pay tax as regular taxable persons with advance tax deposit under Section 27(2). The exclusion reflects the temporary, episodic nature of NRTP activity, which is inconsistent with the composition regime designed for steady small businesses.</p></div>
