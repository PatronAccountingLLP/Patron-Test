        <div class="two-column">
            <div class="column-content">
                <h2 class="section-title">What Is Anti-Profiteering Under GST</h2>
                <div class="highlight-box" style="background:var(--blue-lighter);border-left:4px solid var(--blue);padding:20px 24px;border-radius:0 var(--radius-md) var(--radius-md) 0;margin-bottom:24px;">
                    <p style="font-size:15px;color:var(--text-primary);line-height:1.7;margin:0;"><strong>Definition:</strong> Anti-profiteering under Section 171(1) of the CGST Act 2017 is the statutory obligation on every registered person to pass on the benefit of any reduction in the rate of GST or the benefit of input tax credit to consumers by way of commensurate reduction in the price of goods or services.</p>
                </div>
                <div class="content-text">
                    <p>The anti-profiteering mechanism was introduced to protect consumers during the transition to GST and following subsequent rate reductions. The <strong>Director General of Anti-Profiteering (DGAP)</strong> investigates complaints and submits findings to the authority - which, since <strong>1 October 2024</strong>, is the <strong>GSTAT Principal Bench in New Delhi</strong> under <strong><a href="https://cbic-gst.gov.in/" target="_blank" rel="noopener">Notification 18/2024-CT</a></strong>. Previously, this jurisdiction lay with the National Anti-Profiteering Authority (NAA) and briefly with the Competition Commission of India (CCI).</p>
                    <p>Anti-profiteering proceedings under <strong>Section 171 CGST Act</strong> are fundamentally different from standard <a href="/gstat-appeal-filing">GSTAT appeals</a> under <strong>Section 112</strong> - they are not appeals against first appellate orders but original proceedings where the DGAP investigates and the Principal Bench adjudicates as the authority of first instance, making the defence strategy more akin to a trial than an appeal.</p>
                    <p>The anti-profiteering authority has transitioned through three institutional phases: the <strong>National Anti-Profiteering Authority (NAA)</strong> (November 2017 to November 2022), the <strong>Competition Commission of India (CCI)</strong> (December 2022 to September 2024), and now the <strong>GSTAT Principal Bench</strong> (from 1 October 2024 under Notification 18/2024-CT). All three are referred to as 'the Authority' under Section 171(2).</p>
