        <div class="text-content">
                <h2 class="section-title">Who Faces Anti-Profiteering Action Under Section 171</h2>
                <div class="content-text">
                    <p>Anti-profiteering under <strong>Section 171</strong> applies to any registered person under the CGST Act who has benefited from a GST rate reduction or increased ITC availability but has not passed this benefit to consumers through commensurate price reduction. Sectors most commonly affected include:</p>
                    <ul>
                        <li><strong>Real Estate</strong> - Builders and developers facing ITC reversal on under-construction properties, JDA taxation disputes, and affordable housing GST rate changes. Multiple GSTAT orders in 2025-2026 involve real estate (Paarth Infrabuild, Riddhi Siddhi Construction, Axis Infratech, Bengal Peerless).</li>
                        <li><strong>FMCG and Retail</strong> - Consumer goods companies and distributors including franchise operations. The GSTAT's first anti-profiteering order (Urban Essence / Subway, August 2025) and the Raj &amp; Co / L'Oreal ruling both involved FMCG distribution.</li>
                        <li><strong>Hospitality and Restaurants</strong> - The GST rate reduction on restaurant services from 18% to 5% (November 2017) generated significant anti-profiteering investigations.</li>
                    </ul>
                    <p><strong>Important:</strong> No new complaints are accepted after <strong>1 April 2025</strong> (Notification 19/2024-CT). However, all cases filed before this date - and all pending investigations by DGAP - continue to be adjudicated by the GSTAT Principal Bench. The government is considering reviving anti-profiteering provisions for a limited period following the 56th GST Council rate reduction recommendations.</p>
