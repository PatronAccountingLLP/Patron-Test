        <div class="text-content">
                <h2 class="section-title">4 Common Challenges in Anti-Profiteering Cases</h2>
                <div class="content-text">
                    <h3>Expanded Investigation Scope</h3>
                    <p>The DGAP can expand the investigation beyond the original complaint to cover all products under a GSTIN. The Urban Essence ruling confirmed that a complaint about one product allows the DGAP to examine rate-cut benefit for all products - requiring comprehensive data preparation from day one.</p>
                    <h3>Commensurate Reduction Methodology Disputes</h3>
                    <p>The DGAP's methodology for calculating 'commensurate reduction' is frequently challenged - particularly whether it should be computed at the product level, brand level, or GSTIN aggregate level, and whether cost increases can offset the obligation to reduce prices.</p>
                    <h3>Interest and Penalty Timing</h3>
                    <p>The applicability of <strong>18% interest</strong> and <strong>10% penalty</strong> depends on the date of profiteering. Pre-01.01.2020 profiteering attracts neither interest nor penalty (confirmed in P&amp;G ruling). Post-01.01.2020 profiteering attracts both - but the penalty is waived if the profiteered amount is deposited within 30 days of the order.</p>
                    <h3>Consumer Welfare Fund vs. Individual Refund</h3>
                    <p>Determining whether the profiteered amount should be refunded to identifiable individual recipients or deposited in the Consumer Welfare Fund is a recurring practical challenge - affecting both the quantum and the logistics of compliance.</p>
                    <div class="highlight-box" style="background:var(--orange-light);border-radius:var(--radius-md);padding:24px;margin-top:24px;">
                        <h3 style="color:var(--blue);margin-bottom:12px;">Illustrative Scenario</h3>
                        <p>A real estate developer with an annual turnover of approximately Rs 300 crore received a DGAP investigation report alleging profiteering of Rs 1.2 crore on an affordable housing project following the GST rate reduction on under-construction flats. Patron Accounting's GSTAT team prepared a detailed pricing and ITC analysis demonstrating that construction cost increases had partially offset the GST benefit - resulting in the Principal Bench accepting a reduced profiteering determination and the developer depositing the revised amount within 30 days to avoid the 10% penalty under Section 171(3A).</p>
