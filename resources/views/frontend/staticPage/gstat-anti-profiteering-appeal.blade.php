                        <div class="faq-expanded__a"><p>Anti-profiteering under <strong>Section 171(1) CGST Act</strong> requires every registered person to pass on the benefit of GST rate reductions or increased ITC to consumers by reducing prices. It applies to all registered businesses - particularly in real estate, FMCG, retail, and hospitality sectors where rate changes have been frequent. The GSTAT Principal Bench now adjudicates all cases.</p></div>
