                <h2 class="section-title">Who Should File a GSTAT Appeal</h2>
                <p>Any person aggrieved by an order of the First Appellate Authority under <strong>Section 107</strong> or the Revisional Authority under <strong>Section 108 of the CGST Act</strong> can file an appeal before the GSTAT. This includes registered taxpayers who received:</p>
                <ul>
                    <li><strong>Adverse GST demand orders</strong> where the first appellate authority upheld the demand fully or partially</li>
                    <li><strong>ITC reversal orders</strong> - Input Tax Credit disallowed or reversed by the department</li>
                    <li><strong>Penalty orders</strong> - Penalties imposed under various GST provisions</li>
                    <li><strong>Refund rejection orders</strong> - GST refund claims denied at the first appellate stage</li>
                </ul>
                <p>Under <strong>Section 112(1) CGST Act 2017</strong>, the GSTAT appeal must be filed within <strong>3 months</strong> of the date of communication of the order. For orders communicated before 1 April 2026, the deadline has been extended to <strong>30 June 2026</strong> by Notification S.O. 4220(E) dated 17 September 2025.</p>
                <p>The Tribunal may refuse to admit appeals where the tax, ITC, or penalty involved does not exceed Rs 50,000 under <strong>Section 112(2)</strong>.</p>
