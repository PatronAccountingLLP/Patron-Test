                <h2 class="section-title">What Is GSTAT - The GST Appellate Tribunal</h2>
                <div class="highlight-box" style="background:var(--blue-lighter);border-radius:var(--radius-md);padding:20px 24px;margin-bottom:20px;">
                    <p style="margin:0;"><strong>Definition:</strong> GSTAT (Goods and Services Tax Appellate Tribunal) is the statutory appellate tribunal constituted under <strong>Section 109 of the Central Goods and Services Tax Act 2017</strong> to hear second appeals against orders of the first appellate authority in GST matters across India. It has its Principal Bench at New Delhi and 31 State Benches.</p>
                </div>
                <p>The GSTAT is the highest court in the country on questions of fact in GST matters. Each bench comprises two Judicial Members and two Technical Members - one from the Central Government and one from the State Government. The Tribunal was operationalised on 24 September 2025 and is the first tribunal in India to go fully digital from inception, with all appeals filed electronically through the official GSTAT e-filing portal at <strong><a href="https://efiling.gstat.gov.in" target="_blank" rel="noopener">efiling.gstat.gov.in</a></strong>.</p>
                <p><strong>GSTAT vs Commissioner (Appeals):</strong> GSTAT, unlike the Commissioner (Appeals) under <strong>Section 107 CGST Act</strong>, is a judicial body - not a departmental authority - and its orders carry the force of a court decree, making GSTAT the first genuinely independent forum in the GST appellate hierarchy.</p>
                <p>GSTAT (Goods and Services Tax Appellate Tribunal), also referred to as the GST Tribunal or GST Appellate Tribunal, was constituted under <strong>Section 109 CGST Act 2017</strong> by the Central Government.</p>
