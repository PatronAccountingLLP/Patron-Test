    <div class="content-container">
        <div class="text-content">
                <h2 class="section-title">GSTAT Appeal Filing in India - Overview</h2>
            <div class="highlight-box" style="background:var(--orange-lighter);border-left:4px solid var(--orange);padding:20px 24px;border-radius:var(--radius-md);margin-bottom:24px;">
                <p style="margin:0;font-size:15px;line-height:1.7;"><strong>TL;DR:</strong> GSTAT appeal filing under <strong>Section 112 CGST Act 2017</strong> requires a <strong>10% pre-deposit</strong> of disputed tax (capped at Rs 20 crore under CGST), filed electronically via <strong>Form GST APL-05</strong> on <a href="https://efiling.gstat.gov.in" target="_blank" rel="noopener">efiling.gstat.gov.in</a> within <strong>3 months</strong> of the appellate order. Pre-deposit triggers automatic stay of recovery under <strong>Section 112(9)</strong>. Backlog appeals must be filed by <strong>30 June 2026</strong>.</p>
            </div>
            <div class="table-responsive-wrapper" style="margin-bottom:24px;">
                <table>
                    <thead><tr><th>Parameter</th><th>Details</th></tr></thead>
                    <tbody>
                        <tr><td>Governing Law</td><td>Section 112, Central Goods and Services Tax Act, 2017</td></tr>
                        <tr><td>Pre-Deposit</td><td>10% of disputed tax under Section 112(8) - capped at Rs 20 crore CGST</td></tr>
                        <tr><td>Time Limit</td><td>3 months from order communication under Section 112(1)</td></tr>
                        <tr><td>Condonation</td><td>Up to 3 additional months under Section 112(6) - total outer limit 6 months</td></tr>
                        <tr><td>Form</td><td>Form GST APL-05 on efiling.gstat.gov.in</td></tr>
                        <tr><td>Stay of Recovery</td><td>Automatic under Section 112(9) on payment of pre-deposit</td></tr>
                        <tr><td>Backlog Deadline</td><td>30 June 2026 for pre-1 April 2026 orders (Notification S.O. 4220(E))</td></tr>
                    </tbody>
                </table>
            </div>
            <p>GSTAT appeal filing in India is a critical step for any business that has received an adverse order from the GST First Appellate Authority or Revisional Authority. <strong>Section 112 of the Central Goods and Services Tax Act, 2017</strong> provides the statutory framework for filing a second appeal before the Goods and Services Tax Appellate Tribunal, constituted under <strong>Section 109 CGST Act 2017</strong>. Patron Accounting provides end-to-end GSTAT appeal filing and representation services, with GSTAT matters led by of-counsel <a href="#">Subham Jhunjhunwala</a>.</p>
