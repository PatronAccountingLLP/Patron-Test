                <h2 class="section-title">Who Should File a GSTAT Cross Objection</h2>
                <div class="content-text">
                    <p>A <strong>GSTAT cross objection</strong> should be filed by any party who receives notice that the opposing party has filed a GSTAT appeal - and who wishes to challenge any part of the original order that was adverse to them. Common scenarios include:</p>
                    <ul>
                        <li><strong>Taxpayer as respondent</strong> - The GST department files an appeal challenging the Commissioner (Appeals) order that partially favoured the taxpayer. The taxpayer can cross-object on the issues where the order went against them - without filing a separate appeal.</li>
                        <li><strong>Department as respondent</strong> - A taxpayer files a GSTAT appeal. The department can cross-object on issues where the first appellate order reduced the original demand or granted partial relief.</li>
                    </ul>
