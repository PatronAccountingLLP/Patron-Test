            <div class="column-content">
                <h2 class="section-title">What Is a GSTAT Cross Objection</h2>
                <div class="highlight-box" style="background:var(--blue-lighter);border-left:4px solid var(--blue);padding:20px 24px;border-radius:0 var(--radius-md) var(--radius-md) 0;margin-bottom:24px;">
                    <p style="font-size:15px;color:var(--text-primary);line-height:1.7;margin:0;"><strong>Definition:</strong> A GSTAT cross objection is a memorandum filed by the respondent under <strong>Section 112(5) of the Central Goods and Services Tax Act 2017</strong>, challenging any part of the order appealed against by the opposing party, within 45 days of receipt of notice of the appeal.</p>
                </div>
                <div class="content-text">
                    <p>A cross objection allows the respondent to raise issues in the impugned order that were adverse to them - without filing a separate appeal, paying a separate pre-deposit, or being bound by the original 3-month appeal limitation under <strong>Section 112(1)</strong>. Once filed, the Tribunal treats the cross objection as if it were an appeal filed within the time specified in Section 112(1) - giving it full appellate status.</p>
                    <p>A <strong>GSTAT cross objection under Section 112(5)</strong> is fundamentally different from an independent appeal under <strong>Section 112(1)</strong> - the cross objection is triggered by the opposing party's appeal, carries no separate pre-deposit obligation, has a shorter 45-day limitation (not 3 months), and can only be filed by the party against whom the appeal has been preferred.</p>
                    <p>The cross objection is filed in <strong>Form GST APL-06</strong> on the GSTAT e-filing portal at <a href="https://efiling.gstat.gov.in" target="_blank" rel="noopener">efiling.gstat.gov.in</a>, as prescribed by <strong>Rule 110(2) of the CGST Rules 2017</strong>. It is distinct from Form GST APL-05 (appellant's appeal) and Form GST APL-07 (departmental application).</p>
