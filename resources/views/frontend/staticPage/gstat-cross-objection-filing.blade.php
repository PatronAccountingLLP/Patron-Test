                <div class="faq-expanded__list">
                    <div class="faq-expanded__item" id="faq-1">
                        <h3 class="faq-expanded__q">What is a cross objection in a GSTAT appeal?</h3>
                        <div class="faq-expanded__a"><p>A cross objection is a memorandum filed by the respondent under <strong>Section 112(5) CGST Act</strong> to challenge any part of the impugned order when the opposing party files a GSTAT appeal. It allows the respondent to raise adverse findings without filing a separate appeal or paying additional pre-deposit.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-2">
                        <h3 class="faq-expanded__q">What is the time limit for filing a GSTAT cross objection?</h3>
                        <div class="faq-expanded__a"><p><strong>45 days</strong> from the date of receipt of notice that an appeal has been filed under <strong>Section 112(5) CGST Act 2017</strong>. The Tribunal may condone delay up to 45 additional days under Section 112(6) on sufficient cause. The total outer limit is 90 days.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-3">
                        <h3 class="faq-expanded__q">Is pre-deposit required for a cross objection?</h3>
                        <div class="faq-expanded__a"><p><strong>No.</strong> The pre-deposit obligation under <strong>Section 112(8)</strong> applies only to the party filing the original appeal. The respondent filing a cross objection under Section 112(5) has no separate pre-deposit requirement. This makes the cross objection the most cost-effective remedy at the GSTAT stage.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-4">
                        <h3 class="faq-expanded__q">Can the GSTAT cross objection deadline be extended?</h3>
                        <div class="faq-expanded__a"><p>Yes - under <strong>Section 112(6) CGST Act 2017</strong>, the Tribunal may permit filing of a cross objection within <strong>45 additional days</strong> after expiry of the 45-day period if satisfied that sufficient cause existed for the delay. Beyond 90 days total, the remedy is permanently lost.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-5">
                        <h3 class="faq-expanded__q">What happens if I miss the GSTAT cross objection deadline?</h3>
                        <div class="faq-expanded__a"><p>Missing both the 45-day window and the 45-day condonation period permanently closes the cross objection remedy. The respondent would then need to file an independent appeal under Section 112(1) within its own limitation - which requires pre-deposit - or approach the High Court under Article 226.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-6">
                        <h3 class="faq-expanded__q">What form is used for GSTAT cross objection?</h3>
                        <div class="faq-expanded__a"><p><strong>Form GST APL-06</strong> is the prescribed form under <strong>Rule 110(2) CGST Rules 2017</strong>. It must be filed electronically on the GSTAT portal at <a href='https://efiling.gstat.gov.in' target='_blank' rel='noopener'>efiling.gstat.gov.in</a>, signed and verified in the manner specified in Rule 26.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-7">
                        <h3 class="faq-expanded__q">Can I file both an appeal and a cross objection?</h3>
                        <div class="faq-expanded__a"><p>Yes - if the taxpayer has grounds for an independent appeal under Section 112(1) and also receives notice of the department's appeal, both can be filed. The independent appeal requires pre-deposit under Section 112(8). The cross objection does not. Both will be heard together by the Tribunal.</p></div>
                    </div>
                    <div class="faq-expanded__item" id="faq-8">
                        <h3 class="faq-expanded__q">How is a cross objection different from a reply to the appeal?</h3>
                        <div class="faq-expanded__a"><p>A reply defends against the appellant's grounds. A <strong>cross objection</strong> goes further - it challenges parts of the impugned order that the appellant did not appeal. The Tribunal treats the cross objection as an independent appeal, potentially modifying the order in the respondent's favour on issues the appellant never raised.</p></div>
