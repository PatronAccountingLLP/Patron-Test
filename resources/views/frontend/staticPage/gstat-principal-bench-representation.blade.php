        <div class="text-content">
                <h2 class="section-title">3 Categories of Cases at the Principal Bench</h2>
                <div class="content-text">
                    <h3>Place of Supply Disputes (Section 109(5) Proviso)</h3>
                    <p>Any appeal where the dispute involves determination of the place of supply under Sections 10 to 14 of the IGST Act 2017 must be heard by the Principal Bench. This covers inter-state vs intra-state classification disputes, export of services vs intermediary classification, OIDAR service place of supply, and cross-border supply determination.</p>
                    <h3>Anti-Profiteering Matters (Section 171)</h3>
                    <p>Since October 2024, the GSTAT Principal Bench has taken over jurisdiction from the NAA and CCI to examine whether GST rate reductions and ITC benefits have been passed on to consumers. The Principal Bench hears both new DGAP reports and matters remanded by the Delhi High Court.</p>
                    <h3>NAAR - Advance Ruling Appeals (Section 101A/101B)</h3>
                    <p>From April 2026, the Principal Bench functions as the National Appellate Authority for Advance Ruling, adjudicating cases where two or more State Advance Ruling Authorities have issued conflicting rulings on identical questions of law.</p>
