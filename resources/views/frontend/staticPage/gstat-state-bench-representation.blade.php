                <h2 class="section-title">Who Should File a GSTAT State Bench Appeal?</h2>
                <p>Any person aggrieved by an order of the Commissioner (Appeals) or the Revisional Authority under <strong>Section 107 or Section 108 CGST Act 2017</strong> may file an appeal before the State Bench having territorial jurisdiction. State Bench appeals cover:</p>
                <ul><li><strong>Assessment and demand orders</strong> - Tax demand upheld at first appellate stage</li><li><strong>ITC reversal orders</strong> - Input Tax Credit disallowed or reversed</li><li><strong>Refund rejection orders</strong> - GST refund claims denied</li><li><strong>Penalty orders</strong> - Including penalty-only demands (Finance Act 2025 proviso applies)</li><li><strong>Anti-profiteering matters</strong> - From April 2026 onwards</li></ul>
                <p>The appeal must be filed within <strong>3 months from the date of communication</strong> under <strong>Section 112(1)</strong>. For orders before 1 April 2026, the deadline is <strong>30 June 2026</strong> under Notification S.O. 4220(E).</p>
