                <h2 class="section-title">What Is a GSTAT State Bench?</h2>
                <div class="highlight-box" style="background:var(--blue-lighter);border-radius:var(--radius-md);padding:20px 24px;margin-bottom:20px;"><p style="margin:0;"><strong>Definition:</strong> A GSTAT State Bench is a regional appellate bench of the Goods and Services Tax Appellate Tribunal, constituted under <strong>Section 109(6) of the Central Goods and Services Tax Act 2017</strong>, to hear and adjudicate GST appeals arising within its assigned state or group of states.</p></div>
                <p>State Benches hear all GSTAT appeals except those involving place of supply disputes - which fall under the exclusive jurisdiction of the Principal Bench at New Delhi under <strong>Section 109(7) CGST Act</strong>. Each State Bench comprises two Judicial Members and two Technical Members. Appeals from State Bench orders lie to the jurisdictional High Court on substantial questions of law.</p>
                <p><strong>State Bench vs Commissioner (Appeals):</strong> GSTAT State Benches, unlike the Commissioner (Appeals) under <strong>Section 107 CGST Act</strong>, are judicial bodies - their orders carry the force of a court decree, and a State Bench decision binds all authorities within its territorial jurisdiction until reversed by the High Court or a Larger Bench.</p>
                <div class="highlight-box" style="background:#f0fdf4;border-radius:var(--radius-md);padding:16px 20px;margin-top:20px;"><p style="margin:0;font-size:14px;"><strong>Key Terms:</strong></p><ul style="margin-top:8px;">
                    <li><strong>State Bench</strong> - Regional GSTAT bench under Section 109(6) for state-level appeals</li>
                    <li><strong>Principal Bench</strong> - National bench at New Delhi under Section 109(3) for place of supply disputes</li>
                    <li><strong>Pre-Deposit</strong> - 10% of disputed tax under Section 112(8), capped at Rs 20 crore CGST</li>
                    <li><strong>Stay of Recovery</strong> - Automatic under Section 112(9) on filing with pre-deposit</li>
                    <li><strong>Condonation</strong> - Up to 3 additional months under Section 112(6)</li>
