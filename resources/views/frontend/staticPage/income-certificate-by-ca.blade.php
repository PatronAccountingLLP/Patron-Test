            <h2 class="section-title">Income Certificate, ITR, and Net Worth: What Is the Difference?</h2>
            <div class="content-text">
                
                <p>These three are often confused, but they answer different questions. An income tax return is the return you file with the tax department, declaring income and tax; Form 16 is your employer's certificate of salary and TDS. An income certificate is a CA's attestation that consolidates your total annual income from all sources into one statement, drawing on those very documents, and is what an embassy, bank, or school actually asks for as income proof. It is particularly valuable for the self-employed and freelancers, who have no Form 16 and whose income is spread across sources.</p>
                <p>A net worth certificate answers a different question again: not what you earn in a year, but what you are worth at a point in time, your assets minus your liabilities. Income is a flow; net worth is a snapshot. For a student or tourist visa, embassies frequently want both, the income certificate to show the family can fund ongoing expenses, and the net worth certificate to show the overall financial backing. We prepare each correctly, and together where needed.</p>
                <p>An income certificate is not a statutory government form; it is a CA attestation of income for the requesting authority, verified against your records. UDINs can be verified with the <a href="https://www.icai.org" target="_blank" rel="noopener">Institute of Chartered Accountants of India (icai.org)</a>, and the underlying ITR and AIS sit with the Income Tax Department. The CA certifies only genuine, verified income. This page is the general income certificate; practising professionals such as doctors and lawyers may instead need a <a href="/professional-income-certificate">professional income certificate</a> framed on the practice gross-receipts basis.</p>

