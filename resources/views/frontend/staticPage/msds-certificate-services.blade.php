<tr><td>MSIHC Rules, 1989 - Schedule 9</td><td>Primary Indian regulation for MSDS/SDS. Schedule 9 specifies the 9-section Indian SDS format. Covers 3 schedules of hazardous chemicals. SDS must be maintained by importers, manufacturers, and storage operators.</td></tr>
<tr><td>GHS (Globally Harmonized System) - UN</td><td>International standard for chemical classification and SDS format. 16-section SDS. India has not officially adopted GHS yet; Draft Chemicals Rules 2020 proposes adoption. 16-section format is currently acceptable and mandatory for export.</td></tr>
<tr><td>OSHA HCS (29 CFR 1910.1200) - USA</td><td>Mandatory for exporting chemical products to the United States. Requires 16-section SDS in English.</td></tr>
<tr><td>EU REACH / CLP Regulation 1272/2008</td><td>Mandatory for chemical products exported to European Union. 16-section SDS in destination EU member state's language required.</td></tr>
<tr><td>IATA Dangerous Goods Regulations (DGR)</td><td>Mandatory for air shipment of dangerous goods. MSDS/SDS must accompany air cargo of hazardous substances.</td></tr>
