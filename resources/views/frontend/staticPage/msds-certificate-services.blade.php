            <div class="column-content">
                <h2 class="section-title">What is an MSDS Certificate?</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>An MSDS Certificate (Material Safety Data Sheet)</strong> is a standardized technical document that provides detailed information about a product's chemical composition, physical and health hazards, safe handling and storage procedures, and emergency response measures.</p>
<p>The MSDS is the primary safety communication tool for chemical products across the supply chain - from manufacturer to transporter, distributor, end-user, and emergency responder. Under the UN Globally Harmonized System (GHS), the document is now officially called a Safety Data Sheet (SDS) and follows a globally standardized 16-section format. In India, the term 'MSDS' is still widely used interchangeably with 'SDS'.</p>
<p>The document is prepared based on product formulation data, laboratory test results (pH, flash point, density, viscosity), and hazard classification per GHS criteria. For imports into India, the MSDS must accompany the shipment as per MSIHC Rules, 1989 Schedule 9. For exports, a fresh MSDS is prepared per the destination country's regulatory requirements.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for MSDS Certificate Services:</strong></p>
                    <p><strong>MSDS</strong> - Material Safety Data Sheet - the traditional term for the chemical safety document. Still widely used in India.</p>
<p><strong>SDS</strong> - Safety Data Sheet - the current official term under GHS. Follows a standardized 16-section format. MSDS and SDS are used interchangeably.</p>
<p><strong>GHS</strong> - Globally Harmonized System of Classification and Labelling of Chemicals - UN standard. India has not yet officially adopted GHS; Draft Chemicals Rules 2020 proposes adoption.</p>
<p><strong>MSIHC Rules 1989</strong> - Manufacture, Storage and Import of Hazardous Chemicals Rules, 1989 - the primary Indian regulation for chemical safety under Environment (Protection) Act, 1986.</p>
<p><strong>Hazard Classification</strong> - Process of identifying a chemical's health, physical, and environmental hazards per GHS criteria before preparing the MSDS.</p>
<p><strong>EHS Author</strong> - Environment, Health and Safety professional who collects formulation data, performs hazard classification, and prepares the MSDS.</p>

