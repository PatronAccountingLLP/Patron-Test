            <h2 class="section-title">Legal and Compliance Framework</h2>
            <div class="content-text">
                
                <p><strong>Section 45-IA, RBI Act, 1934:</strong> no company can commence or carry on the business of a non-banking financial institution without obtaining a Certificate of Registration from the <a href="https://www.rbi.org.in" target="_blank" rel="noopener">RBI</a> and having the prescribed Net Owned Fund.</p>
                <p><strong>NOF and Principal Business Criterion:</strong> the minimum NOF is INR 10 crore for most categories, ab initio for new applicants, and the company must meet the Principal Business Criterion of 50% or more financial assets and 50% or more income from those assets.</p>
                <p><strong>Scale Based Regulation Master Direction, 2023:</strong> NBFCs are classified into Base, Middle, Upper and Top Layers and by activity into types such as the NBFC-ICC, with progressively stricter prudential and governance norms by layer; the older NBFC-ND, NBFC-D and NBFC-ND-SI labels have been mapped into this framework. Applications are filed on the <a href="https://cosmos.rbi.org.in" target="_blank" rel="noopener">RBI COSMOS portal</a>.</p>
                <p><strong>Deposits and ongoing rules:</strong> NBFCs cannot accept demand deposits, deposit-taking NBFCs face stricter norms, and registered NBFCs must follow RBI prudential, KYC, digital-lending and reporting requirements on an ongoing basis. The company itself is incorporated via the <a href="https://www.mca.gov.in" target="_blank" rel="noopener">MCA</a>.</p>

