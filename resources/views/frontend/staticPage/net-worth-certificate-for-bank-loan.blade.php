            <h2 class="section-title">Bank Loan Net Worth Certificate: Scope, Deliverables and Who It Suits</h2>
            <div class="content-text">
                <div class="highlight-box" style="margin-bottom:20px;">
                    <p><strong>&#128204; TL;DR &mdash; Net Worth Certificate for Bank Loan at a Glance</strong></p>
                    <p>A net worth certificate for a bank loan gives the credit team an independently verified figure for whoever carries the risk. That is the borrower on some files, and a co-applicant, a joint owner or a guarantor on others. Assets are stated at values the file can support, and existing borrowings are deducted openly instead of being netted off. It carries a UDIN the lender can verify.</p>
                </div>
<p>Credit teams are reading for exposure, not for a headline number. They want to know which assets could be realised, what is already pledged, and whether anything is left once existing commitments are counted. The same certificate serves a business facility, a home loan or a working capital limit, but what the credit team weighs changes with each of them.</p><p>Files come back for a small number of recurring reasons. An asset already charged to another lender gets counted twice. A property is stated at a value the branch will not accept. A guarantor's own borrowings are left out. This page covers how each is evidenced, how co-applicants and joint owners are treated, and what <a href="/blog/documents-required-for-net-worth-certificate">the papers required</a> must establish under the <a href="https://www.rbi.org.in" target="_blank" rel="noopener">Reserve Bank's lending directions</a>.</p>
