                <div class="faq-expanded__list">
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Do banks accept a certificate issued by the borrower's own chartered accountant?</h3>
  <div class="faq-expanded__a"><p>In most cases yes, and it is the normal practice for retail and MSME lending. What the credit officer checks is that the signatory holds a <a href="/glossary/networth/certificate-of-practice-cop">Certificate of Practice</a> and that the UDIN resolves on the ICAI portal. Some banks maintain an empanelled list for large exposures, and there the panel CA has to sign.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">How recent must the certificate be when the loan is sanctioned?</h3>
  <div class="faq-expanded__a"><p>Lenders generally want the position stated within the last three months, and many credit policies treat anything older than six months as stale. Because sanction can take weeks, a certificate obtained too early expires inside the process. Where the file drags, the branch asks for a refreshed certificate rather than an extension of the old one.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Does a lender insist on its own template instead of the CA's?</h3>
  <div class="faq-expanded__a"><p>Frequently. Public sector banks in particular circulate a prescribed annexure with fixed asset heads and a declaration paragraph, and the credit team will not accept a substitute layout. The CA fills that annexure and attaches the detailed schedule behind it, so the verification work is the same and only the presentation follows the bank.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Is a certificate still needed when collateral has already been offered?</h3>
  <div class="faq-expanded__a"><p>Usually yes, because the two answer different questions. The <a href="/glossary/networth/collateral">collateral</a> valuation tells the bank what one asset would fetch on enforcement; the net worth certificate tells it what the borrower is worth after all liabilities. Credit policies commonly require both before an unsecured shortfall or a personal guarantee is accepted.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Does the certificate have to be addressed to a named bank and branch?</h3>
  <div class="faq-expanded__a"><p>It is better practice and most banks require it. Addressing the certificate to the sanctioning branch, and naming the purpose, limits who may rely on it and lets the CA scope the work to that use. An open certificate addressed to whomsoever it may concern is accepted for some purposes but is weaker evidence.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Are borrowings from relatives and friends disclosed on it?</h3>
  <div class="faq-expanded__a"><p>Yes, every liability is disclosed whether or not it is documented or interest-bearing. Informal borrowings are exactly what a lender is trying to surface, since they compete for the same repayment capacity as the proposed loan. Omitting them and having them appear later in the bank statement scrutiny damages the whole application.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Are outstanding balances on existing loans deducted from the certified figure?</h3>
  <div class="faq-expanded__a"><p>The outstanding principal is deducted, not the sum of future instalments. A home loan with twelve years to run reduces net worth by the balance owed today, while the interest yet to accrue is not a present liability. Lenders separately use the instalment burden to assess servicing capacity, which is a different calculation.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Does a business loan need the firm's certificate or the proprietor's?</h3>
  <div class="faq-expanded__a"><p>For a proprietary concern the two are the same person, so one certificate covering personal and business assets is issued. For a partnership or a company the borrower is the entity. Lenders normally ask for the entity's certificate plus a separate one for each partner, director or guarantor whose personal means back the facility.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Can a declined application be resubmitted with a revised certificate?</h3>
  <div class="faq-expanded__a"><p>A certificate can be reissued if the underlying position has genuinely changed or an error is corrected. The reissue carries a fresh date and a fresh UDIN. What a CA cannot do is restate the same date at a higher figure to fit the sanction. The original UDIN stays on record either way.</p></div>
</div>
                    <div class="faq-expanded__item">
  <h3 class="faq-expanded__q">Is a fresh certificate needed when a working capital limit is renewed?</h3>
  <div class="faq-expanded__a"><p>Yes. Cash credit and overdraft limits are typically reviewed every twelve months. The renewal file is rebuilt with current financials, so the net worth certificate is refreshed with them. Borrowers who treat renewal as automatic are the ones caught out when the branch asks for a certificate at short notice.</p></div>
</div>
