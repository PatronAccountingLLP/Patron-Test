            <span class="section-eyebrow"></span>
            <h2 class="section-title">Home Loans and Property Finance</h2>
            <div class="content-text">
                <ul class="al-list">
                    <li><span class="al-t">How lenders read property in a home loan file</span><span class="al-d">For a home loan against the property being purchased, a separate net worth certificate is very often not required at all, and we will say so. The lender values the security itself and assesses repayment capacity from income documents. A certificate becomes relevant where the borrower is self-employed, where the loan is against an existing property, or where the sanction is large enough that the branch wants the wider position.</span></li>
                    <li><span class="al-t">Existing EMIs and how they affect eligibility</span><span class="al-d">Every running loan reduces what a lender will advance, and the certificate has to show them rather than net them away silently. Outstanding balances are stated against the assets they secure, so the reader can see both the property and the borrowing over it. A file that shows assets without the corresponding EMIs is recalculated by the credit team, and the recalculation is always less favourable than the disclosure would have been.</span></li>
                    <li><span class="al-t">Under-construction property</span><span class="al-d">A property still under construction is not held on the same terms as a completed one. What the buyer holds is a set of rights under an agreement, with payments made to date and payments still due. The certificate states the position that way rather than recording a completed asset, because the difference matters to a lender assessing security and to any recipient assessing what could actually be sold.</span></li>
                    <li><span class="al-t">Where the property is already mortgaged</span><span class="al-d">A loan against an existing property needs the current charge established before anything else. The property is stated at its own value with the outstanding balance against it, and what remains is what a second lender can look to. Where the first <a href="/glossary/networth/mortgage">mortgage</a> was created by deposit of title deeds it may leave no public trace at all, so the lender's own confirmation is what evidences it. A clean <a href="/glossary/networth/encumbrance-certificate">encumbrance certificate</a> is not proof that a property is unencumbered, and treating it as one is how a second charge application fails late.</span></li>
                </ul>
