<section class="content-section" id="joint-owners-and-co-section">
    <div class="content-container">
        <div class="text-content">
            <span class="section-eyebrow"></span>
            <h2 class="section-title">Joint Owners and Co-Applicants</h2>
            <div class="content-text">
                <ul class="al-list">
                    <li><span class="al-t">Whose net worth counts</span><span class="al-d">Where a property or a facility is held jointly, the first question is whose position the lender is assessing, and the answer is rarely everybody equally. A co-applicant on a loan is assessed because they are liable for repayment. A joint owner of the security is assessed because their consent and their share are needed to enforce it. Those are different roles and a branch that asks for a certificate for joint owners in India usually means one of them specifically. We read the requirement letter before deciding whose records to ask for.</span></li>
                    <li><span class="al-t">One certificate or two</span><span class="al-d">Two joint owners are not certified in one document, because a single combined figure cannot be attributed to either of them. Each person receives their own certificate stating their own position. The jointly held asset appears in both, at the share genuinely held. The two certificates are prepared from the same underlying records and issued together. The branch can then read them side by side and see the shares sum to the whole rather than exceeding it.</span></li>
                    <li><span class="al-t">A co-applicant against a joint owner</span><span class="al-d">These get used interchangeably in conversation and they are not the same. A co-applicant shares liability for the debt and may own nothing. A joint owner holds a share of the asset and may have no liability at all. A spouse added to a property for succession reasons is often a joint owner and not a co-applicant; a parent added to strengthen an application is often a co-applicant and not an owner. The certificate says which role the person occupies rather than leaving the branch to infer it.</span></li>
                    <li><span class="al-t">Apportioning jointly held assets</span><span class="al-d">A jointly held asset is entered at the share actually held, and the basis for that share is stated. Where the registered instrument names the shares, that governs. Where it records joint ownership without shares, the default position is equal shares unless the funding trail shows otherwise, and where it does show otherwise the trail is what is cited. An asset entered at full value in two separate certificates, instead of apportioned between them, is the commonest error in joint applications. A credit team that spots it discounts both documents rather than one.</span></li>
                </ul>
            </div>
        </div>
    </div>
</section>

<section class="content-section" id="guarantors-and-third-party-section">
    <div class="content-container">
        <div class="text-content">
            <span class="section-eyebrow"></span>
            <h2 class="section-title">Guarantors and Third-Party Security</h2>
            <div class="content-text">
                <ul class="al-list">
                    <li><span class="al-t">What a guarantor's certificate must prove</span><span class="al-d">A guarantor is assessed personally, because the guarantee is a personal liability that survives whatever happens to the borrower. A networth certificate for an individual guarantor therefore covers everything they hold in their own name, not the borrower's business and not any entity they are connected to. Company accounts are irrelevant to this question however strong they look. What the lender is testing is whether this individual could meet the obligation if called on.</span></li>
                    <li><span class="al-t">Education loan guarantors</span><span class="al-d">Education loans are where most individual guarantee requirements arise, and lenders in this segment including HDFC Credila and the public sector banks ask for a guarantor or co-applicant certificate as standard. The guarantor is usually a parent, and the certificate is read alongside the loan sanction and the admission letter. Where the same parent is also sponsoring the <a href="/net-worth-certificate-for-visa">visa application</a>, one set of records supports both documents, but the two certificates are drawn for their own readers rather than reused.</span></li>
                    <li><span class="al-t">UDIN verification by the lender</span><span class="al-d">Every certificate we issue carries a Unique Document Identification Number generated on the ICAI portal, and a lender can verify it there without contacting us. This matters more for a guarantee than for most engagements, because the branch is relying on a document about somebody who is not their customer. UDIN verification lets the credit team confirm the signatory independently before the guarantee is accepted.</span></li>
                    <li><span class="al-t">What the guarantor is actually taking on</span><span class="al-d">A guarantee is a contingent liability for the guarantor, and it belongs on their own <a href="/glossary/networth/statement-of-affairs">statement of affairs</a> from the day it is signed. It costs nothing while the borrower pays and becomes the whole amount if they stop. Guarantors are frequently unaware that an existing guarantee reduces what they can borrow themselves, which is why we ask about guarantees already given before certifying a new one.</span></li>
                    <li><span class="al-t">Third-party security without a guarantee</span><span class="al-d">Not everybody who supports a loan is a guarantor. A person who offers their property as security without accepting personal liability is a third-party mortgagor, and their exposure is limited to that asset. The distinction matters because the certificate is drawn differently. A guarantor is certified on their whole position; a third-party mortgagor may only need the asset offered evidenced and its title established. Branches use the two words interchangeably, so we read the security documents rather than the covering letter.</span></li>
                </ul>
            </div>
        </div>
