    <div class="content-container">
        <div class="two-column">
            <div class="column-content">
                <h2 class="section-title">What Is a Net Worth Certificate for a Bank Loan?</h2>
                <div class="content-text what-is-definition">
<p>In lending, a <a href="/net-worth-certificate">net worth certificate</a> is an attested statement of what a borrower, co-applicant, <a href="/blog/joint-owners-net-worth-certificate-explained">joint owner</a> or guarantor holds against what they owe. It is one input into a credit file, not the file itself.</p><p>Its limits define its use. It is not a credit appraisal and reaches no view on eligibility, sanction or servicing capacity. It is not a valuation report: property and unlisted holdings are stated on a disclosed basis, which a bank may accept, discount or value independently. And it does not confirm that an asset is unencumbered beyond the charges disclosed in the records examined.</p>
                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key terms on this page:</strong></p>
                    <div class="key-terms"><ul class="al-list">
                    <li><span class="al-t"><a href="/glossary/networth/lien">Lien</a></span><span class="al-d">A lien is a creditor's right to retain something belonging to a debtor until what is owed has been paid.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/pledge">Pledge</a></span><span class="al-d">A pledge is a security interest over movable property where possession passes to the creditor while ownership remains with the borrower.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/hypothecation">Hypothecation</a></span><span class="al-d">Hypothecation creates a charge over movable property without the creditor taking possession of it.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/mortgage">Mortgage</a></span><span class="al-d">A mortgage is a transfer of an interest in immovable property to secure a debt.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/collateral">Collateral</a></span><span class="al-d">Collateral is anything a borrower gives a lender the right to sell if the loan is not repaid.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/margin-money">Margin Money</a></span><span class="al-d">Margin money is the borrower's own contribution to a funded purchase, and it is fixed as the difference between the asset's value and what the lender will advance.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/loan-to-value-ratio-ltv">Loan-to-Value Ratio (LTV)</a></span><span class="al-d">Loan to value expresses the advance as a proportion of the asset securing it.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/debt-service-coverage-ratio-dscr">Debt Service Coverage Ratio (DSCR)</a></span><span class="al-d">Debt service coverage ratio measures how much cash is available for every rupee of repayment falling due.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/moratorium">Moratorium</a></span><span class="al-d">A moratorium suspends repayment for a stated period.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/bank-guarantee-bg">Bank Guarantee (BG)</a></span><span class="al-d">A bank guarantee is the bank's own promise to pay a stated sum if its customer fails to perform.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/letter-of-credit-lc">Letter of Credit (LC)</a></span><span class="al-d">A letter of credit is an undertaking by a bank to pay a seller against documents rather than against goods.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/credit-information-report-cibil">Credit Information Report (CIBIL)</a></span><span class="al-d">A credit information report records how a borrower has behaved, not what they own.</span></li>
                    <li><span class="al-t"><a href="/glossary/networth/debt-to-equity-ratio">Debt-to-Equity Ratio</a></span><span class="al-d">The debt-to-equity ratio is built from two totals that sit on the same balance sheet.</span></li>
                    </ul></div>
