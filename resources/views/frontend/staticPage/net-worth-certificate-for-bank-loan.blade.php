            <h2 class="section-title">The Legal and Professional Framework Behind Bank Loan Net Worth Certificates</h2>
            <div class="content-text">
                <p>Nothing in banking law prescribes the form of a net worth certificate. What the law does prescribe is where security interests are recorded, and that is what turns a certificate from an assertion into something a credit team can test.</p>
                <p>A lender will run its own searches whatever the certificate says. The provisions below govern what those searches will find, and the professional framework governs how the position is prepared before they are run.</p>
                <ul class="al-list">
                    <li><span class="al-t"><strong>CERSAI, the Central Registry of Securitisation Asset Reconstruction and Security Interest</strong></span><span class="al-d">records security interests created over property, and a lender searches it as a matter of course. A charge omitted from the certificate but present in the registry costs more credibility than the asset was worth.</span></li>
                    <li><span class="al-t"><strong>Section 17, Registration Act 1908</strong></span><span class="al-d">makes the registered instrument the evidence of title, and the registered share is what a jointly held asset may be entered at rather than its whole value.</span></li>
                    <li><span class="al-t"><strong>Section 129, Companies Act 2013</strong></span><span class="al-d">requires audited financial statements to be prepared where the borrower is a company, and three years of them are what the appraisal note is usually built around.</span></li>
                    <li><span class="al-t"><strong>Section 139, Income-tax Act 1961</strong></span><span class="al-d">produces the returns a credit team reads for direction as well as level, since a position unsupported by declared income is discounted before it reaches the sanctioning authority.</span></li>
                    <li><span class="al-t"><strong>ICAI Guidance Note on Reports or Certificates for Special Purposes (Revised 2016)</strong></span><span class="al-d">governs how the certificate is framed for a credit file, and requires the basis of every stated value to be disclosed rather than left for the branch's valuer to reconstruct.</span></li>
                    <li><span class="al-t"><strong>ICAI Council direction on UDIN, mandatory from 1 February 2019</strong></span><span class="al-d">allows the branch to verify the certificate on the ICAI portal before the credit note is written rather than after the facility is sanctioned.</span></li>
                </ul>
