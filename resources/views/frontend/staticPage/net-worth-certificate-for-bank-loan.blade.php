<section class="content-section" id="business-loans-and-working-section">
    <div class="content-container">
        <div class="text-content">
            <span class="section-eyebrow"></span>
            <h2 class="section-title">Business Loans and Working Capital Limits</h2>
            <div class="content-text">
                <ul class="al-list">
                    <li><span class="al-t">What the credit note actually asks for</span><span class="al-d">A business loan file is assessed on the borrowing entity and on whoever stands behind it, and the credit note usually names both. For an unsecured facility the certificate is the comfort, because there is no security to fall back on. For a secured facility it sits alongside the valuation and the charge search. Asking the branch which of the two situations applies takes one call and decides whose position is certified.</span></li>
                    <li><span class="al-t">Firm net worth against promoter net worth</span><span class="al-d">Lenders assessing a working capital limit frequently want both, and they want them presented separately rather than added together. The firm's position shows what the business holds. The <a href="/net-worth-certificate-for-rera-registration">promoter</a>'s shows what stands behind it if the business cannot pay. Combining the two overstates the position, because the promoter's capital in the firm then appears on both sides of the same total.</span></li>
                    <li><span class="al-t">Cash credit and overdraft renewals</span><span class="al-d">A renewal is not a fresh sanction and the credit team is looking for movement rather than for a first impression. The certificate is drawn to the same basis as the previous year so the two are comparable, and any material change is explained rather than left to be discovered. Where the limit has been fully drawn throughout the year, that is visible in the statements and is better addressed in the file than in a query.</span></li>
                    <li><span class="al-t">Drawing power and the stock statement</span><span class="al-d">Working capital limits are not assessed on net worth alone. The branch calculates drawing power from stock and receivables after margin, usually monthly, and the net worth certificate sits behind that as evidence of the standing of whoever is borrowing. Where the two disagree it is worth resolving before submission. Stock valued on one basis in the certificate and another in the monthly statement is a question the credit team will raise. Preparing both from the same records, on the same basis, removes it. Preparing both from the same records, on the same basis, removes the question before it is asked.</span></li>
