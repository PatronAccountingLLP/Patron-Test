                <div class="content-text what-is-definition">
                    
                    <p><strong>Definition:</strong> A Net Worth Certificate for Business Loan is a CA-issued document, signed under UDIN, certifying the total assets minus liabilities of the borrowing firm or of an individual partner / director / guarantor as on a specific date for submission to a bank or NBFC.</p>
                    <p>Structurally, a business-loan net worth certificate has more layers than a visa or general-purpose certificate. For the borrowing entity, business assets dominate: paid-up capital (or partners capital), reserves, undistributed profits, plant and machinery at written-down value, debtors net of provisions, inventory at lower of cost or realisable value, business bank balances, and security deposits. Liabilities include secured borrowings, unsecured loans, trade payables, statutory dues (GST, TDS, PF, ESI), and accumulated losses. For each partner, director, or guarantor, the certificate moves to the personal asset side - residential property, investments, vehicles, gold, personal bank balances - minus personal liabilities like home loan, car loan, and credit card outstandings.</p>
                    <p>For business loan use, three additional features are non-negotiable: a purpose statement naming the lending bank and loan facility (for example, "This certificate is issued in support of the Cash Credit Limit of Rs 50 lakh applied for at State Bank of India, MG Road branch"); a UDIN generated on the ICAI portal at <a href="https://udin.icai.org" target="_blank" rel="noopener">udin.icai.org</a>; and the CA membership number plus firm registration number. For company borrowers, the certificate must additionally state that the net worth has been computed in accordance with Section 2(57) of the Companies Act, 2013 (paid-up share capital + reserves - accumulated losses - deferred expenditure not written off). A certificate without UDIN is treated by bank credit officers as unverified.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Net Worth Certificate for Business Loan:</strong></p>
                    <ul>
                        <li><strong>UDIN:</strong> 18-digit Unique Document Identification Number generated on the ICAI portal. Mandatory on every CA certificate since 1 February 2019. Bank credit officers verify it at udin.icai.org.</li>
