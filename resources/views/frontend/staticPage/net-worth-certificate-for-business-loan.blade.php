                        <li><strong>Section 2(57) of the Companies Act, 2013:</strong> Statutory definition of net worth for companies and LLPs - paid-up share capital + reserves - accumulated losses - deferred expenditure not written off.</li>
                        <li><strong>MSMED Act, 2006:</strong> Micro, Small and Medium Enterprises Development Act - statutory basis for MSME classification, Udyam Registration, and CGTMSE eligibility.</li>
