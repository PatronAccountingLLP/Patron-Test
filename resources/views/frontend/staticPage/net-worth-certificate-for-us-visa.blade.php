                <div class="content-text what-is-definition">
                    
                    <p><strong>Definition:</strong> A Net Worth Certificate for US Visa is a Chartered Accountant-issued document, signed under UDIN, certifying the applicant or sponsor total assets minus liabilities in INR and USD for submission to the US embassy.</p>
                    <p>Structurally, the certificate is a one to two page statement on the CA letterhead listing every material asset (bank balances, fixed deposits, mutual funds, equity shares, immovable property at conservative fair value, gold, business interests, receivables) and every material liability (home loans, personal loans, education loans, credit card outstandings, business borrowings). The net worth is the arithmetic difference, expressed in INR and converted to USD at the Reserve Bank of India reference rate on the certificate date.</p>
                    <p>For US visa use, three additional features are non-negotiable: a purpose statement naming the visa category (for example, "This certificate is issued for the F-1 student visa application of Mr. X at the US Embassy, New Delhi"); a UDIN generated on the ICAI portal at <a href="https://udin.icai.org" target="_blank" rel="noopener">udin.icai.org</a>; and the CA membership number plus firm registration number. A certificate without UDIN is treated by US consulates as unverified.</p>

