            <h2 class="section-title">Legal and Compliance Framework for Partnership Firms</h2>
            <div class="content-text">
                
                <p><strong>Governing Act:</strong> <a href="https://www.indiacode.nic.in/bitstream/123456789/19863/1/indian_partnership_act_1932.pdf" target="_blank" rel="noopener">Indian Partnership Act, 1932</a> (Act No. IX of 1932)</p>
                <p><strong>Key Sections:</strong> Section 4 defines 'partnership' as the relation between persons who have agreed to share profits of a business carried on by all or any of them acting for all. Section 5 clarifies partnership is not created by status. Section 25 establishes joint and several liability for all acts of the firm. Section 57 empowers State Governments to appoint Registrars. Section 58 prescribes the application for registration. Section 59 covers registration procedure. Section 69 specifies disabilities of non-registration - unregistered firms cannot sue third parties, enforce claims exceeding Rs 100, or allow partners to sue each other.</p>
                <p><strong>Penalty Provisions:</strong> Under Section 70 of the Indian Partnership Act, 1932, any person who furnishes false particulars in a statement or notice delivered to the Registrar shall be punishable with imprisonment which may extend to 3 months or fine up to Rs 500 or both. Under Section 25, partners are jointly and severally liable for all acts of the firm - unlimited personal liability for firm debts and obligations.</p>
                <p><strong>Tax Provisions:</strong> Partnership firm taxed at 30% flat rate + 4% Health and Education Cess under the Income Tax Act, 1961. Surcharge of 12% applicable if total income exceeds Rs 1 crore. Tax audit mandatory under Section 44AB if turnover exceeds Rs 1 crore (Rs 10 crore if 95%+ digital transactions). GST registration mandatory if turnover exceeds Rs 40 lakh (goods) or Rs 20 lakh (services) under CGST Act, 2017.</p>
                <p><strong>Regulatory Authority:</strong> Registrar of Firms (state-level, appointed under Section 57, Indian Partnership Act, 1932).</p>

