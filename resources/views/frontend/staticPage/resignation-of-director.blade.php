<tr><td>Section 168(1), Companies Act 2013</td><td>Resignation by written notice to company. Board to take note. Company to intimate ROC in DIR-12 and disclose in Board Report.</td></tr>
<tr><td>Section 168(2)</td><td>Effective from date company receives notice, or later date in notice, whichever is later. Resigned director remains liable for offences during tenure.</td></tr>
<tr><td>Section 168(3)</td><td>If all directors resign simultaneously, promoter or Central Government appoints interim directors until general meeting.</td></tr>
