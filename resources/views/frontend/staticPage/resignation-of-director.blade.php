        <div class="two-column">
            <div class="column-content">
                <h2 class="section-title">What is Resignation of Director?</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>Resignation of a Director</strong> is the voluntary exit of a person from the Board of Directors of a company by submitting written notice to the company under Section 168 of the Companies Act 2013, with the resignation taking effect on the date the notice is received by the company or the date specified by the director in the notice, whichever is later.</p>
<p>A resignation is not accepted or rejected by the Board - it takes effect by operation of law once notice is received. The Board's role is only to take note of the resignation and authorise the company to file DIR-12. A director who has resigned remains liable for all acts and offences that occurred during their tenure, even after their exit date.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Resignation of Director:</strong></p>
                    <p><strong>Form DIR-12</strong> - MCA form filed by the company to inform ROC about director resignation - mandatory within 30 days under Sections 168 and 170(2), Rule 15 and Rule 18.</p>
<p><strong>Form DIR-11</strong> - MCA form filed by the resigning director to self-report resignation - optional since Companies (Amendment) Act 2017 changed 'shall' to 'may' in Rule 16. Recommended when director suspects company may delay DIR-12.</p>
<p><strong>Effective Date</strong> - Date company receives written notice OR date specified by director in notice, whichever is LATER - Section 168(2).</p>
<p><strong>DIN</strong> - Director Identification Number. After DIR-12 is filed, DIN is marked as 'Resigned' on MCA Master Data.</p>
<p><strong>Post-Resignation Liability</strong> - Under Section 168(2) proviso, a resigned director remains personally liable for all offences during their tenure.</p>

