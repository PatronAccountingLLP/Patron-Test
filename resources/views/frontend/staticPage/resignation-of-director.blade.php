            <h2 class="section-title">Who Can Resign and Effective Date Rules</h2>
            <div class="content-text">
                
                <p>Section 168 applies to all directors of every company registered under the Companies Act 2013:</p>
<ul>
<li>Executive directors and Whole-Time Directors (WTDs) - may also need to comply with service contract terms</li>
<li>Non-executive and Independent Directors - resignation takes effect on notice date with no board approval needed</li>
<li>Nominee Directors - resignation must be coordinated with the nominating institution</li>
<li>Managing Directors - if resigning as both MD and director, ensure both roles addressed in resignation letter</li>
<li>Foreign Directors - may authorise a CA, CS, or CMA in practice to sign and file DIR-11 on their behalf under Rule 16</li>
<li>Directors in OPCs - if the sole director resigns, they must appoint a replacement before vacating office</li>
</ul>
<p style='margin-top:16px;'><strong>Effective Date Examples:</strong> If director sends notice on 5 March 2026, company receives it on 8 March with no future date specified, effective date is 8 March 2026. If notice says 'effective from 31 March 2026', effective date is 31 March 2026 (later date).</p>

