            <h2 class="section-title">Legal Framework for Trademark Assignment in India</h2>
            <div class="content-text">
                
                <p><strong>Governing Law:</strong> <a href="https://www.indiacode.nic.in/handle/123456789/1993" target="_blank" rel="noopener">Trade Marks Act, 1999</a> (Sections 37-45); Trademark Rules, 2017.</p>
<p><strong>Key Provisions:</strong></p>
<ul>
<li><strong>Section 37:</strong> Power to assign and give receipts for consideration.</li>
<li><strong>Section 38:</strong> Registered TMs assignable with/without goodwill, for all/some goods.</li>
<li><strong>Section 39:</strong> Unregistered TMs also assignable.</li>
<li><strong>Section 40:</strong> Restriction on creating multiple exclusive rights for same goods. Validity certificate under 40(2).</li>
<li><strong>Section 41:</strong> Restriction on territorial exclusive rights in different parts of India.</li>
<li><strong>Section 42:</strong> Assignment without goodwill - mandatory advertisement as directed by Registrar.</li>
<li><strong>Section 44:</strong> Associated trademarks must be assigned together.</li>
<li><strong>Section 45:</strong> Registration mandatory within 6 months (extendable by 6). Unrecorded = unenforceable.</li>
</ul>
<p><strong>Forms:</strong> <a href="https://ipindia.gov.in/writereaddata/Portal/Images/pdf/FORM-TM-P.pdf" target="_blank" rel="noopener">Form TM-P</a> | <a href="https://www.wipo.int/wipolex/en/text/128107" target="_blank" rel="noopener">TM Act (WIPO)</a></p>

