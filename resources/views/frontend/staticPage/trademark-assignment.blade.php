                    <p><strong>Assignor:</strong> Current proprietor transferring ownership through the assignment deed.</p>
<p><strong>Assignee:</strong> Person/entity receiving ownership. Becomes new proprietor upon recording.</p>
<p><strong>Assignment with Goodwill:</strong> Transfer of trademark along with business reputation and customer association connected to it.</p>
<p><strong>Assignment without Goodwill (Gross Assignment):</strong> Transfer of trademark rights only. Section 42 requires mandatory advertisement as directed by the Registrar.</p>
<p><strong>Form TM-P:</strong> Multi-purpose form under Trademark Rules 2017 for recording assignments, transmissions, and changes with the Registrar.</p>
<p><strong>Transmission:</strong> Transfer by operation of law (death, inheritance, court order) - distinct from voluntary assignment.</p>

