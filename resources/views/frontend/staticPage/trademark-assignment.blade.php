                <div class="content-text what-is-definition">
                    
                    <p>Trademark Assignment is the permanent transfer of ownership from the <strong>assignor</strong> (current owner) to the <strong>assignee</strong> (new owner) through a written agreement, as defined under <strong>Section 2(1)(b) of the Trade Marks Act, 1999</strong>. The assignment may cover all or some goods/services, and may be with or without goodwill.</p>
<p>The framework is in Sections 37-45: Section 37 (power to assign), Section 38 (registered TMs), Section 39 (unregistered TMs), Sections 40-41 (restrictions on multiple exclusive rights and territorial conflicts), Section 42 (conditions for assignment without goodwill), and Section 45 (mandatory registration with the Trademark Registry).</p>
<p>The assignment is recorded by filing <a href="https://ipindia.gov.in/writereaddata/Portal/Images/pdf/FORM-TM-P.pdf" target="_blank" rel="noopener">Form TM-P</a> with the Registrar, who updates the Register of Trademarks. An unrecorded assignment is not enforceable against third parties. See the <a href="https://www.wipo.int/wipolex/en/text/128107" target="_blank" rel="noopener">Trade Marks Act on WIPO</a>.</p>

                </div>
