                <h2 class="section-title">What Is Trademark Formality Check Fail?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>After a trademark application is filed under Section 18 of the Trade Marks Act, 1999, the Trademark Registry performs a preliminary administrative screening before assigning the application for substantive examination. This screening checks whether the application meets all formal requirements - correct forms, complete documentation, proper classification, correct fees, and accurate applicant details.</p>
                    <p>If all formal requirements are met, the status is updated to 'Formalities Chk Pass' on the IP India portal, and the application proceeds to: (a) 'Send to Vienna Codification' (for device marks/logos) or (b) directly to 'Marked for Exam' (for wordmarks). If any formal requirement is not met, the status is updated to 'Formalities Chk Fail', and the Registry issues a notice (sometimes called a 'keep pending notice') to the applicant or their agent, specifying the exact deficiencies that need to be rectified.</p>
                    <p>This status does NOT mean your trademark application has been rejected. It is a procedural hold that can be resolved by filing an appropriate reply with the corrections. The application moves forward to 'Formalities Chk Pass' once the Registry is satisfied with the reply. If the reply is inadequate, the status may remain as 'Formalities Chk Fail' with a fresh notice. However, if no reply is filed within 30 days, the application is marked 'Abandoned' and all investment in filing is lost.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Trademark Formality Check Fail:</strong></p>
                    <ul>
                        <li><strong>Formalities Chk Fail:</strong> IP India portal status indicating that the trademark application has not passed the preliminary administrative screening due to procedural/documentary deficiencies.</li>
                        <li><strong>MIS-F (Miscellaneous Reply to Formality Check):</strong> The reply mechanism on the IP India portal. Filed under 'Miscellaneous Reply' > 'Reply to Formality Check (MIS-F)' using the trademark application number.</li>
                        <li><strong>Form TM-M:</strong> Amendment form used to correct details in a filed trademark application (name, address, classification, goods/services description). Government fee: Rs 900 for individuals/startups, Rs 1,800 for others.</li>
                        <li><strong>NICE Classification:</strong> International classification system for goods and services (45 classes: 1-34 for goods, 35-45 for services). Selecting the wrong class is a top reason for formality check fail.</li>
                        <li><strong>Vienna Codification:</strong> International classification for figurative elements (logos, labels, artwork) in trademarks. Device marks are sent to Vienna Codification before formality check.</li>
                        <li><strong>Form TM-48:</strong> Power of Attorney authorising a trademark agent/attorney to act on behalf of the applicant.</li>
                    </ul>

