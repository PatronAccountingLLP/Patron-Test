        <div class="two-column">
            <div class="column-content">
                <h2 class="section-title">What Is Trademark Opposition?</h2>
                <div class="content-text what-is-definition">
                    
                    <p><strong>Trademark opposition is a formal legal proceeding under Section 21 of the Trade Marks Act, 1999, where any person challenges a published trademark application before it proceeds to registration.</strong></p>
<p>After the Examiner accepts an application and it is published in the <a href="https://ipindia.gov.in/journal-tm.htm" target="_blank" rel="noopener">Trade Marks Journal</a>, it enters a <strong>4-month opposition window</strong>. During this period, any person may file a Notice of Opposition using <strong>Form TM-O</strong>, citing grounds under Section 9 (absolute) or Section 11 (relative). Opposition is distinct from objection - objection is raised by the Examiner during examination; opposition is filed by a third party after acceptance.</p>
<p>The Registrar evaluates based on evidence and arguments from both parties and decides under <strong>Section 21(5)</strong> whether to allow registration, refuse it, or impose conditions. Appeals lie to the High Court under <a href="https://www.indiacode.nic.in/handle/123456789/1993" target="_blank" rel="noopener">Section 91</a>.</p>

                </div>
                <div class="highlight-box" style="margin-top:20px;">
                    <p><strong>Key Terms for Trademark Opposition:</strong></p>
                    <p><strong>Notice of Opposition:</strong> Filed in Form TM-O within 4 months of journal publication under Section 21(1). Fee: Rs 2,700 per class.</p>
<p><strong>Counter-Statement:</strong> Applicant's reply filed in Form TM-O within 2 months. Failure = deemed abandonment under Section 21(2). Non-extendable.</p>
<p><strong>Opponent:</strong> The challenging party. Under Indian law, any person can oppose - not limited to trademark owners. Even consumers can file.</p>
<p><strong>Evidence by Affidavit:</strong> Three stages - opponent's evidence (Rule 45), applicant's evidence (Rule 46), opponent's reply evidence (Rule 47).</p>
<p><strong>Trade Marks Journal:</strong> Official weekly publication at ipindia.gov.in. Published every Monday. The 4-month opposition clock starts from the publication date.</p>

