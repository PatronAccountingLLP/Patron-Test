                <h2 class="section-title">What Is Trademark Rectification?</h2>
                <div class="content-text what-is-definition">
                    
                    <p>Trademark rectification is the process of correcting, varying, or cancelling entries in the Register of Trademarks maintained by the Registrar under the Trade Marks Act, 1999. It encompasses three distinct but interrelated provisions:</p>
                    <p><strong>Section 47 - Removal for Non-Use:</strong> Provides for removal of a registered trademark from the Register on the ground that it was registered without bona fide intention to use, or that there has been no bona fide use for a continuous period of 5 years from the date of registration up to 3 months before the rectification application. The initial 5 years after registration constitute a 'grace period' during which the mark is protected from non-use challenges.</p>
                    <p><strong>Section 57 - Power to Cancel, Vary, or Rectify:</strong> Empowers the Registrar or the High Court to cancel or vary the registration, or rectify the Register, on the grounds of: contravention or failure to observe a condition of registration, absence or omission of an entry, entry made without sufficient cause (including fraud or misrepresentation), entry wrongly remaining on the Register, or any error or defect in an entry.</p>
                    <p><strong>Section 58 - Correction of Register:</strong> Allows the Registrar, on application by the registered proprietor, to correct or change any error in the particulars or entry, cancel the entry, or strike out goods/services/classes from the registration.</p>

