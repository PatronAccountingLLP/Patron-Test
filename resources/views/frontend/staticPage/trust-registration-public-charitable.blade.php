                <div class="content-text what-is-definition">
                    
                    <p><strong>A public charitable trust is a legal arrangement under the Indian Trusts Act, 1882 in which a settlor transfers property to trustees to hold for a charitable purpose that benefits the public at large.</strong> Its objects must be exclusively charitable, such as relief of the poor, education, medical relief, or any object of general public utility.</p>
                    <p>Unlike a private trust, a public charitable trust serves society rather than named individuals, and it can claim income tax exemption and offer donor deductions once registered under <strong>Section 332 (RNPO) and Section 354</strong> of the Income Tax Act, 2025, the provisions that replaced 12A/12AB and 80G from 1 April 2026.</p>

