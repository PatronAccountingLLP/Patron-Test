  <div class="step-content">
    <span class="step-badge">Step 2</span>
    <h3 class="step-title">Test the cut-off both ways</h3>
    <p class="step-description">We work the last and first document numbers on either side of the year-end, covering despatches, goods receipts, invoices and e-way bills. That catches goods received but not invoiced, and invoices raised for goods not yet despatched. Cut-off errors move profit between two years.</p>
  </div>
