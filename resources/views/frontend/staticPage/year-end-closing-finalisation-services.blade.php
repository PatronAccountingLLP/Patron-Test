            <div class="step-card">
  <div class="step-content">
    <span class="step-badge">Step 1</span>
    <h3 class="step-title">Close the sub-ledgers first</h3>
    <p class="step-description">Sales, purchase, payroll, fixed asset and inventory sub-ledgers are closed and agreed to their control accounts before anything else happens. Once agreed, the period is restricted so a late entry cannot silently change a figure that has already been reviewed and signed off.</p>
  </div>
  <div class="step-visual"><div class="step-illustration" style="padding:0;background:none;"><img src="/images/accounting-cluster/year-end-closing-finalisation-services/step-1-close-the-sub-ledgers-first.webp" alt="Illustration for Close the sub-ledgers first: Sales, purchase, payroll, fixed asset and inventory sub-ledgers are closed and" loading="lazy" width="1200" height="896" style="width:100%;height:auto;border-radius:var(--radius-xl);"></div></div>
</div>
