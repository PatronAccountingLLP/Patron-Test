      <section id="what-the-word-adjusted-adds-back-and-strips-out" class="gl-sec">
        <h2>What the Word &#x27;Adjusted&#x27; Adds Back and Strips Out</h2>
        <div class="definition-box" itemprop="description"><p>Adjusted net worth is net worth after a specific reader's own additions and subtractions have been applied. The word adjusted has no fixed meaning standing alone, which is precisely why it always has to be read against whoever used it. A regulator may require subordinated debt to be added back, on the view that money which cannot be withdrawn ahead of other creditors behaves like capital. A lender may strip out amounts due from directors and related parties, on the view that money lent inside a group is not available to service a loan taken outside it. A tender authority may remove revaluation reserves, on the view that an unrealised uplift is not capacity. The same company can therefore carry three different adjusted figures on the same day. All three are correct, because three readers asked three different questions. Treating adjusted net worth as a single defined quantity is the most common error made with the term, and it usually surfaces when a figure prepared for one recipient is submitted to another.</p></div>
      </section>
      <section id="how-add-backs-and-deductions-are-disclosed-by-th" class="gl-sec">
        <h2>How Add-Backs and Deductions Are Disclosed by the Certifying CA</h2>
        <p>Because the adjustments are the substance rather than the decoration, they are disclosed individually rather than netted into a total. The certificate states the starting figure, lists each add-back and each deduction on its own line together with the requirement that called for it, and arrives at the adjusted figure. A reader can then check whether the adjustments made are the adjustments they actually asked for, which is the only thing that makes the document useful to them. Presenting an adjusted figure without the workings is close to useless, because the recipient has no way of knowing whether their definition was applied or somebody else's. Where a requirement is ambiguous, and published definitions frequently are, the certifying accountant records the interpretation taken rather than choosing silently and hoping. That note costs a line and saves the entire document, since an interpretation stated openly can be corrected while one buried in the arithmetic cannot.</p>
      </section>
      <section id="adjustments-rbi-sebi-and-tender-authorities-spec" class="gl-sec">
        <h2>Adjustments RBI, SEBI and Tender Authorities Specify in India</h2>
        <p>In Indian practice the adjustments most often specified come from three directions. The Reserve Bank prescribes deductions for regulated entities, most visibly the group exposure deduction that turns owned funds into net owned fund for a non-banking financial company. Market regulators set their own net worth requirements for registered intermediaries, each with defined exclusions that differ from the company law definition. Tender authorities and public sector undertakings publish their own definitions inside the bid document, and these vary between departments and sometimes between two tenders issued by the same department in the same year. None of them can be assumed from experience of the last file. The requirement is read from the document that imposed it, before any computation begins, because discovering afterwards that a different definition applied means the work is done again rather than adjusted. Where a bidder holds an adjusted certificate prepared for a different authority, it is read for its workings rather than its total. The workings usually transfer even when the conclusion does not. Rebuilding from them takes less time than starting again.</p>
      </section>
      <section id="concepts-read-alongside-adjusted-net-worth" class="gl-sec">
        <h2>Concepts Read Alongside Adjusted Net Worth</h2>
        <p>The concepts read alongside an adjusted figure fall into two groups. The first is the other main variant of the same measure, arrived at by removing intangibles rather than applying a reader's own rules. The two are regularly confused, because both are smaller than the headline number. The second group is the individual items that adjustments most commonly target: the reserve created by revaluing an asset upward without selling it, and the losses carried forward that reduce what is genuinely there. For a regulated entity there is also the regulatory capital measure, which applies its own defined additions and deductions for supervisory purposes and should not be treated as interchangeable with any of the others. Knowing which of these a recipient means is most of the work. <a href="/glossary/networth/tangible-net-worth">Tangible Net Worth</a>, <a href="/glossary/networth/revaluation-reserve">Revaluation Reserve</a>, <a href="/glossary/networth#accumulated-losses">Accumulated Losses</a>, <a href="/glossary/networth/tier-i-capital">Tier I Capital</a>. A reader who knows which of these four a requirement means can usually reconstruct the intended figure from a certificate prepared on another basis. A reader who does not will simply reject the document and ask for a fresh one.</p>
      </section>
