<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What is the difference between net worth and adjusted net worth?</h3>
<div class="faq-expanded__a"><p>Net worth is the raw figure: assets less liabilities. Adjusted net worth is that figure after the add-backs and deductions a specific reader requires. A lender may deduct amounts due from related parties and add back subordinated promoter loans; a regulator may exclude revaluation gains. The adjusted number means nothing without the rule that produced it.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Who decides which adjustments apply?</h3>
<div class="faq-expanded__a"><p>The party requiring the figure. A sanction letter lists its covenant adjustments, a tender document lists its own, and a regulator publishes a computation. A chartered accountant applies the stated basis and names it on the certificate, because an adjusted figure without its rule cannot be checked by anyone.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is adjusted net worth higher or lower than book net worth?</h3>
<div class="faq-expanded__a"><p>Usually lower, though not always. Deductions for intangibles, related-party receivables and revaluation reserves pull the figure down. Add-backs for subordinated debt or quasi-equity instruments push it up. Which way it moves depends entirely on the adjustment list, which is why the two figures are never used interchangeably.</p></div>
