<h3 class="faq-expanded__q">What transactions appear in the Annual Information Statement?</h3>
<div class="faq-expanded__a"><p>Interest and dividend received, purchases and sales of securities and mutual funds, foreign remittances, property registrations above reporting thresholds, and large cash deposits. Section 285BB and Rule 114-I provide for the statement, which the department builds from reports filed by banks, registrars and other entities.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How is the Annual Information Statement used when certifying net worth?</h3>
<div class="faq-expanded__a"><p>As a completeness check. An asset visible in the statement but absent from the client&#x27;s schedule is a gap the chartered accountant has to resolve before signing. Legitimate explanations exist, such as a jointly held account or an asset disposed of during the year, and each is documented.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Can entries in the Annual Information Statement be wrong?</h3>
<div class="faq-expanded__a"><p>Yes, and feedback can be submitted against an entry the taxpayer disputes. Reporting entities occasionally file duplicate or misattributed transactions, particularly on jointly held accounts. That is why a mismatch is investigated rather than treated as proof that the client withheld something. Feedback is submitted on the compliance portal and the reporting entity is asked to confirm or revise.</p></div>
