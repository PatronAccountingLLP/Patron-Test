      <section id="what-the-ais-reports-back-to-a-taxpayer" class="gl-sec">
        <h2>What the AIS Reports Back to a Taxpayer</h2>
        <div class="definition-box" itemprop="description"><p>The annual information statement reports back to a taxpayer what the department has been told about them by third parties. It carries interest credited by banks, dividends paid by companies, and purchases and sales of securities reported by depositories and registrars. Mutual fund transactions, foreign remittances, property transactions above the reporting threshold and high-value cash deposits appear alongside them. It is broader than the tax credit statement that preceded it, because it reports transactions rather than only tax deducted. For a taxpayer it is a summary of their financial year as the department sees it, assembled from reports the taxpayer never sent. That is both its value and its limitation: it is comprehensive about what was reported and silent about anything that was not.</p></div>
      </section>
      <section id="using-ais-entries-to-test-whether-an-asset-list" class="gl-sec">
        <h2>Using AIS Entries to Test Whether an Asset List Is Complete</h2>
        <p>For anybody preparing a statement of assets it is an unusually good completeness check. A client who has forgotten a dormant demat account, a small deposit at a bank they no longer use, or a property transaction from earlier in the year will frequently find it listed. Running the statement against the asset list surfaces holdings that would otherwise be omitted, and omissions are what damage a certificate rather than misvaluations. It also works in the other direction: an entry the client cannot explain is worth resolving before the certificate is signed. A lender or a mission obtaining the same statement will ask about it. The test runs in one direction only, and that limit matters. An entry in the statement that is missing from the asset list is a gap worth explaining, but an asset absent from the statement is not thereby doubtful. Property bought years ago, jewellery, and holdings abroad may generate no reportable event in the year at all. Treating the statement as a complete inventory rather than a record of reported transactions is the mistake that produces both false alarms and false comfort.</p>
      </section>
      <section id="submitting-feedback-reading-the-tis-summary-and" class="gl-sec">
        <h2>Submitting Feedback, Reading the TIS Summary and Handling Common Mismatches</h2>
        <p>Taxpayers can submit feedback against individual entries, marking them as correct, duplicated, belonging to somebody else, or otherwise disputed. The feedback flows into a revised view and into the taxpayer information summary, which aggregates the statement into the figures that pre-fill a return. Common mismatches include interest reported gross where the taxpayer accounted for it net, joint holdings reported in full against one holder, and transactions reported against a PAN by mistake. None of these is unusual and all are worth clearing, because an unaddressed mismatch tends to resurface as a query long after the year has closed. Mismatches fall into a few recurring shapes once you have seen enough of them. A joint holding reported in full against each holder rather than split by share is the most common. Gross sale consideration reported where the taxpayer accounts for the gain is next. Duplicate reporting by two intermediaries for one transaction is third. Each has a feedback category built for it, and choosing the category that actually describes the position matters more than the accompanying note.</p>
      </section>
      <section id="statements-compared-with-the-ais" class="gl-sec">
        <h2>Statements Compared With the AIS</h2>
        <p>The statements compared with this one each cover part of the same ground. One reports tax deducted and collected and is the narrower predecessor. One is the acknowledgement confirming a return was filed. One is the depository's own record of securities held. The last is the broader question of tracing an asset back to its origin, which a reader often begins from entries shown here. The statements set beside this one differ in what they are for rather than in what they contain. One is the older record, now narrowed to tax deducted, collected and paid. One is the summary view derived from this statement, aggregated by information category and carrying the value taken forward after feedback. One is the prefilled return itself, which draws on both. <a href="/glossary/networth/form-26as">Form 26AS</a>, <a href="/glossary/networth#itr-v-acknowledgement">ITR-V (Acknowledgement)</a>, <a href="/glossary/networth#demat-holding-statement">Demat Holding Statement</a>, <a href="/glossary/networth/source-of-funds">Source of Funds</a>. Reading them as a sequence rather than as alternatives is what makes the exercise quick: the summary tells you where to look, and the detailed statement tells you what is there.</p>
      </section>
