      <section id="what-an-apostille-certifies-and-what-it-delibera" class="gl-sec">
        <h2>What an Apostille Certifies and What It Deliberately Does Not</h2>
        <div class="definition-box" itemprop="description"><p>An apostille certifies that a signature on a public document is genuine and that the person who signed held the office they claimed. That is the whole of what it does. It says nothing about whether the contents are true, whether the figures are right, or whether the document is fit for the purpose it is being used for. A consular officer receiving an apostilled net worth certificate knows that a real chartered accountant signed it and that the Ministry of External Affairs verified the signature. They do not know, from the apostille, that the assets exist. This is the distinction most applicants miss, and it explains why a mission can accept the legalisation and still question the document. The apostille authenticates the author, not the argument. It exists so that a reader in another country does not have to know what an Indian chartered accountant's signature looks like. That is a real problem it solves well, and the only one it solves at all.</p></div>
      </section>
      <section id="preparing-a-certified-net-worth-document-so-it-s" class="gl-sec">
        <h2>Preparing a Certified Net Worth Document So It Survives Legalisation</h2>
        <p>Preparing a certificate so it survives legalisation means finishing it first. The apostille is affixed to a specific physical document, and it authenticates that document's signature. Change anything afterwards, even a spelling in a name, and a new original has to be signed and the whole process repeated. That is why a certificate goes for apostille only when the figures are settled, the recipient's format has been confirmed and the applicant has read it. Several steps also have to happen in order. Notarisation, where the destination requires it, comes before the ministry sees the document. The chartered accountant's signature and UDIN come before that. Working backwards from an appointment date rather than forwards from today is the only reliable way to fit the sequence into the time available. Applicants who start the legalisation early are the ones who most often have to start it again. Where the certificate runs to several pages, the pages are secured together before signature rather than after, because a legalised document that can be separated invites the question of what was attached when.</p>
      </section>
      <section id="mea-apostille-notarisation-and-the-route-through" class="gl-sec">
        <h2>MEA Apostille, Notarisation and the Route Through Indian Branch Secretariats</h2>
        <p>In India the apostille is issued by the Ministry of External Affairs, and documents reach it through authorised intermediaries rather than over a public counter. Regional authentication centres and branch secretariats handle collection in the major cities, and several states require a prior authentication by a designated state authority before the ministry will act. A document originating in one state and apostilled through another's channel is a common cause of delay. Notarisation by a notary public is a separate step from apostille and is not a substitute for it, though the two are frequently confused in conversation. Turnaround varies by centre and by season, and the months before major intake deadlines are the slowest. None of this is difficult, but all of it takes calendar time that an appointment already booked may not leave.</p>
      </section>
      <section id="legalisation-steps-that-follow-or-replace-an-apo" class="gl-sec">
        <h2>Legalisation Steps That Follow or Replace an Apostille</h2>
        <p>The steps that follow or replace an apostille depend entirely on the destination. Where a country is not party to the Hague Convention, the apostille route does not apply at all and a longer chain of authentication ending in that country's embassy is required instead. Where notarisation is expected it precedes everything. And where a document is signed by a professional, the reader may separately want to satisfy themselves that the professional was entitled to sign, which is a different check again. Between them these four cover the whole question of how a document signed in India comes to be relied on abroad. The steps compared here also differ in how much can be corrected afterwards, which is the practical reason to settle the route first. <a href="/glossary/networth#consular-legalisation">Consular Legalisation</a>, <a href="/glossary/networth#notarisation">Notarisation</a>, <a href="/glossary/networth/certificate-of-practice-cop">Certificate of Practice (COP)</a>, <a href="/glossary/networth/attestation">Attestation</a>. A document sent down the wrong route is rarely salvageable in part. Because legalisation attaches to a signed original and each stage certifies the stage before it, an error found at the last counter usually means beginning again at the first, with the certificate itself reissued.</p>
      </section>
