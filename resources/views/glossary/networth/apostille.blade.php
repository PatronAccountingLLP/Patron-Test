<h3 class="faq-expanded__q">What does an apostille do?</h3>
<div class="faq-expanded__a"><p>It certifies the origin of a public document so another country accepts it without further legalisation. The 1961 Hague Convention created the mechanism, and India joined it in 2005. An apostille says the signature and seal are genuine; it says nothing about whether the contents are correct.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Who issues apostilles in India?</h3>
<div class="faq-expanded__a"><p>The Ministry of External Affairs, centrally, with documents routed through authorised collection channels rather than presented over a counter. Several document types must first be authenticated by the relevant state authority or by a notary. Only then does the Ministry apply the apostille sticker. Educational and personal documents commonly need that state-level step before the Ministry will act.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What happens when the destination country is not a party to the Convention?</h3>
<div class="faq-expanded__a"><p>Consular legalisation applies instead. The document is authenticated in India and then attested by the destination country&#x27;s embassy or consulate here, which is a longer chain. Applicants planning for one country and later switching to another are the ones caught out by the difference. The Ministry of External Affairs authenticates first, and the foreign mission in India attests afterwards.</p></div>
