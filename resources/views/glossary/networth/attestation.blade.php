<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does attestation mean in professional practice?</h3>
<div class="faq-expanded__a"><p>It means a member confirms, on the basis of evidence examined, that a document or a figure is true. The Institute treats attestation as a reserved function of members in practice. It is a positive statement backed by working papers, not a formality performed on the client&#x27;s word.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does attestation differ from an audit opinion?</h3>
<div class="faq-expanded__a"><p>Scope and framework. An audit expresses an opinion on financial statements as a whole, under the Standards on Auditing, after planned procedures across a period. An attestation certificate addresses one figure or one document at one date. The ICAI Guidance Note on Reports or Certificates for Special Purposes governs the latter.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is a notary&#x27;s attestation the same thing?</h3>
<div class="faq-expanded__a"><p>No. A notary attests execution or certifies that a copy matches an original; the notary makes no statement about whether the contents are correct. A chartered accountant&#x27;s attestation speaks to the substance of the figure. Documents often carry both, because they answer different questions for the recipient.</p></div>
