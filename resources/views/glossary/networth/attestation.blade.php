      <section id="attestation-audit-and-plain-copy-signing-are-not" class="gl-sec">
        <h2>Attestation, Audit and Plain Copy-Signing Are Not the Same Thing</h2>
        <div class="definition-box" itemprop="description"><p>Attestation, audit and signing a copy are three different things and are treated as one by almost everybody outside the profession. Signing a copy confirms that the copy matches an original the signatory has seen, and nothing more. An audit is an examination of financial statements against a framework, conducted under auditing standards, resulting in an opinion with a defined level of assurance. Attestation sits between them: the professional examines specific information against specific criteria and states a conclusion about it. A net worth certificate is an attestation engagement. Calling it an audit overstates it, and calling it a signed copy understates it to the point of misdescription. The distinction is not a matter of formality but of what the signature asserts. Copy signing asserts that the copy matches the original. An audit expresses an opinion on financial statements taken as a whole, reached under a defined framework. Collapsing the three is how a recipient ends up relying on far less than they think.</p></div>
      </section>
      <section id="the-assurance-a-ca-actually-gives-when-attesting" class="gl-sec">
        <h2>The Assurance a CA Actually Gives When Attesting a Figure</h2>
        <p>The assurance actually given is narrower than a client usually assumes and is stated on the document itself. The accountant confirms that the figures agree with the records examined, that the basis of preparation is as described, and that the scope was what the certificate says it was. What is not confirmed is that the records are complete, because completeness rests on the client's own representation, or that the assets exist beyond the evidence examined. The limitations are not defensive boilerplate. They are what makes the positive statements meaningful, because a conclusion offered without a stated scope could mean anything. What the reader gets is assurance on a stated matter, reached on stated procedures, and bounded by both. A certified figure is not a guarantee of solvency or a prediction that it will hold. It is a professional's statement that a specific number, computed on a specified basis from specified records, is what it is said to be on the date named. Anything beyond that is inference by the reader rather than assurance by the signatory.</p>
      </section>
      <section id="icai-guidance-and-udin-tagging-on-attestation-en" class="gl-sec">
        <h2>ICAI Guidance and UDIN Tagging on Attestation Engagements in India</h2>
        <p>In India the framework comes from the Institute's guidance on reports and certificates for special purposes, revised in 2016, which sets out how such engagements are accepted, performed and reported. Every certificate signed by a practising member also requires a unique document identification number generated on the Institute's portal, mandatory since February 2019, which lets a recipient verify the signature independently. A certificate without a UDIN is not merely informal; it is non-compliant, and the member issuing it is answerable to the disciplinary process. The unique number generated for each such document has changed verification more than anything else in recent practice. A reader can confirm independently that the document was issued by the member who appears to have signed it, on the date it carries. It does not verify the content, and readers who treat a valid number as endorsement of the figure have misunderstood what it certifies.</p>
      </section>
      <section id="assurance-vocabulary-surrounding-attestation" class="gl-sec">
        <h2>Assurance Vocabulary Surrounding Attestation</h2>
        <p>The assurance vocabulary surrounding attestation describes the engagement and its supports. One is the engagement type itself, which the guidance defines. One is the written confirmation from the client that underpins the completeness the accountant cannot independently establish. One is the authority without which a member may not sign at all. The last is what a client does when they sign their own copy, which is not attestation by anybody. The vocabulary around this term marks out levels of assurance that are frequently collapsed into one another. <a href="/glossary/networth#certification-engagement">Certification Engagement</a>, <a href="/glossary/networth/management-representation-letter">Management Representation Letter</a>, <a href="/glossary/networth/certificate-of-practice-cop">Certificate of Practice (COP)</a>, <a href="/glossary/networth#self-attestation">Self-Attestation</a>. One is the highest level, expressed as an opinion. One is the limited form, expressed negatively. One is the agreed-procedures engagement, which reports findings and expresses no conclusion at all. A recipient asking for a certificate when they need an opinion, or accepting findings as though they were a conclusion, is relying on something the document never offered.</p>
      </section>
