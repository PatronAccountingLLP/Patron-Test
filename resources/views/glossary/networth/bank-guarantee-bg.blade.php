      <section id="how-a-bank-guarantee-is-invoked-and-honoured" class="gl-sec">
        <h2>How a Bank Guarantee Is Invoked and Honoured</h2>
        <div class="definition-box" itemprop="description"><p>A bank guarantee is the bank's own promise to pay a stated sum if its customer fails to perform. Invocation is what turns the promise into a payment. The beneficiary writes to the issuing branch within the guarantee's validity, stating that the customer has defaulted in the terms the guarantee describes. The bank then pays. It does not investigate the underlying dispute, because a guarantee is independent of the contract behind it, and that independence is the whole reason a beneficiary accepts one. The customer's remedy, if the invocation was wrong, is against the beneficiary afterwards rather than against the bank beforehand. This catches applicants by surprise more often than any other feature of the instrument. A guarantee is not a deposit held in reserve and it is not conditional on the bank agreeing that a default occurred. Validity matters as much as the amount. A guarantee lapses on its expiry date unless the beneficiary has invoked it or the parties have extended it, and a claim made a day late fails however genuine the default. Indian guarantees usually carry a claim period beyond expiry for exactly this reason.</p></div>
      </section>
      <section id="why-an-issuing-bank-reviews-net-worth-before-san" class="gl-sec">
        <h2>Why an Issuing Bank Reviews Net Worth Before Sanctioning BG Limits</h2>
        <p>An issuing bank reviews net worth before sanctioning a guarantee limit because it is taking the customer's risk without advancing any money. Nothing leaves the bank on the day the guarantee is issued, and if it is never invoked nothing ever does. What the bank is underwriting is the possibility of paying out and then recovering from the customer, which makes the customer's own standing the entire security. A certified position tells the credit team what could be recovered, and it is read alongside the charge position over the assets it names. This is why a guarantee limit is frequently harder to obtain than a funded loan of the same amount, and why an applicant with strong turnover but thin net worth is often declined. The review is repeated at renewal rather than done once. A limit sanctioned against last year's position is reassessed against this year's, and a borrower whose net worth has fallen may find the limit reduced even though nothing was ever invoked. Keeping a current certificate on file shortens that conversation considerably.</p>
      </section>
      <section id="margin-counter-guarantees-and-commission-indian" class="gl-sec">
        <h2>Margin, Counter-Guarantees and Commission Indian Banks Apply to BG Limits</h2>
        <p>Indian banks apply three levers to a guarantee limit. Margin is cash or a deposit held against the exposure, commonly a proportion of the guarantee amount, and it is lien marked so the customer cannot withdraw it. A counter-guarantee is the customer's own written undertaking to reimburse the bank on invocation, and it is executed before issue. Commission is charged on the amount and the tenor together, so a longer guarantee costs more even where the sum is identical. All three appear in the sanction letter, and the margin in particular has to be disclosed on a net worth statement, because a lien-marked deposit is owned but not available. Where a guarantee is issued in favour of a government department, the format is usually prescribed by that department and the bank will not vary it. The applicant supplies the wording; the bank supplies the credit. Getting the format from the beneficiary before approaching the bank saves a round of amendments that can take a fortnight.</p>
      </section>
      <section id="instruments-grouped-with-the-bank-guarantee" class="gl-sec">
        <h2>Instruments Grouped With the Bank Guarantee</h2>
        <p>The instruments grouped with a bank guarantee share the feature that somebody stands behind somebody else's obligation. One is the general term for whatever a lender takes as security. One is the customer's own contribution, which determines how much the bank is exposed to in the first place. One is the specific guarantee a contractor gives that work will be completed to terms, which is what most tender guarantees actually are. The last is the person who accepts liability for another's debt, which is the individual equivalent of what a bank is doing here. <a href="/glossary/networth/collateral">Collateral</a>, <a href="/glossary/networth/margin-money">Margin Money</a>, <a href="/glossary/networth/performance-guarantee">Performance Guarantee</a>, <a href="/glossary/networth/surety">Surety</a>. Reading them together explains why a bidder often needs two instruments for one contract: one securing the bid itself and another securing performance once the contract is awarded.</p>
