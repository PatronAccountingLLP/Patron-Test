      <section id="how-a-blocked-account-works-and-who-is-asked-to" class="gl-sec">
        <h2>How a Blocked Account Works and Who Is Asked to Open One</h2>
        <div class="definition-box" itemprop="description"><p>A blocked account is a bank account opened in the destination country into which a student deposits a year's living costs before the visa is granted. The money is genuinely blocked: the holder can withdraw only a fixed monthly amount once they arrive, which is the point of the arrangement. It exists so that a mission does not have to assess whether an applicant will actually have money to live on, because the money is already there and cannot be spent early. Germany is the destination most associated with the requirement, and several others operate comparable arrangements under different names. The amount is set by the destination and revised periodically, and it usually covers one year rather than the whole course. Opening one is a bank process rather than a visa process, and it has to be complete before the appointment rather than alongside it. Who is asked to open one follows from the visa category rather than from the applicant's means. A student on a route that requires it opens one however substantial their family's position, because the condition attaches to the route. Demonstrating wealth by other evidence does not displace it.</p></div>
      </section>
      <section id="whether-a-blocked-balance-belongs-in-your-certif" class="gl-sec">
        <h2>Whether a Blocked Balance Belongs in Your Certified Asset List</h2>
        <p>Whether a blocked balance belongs on a certified asset list depends on what the certificate is being asked to show. The money is still the applicant's: it has been transferred, not spent, and it will be released to them in instalments. So it is an asset. What it is not is available, and a statement that lists it among liquid holdings without saying it is blocked overstates what the applicant can reach. The honest presentation shows the balance, names it as blocked, and states the monthly release limit. Where the certificate is being prepared for the same visa application that the blocked account supports, disclosing it twice in different guises is the error to avoid. The mission is looking at one pot of money and should not be shown two.</p>
      </section>
      <section id="remitting-from-india-into-a-blocked-account-bank" class="gl-sec">
        <h2>Remitting From India Into a Blocked Account: Bank, TCS and Paperwork Touchpoints</h2>
        <p>Remitting into a blocked account from India runs through the liberalised remittance scheme, so the transfer sits inside the per-financial-year limit that applies to a resident individual. The bank handling the outward remittance collects Form A2 and the supporting documents. Tax is collected at source on the remittance under the provisions applying to education-related transfers, at a rate that depends on whether the funds come from an education loan. Where a parent remits on the student's behalf, the limit applies to the parent. Banks vary in how quickly they process these, and the documentary requirements at the branch are frequently heavier than the scheme itself demands. Starting the remittance before the account paperwork is complete is the usual cause of a missed appointment. The remittance runs under the outward scheme available to resident individuals, so the declarations and collection at source that apply to any such transfer apply here too. Applicants who budget only for the deposit are surprised by what the transfer itself costs.</p>
      </section>
      <section id="deposit-structures-compared-with-a-blocked-accou" class="gl-sec">
        <h2>Deposit Structures Compared With a Blocked Account</h2>
        <p>The deposit structures compared with a blocked account all involve money set aside rather than spent, and they differ in who controls the release. One is the scheme governing the outward remittance itself. One is the ordinary term deposit, which is the applicant's to break subject to a penalty. One is the wider evidence pack a mission assesses. The last is the requirement the blocked account exists to satisfy in the first place. The structures set beside this one are all ways of demonstrating that money is both present and committed, and they differ in who holds the constraint. <a href="/glossary/networth/liberalised-remittance-scheme-lrs">Liberalised Remittance Scheme (LRS)</a>, <a href="/glossary/networth#fixed-deposit-receipt-fdr">Fixed Deposit Receipt (FDR)</a>, <a href="/glossary/networth/proof-of-funds-pof">Proof of Funds (POF)</a>, <a href="/glossary/networth#maintenance-funds">Maintenance Funds</a>. A lien or a marked deposit leaves the money with your own bank under an instruction. A blocked account moves it to an institution in the destination country under rules the applicant cannot vary. That difference in custody is exactly what a visa officer is buying, and it is why an Indian deposit under lien is not usually accepted as a substitute.</p>
