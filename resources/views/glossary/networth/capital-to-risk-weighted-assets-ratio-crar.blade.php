<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does CRAR measure?</h3>
<div class="faq-expanded__a"><p>It measures capital against risk weighted assets, expressed as a percentage. Assets are weighted by the risk the regulator attributes to them, so a government security carries a far lower weight than an unsecured loan. The ratio therefore reflects the risk taken, not just the size of the balance sheet.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does CRAR differ from the net owned fund test?</h3>
<div class="faq-expanded__a"><p>Net owned fund is an absolute rupee floor that a company must meet to hold registration. CRAR is a relative measure that moves with the book: it falls as lending grows unless capital grows too. An NBFC can comfortably clear the fund floor and still breach the ratio.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Which NBFCs have to maintain it?</h3>
<div class="faq-expanded__a"><p>Applicability follows the Reserve Bank&#x27;s scale based regulation framework, under which requirements differ across the layers and categories it defines. The minimum ratio, and the portion that must be Tier I, are set in the applicable master direction, which is where the current figure is read from.</p></div>
