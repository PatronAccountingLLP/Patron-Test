      <section id="how-crar-weighs-capital-against-risk-weighted-ex" class="gl-sec">
        <h2>How CRAR Weighs Capital Against Risk-Weighted Exposure</h2>
        <div class="definition-box" itemprop="description"><p>The capital to risk-weighted assets ratio measures regulatory capital against exposures adjusted for how risky they are. The denominator is not the balance sheet total. Each asset is multiplied by a weight reflecting its risk. A government security may attract a weight of zero while an unsecured personal loan attracts the full amount, and off-balance-sheet exposures are converted and included. The numerator is capital as the regulator defines it, in tiers. Dividing one by the other gives a ratio expressed as a percentage. The point of the construction is that two lenders with identical balance sheets and very different lending books produce very different ratios. Weighting is the whole of the idea. Two lenders with identical capital and identical books can report ratios far apart, because exposures are scaled by the risk assigned to them before the comparison is made.</p></div>
      </section>
      <section id="where-crar-reporting-and-net-owned-fund-certific" class="gl-sec">
        <h2>Where CRAR Reporting and Net Owned Fund Certification Part Ways</h2>
        <p>Reporting this ratio and certifying net owned fund are separate exercises that share some inputs, and conflating them causes real errors. Net owned fund starts from owned funds and deducts group and subsidiary exposure above a threshold, producing an absolute figure measured against a minimum. The capital ratio weights the whole asset book and produces a percentage measured against a percentage floor. A company can comfortably clear its net owned fund minimum while sitting close to its capital ratio floor, or the reverse. Certifying one says nothing about the other, and a certificate should not be read as covering both. The two are computed for different readers and cannot be reconciled line by line. One is a ratio reported periodically to demonstrate adequacy against the book as it stands. The other is an absolute amount certified at a date to demonstrate that a threshold is met. A firm can be comfortable on one and tight on the other at the same moment. A reader given one when they asked for the other has not been given a smaller version of what they wanted. They have been given a different measure.</p>
      </section>
      <section id="the-minimum-crar-and-tier-ii-ceiling-rbi-applies" class="gl-sec">
        <h2>The Minimum CRAR and Tier II Ceiling RBI Applies to NBFCs</h2>
        <p>The Reserve Bank prescribes a minimum ratio for non-banking financial companies, with tier I subject to its own floor within the total. It caps tier II capital at the amount of tier I so that the weaker tier cannot substitute for the stronger. The applicable minimums differ by the company's classification and have been revised as the scale-based framework has been applied. The figure that applies to a particular company is read from the current Master Direction rather than from memory. Reporting is through the periodic returns, and the statutory auditor's certificate speaks to compliance annually. The ceiling on the supplementary layer is what stops the ratio being met with the cheaper kind of capital. Supplementary capital counts only up to the amount of the core layer, so the core is the binding constraint in practice. A firm planning to raise subordinated debt to close a shortfall discovers this at the point the amount is fixed.</p>
      </section>
      <section id="adequacy-measures-reported-with-crar" class="gl-sec">
        <h2>Adequacy Measures Reported With CRAR</h2>
        <p>The adequacy measures reported alongside this ratio describe the capital being measured. One is the core tier, which carries the floor within the floor. One is the supplementary tier, which is capped by reference to the first. One is the reserve category that feeds the core tier. The last is gearing, which asks a similar question without weighting anything and is what a non-financial business would be measured on instead. The measures reported alongside it look at the same balance sheet from different vantage points. <a href="/glossary/networth/tier-i-capital">Tier I Capital</a>, <a href="/glossary/networth#tier-ii-capital">Tier II Capital</a>, <a href="/glossary/networth/free-reserves">Free Reserves</a>, <a href="/glossary/networth/debt-to-equity-ratio">Debt-to-Equity Ratio</a>. One is the absolute capital base before risk is considered. One is the core layer inside it. One is the asset-quality measure that tells the reader why the capital may be needed. A ratio comfortably above the floor alongside deteriorating asset quality is a different story from the same ratio alongside a clean book.</p>
      </section>
