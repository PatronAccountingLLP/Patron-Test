      <section id="what-a-cop-authorises-a-chartered-accountant-to" class="gl-sec">
        <h2>What a COP Authorises a Chartered Accountant to Do</h2>
        <div class="definition-box" itemprop="description"><p>A certificate of practice authorises a member of the Institute of Chartered Accountants of India to practise as a chartered accountant. Membership alone does not. A member without a certificate of practice is qualified, but not entitled to hold out as being in practice, to sign attest reports, or to accept engagements reserved to practising members. The certificate is applied for separately, is renewed annually, and can be surrendered when a member moves into employment. Many members in industry hold membership without one, entirely properly, and are not entitled to sign a certificate of the kind this cluster is about. Membership and practice are separate permissions, and the second is the one that matters here. A member in employment remains a chartered accountant and may not sign in practice; the certificate is what converts the qualification into the authority to certify for a client.</p></div>
      </section>
      <section id="why-a-certificate-signed-without-a-live-cop-carr" class="gl-sec">
        <h2>Why a Certificate Signed Without a Live COP Carries No Weight</h2>
        <p>A certificate signed without a live certificate of practice carries no weight and creates a problem for everybody. The recipient has a document that does not do what it appears to do. The signatory is exposed to disciplinary proceedings for holding out as being in practice. And the client is left needing the work done again, usually against a deadline that has moved closer. This is not a theoretical risk: members do lapse in renewing, and a member who has taken employment may not appreciate that the entitlement went with it. A certificate signed without it fails on authority rather than on content. The figure may be correct and the work competent, and the document still cannot do the job it was obtained for, because the reader relies on the signatory's standing rather than on their arithmetic. Discovering this at the counter usually means the engagement is repeated by someone else at the applicant's cost. The check costs the recipient nothing and the failure costs the applicant an appointment, which is a poor trade to discover late. It is also entirely avoidable by asking before the engagement rather than after.</p>
      </section>
      <section id="checking-membership-number-cop-status-and-udin-t" class="gl-sec">
        <h2>Checking Membership Number, COP Status and UDIN Through ICAI</h2>
        <p>Verification is straightforward and takes minutes. The Institute publishes a members directory allowing a search by membership number, which returns the member's status and whether a certificate of practice is held. Firm registration numbers can be checked similarly. And the unique document identification number on the certificate itself can be verified on the Institute's UDIN portal, which confirms that this specific document was generated by this member. A recipient who checks all three has established that the signatory exists, is entitled to sign, and issued this document. Both checks are open to the recipient and take minutes. The membership record confirms the person exists and is in good standing; the document number confirms this particular certificate was generated by that member. Institutions that receive certificates in volume increasingly run both as a matter of course, which is worth knowing before assuming a signature and a stamp will pass unexamined.</p>
      </section>
      <section id="credentials-often-mistaken-for-a-certificate-of" class="gl-sec">
        <h2>Credentials Often Mistaken for a Certificate of Practice</h2>
        <p>The credentials often mistaken for a certificate of practice are the ones that appear alongside it. One is the membership number, which every member holds whether in practice or not. One is the attestation function that the certificate authorises. One is the peer review certificate, which relates to a firm's quality processes rather than to an individual's entitlement. The last is the engagement type itself, which only a practising member may accept. The credentials mistaken for this one are real qualifications that authorise something else. <a href="/glossary/networth#icai-membership-number">ICAI Membership Number</a>, <a href="/glossary/networth/attestation">Attestation</a>, <a href="/glossary/networth#peer-review-certificate">Peer Review Certificate</a>, <a href="/glossary/networth#certification-engagement">Certification Engagement</a>. One is the membership itself, which the practice certificate is issued against. One belongs to a different professional body with its own reserved areas. One is a registration for a specific kind of valuation work. Each is genuine, and none of them substitutes where a recipient has asked for a practising chartered accountant.</p>
      </section>
