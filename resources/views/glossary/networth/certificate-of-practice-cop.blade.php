<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does a Certificate of Practice permit?</h3>
<div class="faq-expanded__a"><p>It permits a member of the Institute of Chartered Accountants of India to practise and to sign attestation work. Section 6 of the Chartered Accountants Act 1949 requires it, so a qualified member in employment cannot issue certificates to third parties without holding one. The Institute&#x27;s disciplinary machinery under the same Act applies to any member who attests without it.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How can a recipient check that a signatory holds one?</h3>
<div class="faq-expanded__a"><p>Through the Institute&#x27;s public member search, using the membership number printed on the document. The search returns the member&#x27;s status and whether they hold a Certificate of Practice. A recipient can also verify the UDIN quoted, which ties the document to a member in practice at the time of signing.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does a Certificate of Practice need renewal?</h3>
<div class="faq-expanded__a"><p>Yes, annually. A Certificate of Practice is renewed each year on payment of the prescribed fee, and it can be surrendered when a member moves into employment. A certificate signed while the practising status had lapsed is defective, which is why the membership number and the signing date matter together.</p></div>
