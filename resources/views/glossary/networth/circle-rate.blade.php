<h3 class="faq-expanded__q">What is a circle rate?</h3>
<div class="faq-expanded__a"><p>It is the minimum value the state government notifies for property in a locality, below which an instrument cannot be stamped. States use different names for the same instrument, including ready reckoner rate in Maharashtra and jantri in Gujarat. Rates are notified by area and by property category.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does the circle rate equal market value?</h3>
<div class="faq-expanded__a"><p>Rarely. It is an administrative floor revised periodically, so in fast-moving localities the market runs above it while in weak markets transactions can struggle to reach it. A certificate reporting property at circle rate value is reporting a conservative figure and should say which basis it used.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does income tax law take note of the rate?</h3>
<div class="faq-expanded__a"><p>Yes. Where consideration on transfer of immovable property falls below the stamp duty value, income tax provisions substitute the stamp duty value. That applies to both the transferor and the buyer, subject to a tolerance band. The rate therefore has consequences beyond the duty itself.</p></div>
