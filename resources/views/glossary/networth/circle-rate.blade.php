      <section id="what-a-circle-rate-is-and-which-authority-notifi" class="gl-sec">
        <h2>What a Circle Rate Is and Which Authority Notifies It</h2>
        <div class="definition-box" itemprop="description"><p>A circle rate is the minimum value at which a property may be registered in a given locality, notified by the state government. Its purpose is revenue rather than valuation: it establishes a floor below which stamp duty cannot be computed, which prevents parties understating a price to reduce duty. Different states use different names for the same instrument. Maharashtra calls it the ready reckoner rate, Gujarat calls it the jantri, Haryana and several northern states call it the collector rate, and Delhi uses circle rate. The authority notifying it is usually the revenue department or the inspector general of registration, and the rates are revised periodically rather than continuously. The rate is a floor for duty rather than an opinion on worth. It is revised on the authority's own cycle, which in several states has run years behind the market, so it can sit well below or occasionally above what a property would fetch.</p></div>
      </section>
      <section id="which-property-value-is-reported-and-how-the-bas" class="gl-sec">
        <h2>Which Property Value Is Reported and How the Basis Is Disclosed</h2>
        <p>Which value is reported on a certificate depends on what the reader is being asked to assess, and the basis is disclosed either way. Where the certificate states market value, the notified rate is a cross-check rather than the figure. Where the notified rate is used, the certificate says so. The notified figure trails the market in most districts and can overshoot it where prices have fallen since the last revision. Presenting the notified rate as a market valuation, or the reverse, is the error that makes a property entry indefensible. Stating the basis costs a line and settles the question before a reader raises it. Where the two bases diverge sharply, naming both is stronger than choosing one. A statement that reports the value adopted, the basis for it and the other figure alongside gives the reader what they need to test it. Forecloses the suspicion that the higher of the two was picked without saying so.</p>
      </section>
      <section id="ready-reckoner-rates-guidance-values-and-section" class="gl-sec">
        <h2>Ready Reckoner Rates, Guidance Values and Section 50C Implications by State</h2>
        <p>The rates matter beyond stamp duty because income tax provisions attach to them. Where a property is transferred below the notified value, the difference can be treated as income in the hands of the buyer. The notified value is also substituted for the consideration in computing the seller's capital gain, subject to a tolerance band. That makes the notified rate relevant to a transaction long after registration, and it makes a valuation that ignores it incomplete. Practice on how closely notified rates track the market varies enormously by state and by locality, with some rates badly out of date. The name changes across state lines even where the function does not, and so does the granularity. Some authorities notify by locality and building type, others street by street, and a few distinguish floor and age. Anyone reading an interstate asset list is comparing figures produced by materially different methods, which is worth stating rather than leaving the reader to discover.</p>
      </section>
      <section id="property-valuation-bases-related-to-circle-rate" class="gl-sec">
        <h2>Property Valuation Bases Related to Circle Rate</h2>
        <p>The valuation bases related to this one are the alternatives a reader may have in mind. One is the price a willing buyer and seller would agree, which is what most recipients actually want. One is the duty the notified rate exists to compute. One is the registered specialist whose valuation report is recognised in law when the sum at stake warrants one. The last is the instrument evidencing that the property is the applicant's at all. The bases set beside this one are the alternatives a reader may have in mind when they ask what a property is worth. <a href="/glossary/networth/fair-market-value-fmv">Fair Market Value (FMV)</a>, <a href="/glossary/networth/stamp-duty">Stamp Duty</a>, <a href="/glossary/networth#registered-valuer">Registered Valuer</a>, <a href="/glossary/networth#title-deed">Title Deed</a>. One is the price actually agreed between the parties. One is the figure a registered valuer arrives at on inspection. One is the amount the books carry. A certificate that does not say which of these it used has not reported a value at all, because the same property can carry four defensible and widely separated numbers at once.</p>
      </section>
