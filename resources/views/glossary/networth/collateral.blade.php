      <section id="what-lenders-accept-as-collateral-and-at-what-ha" class="gl-sec">
        <h2>What Lenders Accept as Collateral and at What Haircut</h2>
        <div class="definition-box" itemprop="description"><p>Collateral is anything a borrower gives a lender the right to sell if the loan is not repaid. What lenders accept, and at what discount, follows how quickly the asset could be turned into money. Fixed deposits with the same bank are accepted at close to face value, because the bank can simply appropriate them. Immovable property is accepted at a substantial discount to market value. Selling it takes months and may need a court. Listed shares are accepted with a wide haircut that moves with the market. Stock and receivables are accepted only under a floating charge with regular reporting, since both change daily. Gold sits near the top because it is liquid and easy to value. The discount is the lender's estimate of what will be left after cost, delay and price movement. Haircuts are not fixed by regulation for most asset classes; they are the lender's own policy and they move with market conditions. A share portfolio accepted at a given margin in a calm market is marked down in a volatile one. The borrower is asked to top up rather than consulted about the change.</p></div>
      </section>
      <section id="why-a-certified-net-worth-figure-is-not-the-same" class="gl-sec">
        <h2>Why a Certified Net Worth Figure Is Not the Same as Collateral Cover</h2>
        <p>A certified net worth figure and collateral cover answer different questions, and confusing them is the most common misunderstanding in a credit conversation. Net worth says what a person or a business is worth after everything owed. Collateral cover says what this particular lender can seize and sell. A borrower can be worth a great deal while offering nothing chargeable. The wealth sits in a private company, in a property held jointly with somebody who will not sign, or in assets already pledged. The reverse also happens: a modest position can carry excellent cover where the one asset is clean, unencumbered and easy to value. The practical consequence is that a borrower should establish what is chargeable before an application rather than during it. An asset held jointly needs the other holder's consent. One already mortgaged needs the first lender's no-objection. Both take time that an application in flight does not have.</p>
      </section>
      <section id="collateral-free-limits-cgtmse-cover-and-indian-b" class="gl-sec">
        <h2>Collateral-Free Limits, CGTMSE Cover and Indian Bank Appraisal Practice</h2>
        <p>Indian practice has moved a good way toward lending without collateral for small borrowers. Guarantee schemes covering micro and small enterprises let a bank advance against a guarantee fund rather than against security, and the fee for that cover is passed to the borrower. Working capital limits below prescribed thresholds are frequently sanctioned collateral-free on the strength of the appraisal alone. Where collateral is taken, the appraisal note records what it is, what it was valued at, who valued it and what charge has been created. A certified statement supports that note rather than replacing it, and it is read for what is unencumbered. Where a scheme guarantee is used, the borrower should understand that it protects the lender rather than them: default still leads to recovery action against the borrower, and the fund reimburses the bank afterwards. The absence of collateral is not an absence of liability, and that misunderstanding is common.</p>
      </section>
      <section id="security-concepts-sitting-beside-collateral" class="gl-sec">
        <h2>Security Concepts Sitting Beside Collateral</h2>
        <p>The concepts sitting beside collateral describe how security is created and what it is worth. Two are the mechanisms themselves, one for immovable property working through an interest in the land, and one for movables where the borrower keeps possession and carries on trading. One is the ratio deciding how much a lender will advance against a given asset. The last is what the asset would actually fetch under time pressure, which is the figure a recovery officer works to rather than the one on the valuation. <a href="/glossary/networth/mortgage">Mortgage</a>, <a href="/glossary/networth/hypothecation">Hypothecation</a>, <a href="/glossary/networth/loan-to-value-ratio-ltv">Loan-to-Value Ratio (LTV)</a>, <a href="/glossary/networth#realisable-value">Realisable Value</a>. Between them these four cover almost every question a credit officer asks about security. What it is, how the charge is created, how much is advanced against it, and what it would really fetch. Establishing that early is what keeps an application moving.</p>
