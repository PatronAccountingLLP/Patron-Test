<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does a contingent liability differ from a provision?</h3>
<div class="faq-expanded__a"><p>A provision is recognised in the accounts because an outflow is probable and can be estimated. A contingent liability is only disclosed, because the obligation depends on an uncertain future event or cannot be measured reliably. Accounting Standard 29 draws that line, and Schedule III requires the disclosure in company accounts.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Do contingent liabilities reduce net worth?</h3>
<div class="faq-expanded__a"><p>They do not reduce the computed figure, but they are disclosed alongside it. A personal guarantee given for a group company&#x27;s borrowing, or a disputed tax demand under appeal, sits outside the arithmetic. A reader who ignores that note can badly misjudge the position the certificate reports.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What are the commonest examples on an individual&#x27;s statement?</h3>
<div class="faq-expanded__a"><p>Guarantees stand first: a personal guarantee for a company loan, or standing as co-borrower on a relative&#x27;s facility. Pending litigation with a monetary claim comes next, then disputed income tax or GST demands. Each is listed with the amount at stake and the current stage of the proceeding.</p></div>
