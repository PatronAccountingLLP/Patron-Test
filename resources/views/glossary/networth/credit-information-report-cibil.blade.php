<h3 class="faq-expanded__q">What does a credit information report contain?</h3>
<div class="faq-expanded__a"><p>It lists a borrower&#x27;s credit facilities, sanctioned and outstanding amounts, repayment history and enquiries made by lenders. Credit information companies are licensed under the Credit Information Companies (Regulation) Act 2005 and are supervised by the Reserve Bank. Several companies operate, so reports can differ in detail.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does the report not show?</h3>
<div class="faq-expanded__a"><p>It does not show assets, income or net worth. Borrowings from relatives, unregistered private loans and liabilities never reported to a bureau stay invisible. That gap is precisely why a lender reads a net worth certificate alongside the report rather than relying on either on its own.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Can an individual obtain their own report?</h3>
<div class="faq-expanded__a"><p>Yes. The Reserve Bank requires credit information companies to provide one free full credit report to an individual each calendar year, on request through the company&#x27;s own channel. Errors are corrected through the dispute process with the company and the lender that reported the entry.</p></div>
