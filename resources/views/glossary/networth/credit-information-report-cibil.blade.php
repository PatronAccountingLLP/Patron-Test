      <section id="what-a-credit-bureau-record-says-about-a-borrowe" class="gl-sec">
        <h2>What a Credit Bureau Record Says About a Borrower</h2>
        <div class="definition-box" itemprop="description"><p>A credit information report records how a borrower has behaved, not what they own. It lists every credit facility reported by a member lender, the sanctioned amount, the balance outstanding and the repayment history month by month. It carries enquiries made by other lenders, which is why several applications in quick succession read badly. It carries settlements and write-offs, which stay visible for years and are read far more harshly than a late payment. The score derived from it is a summary of that history rather than an assessment of means. A borrower who has never taken credit has no history to summarise, which is a different problem from a poor one and is treated differently by a careful appraiser. Joint facilities appear on both parties' reports in full, not by share. A co-applicant carries the entire outstanding on their own record. That reduces what they can borrow independently. People who signed years ago to help a relative are regularly surprised by this when their own application is assessed.</p></div>
      </section>
      <section id="why-a-clean-bureau-report-is-no-substitute-for-c" class="gl-sec">
        <h2>Why a Clean Bureau Report Is No Substitute for Certified Net Worth</h2>
        <p>A clean bureau report is no substitute for a certified position because the two describe different risks. The report says the borrower has paid what they took on so far. It says nothing about whether they could meet a much larger obligation, or what would be left to recover if they could not. A salaried borrower with a spotless record and no assets, and a business owner with a patchy record and unencumbered property, present opposite pictures. A lender assessing a secured facility wants both documents. This is why a credit team asks for a net worth certificate even where the score is excellent. The two documents also differ in who produces them. A bureau report is generated from lender submissions with no involvement from the borrower at all. A net worth certificate is prepared by a professional from records the borrower supplies, under a framework that makes the professional answerable for it.</p>
      </section>
      <section id="cibil-equifax-experian-and-crif-high-mark-under" class="gl-sec">
        <h2>CIBIL, Equifax, Experian and CRIF High Mark Under the CIC Regulation Act</h2>
        <p>Four bureaux operate in India under the same regulatory framework, and lenders subscribe to one or more rather than all. Because reporting is by member lender, the same borrower can show slightly different histories across bureaux, and a facility from a lender that reports to only one will be invisible on the others. A borrower is entitled to a free report from each in a year, and correcting an error is worth doing before an application rather than during one. Disputed entries take weeks to resolve, and an application in flight does not wait. Reports are updated on a cycle rather than in real time, so a loan closed last week may still show as outstanding. A closure letter from the lender is the document that settles the point while the bureau catches up, and it is worth obtaining at closure rather than requesting months later.</p>
      </section>
      <section id="credit-assessment-inputs-related-to-bureau-repor" class="gl-sec">
        <h2>Credit Assessment Inputs Related to Bureau Reports</h2>
        <p>The related concepts are the other inputs a credit team assembles around the report. One is the appraisal process itself, which weighs all of them together. One is the document recording the terms finally offered. One is the ratio testing whether income covers repayment. The last is the person added to an application to strengthen it, whose own report is pulled and read on the same basis. <a href="/glossary/networth#credit-appraisal">Credit Appraisal</a>, <a href="/glossary/networth#sanction-letter">Sanction Letter</a>, <a href="/glossary/networth/debt-service-coverage-ratio-dscr">Debt Service Coverage Ratio (DSCR)</a>, <a href="/glossary/networth#co-applicant">Co-applicant</a>. A lender reads all four together, and a weakness in one is frequently offset by strength in another rather than being fatal on its own. The report and the certificate are also read on different timescales. A bureau record describes conduct over years and changes slowly; a net worth statement describes a position on one day and can change materially in a month. A lender assessing a long facility weighs the first more heavily, while one assessing a guarantee or a bid weighs the second.</p>
      </section>
