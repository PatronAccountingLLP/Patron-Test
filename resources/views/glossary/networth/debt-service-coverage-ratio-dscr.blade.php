      <section id="what-dscr-measures-per-rupee-of-repayment-due" class="gl-sec">
        <h2>What DSCR Measures Per Rupee of Repayment Due</h2>
        <div class="definition-box" itemprop="description"><p>Debt service coverage ratio measures how much cash is available for every rupee of repayment falling due. The numerator is earnings available to service debt, usually profit after tax with depreciation and interest added back, because neither leaves the business as cash for this purpose. The denominator is the full obligation for the period: principal instalments plus interest. A ratio of one means the business generates exactly what it owes, with nothing spare for a bad month. Anything below one means the shortfall has to come from somewhere else. The measure is forward-looking where it is built from projections and backward-looking where it is built from audited results, and a lender usually wants to see both. Where a business has several facilities the ratio is calculated on the total obligation rather than on each loan. Taking an additional facility can therefore push a comfortable borrower below the threshold. Lenders model the new loan into the existing position before sanctioning rather than after.</p></div>
      </section>
      <section id="reading-dscr-against-a-certified-balance-sheet-p" class="gl-sec">
        <h2>Reading DSCR Against a Certified Balance Sheet Position</h2>
        <p>Read against a certified balance sheet position the ratio answers a question net worth cannot. Net worth is a stock: what is owned at one moment. Debt service coverage is a flow: what the business produces over a period. A borrower can be asset rich and still fail the ratio, which is the classic position of a business holding property while trading thinly. The reverse is equally common in services, where cash generation is strong and there is almost nothing on the balance sheet to certify. A credit note reads the two together, and a certificate that presents the stock without acknowledging the flow answers only half of what was asked. For a proprietor the distinction blurs, because household drawings come out of the same cash the ratio is measuring. A realistic calculation deducts what the family actually lives on, and a projection that ignores drawings overstates coverage in a way an experienced appraiser will correct downwards.</p>
      </section>
      <section id="benchmarks-indian-bankers-expect-in-project-repo" class="gl-sec">
        <h2>Benchmarks Indian Bankers Expect in Project Reports and CMA Data</h2>
        <p>Indian bankers typically look for coverage comfortably above one in a project report, with the exact expectation varying by sector and by the tenor of the facility. Longer loans attract a higher expectation, because more can go wrong over the period. The credit monitoring data a borrower submits carries the projections the ratio is built from, and a projection that assumes a sharp margin improvement in year one is discounted by an experienced appraiser. Where a moratorium applies, the ratio in the early years is calculated on interest alone and rises sharply when principal begins, which is the point most projections quietly gloss over. Average coverage across the loan's life and minimum coverage in any single year are both examined. A facility that averages comfortably while dipping below one in year three has a problem in year three. The minimum is usually the number that decides the sanction.</p>
      </section>
      <section id="coverage-and-leverage-metrics-near-dscr" class="gl-sec">
        <h2>Coverage and Leverage Metrics Near DSCR</h2>
        <p>The measures near this one are the other tests a credit team applies. One is gearing, which looks at the balance sheet rather than the cash flow. One is the appraisal that weighs both. One is the repayment holiday that changes the ratio's shape over time. The last is the borrower's own contribution, which reduces the obligation the ratio has to cover. <a href="/glossary/networth/debt-to-equity-ratio">Debt-to-Equity Ratio</a>, <a href="/glossary/networth#credit-appraisal">Credit Appraisal</a>, <a href="/glossary/networth/moratorium">Moratorium</a>, <a href="/glossary/networth/margin-money">Margin Money</a>. Read together they describe both the balance sheet and the cash flow, which is what a credit note is ultimately weighing. A borrower strong on one and weak on the other is the normal case rather than the exception. The ratio is also the number most often negotiated, because it rests on projections rather than on history. A borrower who understands how their own figures were built can discuss them with the appraiser; one who received the projection from a consultant usually cannot, and that shows in the meeting. Both numbers belong in the file.</p>
      </section>
