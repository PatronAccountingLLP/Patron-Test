<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How is the debt to equity ratio computed?</h3>
<div class="faq-expanded__a"><p>Borrowed funds are divided by owners&#x27; funds. Borrowings include term loans, working capital facilities and, depending on the reader&#x27;s convention, unsecured loans from promoters. Owners&#x27; funds are share capital and reserves for a company, or capital accounts for a firm. The convention used should be stated.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Why do tenders and lenders look at it?</h3>
<div class="faq-expanded__a"><p>Because it signals how much cushion sits beneath the debt. A highly leveraged bidder has less capacity to absorb a loss on a contract, so tender conditions often set a ceiling. Lenders write the ratio into covenants, which the borrower then has to keep testing after drawdown.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Do subordinated promoter loans count as debt?</h3>
<div class="faq-expanded__a"><p>It depends on the treatment agreed. Where a promoter loan is formally subordinated to the lender&#x27;s dues and is not repayable during the facility, many appraisers treat it as quasi-equity. Absent that undertaking it is debt, which can move the ratio materially in either direction.</p></div>
