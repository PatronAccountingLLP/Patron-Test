      <section id="how-the-ratio-is-built-from-two-balance-sheet-to" class="gl-sec">
        <h2>How the Ratio Is Built From Two Balance Sheet Totals</h2>
        <div class="definition-box" itemprop="description"><p>The debt-to-equity ratio is built from two totals that sit on the same balance sheet. Debt is borrowed money: term loans, working capital limits, debentures and, depending on the definition a reader applies, unsecured loans from directors or partners. Equity is what the owners have put in and left in: share capital, the securities premium account and reserves built from profits, less accumulated losses. Dividing one by the other gives gearing. The arithmetic is trivial and the definitions are not, because whether a director's loan counts as debt or as quasi-equity can move the ratio substantially. A reader who does not say which definition they used has not communicated a ratio at all. Off-balance-sheet obligations complicate the picture further. Operating leases, guarantees given for group companies and bills discounted with recourse are all leverage a simple ratio will not capture. A careful reader asks about them rather than accepting the computed figure.</p></div>
      </section>
      <section id="why-tender-committees-pair-gearing-with-a-certif" class="gl-sec">
        <h2>Why Tender Committees Pair Gearing With a Certified Net Worth Figure</h2>
        <p>Tender committees pair gearing with a certified net worth figure because each covers the other's blind spot. Net worth states a size. Gearing states how that size was arrived at, and a business worth a given amount having borrowed heavily is in a different position from one worth the same having borrowed nothing. A committee assessing whether a bidder can carry a contract wants both the scale and the strain. This is also why the tangible measure is often specified alongside: gearing calculated on equity inflated by goodwill flatters the borrower exactly where the flattery matters most. The pairing also protects the bidder. A modest net worth with very low gearing demonstrates capacity the absolute figure understates. A bidder in that position should present both, not only the number the tender asked for.</p>
      </section>
      <section id="leverage-levels-indian-bankers-treat-as-comforta" class="gl-sec">
        <h2>Leverage Levels Indian Bankers Treat as Comfortable in Manufacturing and Services</h2>
        <p>Indian bankers are generally comfortable with lower gearing in services than in manufacturing, because a manufacturer's borrowing is usually backed by plant and stock while a services business borrows against cash flow. Capital-intensive sectors carry higher ratios as a matter of course and are read against sector norms rather than against an absolute. What draws attention is a sharp movement between years with no corresponding change in the business, which usually means either a large fresh borrowing or a reserve that has been reclassified. Both are worth explaining in the file before the appraiser asks. Lenders also watch the direction of travel. Gearing rising steadily across three years reads worse than a single high year following an acquisition, because one describes a trend and the other an event. The explanation belongs in the file either way.</p>
      </section>
      <section id="leverage-measures-related-to-debt-and-equity" class="gl-sec">
        <h2>Leverage Measures Related to Debt and Equity</h2>
        <p>The related measures describe capital from other angles. One is the part of reserves genuinely available rather than earmarked, which is where a good deal of apparent equity turns out not to be. One is net worth after intangibles are removed. One tests cash against repayment rather than capital against borrowing. The last is the regulatory capital measure applied to financial institutions, which uses its own definitions entirely. <a href="/glossary/networth/free-reserves">Free Reserves</a>, <a href="/glossary/networth/tangible-net-worth">Tangible Net Worth</a>, <a href="/glossary/networth/debt-service-coverage-ratio-dscr">Debt Service Coverage Ratio (DSCR)</a>, <a href="/glossary/networth/tier-i-capital">Tier I Capital</a>. Each answers a different question about the same capital, and a reader who knows which one a requirement means avoids the commonest error in tender documentation. Gearing is also the measure most affected by how a certificate treats director and partner loans. Classified as debt it worsens the ratio; classified as quasi-equity it improves it. Stating which treatment was applied, and why, is what separates a figure a reader can rely on from one they have to interrogate. Gearing is finally a question about who carries the risk. Equity absorbs losses first and debt does not, so a highly geared business fails sooner when trading turns, whatever its assets are worth on the day they were certified. That is the question a lender is finally asking.</p>
      </section>
