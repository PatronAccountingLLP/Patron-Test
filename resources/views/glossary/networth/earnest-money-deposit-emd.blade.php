      <section id="what-an-emd-secures-and-when-a-bidder-forfeits-i" class="gl-sec">
        <h2>What an EMD Secures and When a Bidder Forfeits It</h2>
        <div class="definition-box" itemprop="description"><p>An earnest money deposit is money a bidder lodges with a tendering authority to show the bid is serious. It is returned to unsuccessful bidders once the contract is awarded, and returned to the winner once the performance security is furnished. Forfeiture is what gives it teeth. A bidder who withdraws during the validity period loses the deposit outright. So does one who refuses the contract after selection, or fails to furnish the performance guarantee in time. Some conditions add forfeiture for materially false statements in the bid. The amount is usually a small proportion of the estimated contract value. It is lodged by demand draft, bank guarantee or online transfer, depending on the portal. Because it is money out of the business until the award is decided, a bidder tendering for several contracts at once can have a substantial sum tied up across them. That is worth planning for rather than discovering. The deposit is also refundable rather than a cost, which bidders sometimes forget when costing a tender. What it costs is the use of the money for the period it is held, and on a portal where refunds run slow that period can be months after the award.</p></div>
      </section>
      <section id="how-solvency-proof-and-emd-conditions-interact-i" class="gl-sec">
        <h2>How Solvency Proof and EMD Conditions Interact Inside a Bid Pack</h2>
        <p>Solvency proof and the deposit sit in the same bid pack and answer adjacent questions. The deposit shows the bidder has put something at risk. The solvency certificate shows the bidder could carry the contract if awarded. An authority reads them together: a large deposit from a bidder with no demonstrated standing is not reassuring, and a strong certificate from a bidder unwilling to lodge a deposit is not either. The conditions frequently tie the two together. Solvency of a stated multiple of the contract value is required alongside a deposit of a stated percentage. Where the certificate is written to the wrong figure the bid is rejected at the technical stage, before anybody opens the price envelope. That is why the sum is taken from the tender document rather than from experience of the last one.</p>
      </section>
      <section id="msme-exemptions-and-bid-security-declarations-on" class="gl-sec">
        <h2>MSME Exemptions and Bid Security Declarations on GeM and CPP Portal</h2>
        <p>Indian procurement has moved substantially toward exempting small enterprises. Registered micro and small enterprises are commonly exempt from lodging a deposit on central government tenders, on production of their registration, and many state authorities follow the same practice. In place of cash, several portals now accept a bid security declaration. It is an undertaking not to withdraw or vary the bid during validity, on pain of suspension from bidding for a period. The government procurement portal and the central public procurement portal both support this route. The exemption covers the deposit; it does not usually cover the performance security, and bidders regularly assume otherwise. Where an exemption is claimed the registration certificate is uploaded with the bid, and an expired registration invalidates the claim as surely as never having had one. Checking the validity date before bidding is a two-minute task that saves a rejection.</p>
      </section>
      <section id="bid-stage-deposits-related-to-the-emd" class="gl-sec">
        <h2>Bid-Stage Deposits Related to the EMD</h2>
        <p>The deposits related to this one all sit at the bid or award stage and are frequently confused. One is the declaration route several portals now accept in place of cash. One is the security furnished after award, which is larger and lasts through the contract. One is the bank instrument most often used to furnish either. The last is the measure an authority applies to decide whether the bidder could carry the work at all. A bidder who understands which of the four a condition is asking for avoids the commonest technical rejection in Indian tendering. <a href="/glossary/networth#bid-security">Bid Security</a>, <a href="/glossary/networth/performance-guarantee">Performance Guarantee</a>, <a href="/glossary/networth/bank-guarantee-bg">Bank Guarantee (BG)</a>, <a href="/glossary/networth/solvency-ratio">Solvency Ratio</a>. The sequence also explains why a bidder needs banking capacity as well as financial standing: several of these instruments have to be issued by a bank against a limit. That is a planning question, not a paperwork one. Bidders plan for it or they trip over it.</p>
      </section>
