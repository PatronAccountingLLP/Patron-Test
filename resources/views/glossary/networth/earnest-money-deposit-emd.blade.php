<h3 class="faq-expanded__q">How does an earnest money deposit relate to a solvency requirement?</h3>
<div class="faq-expanded__a"><p>They test different things at the same stage. The deposit is cash actually lodged; the solvency condition asks whether the bidder could carry the contract. A bidder can fund the deposit and still fail the financial criteria, which is why tenders routinely require both in the same envelope.</p></div>
