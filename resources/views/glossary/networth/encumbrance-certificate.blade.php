      <section id="what-an-encumbrance-certificate-records-over-a-c" class="gl-sec">
        <h2>What an Encumbrance Certificate Records Over a Chosen Period</h2>
        <div class="definition-box" itemprop="description"><p>An encumbrance certificate records the transactions registered against a property over a period the applicant chooses. It lists sales, mortgages, gifts, partitions and court attachments that were registered in that window, with the parties and the dates. What it does not record is anything that was never registered, and that limitation is the most important thing to understand about it. An equitable mortgage created by depositing title deeds with a bank frequently leaves no entry at all, so a certificate showing no encumbrance is not proof that a property is unencumbered. It is proof that nothing was registered, which is a narrower and less comforting statement. What it records is confined to instruments registered with that sub-registrar for the period asked for, and both limits bite. A charge created outside the period, or created by an unregistered instrument, leaves no trace on the search, and the certificate does not claim otherwise.</p></div>
      </section>
      <section id="why-a-clean-ec-strengthens-the-asset-side-of-a-c" class="gl-sec">
        <h2>Why a Clean EC Strengthens the Asset Side of a Certified Statement</h2>
        <p>A clean certificate nonetheless strengthens the asset side of a statement considerably, because it removes the largest single doubt about the largest single asset. A reader assessing an immovable property wants to know two things: that the applicant owns it, and that nobody else has a claim over it. The title document answers the first and this certificate answers most of the second. Attaching both alongside the property entry means a recipient does not have to run their own search before acting, which is frequently what decides how quickly a file moves. The period requested therefore carries as much weight as the result. A search covering thirteen years where the property changed hands fifteen years ago proves considerably less than it appears to. Where the holding is long-standing, the search runs back to the acquisition, and the certified statement says what window was covered rather than reporting a clean result without its span. A clean result is also perishable. It speaks to the date the search was run, and a charge registered the following week will not appear on it. That is why a reader assessing a substantial holding looks at how recent the certificate is.</p>
      </section>
      <section id="sub-registrar-applications-form-15-and-form-16-o" class="gl-sec">
        <h2>Sub-Registrar Applications, Form 15 and Form 16 Outputs and State Portal Practice</h2>
        <p>The certificate is obtained from the sub-registrar's office having jurisdiction over the property, on an application specifying the property and the period. Most states now accept online applications through their registration portal and return a digitally signed document. Two forms are commonly issued: one listing the transactions found, and one certifying that no transaction was recorded in the period searched. The period requested matters more than applicants expect. Searches run over thirteen years and over thirty years are not the same enquiry, and lenders differ on which they will accept. Portal practice has diverged sharply between states, and it changes what can be promised on a timeline. Several states now return the search online within days for records held digitally. Others digitised from a cut-off date and still require a manual search of the older registers, which is slower and cannot be expedited by applying again.</p>
      </section>
      <section id="title-documents-requested-along-with-an-ec" class="gl-sec">
        <h2>Title Documents Requested Along With an EC</h2>
        <p>The title documents requested alongside an encumbrance certificate complete the picture of ownership and claim. One is the registered instrument by which the property was acquired. One is the mechanism by which a lender takes security over it. One is the broad idea of a recorded claim standing against property. The last describes the resulting state of an asset that carries one. The documents requested alongside it answer the questions this search cannot. <a href="/glossary/networth#title-deed">Title Deed</a>, <a href="/glossary/networth/mortgage">Mortgage</a>, <a href="/glossary/networth#charge-on-assets">Charge on Assets</a>, <a href="/glossary/networth#encumbered-asset">Encumbered Asset</a>. One establishes how the current holder came to own the property. One shows the local body's record of who is assessed for it. One confirms nothing is outstanding to that body. The search establishes what has been registered against the property; the others establish who holds it and on what terms. Producing the search alone tends to prompt a request for the rest, so they travel together.</p>
      </section>
