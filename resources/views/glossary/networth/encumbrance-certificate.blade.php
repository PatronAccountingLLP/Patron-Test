<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does an encumbrance certificate show?</h3>
<div class="faq-expanded__a"><p>It lists transactions registered against a property over a stated period, including sales, mortgages, gifts and other charges. The sub-registrar issues it from the registration index for the period requested. It is the standard evidence that a property is free of registered charges. Several states now issue it online from the registration department&#x27;s own portal.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does an encumbrance certificate not show?</h3>
<div class="faq-expanded__a"><p>Anything that was never registered. Unregistered agreements, oral arrangements, disputes pending in court and tax or municipal dues do not appear. A clean certificate therefore narrows the risk without eliminating it, which is why lenders run a title search alongside rather than relying on it alone.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What period should be requested?</h3>
<div class="faq-expanded__a"><p>Long enough to cover the chain being relied on. Lenders commonly ask for thirteen or thirty years, depending on their policy and the state. For a solvency or net worth engagement, the period is chosen to cover the ownership the certificate reports, since a short window can miss an older charge.</p></div>
