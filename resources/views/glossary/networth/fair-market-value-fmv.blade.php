<h3 class="faq-expanded__q">How is fair market value established for a certificate?</h3>
<div class="faq-expanded__a"><p>From a source the reader can test. A registered valuer&#x27;s report is the strongest, followed by the state&#x27;s notified rate for property and the exchange quotation for listed securities. An owner&#x27;s estimate is not evidence. The certificate names the source used, because a value with no stated basis cannot be verified.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does income tax law define fair market value?</h3>
<div class="faq-expanded__a"><p>Yes, and for several purposes. The Income-tax Act defines fair market value, and Rule 11UA of the Income-tax Rules prescribes computation methods for unquoted shares and certain other assets. Those methods are designed for tax provisions, so they do not automatically govern what a lender or a tender authority accepts.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Who is a registered valuer?</h3>
<div class="faq-expanded__a"><p>A person registered under the Companies Act framework administered through the Insolvency and Bankruptcy Board of India. Registration is by asset class, such as land and building, plant and machinery, or securities. Valuations required by the Companies Act must come from a valuer registered in the relevant class.</p></div>
