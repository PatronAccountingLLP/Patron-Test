      <section id="what-makes-a-value-fair-between-willing-parties" class="gl-sec">
        <h2>What Makes a Value &#x27;Fair&#x27; Between Willing Parties</h2>
        <div class="definition-box" itemprop="description"><p>Fair market value is the price an asset would fetch between a willing buyer and a willing seller, both reasonably informed and neither under compulsion to transact. Every element of that definition does work. Willing excludes a distress sale, where the seller's need drags the price below what the asset is genuinely worth. Reasonably informed excludes a bargain struck because one side did not know something material. Not under compulsion excludes a forced auction, where the timetable rather than the asset sets the price. What results is a hypothetical price rather than an observed one, since by definition no such transaction has taken place. Fair market value is therefore always an opinion supported by evidence rather than a fact read off a document. A certificate presenting it as fact has misdescribed what it offers. The consequence for certification is that two competent professionals can reach different figures for the same asset without either being negligent. What separates a defensible opinion from a careless one is the evidence recorded behind it. None of this makes the concept vague. It makes it a conclusion that has to be supported rather than a figure that can be asserted.</p></div>
      </section>
      <section id="valuation-evidence-required-before-an-asset-is-s" class="gl-sec">
        <h2>Valuation Evidence Required Before an Asset Is Stated at FMV</h2>
        <p>Because it is an opinion, the evidence behind it is what makes it defensible when somebody disagrees. For listed securities the evidence is the quoted price on a stated date, which is as close to certainty as valuation gets and needs no further support. For immovable property it is comparable transactions in the same locality, the government's own guidance value, and where the amount justifies the cost a registered valuer's report. For unlisted shares it is the underlying audited accounts together with an accepted valuation method, named openly rather than left implicit. A certificate presents the basis alongside the figure in every case, because a valuation whose reasoning is not visible is the entry a reader discounts first and questions hardest. The basis is not supporting detail; it is the substance of what is being certified. A basis stated in one line costs nothing to include. Omitting it invites the reader to substitute a more conservative assumption of their own, and they invariably do.</p>
      </section>
      <section id="registered-valuer-reports-circle-rates-and-broke" class="gl-sec">
        <h2>Registered Valuer Reports, Circle Rates and Broker Quotes: What Carries Weight in India</h2>
        <p>In Indian practice the three common sources carry very different weight and should not be treated as alternatives. A registered valuer's report is the strongest, is required outright for several statutory purposes, and is what a lender's own panel valuer will be measured against. The circle rate, or its state equivalent such as the ready reckoner in Maharashtra or the jantri in Gujarat, is a government-notified floor for stamp duty rather than a market price at all. It can sit well below what a property would fetch and occasionally above it, and using it as a valuation without saying so misleads in either direction. A broker's quotation is the weakest of the three, since it reflects an asking price rather than a concluded transaction, and it is used to corroborate a figure rather than to establish one. Where two sources conflict, the certificate names both and explains which was preferred. Silently choosing the higher of the two is how a valuation loses its credibility, usually at the moment it matters most.</p>
      </section>
      <section id="valuation-terms-that-travel-with-fmv" class="gl-sec">
        <h2>Valuation Terms That Travel With FMV</h2>
        <p>Valuation vocabulary travels together, and the terms that accompany fair market value answer the questions a sceptical reader asks immediately afterwards. One is what would actually be recovered on a sale under time pressure. That is the figure a lender cares about, and it sits below fair market value by a margin depending on the asset. One is the government-notified rate described above, which is the most misused number in Indian property valuation. One is the qualified professional whose report carries statutory weight. The last is the duty payable on a transfer. It is calculated from the higher of consideration and notified rate, which is why the notified rate exists. <a href="/glossary/networth#realisable-value">Realisable Value</a>, <a href="/glossary/networth/circle-rate">Circle Rate</a>, <a href="/glossary/networth#registered-valuer">Registered Valuer</a>, <a href="/glossary/networth/stamp-duty">Stamp Duty</a>. Together these four explain why the same property can carry three defensible values on one day. None of them is wrong; each answers a different question.</p>
      </section>
