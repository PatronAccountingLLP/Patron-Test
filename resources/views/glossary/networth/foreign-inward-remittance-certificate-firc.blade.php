<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does an FIRC evidence?</h3>
<div class="faq-expanded__a"><p>It evidences that money has been received in India from abroad through the banking channel. The authorised dealer bank issues it with the remitter&#x27;s details, the amount in foreign currency, the rupee equivalent and the purpose of the remittance. It is the standard proof of inward foreign exchange.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Who needs a foreign inward remittance certificate?</h3>
<div class="faq-expanded__a"><p>Exporters of services, companies receiving foreign share capital, and recipients of overseas grants or gifts. It supports the Form FC-GPR filing where the money is share capital, and it evidences realisation of export proceeds. Individuals receiving inward gifts also use it to explain the credit.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is an advice from the bank the same as an FIRC?</h3>
<div class="faq-expanded__a"><p>Not always. Many banks now issue an electronic advice or a foreign inward remittance advice generated from the export data system, and only issue a formal certificate on request. Institutions differ in which they accept, so it is worth confirming what the recipient wants before the credit is several months old.</p></div>
