      <section id="what-an-firc-evidences-about-money-received-from" class="gl-sec">
        <h2>What an FIRC Evidences About Money Received From Abroad</h2>
        <div class="definition-box" itemprop="description"><p>A foreign inward remittance certificate evidences that money arriving in an Indian account came from abroad, naming the remitter, the amount, the currency, the date and the purpose declared for the transfer. It is issued by the bank that received the funds. For anybody certifying a position it answers a question a bank statement cannot: the statement shows a credit, and the certificate shows where the credit came from and why. That distinction matters wherever a large balance has appeared recently, which is exactly the situation a consular officer or a credit team examines first. Exporters use them to evidence realisation of export proceeds, and individuals use them to evidence gifts, salary from overseas employment, proceeds of an overseas sale or repatriated investments. What it does not evidence is why the money was sent. The purpose recorded is the one declared to the bank at the time, so it establishes what was stated rather than what was true. A reader tracing origin will want the underlying agreement as well.</p></div>
      </section>
      <section id="using-an-firc-to-substantiate-inward-funds-shown" class="gl-sec">
        <h2>Using an FIRC to Substantiate Inward Funds Shown in a Certified Statement</h2>
        <p>Using one to substantiate inward funds in a certified statement means attaching it to the specific credit it explains rather than filing it generally. A statement of affairs that shows a balance is stronger when the origin of the largest recent addition is documented beside it, and weaker when the reader has to ask. Where funds arrived from several sources the certificates are listed individually, because a single total explains nothing. Where a remittance was received years ago and the money has since moved between accounts, the certificate still establishes the original source and is worth retaining for that reason. Applicants routinely discard them once the money has arrived, and reconstructing the trail afterwards from bank records is slow and sometimes impossible.</p>
      </section>
      <section id="e-firc-advice-letters-and-what-ad-category-i-ban" class="gl-sec">
        <h2>e-FIRC, Advice Letters and What AD Category-I Banks Now Issue</h2>
        <p>The form of the document has changed. Banks in India moved to an electronic advice for most inward remittances. Authorised dealer category-I banks now issue an advice letter or an electronic certificate rather than the physical instrument that used to be issued for every transfer. For export proceeds the position runs through the export data processing system, and the certificate a bank issues references it. What matters for certification purposes is that whatever the bank issues names the remitter, the purpose and the date, and that it comes from the bank rather than from a payment platform. A screenshot from a transfer service is not the same document and is not treated as one. What banks issue has moved with the reporting system behind it. Physical certificates have largely given way to advices generated against the electronic record, and for several transaction types the bank will decline a certificate and issue an advice instead. An applicant who insists on the older document sometimes finds the request refused outright, when the advice would have been accepted by the reader who asked.</p>
      </section>
      <section id="inward-remittance-documents-related-to-the-firc" class="gl-sec">
        <h2>Inward-Remittance Documents Related to the FIRC</h2>
        <p>The inward-remittance documents related to this one all establish where money came from or where it currently sits. One is the wider concept of tracing an asset back to its origin, which is what the certificate serves. One is the scheme governing money moving the other way. One is the account record the bank itself issues for a given date. The last is the evidence pack a mission or a lender assembles from all of them. The documents grouped with this one all evidence money arriving from outside India and differ in what they prove about it. <a href="/glossary/networth/source-of-funds">Source of Funds</a>, <a href="/glossary/networth/liberalised-remittance-scheme-lrs">Liberalised Remittance Scheme (LRS)</a>, <a href="/glossary/networth#bank-balance-certificate">Bank Balance Certificate</a>, <a href="/glossary/networth/proof-of-funds-pof">Proof of Funds (POF)</a>. One shows that a credit reached the account. One shows the purpose declared for it. One shows the rate at which it was converted. Only the combination establishes that a specific sum arrived from a specific payer for a stated reason, which is what a reader tracing the origin of funds is actually asking.</p>
      </section>
