<div class="faq-expanded__item">
<h3 class="faq-expanded__q">When is Form 15CA enough without 15CB?</h3>
<div class="faq-expanded__a"><p>For remittances that fall outside the certificate requirement. Rule 37BB carves out a specified list of payments and sets thresholds below which only parts of Form 15CA are filed. Above those, and for taxable remittances generally, the accountant&#x27;s certificate in Form 15CB accompanies the filing.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does Form 15CB relate to a net worth certificate?</h3>
<div class="faq-expanded__a"><p>They are separate engagements that often appear in the same file. A remittance abroad for study, investment or property purchase may need Form 15CB for the transfer and a net worth certificate for the receiving institution. One addresses tax on the payment; the other addresses the remitter&#x27;s financial position.</p></div>
