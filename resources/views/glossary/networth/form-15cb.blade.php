<h3 class="faq-expanded__q">What is Form 15CB used for?</h3>
<div class="faq-expanded__a"><p>It is a chartered accountant&#x27;s certificate on a foreign remittance. The member states the nature of the payment, its taxability, the rate of tax deducted and the treaty provision applied. Rule 37BB of the Income-tax Rules governs it, and the certificate supports the remitter&#x27;s declaration in Form 15CA.</p></div>
