      <section id="what-form-15cb-certifies-about-a-payment-made-ab" class="gl-sec">
        <h2>What Form 15CB Certifies About a Payment Made Abroad</h2>
        <div class="definition-box" itemprop="description"><p>Form 15CB is a chartered accountant's certificate about a payment being made to a non-resident. It states the nature of the remittance, the provisions of the Income-tax Act under which it is taxable or not, the rate at which tax should be withheld. Whether a double taxation avoidance agreement applies and with what effect. It is the professional's conclusion on the tax treatment of a specific payment, given before the payment is made. The bank handling the remittance relies on it, because the bank is not in a position to determine the withholding position itself and would otherwise carry the risk of remitting without deduction. What it certifies is narrow and specific: the nature of the payment, the rate at which tax should be withheld, and the provision or treaty article that produces that rate. It is a determination on a single remittance, not a view on the payer. A second remittance to the same payee under the same contract needs its own certificate, because the determination is made against the payment rather than against the relationship.</p></div>
      </section>
      <section id="when-form-15ca-on-its-own-will-not-satisfy-the-r" class="gl-sec">
        <h2>When Form 15CA on Its Own Will Not Satisfy the Remitting Bank</h2>
        <p>Form 15CA is the remitter's own declaration and is filed on the income tax portal. For many remittances it is sufficient by itself, and the rules exempt a specified list of payments and small remittances below a threshold from needing more. Where the remittance is chargeable to tax and exceeds the threshold, the accountant's certificate is required and the declaration references it. A bank asked to remit without the certificate in a case that requires one will decline, which is where remitters discover the requirement, usually with a deadline in front of them. The declaration and the certificate answer different questions, which is why one does not stand in for the other. The declaration is the remitter's own statement of what is being sent and why. The certificate is an independent professional's determination of the tax treatment. Where the remittance is chargeable to tax and above the threshold, the bank wants the second before it will release funds.</p>
      </section>
      <section id="income-tax-portal-filing-dtaa-positions-and-with" class="gl-sec">
        <h2>Income Tax Portal Filing, DTAA Positions and Withholding Rates a CA Verifies</h2>
        <p>The filing runs through the income tax portal, with the accountant submitting the certificate against the remitter's PAN and the remitter then filing the declaration referencing it. The positions the accountant verifies include whether the payment is income arising in India, and whether a treaty reduces or eliminates the withholding. They also cover whether a tax residency certificate and the associated declaration have been obtained from the payee, and what rate finally applies once surcharge and cess are added. Treaty benefit without a residency certificate is the point on which these certificates most often fail scrutiny. Treaty relief is where the work concentrates and where it most often stalls. A reduced rate under a treaty depends on the recipient's residence being established and on the supporting declarations being in hand, and those come from a party abroad on their own timetable. A remittance planned around a treaty rate without them collapses back to the domestic rate.</p>
      </section>
      <section id="cross-border-certificates-related-to-form-15cb" class="gl-sec">
        <h2>Cross-Border Certificates Related to Form 15CB</h2>
        <p>The cross-border certificates related to this one sit at different points in the same flow. One is the attestation discipline the certificate is issued under. One evidences money coming into India rather than going out. One is the scheme governing an individual's outward remittances. The last is the engagement type under which any of these is accepted. The certificates grouped with this one are all documents a cross-border payment may require, issued by different parties for different purposes. <a href="/glossary/networth/attestation">Attestation</a>, <a href="/glossary/networth/foreign-inward-remittance-certificate-firc">Foreign Inward Remittance Certificate (FIRC)</a>, <a href="/glossary/networth/liberalised-remittance-scheme-lrs">Liberalised Remittance Scheme (LRS)</a>, <a href="/glossary/networth#certification-engagement">Certification Engagement</a>. One is issued by the recipient's tax authority abroad. One is a declaration the recipient furnishes. One evidences money arriving in the other direction. A remitter who assembles them in the wrong order usually finds that the one they obtained first has expired by the time the rest arrive.</p>
      </section>
