<h3 class="faq-expanded__q">What does Form 26AS show?</h3>
<div class="faq-expanded__a"><p>Form 26AS is the annual tax statement associated with a permanent account number. It shows tax deducted and collected at source, advance tax and self assessment tax paid, and refunds issued. It reports tax credits rather than the underlying assets those transactions relate to. It is available on the income tax portal against the taxpayer&#x27;s own login for each assessment year.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Why is Form 26AS read before a certificate is issued?</h3>
<div class="faq-expanded__a"><p>Because it corroborates. Interest credited on deposits, rent received and payments on sale of property leave a deduction trail. So an entry in the statement points to an asset or a transaction. A chartered accountant uses it to test whether the client&#x27;s schedule is complete.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does Form 26AS relate to the Annual Information Statement?</h3>
<div class="faq-expanded__a"><p>The wider statement introduced under section 285BB carries a far broader set of reported transactions, while Form 26AS retains the tax credit information. Both are read together, since one shows what tax was deducted and the other shows what the department was told about the transaction.</p></div>
