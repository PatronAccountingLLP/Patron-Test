      <section id="what-form-26as-carries-after-its-rewrite-as-an-a" class="gl-sec">
        <h2>What Form 26AS Carries After Its Rewrite as an Annual Tax Statement</h2>
        <div class="definition-box" itemprop="description"><p>Form 26AS was rewritten from a tax credit statement into an annual tax statement, and what it carries changed with it. It still shows tax deducted at source by every deductor who reported against the taxpayer's PAN, tax collected at source, advance tax and self-assessment tax paid, and refunds issued. To that it added information about specified financial transactions, demands and proceedings pending or completed, and details of tax deducted on the sale of immovable property. Much of the transaction reporting has since moved to the annual information statement, so the two overlap and are read together rather than as alternatives. The rewrite matters mainly for what moved out of it. Reporting that once sat here now appears in the wider annual statement, so a reader working from an older checklist can conclude an entry is missing when it has simply been relocated.</p></div>
      </section>
      <section id="which-26as-entries-a-ca-ties-back-to-declared-in" class="gl-sec">
        <h2>Which 26AS Entries a CA Ties Back to Declared Income and Assets</h2>
        <p>For a certifying accountant the entries that matter are the ones that tie a declared income to an asset. Interest reported by a bank confirms a deposit exists and gives a sense of its size. Tax deducted on a property sale confirms a transaction and its value. Tax deducted by an employer corroborates salary. Where a client's asset list includes a holding that generated no reported income, and where income was reported from a source the client did not mention, both are worth a question. The statement is not proof of ownership, but it is very good at revealing what somebody forgot to mention. Tying the entries back is a reconciliation rather than a lookup. Credits appear against the deductor's reporting and the taxpayer's accounting period, and the two do not always align. A credit can be genuine and still not match the year it is being tested against. Where it does not, the difference is explained rather than adjusted away.</p>
      </section>
      <section id="tds-credits-high-value-transaction-entries-and-t" class="gl-sec">
        <h2>TDS Credits, High-Value Transaction Entries and TRACES Downloads in Indian Practice</h2>
        <p>The statement is downloaded from the TRACES system or through the income tax portal, and it updates as deductors file their quarterly returns. That timing produces the most common confusion: tax deducted in the final quarter of a year frequently does not appear until well after the year has ended, so a statement pulled early looks incomplete. Mismatches between what an employer or bank deducted and what appears are usually a reporting failure by the deductor rather than an error by the taxpayer. Correcting them means going back to the deductor rather than to the department. A credit missing here is usually the deductor's omission and not the taxpayer's. It is corrected by the deductor revising their statement, which the taxpayer can request but cannot perform. Because that correction runs on someone else's timetable, a certificate waiting on it carries an open dependency. Naming that dependency beats letting the date slip without explanation. Waiting is usually the only honest option.</p>
      </section>
      <section id="tax-statements-reviewed-together-with-form-26as" class="gl-sec">
        <h2>Tax Statements Reviewed Together With Form 26AS</h2>
        <p>The tax statements reviewed together with this one each show a different slice. One reports what third parties told the department about transactions rather than about tax. One is the acknowledgement that a return was actually filed. One is the wider discipline of establishing where an asset came from. The last is the reserve classification that matters when the taxpayer is a company rather than an individual. The statements reviewed alongside this one overlap enough to be confused and differ enough to matter. <a href="/glossary/networth/annual-information-statement-ais">Annual Information Statement (AIS)</a>, <a href="/glossary/networth#itr-v-acknowledgement">ITR-V (Acknowledgement)</a>, <a href="/glossary/networth/source-of-funds">Source of Funds</a>, <a href="/glossary/networth/free-reserves">Free Reserves</a>. One is the broader annual record of reported transactions. One is its summarised, category-level view. One is the return that draws on both. This form is the narrowest of the group and also the most authoritative on its own subject, because it reports tax actually credited against the taxpayer's account rather than transactions reported about them. Checking them against each other before certifying is quicker than explaining a difference afterwards.</p>
