      <section id="which-reserves-qualify-as-free-under-section-2-4" class="gl-sec">
        <h2>Which Reserves Qualify as Free Under Section 2(43)</h2>
        <div class="definition-box" itemprop="description"><p>Free reserves are the part of a company's reserves available for distribution as dividend, and section 2(43) of the Companies Act 2013 defines them by exclusion. What counts is reserves built from profits the company actually earned and retained. What does not count is any amount representing unrealised gains, notional or revaluation gains, or a change in the carrying amount of an asset or liability recognised in equity through a fair value adjustment. A reserve earmarked for a specific statutory purpose is not free either, because the company is not at liberty to distribute it. The definition matters beyond dividends, because free reserves feed several other tests including the regulatory capital of a non-banking financial company. The test is availability for distribution rather than presence on the balance sheet. A reserve can be substantial, properly created and audited, and still fall outside the definition because it was never available to be paid out.</p></div>
      </section>
      <section id="how-free-reserves-lift-the-certified-net-worth-o" class="gl-sec">
        <h2>How Free Reserves Lift the Certified Net Worth of a Company</h2>
        <p>Free reserves lift certified net worth because they are one of the additions the statutory definition makes. Paid-up capital, the securities premium account and reserves created out of profits are added together before the deductions are applied. The practical consequence is that a company with modest capital and years of retained earnings can carry a substantial certified position, while one with large capital and accumulated losses carries very little. Classifying reserves correctly is therefore not a presentational nicety. Including a reserve that does not qualify inflates the figure directly, and it is the error a reader with the accounts in front of them is most likely to catch. The lift is real but it is not the same as cash. Reserves represent profits retained rather than money held, and a company can carry sizeable free reserves while being unable to fund a modest payment. A reader assessing capacity to pay looks past the reserve line to what the assets behind it actually are.</p>
      </section>
      <section id="unrealised-gains-notional-credits-and-audited-ac" class="gl-sec">
        <h2>Unrealised Gains, Notional Credits and Audited Accounts Filed With the MCA</h2>
        <p>The reserves most often misclassified are the ones created by an accounting entry rather than by earning. A revaluation reserve arises when an asset is written up without being sold, and the gain is unrealised by definition. Amounts sitting in other comprehensive income under Ind AS are similarly unrealised in most cases. A reserve created by writing back depreciation reverses an earlier charge rather than recording a profit. All are visible in the audited accounts filed with the Ministry of Corporate Affairs, which is where a tender committee or a lender will look. A classification that differs from the filed accounts has to be explained rather than merely asserted. Two exclusions do most of the work in practice and both are routinely missed. Amounts arising from writing an asset up have not been earned and are excluded. Amounts credited on a measurement basis that has not been realised are excluded on the same reasoning. A figure taken from the audited accounts without applying these is usually too high.</p>
      </section>
      <section id="reserve-categories-read-with-free-reserves" class="gl-sec">
        <h2>Reserve Categories Read With Free Reserves</h2>
        <p>The reserve categories read alongside this one are the ones the definition deliberately separates. One arises from writing an asset up and is excluded outright. One arises on a share issue above face value and counts, despite not being a profit. One is the accumulated deficit that reduces the position rather than adding to it. The last is the measure that removes intangibles as well, which several tender conditions specify in preference to the ordinary figure. The reserve categories read with this one sit on the same side of the balance sheet and behave quite differently. <a href="/glossary/networth/revaluation-reserve">Revaluation Reserve</a>, <a href="/glossary/networth/securities-premium">Securities Premium</a>, <a href="/glossary/networth#accumulated-losses">Accumulated Losses</a>, <a href="/glossary/networth/tangible-net-worth">Tangible Net Worth</a>. One arises on a share issue above par and is restricted to named uses. One arises on writing an asset up and is excluded from the certified figure. One is the accumulated balance of profits carried forward. Only the last is freely distributable in the ordinary case, which is why the aggregate of the reserves line answers almost nothing on its own.</p>
      </section>
