<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What counts as free reserves?</h3>
<div class="faq-expanded__a"><p>Section 2(43) of the Companies Act 2013 defines them as reserves available for distribution as dividend, as per the latest audited balance sheet. Unrealised gains, notional gains and revaluation of assets are excluded, as are amounts representing a change in the carrying value on fair value measurement.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Why does the definition matter beyond dividends?</h3>
<div class="faq-expanded__a"><p>Because several provisions key off it. Limits on loans, guarantees and investments, on buy-back and on managerial remuneration are calculated with reference to free reserves. A reserve sitting on the balance sheet that fails the definition therefore cannot support those transactions. Section 186 on loans and investments and section 68 on buy-back both compute their limits that way.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is the securities premium a free reserve?</h3>
<div class="faq-expanded__a"><p>It is not distributable as dividend, and section 52 confines its application to specified purposes. It nevertheless forms part of the net worth computation under section 2(57), which lists it separately from reserves created out of profits. The two questions have different answers. So a reserve can be inside the net worth figure and outside the distributable pool at once.</p></div>
