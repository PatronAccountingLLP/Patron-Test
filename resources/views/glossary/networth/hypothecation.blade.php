      <section id="hypothecation-defined-a-charge-without-handing-o" class="gl-sec">
        <h2>Hypothecation Defined: A Charge Without Handing Over the Goods</h2>
        <div class="definition-box" itemprop="description"><p>Hypothecation creates a charge over movable property without the creditor taking possession of it. The borrower keeps the goods, continues to use them and, in the case of trading stock, continues to sell and replace them as the business requires. This is what makes hypothecation workable for assets a business needs daily. A vehicle being driven, machinery in production, inventory turning over, receivables collected and replaced. The creditor's protection lies in the charge document and its registration rather than in physical control. That is also why hypothecation is considerably easier for a borrower to forget about than a pledge, since nothing has left their hands and daily use continues exactly as before. Nothing about holding the asset reminds the owner that somebody else has a claim over it. The practical consequence is that hypothecated assets look entirely unencumbered to anybody relying on inspection alone. Only the paperwork reveals the charge, which is why the paperwork is what gets examined. The charge is created by the loan agreement itself rather than by any transfer of the goods. That is what allows a business to finance stock it intends to sell the following week.</p></div>
      </section>
      <section id="disclosing-hypothecated-vehicles-stock-and-recei" class="gl-sec">
        <h2>Disclosing Hypothecated Vehicles, Stock and Receivables to the Certifying CA</h2>
        <p>Hypothecated assets are disclosed to the certifying accountant together with the facility they secure, because the asset appears at full value on the statement while being encumbered in substance. A vehicle under a running loan is the most frequently overlooked example. The registration certificate names the borrower as owner, and the loan sits in a separate ledger nobody opens. Stock and receivables hypothecated to a working capital facility are the next most common. The correct presentation shows the asset, the charge over it, the outstanding amount and the lender. A reader can then net the position rather than discovering the charge in their own search. The question is therefore asked directly rather than folded into a general enquiry about borrowings. Clients answer accurately when asked about a specific vehicle or a specific stock line, and vaguely when asked about liabilities in general. Where a facility has been repaid but the charge never released, that is disclosed too. An unsatisfied charge on the record is a question the lender will raise even though nothing is owed.</p>
      </section>
      <section id="cersai-filings-rc-book-endorsements-and-mca-form" class="gl-sec">
        <h2>CERSAI Filings, RC Book Endorsements and MCA Form CHG-1 in Indian Practice</h2>
        <p>The Indian record trail for hypothecation is unusually good and is used as a cross-check rather than taken on trust. Charges created by companies are filed with the Registrar of Companies in Form CHG-1 and appear on the public record at the Ministry of Corporate Affairs. Security interests over assets are registered with CERSAI, which lenders search as a matter of routine before sanctioning. A hypothecated vehicle carries the financier's name endorsed on the registration certificate itself, visible to anybody who looks at it. Between these three sources, a charge omitted from a certificate is likely to surface before the file is decided. Disclosure costs nothing; omission costs the credibility of everything else. A certifying accountant treats these registers as the primary record and the client's recollection as secondary. Where the two disagree the register governs, and the difference is raised rather than reconciled quietly.</p>
      </section>
      <section id="where-hypothecation-ends-and-other-charges-begin" class="gl-sec">
        <h2>Where Hypothecation Ends and Other Charges Begin</h2>
        <p>The boundary between hypothecation and its neighbours is worth reading, because the three security forms are routinely used interchangeably in conversation and are not interchangeable at all. One involves possession passing to the lender, which hypothecation specifically avoids. One applies to immovable property and works through an interest in the land itself rather than a charge over goods. The third is the general concept of a registered claim against assets, which is where a hypothecation becomes visible to the outside world. Alongside them sits the certificate a sub-registrar issues, showing what has been registered against a property. It answers for immovable assets what a CERSAI search answers for movable ones. <a href="/glossary/networth/pledge">Pledge</a>, <a href="/glossary/networth/mortgage">Mortgage</a>, <a href="/glossary/networth#charge-on-assets">Charge on Assets</a>, <a href="/glossary/networth/encumbrance-certificate">Encumbrance Certificate</a>. Knowing which of the three applies decides how the asset is presented on the statement. Using the wrong term suggests the underlying arrangement was never actually examined. The registers described above are what make the distinction checkable by an outsider. Without them, hypothecation would be the easiest charge in Indian lending to leave undisclosed.</p>
      </section>
