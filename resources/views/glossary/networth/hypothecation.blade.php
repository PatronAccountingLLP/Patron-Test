<h3 class="faq-expanded__q">How does hypothecation differ from a pledge?</h3>
<div class="faq-expanded__a"><p>Possession stays with the borrower. Hypothecation creates a charge over movable property without delivering it, which is why it is used for vehicles, stock in trade and book debts. The SARFAESI Act 2002 defines it in those terms, and the borrower goes on using the asset while the charge subsists.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Where is a hypothecation charge registered?</h3>
<div class="faq-expanded__a"><p>For a company, with the Registrar of Companies. Section 77 of the Companies Act 2013 requires charges to be registered within the prescribed period, and the register is public. Vehicle hypothecation is endorsed on the registration certificate. Those records are what a chartered accountant checks before treating an asset as unencumbered.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does hypothecated stock appear in a net worth statement?</h3>
<div class="faq-expanded__a"><p>Yes, as an asset, with the charge disclosed. Stock financed by a cash credit limit is owned by the borrower and enters the schedule at its valuation. The lender&#x27;s charge over it appears in the liabilities and notes, so the reader sees both the asset and the claim against it.</p></div>
