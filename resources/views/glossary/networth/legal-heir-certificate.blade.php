      <section id="what-a-legal-heir-certificate-establishes-about" class="gl-sec">
        <h2>What a Legal Heir Certificate Establishes About Family Ties</h2>
        <div class="definition-box" itemprop="description"><p>A legal heir certificate records who the surviving family members of a deceased person are. It names the spouse, children, parents and, depending on the state, other dependants, and it states their relationship to the deceased. That is all it does. It establishes family ties for administrative purposes: transferring a pension, claiming provident fund or gratuity, transferring a utility connection, or getting a name changed in municipal records. It is not a determination of who inherits what, and it does not resolve a dispute between heirs. Where the family is agreed and the assets are straightforward it is usually sufficient, which is why it is the document most families obtain first and often the only one they need. Because it is quick and cheap it is also over-relied on. Families frequently obtain one, assume the estate is settled, and discover months later that the bank holding the largest balance wants a court order instead.</p></div>
      </section>
      <section id="why-a-ca-wants-heirship-settled-before-listing-i" class="gl-sec">
        <h2>Why a CA Wants Heirship Settled Before Listing Inherited Property</h2>
        <p>A chartered accountant wants heirship settled before inherited property appears on a statement of assets, because until it is settled the applicant may not own what they believe they own. Property standing in a deceased parent's name does not pass to a child on the day of death in any administratively useful sense; it passes on succession, and until the record reflects that, the asset cannot be evidenced by a title document in the applicant's name. Listing it anyway is the kind of entry a bank's own search contradicts. Where the position is unsettled the honest treatment is to disclose the interest and its status rather than to state the asset as owned outright. The same caution applies to bank balances and shares standing in the deceased's name. They belong to the estate until transmission is complete, and an applicant who lists them as their own is describing a position the bank's own records contradict.</p>
      </section>
      <section id="tahsildar-and-revenue-office-issuance-across-ind" class="gl-sec">
        <h2>Tahsildar and Revenue Office Issuance Across Indian States</h2>
        <p>Issuance sits with the revenue administration rather than with a court. A tahsildar, revenue officer or equivalent district authority issues it on application, usually supported by the death certificate, proof of relationship and an affidavit. Several states now accept applications through an online revenue portal and issue digitally signed certificates. Timelines vary widely by state and by district, from a fortnight to a few months, and a local objection extends it further. Because it is an administrative act rather than a judicial one it costs less and takes less time than the court route. That is the whole reason it exists alongside it. Some states issue a family membership certificate serving the same purpose under a different name, and a few require a separate affidavit from the applicant confirming that no other heir exists. Local practice governs, and it varies more than most applicants expect.</p>
      </section>
      <section id="how-its-reach-differs-from-that-of-a-succession" class="gl-sec">
        <h2>How Its Reach Differs From That of a Succession Certificate</h2>
        <p>Its reach is narrower than that of a succession certificate in one decisive respect. A legal heir certificate identifies the heirs; a succession certificate issued by a civil court empowers the holder to collect debts and securities owed to the deceased and gives the payer a discharge. A bank asked to release a substantial balance, or a company asked to transfer shares, will usually want the court document rather than the revenue one, because the discharge protects them. For a pension or a provident fund claim the revenue document is normally enough. Knowing which the institution requires before applying saves months, since the two routes run in different offices. Institutions also differ in what they accept for the same asset class. Two banks holding similar balances can ask for different documents, and the amount at stake is usually what decides it.</p>
      </section>
      <section id="inheritance-proofs-filed-along-with-a-heirship-r" class="gl-sec">
        <h2>Inheritance Proofs Filed Along With a Heirship Record</h2>
        <p>The proofs filed alongside a heirship record are the documents that complete the picture of an estate. One is the court instrument described above, obtained where debts or securities have to be collected. One is the instrument evidencing title to any immovable property, which is what a certifying accountant reads rather than the heirship record itself. One is the undertaking an institution frequently requires from heirs before releasing an asset without a court order. The last is the instrument by which property is transferred during life rather than on death, which is often what a family should have used and did not. <a href="/glossary/networth/succession-certificate">Succession Certificate</a>, <a href="/glossary/networth#title-deed">Title Deed</a>, <a href="/glossary/networth#indemnity-bond">Indemnity Bond</a>, <a href="/glossary/networth#gift-deed">Gift Deed</a>. Getting the requirement from the institution in writing before applying is the single practical step that saves the most time, because the answer varies by branch as well as by bank.</p>
