<h3 class="faq-expanded__q">What is a legal heir certificate?</h3>
<div class="faq-expanded__a"><p>It is a revenue authority document identifying the surviving members of a deceased person&#x27;s family. It is issued at the tehsildar or equivalent level, and is used for pension claims, provident fund settlement, insurance and employment on compassionate grounds. It records who the heirs are.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does a legal heir certificate differ from a succession certificate?</h3>
<div class="faq-expanded__a"><p>By issuing authority and legal effect. A revenue officer issues the heir certificate to identify family members; a civil court grants a succession certificate authorising collection of debts and securities. Banks and depositories dealing with substantial holdings usually want the court document, not the revenue one.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is either enough to transfer immovable property?</h3>
<div class="faq-expanded__a"><p>Neither decides title. Transfer of immovable property on death follows the will, if probated where required, or the applicable succession law, with mutation recorded in the revenue or municipal register. The heir certificate supports the mutation application; it does not by itself establish ownership. Where a will exists, probate under the Indian Succession Act 1925 may be required in some jurisdictions.</p></div>
