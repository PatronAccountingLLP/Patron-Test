<h3 class="faq-expanded__q">What is a letter of credit?</h3>
<div class="faq-expanded__a"><p>It is a bank&#x27;s undertaking to pay a seller against presentation of specified documents, not against physical delivery of goods. Most cross-border credits are issued subject to the ICC Uniform Customs and Practice, currently UCP 600. The bank examines documents on their face and pays if they comply.</p></div>
