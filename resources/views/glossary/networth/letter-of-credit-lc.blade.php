      <section id="what-an-lc-undertakes-to-pay-against" class="gl-sec">
        <h2>What an LC Undertakes to Pay Against</h2>
        <div class="definition-box" itemprop="description"><p>A letter of credit is an undertaking by a bank to pay a seller against documents rather than against goods. The bank pays when the documents presented match the credit exactly: the invoice, the transport document, the insurance certificate and whatever else the credit names. It does not inspect the shipment and it is not concerned with whether the goods arrived in good order. This is what makes an LC workable across borders between parties who have never met, and it is also why a discrepancy as small as a misspelt consignee name can hold up payment. Because payment turns on documents alone, the seller's risk shifts from the buyer's willingness to pay to their own ability to present a compliant set. Discrepancy rates on first presentation are high across the industry, and most are clerical rather than substantive.</p></div>
      </section>
      <section id="how-lc-limits-appear-in-a-borrower-s-certified-l" class="gl-sec">
        <h2>How LC Limits Appear in a Borrower&#x27;s Certified Liability Position</h2>
        <p>An LC limit appears in a borrower's certified liability position even before anything is drawn. The bank has committed to pay on presentation, so the exposure exists from the day the credit is opened. Where the LC is unpaid at the certificate date it is disclosed as a contingent liability beneath the figure rather than deducted from it, because the obligation crystallises only when documents are presented. Where a bill under the credit has already been accepted, that is a firm liability and comes into the computation properly. A certificate prepared for a borrower with LC limits therefore states the sanctioned limit, the amount currently outstanding under it, and whether any bill has been accepted. Reporting only the limit overstates the obligation; reporting only the drawn amount understates the exposure.</p>
      </section>
      <section id="sight-and-usance-lcs-ucp-600-and-indian-import-d" class="gl-sec">
        <h2>Sight and Usance LCs, UCP 600 and Indian Import Documentation</h2>
        <p>Indian import practice runs mostly on two forms. A sight credit pays when compliant documents are presented. A usance credit pays after a stated period, which finances the buyer for that time and appears as an acceptance in the books. Both operate under the uniform customs and practice rules that banks worldwide apply, so a discrepancy is judged against a common standard rather than local usage. The bank also requires margin and a charge over the goods or the documents. Amendments to a credit require the agreement of every party, so a change requested after shipment is slow and occasionally impossible. Getting the terms right at opening is worth more effort than it usually receives. Indian banks also require the underlying import documentation to match the credit exactly, and a mismatch between the bill of entry and the invoice is a common cause of delay at the counter.</p>
      </section>
      <section id="where-an-lc-parts-company-with-a-bank-guarantee" class="gl-sec">
        <h2>Where an LC Parts Company With a Bank Guarantee</h2>
        <p>An LC parts company with a bank guarantee on when payment is expected. A letter of credit is a payment mechanism: everybody involved intends it to be used, and the seller ships expecting to present documents and be paid. A guarantee is a safety net that nobody expects to invoke, and invocation means something has gone wrong. That difference explains why the two are priced and secured differently even where the amounts match. That distinction matters commercially: a business regularly using LCs is financing its trade, while one holding guarantees is providing assurance. Lenders assess the two activities differently. A borrower using both should expect the bank to price them differently as well, since one is a payment it intends to make and the other is a risk it hopes never to carry.</p>
      </section>
      <section id="trade-finance-terms-that-sit-beside-an-lc" class="gl-sec">
        <h2>Trade Finance Terms That Sit Beside an LC</h2>
        <p>The trade finance terms sitting beside a letter of credit are the ones that determine how much of it the borrower funds and what the bank holds. One is the bank's own promise to pay on default rather than on presentation. One is the borrower's cash contribution held against the exposure. One is the wider category of security taken. The last is the document recording the limit, the margin and the conditions attached. <a href="/glossary/networth/bank-guarantee-bg">Bank Guarantee (BG)</a>, <a href="/glossary/networth/margin-money">Margin Money</a>, <a href="/glossary/networth/collateral">Collateral</a>, <a href="/glossary/networth#sanction-letter">Sanction Letter</a>. A borrower carrying both should expect each to be limited separately rather than sharing one overall ceiling. For a certifying accountant the practical point is that trade facilities move quickly. A position accurate at the start of a month can be materially different by its end. The certificate names the date it speaks to, and balances are confirmed with the bank rather than taken from the borrower's ledger.</p>
      </section>
