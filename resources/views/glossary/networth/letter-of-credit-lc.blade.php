<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does a letter of credit differ from a bank guarantee?</h3>
<div class="faq-expanded__a"><p>A credit is a payment mechanism used in the ordinary course of trade; the bank expects to pay. A guarantee is a default mechanism; the bank expects not to. That difference in purpose explains why they are documented, priced and margined differently by the same bank.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does an outstanding credit affect the applicant&#x27;s certified position?</h3>
<div class="faq-expanded__a"><p>It is disclosed while it remains contingent. Once documents are accepted and the bank pays, the applicant owes the bank and the item becomes a recorded liability. Until then it appears as a commitment, with the amount and expiry stated so the reader can see the exposure.</p></div>
