      <section id="what-lrs-permits-a-resident-individual-to-do" class="gl-sec">
        <h2>What LRS Permits a Resident Individual to Do</h2>
        <div class="definition-box" itemprop="description"><p>The liberalised remittance scheme permits a resident individual to remit money abroad up to a limit in each financial year, for a defined set of purposes. Those purposes include education, medical treatment, travel, maintenance of relatives, gifts, and investment in overseas securities or property. What it does not permit is remittance for purposes the scheme excludes, including margin trading and certain capital account transactions. The limit applies per individual rather than per family, so a household can remit several times the individual figure by using each member's allowance, and each member's remittance is documented separately. Minors are covered, with the natural guardian signing. The scheme is a facility rather than an entitlement, and banks apply their own diligence on top of it.</p></div>
      </section>
      <section id="why-banks-seek-a-certified-net-worth-position-be" class="gl-sec">
        <h2>Why Banks Seek a Certified Net Worth Position Before Large Outward Remittances</h2>
        <p>Banks ask for a certified net worth position before a large outward remittance because the scheme puts the onus on them to satisfy themselves that the funds are the remitter's own and lawfully held. A remittance close to the annual limit, particularly one funding an overseas property purchase or a substantial investment, invites the question of where the money came from. A certificate showing the wider position, with the source of the remitted funds identified, answers it in a form the bank can file. Where the remitter is self-employed the certificate carries more weight still, because salary credits are not available as an explanation and the returns alone may not show the accumulation. The bank's interest is in the relationship between the remittance and the position behind it, not in the position alone. A modest transfer from a substantial holder raises nothing. A transfer close to the annual ceiling from someone whose certified position it would largely exhaust invites the obvious question of where the money came from. A statement that anticipates the question travels well; one that waits to be asked invites it twice.</p>
      </section>
      <section id="the-per-financial-year-limit-form-a2-and-tcs-tou" class="gl-sec">
        <h2>The Per-Financial-Year Limit, Form A2 and TCS Touchpoints on LRS Remittances</h2>
        <p>Three touchpoints recur on every remittance. Form A2 is the declaration the remitter signs, stating the purpose and confirming the remittance falls within the scheme. The bank collects supporting documents matched to the purpose declared, and these differ sharply between an education remittance and an investment one. Tax is collected at source on remittances above a threshold, at rates that vary by purpose, with education remittances funded by an education loan treated more favourably than others. The tax collected is creditable against the remitter's own liability rather than being a cost, which remitters frequently misunderstand and occasionally use as a reason to split a transfer, which banks notice. Collection at source is a timing cost rather than a tax cost, and applicants routinely misread it. The amount collected is credited against the remitter's own liability and can be claimed in the return, so what it consumes is cash for a period rather than value. Planning the sequence of transfers within the year, rather than the total, is where the difference actually shows.</p>
      </section>
      <section id="remittance-rules-adjacent-to-the-lrs-route" class="gl-sec">
        <h2>Remittance Rules Adjacent to the LRS Route</h2>
        <p>The rules adjacent to this route govern money moving in the other direction or being converted along the way. One is the discipline of establishing where funds originated, which the scheme's diligence turns on. One is the destination structure a student remittance most often funds. One is the certificate evidencing money that came into India. The last is the document a bank issues recording the rate at which a conversion was done. The rules adjacent to this route govern what may leave India and under whose authority. <a href="/glossary/networth/source-of-funds">Source of Funds</a>, <a href="/glossary/networth/blocked-account">Blocked Account</a>, <a href="/glossary/networth/foreign-inward-remittance-certificate-firc">Foreign Inward Remittance Certificate (FIRC)</a>, <a href="/glossary/networth#currency-conversion-certificate">Currency Conversion Certificate</a>. One sets the framework the scheme sits inside. One covers remittances the scheme does not reach. One governs the certification a bank asks for before releasing funds abroad. Confusing a limit set by the scheme with a restriction imposed elsewhere is common, and it usually surfaces at the counter when the transfer is already time-bound.</p>
      </section>
