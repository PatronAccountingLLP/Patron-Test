<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does the Liberalised Remittance Scheme allow?</h3>
<div class="faq-expanded__a"><p>It allows a resident individual to remit money abroad up to an annual limit set by the Reserve Bank, for permitted current and capital account purposes. Those include education, travel, medical treatment, maintenance of relatives, gifts and overseas investment. The limit applies per individual per financial year.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does tax get collected on a remittance under the scheme?</h3>
<div class="faq-expanded__a"><p>Yes, above a threshold. Section 206C(1G) of the Income-tax Act requires the authorised dealer to collect tax at source on such remittances. Different rates apply to education and medical purposes. The amount collected is credited against the remitter&#x27;s tax liability and appears in their tax statement.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is the scheme available to a company or a firm?</h3>
<div class="faq-expanded__a"><p>No. It is confined to resident individuals, including minors, whose guardian signs the declaration. Companies, firms and other entities remit under separate provisions governing current and capital account transactions. That distinction matters when a family business intends to fund a study or investment abroad. The remitting bank collects a Form A2 declaration confirming the remitter&#x27;s eligibility and the purpose.</p></div>
