<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What is a banker&#x27;s lien?</h3>
<div class="faq-expanded__a"><p>It is a general lien recognised by section 171 of the Indian Contract Act 1872. That lets a banker retain goods bailed to it as security for a general balance of account. In practice a bank marks a lien on a deposit or on securities, so the customer cannot withdraw while dues remain.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does a lien transfer ownership of the asset?</h3>
<div class="faq-expanded__a"><p>No. A lien is a right to retain, not a right of ownership or, by itself, a right to sell. The holder keeps title throughout. That is why an asset under lien still appears in a net worth schedule, with the charge disclosed rather than the asset removed.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How is a lien recorded so a certifying chartered accountant can see it?</h3>
<div class="faq-expanded__a"><p>Through the account or holding statement. A bank marks the lien on the deposit advice or the account record, and a depository shows a freeze or pledge marking against demat holdings. Those markings are the evidence, which is why statements are read as at the certificate date rather than taken from an older printout.</p></div>
