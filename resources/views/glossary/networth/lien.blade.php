      <section id="what-creates-a-lien-over-an-asset-in-india" class="gl-sec">
        <h2>What Creates a Lien Over an Asset in India</h2>
        <div class="definition-box" itemprop="description"><p>A lien is a creditor's right to retain something belonging to a debtor until what is owed has been paid. It arises in two distinct ways. A particular lien attaches to a specific item in respect of a specific debt. That is how a repairer keeps a vehicle until the bill is settled, and a warehouse keeps goods until storage is cleared. A general lien allows the holder to retain anything of the debtor's that comes into their possession, against any balance due. Bankers hold one by long established practice. The feature that matters for certification is that a lien does not transfer ownership at all. The asset remains the debtor's property throughout. That is why it still belongs on a statement of assets, and why the encumbrance appears beside it. Nor does a lien require any registration to be effective between the parties. Its invisibility on public records is precisely why it has to be asked about directly.</p></div>
      </section>
      <section id="how-a-lien-marked-deposit-is-reported-in-a-state" class="gl-sec">
        <h2>How a Lien-Marked Deposit Is Reported in a Statement of Assets and Liabilities</h2>
        <p>A lien-marked deposit is reported at its full value with the lien disclosed against it. It is never dropped from the statement and never shown as free. Dropping it understates the position and creates an obvious question the moment the bank statement shows a balance the certificate does not account for. Showing it as free overstates what is genuinely available and will be corrected by the recipient, usually with a loss of confidence in the rest of the document. The correct presentation gives the deposit, the amount under lien, the creditor holding it and the balance that remains unencumbered. Where the whole deposit is marked, the available column simply reads nil, which is far more informative than an omission and considerably safer than any implication that the money could be reached if needed. The same treatment applies to a balance frozen by an order rather than by a creditor. The money exists, it belongs to the account holder, and it cannot be spent. The same discipline applies to a partial marking. Where only part of a deposit is held, the statement gives both figures rather than rounding to whichever is convenient.</p>
      </section>
      <section id="lien-marking-by-indian-banks-statement-entries-s" class="gl-sec">
        <h2>Lien Marking by Indian Banks: Statement Entries, Set-Off Rights and NOC Letters</h2>
        <p>Indian banks mark liens in ways that leave a visible trail, and each part of it is asked for. The account statement itself usually carries a lien marking or a hold against the balance. The sanction letter for the facility the lien secures will describe the security taken. A no-objection certificate from the bank is what evidences release, and its absence is treated as meaning the lien subsists rather than as an administrative gap. Banks also hold rights of set-off, applying a credit balance against a debt without marking the account. A facility with the same bank is therefore raised even where no lien appears. The absence of a marking is not evidence that the balance is free. Where a bank confirms a balance in writing, the confirmation is asked to state any lien as well. A balance confirmation silent on encumbrance answers only half the question that was put to it.</p>
      </section>
      <section id="other-charge-creating-terms-worth-reading-next" class="gl-sec">
        <h2>Other Charge-Creating Terms Worth Reading Next</h2>
        <p>The other charge-creating terms worth reading next describe the remaining ways an asset can be tied up without changing hands. One is an undertaking not to create any further charge over an asset. It restricts the owner without giving the lender anything to hold, and is easy to overlook because nothing is marked. One is the general concept of a claim registered against assets, which is where a company's charges appear on the public record. One describes the asset that results, encumbered rather than free. The last is the wider category of anything given as security for a facility. Between them they account for almost every reason a holding on a statement may be worth less to a reader than its face value suggests. <a href="/glossary/networth#negative-lien">Negative Lien</a>, <a href="/glossary/networth#charge-on-assets">Charge on Assets</a>, <a href="/glossary/networth#encumbered-asset">Encumbered Asset</a>, <a href="/glossary/networth/collateral">Collateral</a>. The common thread is that ownership is undisturbed while availability is not. A statement recording only ownership tells a reader half of what they need, and it is usually the less useful half.</p>
