      <section id="which-holdings-count-as-liquid-and-which-only-lo" class="gl-sec">
        <h2>Which Holdings Count as Liquid and Which Only Look Liquid</h2>
        <div class="definition-box" itemprop="description"><p>Liquid assets are holdings that can be converted into cash quickly and at a value that can be predicted in advance. Bank balances qualify without argument. Fixed deposits qualify with a reservation, since breaking one early costs interest and a deposit under lien cannot be broken at all while the lien stands. Listed shares and mutual fund units qualify, subject to the caveat that the value on the day of sale is not the value printed on the certificate. Several holdings do not qualify, despite being presented as though they do. Immovable property, unlisted equity, money lent to family and jewellery are the usual ones. Each may be genuinely valuable and each may eventually be sold. None can be turned into money inside the window a reader has in mind. The test is not whether an asset is good. It is whether it can be spent. The category also shifts with circumstance rather than being fixed. A listed holding under a lock-in is not liquid until the lock-in ends, whatever the exchange price says.</p></div>
      </section>
      <section id="how-liquid-holdings-are-segregated-inside-a-cert" class="gl-sec">
        <h2>How Liquid Holdings Are Segregated Inside a Certified Statement</h2>
        <p>Inside a certified statement the liquid holdings are segregated rather than folded into a single total. The statement shows the overall position, then separates what is readily available from what is not, with the basis for the split stated so the reader can disagree with it if they wish. This matters because two applicants with identical net worth can be in entirely different positions. One holds balances that could fund a trip tomorrow; the other holds a property that would take months to sell. Segregation lets the reader see which of the two they are dealing with without interrogating the annexure line by line. Where a holding is partly encumbered, the encumbered portion is shown separately again, because a lien-marked deposit is not available whatever its balance appears to say. The split also protects the preparer. A certificate that never claimed a property was liquid cannot later be said to have implied it.</p>
      </section>
      <section id="why-consulates-and-indian-bankers-weight-savings" class="gl-sec">
        <h2>Why Consulates and Indian Bankers Weight Savings Balances, FDs and Cash Differently</h2>
        <p>Consulates and Indian bankers weight these holdings differently because they are answering genuinely different questions. A visa officer wants to know whether a trip can be funded without the applicant working abroad. Balances held steadily for months therefore outweigh a deposit that appeared last week. A banker assessing a facility wants to know what could be realised if repayment fails. A fixed deposit that can be marked as security beats an equity portfolio that might have halved. The same schedule of holdings therefore reads very differently depending on who receives it, which is why the purpose of the certificate is established before the holdings are classified. Establishing the purpose first is therefore not administrative politeness. It decides which holdings are worth evidencing in detail and which can be stated and left.</p>
      </section>
      <section id="neighbouring-terms-in-the-asset-quality-family" class="gl-sec">
        <h2>Neighbouring Terms in the Asset-Quality Family</h2>
        <p>The neighbouring terms belong to the asset-quality family rather than the asset-value family, and they are the concepts a reader reaches for once liquidity is on the table. One is what an asset would actually fetch if it had to be sold rather than what it is carried at. One is the instrument a bank issues for a term deposit, which is both the most common liquid holding on these statements and the one most often encumbered without the client mentioning it. The other two belong to visa practice specifically: the evidence pack a mission expects, and the expectation that money should have been held for a period rather than assembled for the application. Anyone certifying liquidity for a consular file needs all four. <a href="/glossary/networth#realisable-value">Realisable Value</a>, <a href="/glossary/networth#fixed-deposit-receipt-fdr">Fixed Deposit Receipt (FDR)</a>, <a href="/glossary/networth/proof-of-funds-pof">Proof of Funds (POF)</a>, <a href="/glossary/networth#fund-seasoning">Fund Seasoning</a>. A consular officer and a credit officer will read the same schedule and reach different conclusions from it. Both are entitled to. The schedule simply has to support either reading honestly, which means the classification has to be defensible rather than convenient. Anyone certifying liquidity for a consular file needs all four in view at once.</p>
      </section>
