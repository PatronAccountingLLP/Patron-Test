<h3 class="faq-expanded__q">Which holdings count as liquid?</h3>
<div class="faq-expanded__a"><p>Cash, balances in savings and current accounts, and deposits that can be broken on demand. Listed shares and units of open-ended mutual funds are near-cash, since they settle in days. Property, unlisted shares and receivables are not liquid, however valuable. Indian exchanges settle on a T+1 cycle, while converting property takes weeks or months.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Why do embassies weigh liquid assets more heavily?</h3>
<div class="faq-expanded__a"><p>Because the question they ask is whether the trip can be paid for. A large property holding shows accumulated wealth but cannot buy an air ticket next month. Missions therefore read bank balances and deposits as the operative evidence, with the wider asset schedule supporting the overall financial picture.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is a fixed deposit under lien still a liquid asset?</h3>
<div class="faq-expanded__a"><p>No. A deposit charged to a bank as security for a facility or a guarantee cannot be withdrawn while the charge subsists. It remains an asset and is included, but the lien is disclosed. Presenting encumbered money as available funds is what causes a lender or a mission to query the document.</p></div>
