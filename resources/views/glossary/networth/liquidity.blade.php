      <section id="what-liquidity-measures-over-the-near-term" class="gl-sec">
        <h2>What Liquidity Measures Over the Near Term</h2>
        <div class="definition-box" itemprop="description"><p>Liquidity measures whether obligations falling due in the near term can be met from resources available in the near term. It is a question about timing rather than about size. A business with substantial assets and nothing convertible within the month has a liquidity problem however wealthy it is on paper. The horizon is conventionally twelve months, matching the current classification in a balance sheet: current assets against current liabilities. What makes an asset current is that it will turn into cash within that window in the ordinary course of business. That is why stock counts even though selling it takes effort, and why a fixed deposit maturing in three years does not. The distinction also explains why a business can fail while remaining profitable. Profit is earned over a period and cash arrives when customers pay, and a business growing quickly can be profitable and short of cash at the same time. Lenders watch the gap closely, because it is where otherwise sound businesses come apart.</p></div>
      </section>
      <section id="why-a-solvent-applicant-can-still-fail-a-liquidi" class="gl-sec">
        <h2>Why a Solvent Applicant Can Still Fail a Liquidity Test</h2>
        <p>A solvent applicant can fail a liquidity test because solvency and liquidity ask different questions. Solvency asks whether total assets exceed total liabilities: could everything owed be paid if everything owned were sold. Liquidity asks whether what is due next month can be paid next month. A property developer holding land worth far more than its borrowings is solvent. It can still be unable to meet an instalment. This is the distinction that surprises applicants who present a strong net worth certificate to a tender committee and are told it does not answer the condition. Where the condition names a period, it is asking about liquidity. For an individual the same distinction appears in a different form. Someone holding two properties and no bank balance is solvent and illiquid, and a consulate assessing whether a trip can be funded is asking the second question rather than the first.</p>
      </section>
      <section id="current-and-quick-ratios-indian-banks-compute-fr" class="gl-sec">
        <h2>Current and Quick Ratios Indian Banks Compute From Audited Statements</h2>
        <p>Indian banks compute two ratios from audited statements. The current ratio divides current assets by current liabilities. A result comfortably above one is read as adequate, with the expectation varying by industry. The quick ratio removes stock from the numerator, on the view that inventory is the slowest current asset to realise and the first to lose value in difficulty. A business that passes on the current ratio and fails on the quick one is carrying its liquidity in stock, which a lender treats cautiously. Both are computed from the audited figures rather than from management accounts, which is why the audit date matters to the assessment. Both ratios are read against the industry rather than against an absolute. A retailer carrying heavy stock and a consultancy carrying none produce very different figures from equally sound businesses, and an appraiser who ignores that reaches the wrong conclusion twice over. A lender comparing two applicants in the same trade learns more from the gap between their ratios than from either figure alone.</p>
      </section>
      <section id="short-term-financial-terms-grouped-with-liquidit" class="gl-sec">
        <h2>Short-Term Financial Terms Grouped With Liquidity</h2>
        <p>The short-term terms grouped with liquidity describe what can actually be reached and how fast. One is the category of holdings convertible quickly and at a predictable value. One is the broader ratio family testing whether obligations can be met at all rather than on time. One is what an asset would fetch under time pressure, which is usually below its carrying value and is the figure that matters in a hurry. The last tests whether cash generated covers repayment falling due, which is liquidity expressed as a flow rather than as a stock. <a href="/glossary/networth/liquid-assets">Liquid Assets</a>, <a href="/glossary/networth/solvency-ratio">Solvency Ratio</a>, <a href="/glossary/networth#realisable-value">Realisable Value</a>, <a href="/glossary/networth/debt-service-coverage-ratio-dscr">Debt Service Coverage Ratio (DSCR)</a>. Between them these four separate what is owned from what can be reached, which is the distinction most often lost when a single net worth figure is quoted on its own. Reading them together is what separates a business that is merely asset-rich from one that can actually meet what falls due.</p>
      </section>
