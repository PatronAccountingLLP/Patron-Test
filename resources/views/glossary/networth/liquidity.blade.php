<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does liquidity mean for an individual or a business?</h3>
<div class="faq-expanded__a"><p>It is the ability to meet payments as they fall due from resources that can be converted to cash quickly. Bank balances, breakable deposits and listed securities carry high liquidity. Property, unlisted holdings and slow receivables carry very little, whatever their value on paper. Fixed deposits under lien are the common trap, since the balance exists but cannot be drawn.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How is liquidity measured?</h3>
<div class="faq-expanded__a"><p>By comparing current assets against current liabilities, and by narrowing that comparison to exclude inventory where stock is slow moving. Both are point-in-time measures taken from a dated statement, so they shift as receivables are collected and payables settled. The narrower version is usually called the quick ratio, and appraisers read the two together.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Can a person with high net worth still be illiquid?</h3>
<div class="faq-expanded__a"><p>Frequently, and it is the commonest mismatch in this field. Wealth concentrated in property and unlisted shares produces a large certified figure and very little spendable money. Consulates and lenders assess the two separately, which is why an impressive total does not always carry an application.</p></div>
