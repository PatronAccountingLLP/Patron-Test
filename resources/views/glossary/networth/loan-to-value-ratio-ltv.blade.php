      <section id="how-ltv-is-computed-and-read-by-a-credit-apprais" class="gl-sec">
        <h2>How LTV Is Computed and Read by a Credit Appraiser</h2>
        <div class="definition-box" itemprop="description"><p>Loan to value expresses the advance as a proportion of the asset securing it. A lender advancing eighty rupees against a hundred-rupee property is lending at eighty per cent. The denominator is the lender's own valuation, not the price the buyer paid and not the figure on a certificate. That is the commonest misunderstanding when a sanction comes in lower than expected. Where the two disagree the lender's valuer governs, because it is the lender's money at risk. The gap between the two figures is what the borrower has to fund from their own resources, and discovering it late is what derails a purchase. The ratio is also recalculated during the life of the loan for some products. A gold loan whose security falls in value triggers a margin call. The borrower either tops up or the lender sells. Housing loans are not marked to market this way, which is why the product feels very different to a borrower.</p></div>
      </section>
      <section id="why-a-strong-certified-net-worth-does-not-move-t" class="gl-sec">
        <h2>Why a Strong Certified Net Worth Does Not Move the LTV Cap</h2>
        <p>A strong certified net worth does not move the cap, and borrowers are frequently surprised by this. The ceiling is a rule about the asset rather than about the person: it exists so that a fall in value does not leave the loan larger than the security. Substantial wealth elsewhere may improve the interest rate offered, may remove the need for a guarantor, and may get a marginal file approved. It does not raise the proportion the lender will advance against that particular property. What net worth can do is demonstrate that the borrower can fund the balance, which is a different question the same certificate happens to answer. Where a borrower genuinely needs a higher advance, the answer is usually a second asset rather than an argument about the first. Adding collateral changes the denominator; demonstrating wealth does not.</p>
      </section>
      <section id="rbi-ceilings-across-home-loans-gold-loans-and-lo" class="gl-sec">
        <h2>RBI Ceilings Across Home Loans, Gold Loans and Loans Against Property</h2>
        <p>The Reserve Bank sets ceilings that vary by product and, for housing, by the size of the loan, with smaller loans permitted a higher proportion than larger ones. Gold loans carry their own ceiling, tightened because the security is volatile and easily realised. Loans against property sit well below housing levels, since the purpose is not the acquisition of the asset and recovery is harder. Individual lenders apply their own limits below the regulatory ceiling, so the number quoted in a sanction letter is the lender's policy rather than the regulator's maximum. The ceiling applies to the sanctioned amount rather than to the balance outstanding, so a loan that has been partly repaid sits below the ceiling by definition. That headroom is sometimes available as a top-up, subject to the lender's own policy.</p>
      </section>
      <section id="ratios-frequently-quoted-alongside-ltv" class="gl-sec">
        <h2>Ratios Frequently Quoted Alongside LTV</h2>
        <p>The ratios quoted alongside this one describe value and contribution. One is the open-market price the denominator is trying to capture. One is the borrower's own share of the purchase. One is the wider category of what has been given as security. The last is the instrument creating the charge over immovable property. <a href="/glossary/networth/fair-market-value-fmv">Fair Market Value (FMV)</a>, <a href="/glossary/networth/margin-money">Margin Money</a>, <a href="/glossary/networth/collateral">Collateral</a>, <a href="/glossary/networth/mortgage">Mortgage</a>. Together they explain most of the gap between what a borrower expects to receive and what the sanction letter finally offers. The ratio is also where a valuation dispute becomes concrete. A borrower who disagrees with the lender's valuer is really disagreeing about the advance, and the route to changing it is a second valuation rather than an argument about the first. Lenders will usually consider one, at the borrower's cost. The ceiling also explains why two borrowers buying identical properties can receive very different sanctions. One product's cap, one lender's policy within it, and one valuer's opinion of the same asset are three separate variables, and only the last is open to challenge. Knowing which is which saves an argument with the wrong party. Establishing the cap before house-hunting rather than after an offer is accepted avoids the commonest and most expensive surprise in a property purchase.</p>
      </section>
