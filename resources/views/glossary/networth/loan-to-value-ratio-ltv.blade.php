<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How is loan to value calculated?</h3>
<div class="faq-expanded__a"><p>The sanctioned loan amount is divided by the assessed value of the security, expressed as a percentage. A loan of forty lakh rupees against property valued at fifty lakh gives eighty per cent. Lenders use the lower of purchase price and valuation, so the ratio is rarely computed on the buyer&#x27;s figure alone.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Are there regulatory caps on the ratio?</h3>
<div class="faq-expanded__a"><p>Yes. The Reserve Bank prescribes ceilings for housing loans that step down as the loan size rises, and separate ceilings apply to loans against gold and against securities. Those are outer limits; individual lenders commonly lend below them depending on the borrower&#x27;s profile. The ratio is tested at sanction and again on any enhancement of the facility.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does the ratio interact with a net worth certificate?</h3>
<div class="faq-expanded__a"><p>It does not enter the certificate, but it explains why one is asked for. Where the ratio a borrower needs exceeds what the lender will grant, the shortfall must come from the borrower&#x27;s own means. The certificate is how those means are evidenced. Lenders call that gap margin money, and they ask for it to be evidenced from the borrower&#x27;s own resources.</p></div>
