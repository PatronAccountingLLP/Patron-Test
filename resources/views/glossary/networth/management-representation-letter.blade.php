<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What is a management representation letter?</h3>
<div class="faq-expanded__a"><p>It is a written confirmation from the client that they have disclosed everything relevant. It typically covers completeness of assets and liabilities, guarantees given, charges created, and disputes pending. Standard on Auditing 580 deals with written representations, and the same discipline is applied to certification engagements.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does a management representation letter replace the chartered accountant&#x27;s verification?</h3>
<div class="faq-expanded__a"><p>No, and treating it as a substitute is the error it invites. Representations complement evidence; they do not stand in place of it. Where a matter can be tested against a bank statement, a title deed or a registry record, the member tests it. The letter covers what cannot be independently verified.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What happens if a client refuses to sign one?</h3>
<div class="faq-expanded__a"><p>The engagement usually stops. A refusal to confirm completeness leaves the member unable to conclude that all liabilities have been disclosed, which is the assertion a net worth figure depends on. In practice the refusal itself signals the problem, and the certificate is not issued.</p></div>
