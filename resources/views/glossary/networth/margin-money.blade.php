<h3 class="faq-expanded__q">What is margin money?</h3>
<div class="faq-expanded__a"><p>It is the borrower&#x27;s own contribution towards the cost of an asset or a project, put in alongside the lender&#x27;s funds. A lender financing eighty per cent of a purchase expects the remaining twenty from the borrower. That contribution is what gives the borrower a stake in the outcome.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Where does the evidence for margin money come from?</h3>
<div class="faq-expanded__a"><p>From the borrower&#x27;s own resources, traced to a source. Bank balances, a matured deposit, sale proceeds or a documented family gift all serve. What lenders reject is margin arranged by a fresh unsecured borrowing, since that leaves the borrower with no real stake and a second obligation to service.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is margin money the same as a deposit against a bank guarantee?</h3>
<div class="faq-expanded__a"><p>The idea is similar but the mechanics differ. A guarantee margin is cash the bank holds, often under lien, as partial cover for the commitment it has issued. Project margin is money already spent on the asset. Both reduce the lender&#x27;s exposure; only one remains a recorded deposit.</p></div>
