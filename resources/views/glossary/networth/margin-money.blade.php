      <section id="how-margin-money-is-fixed-and-where-it-must-come" class="gl-sec">
        <h2>How Margin Money Is Fixed and Where It Must Come From</h2>
        <div class="definition-box" itemprop="description"><p>Margin money is the borrower's own contribution to a funded purchase, and it is fixed as the difference between the asset's value and what the lender will advance. It has to be genuinely the borrower's. Lenders examine where it came from, because a margin funded by another borrowing defeats its purpose. The point is that the borrower carries the first loss and therefore has an interest in the asset surviving. A sudden credit shortly before disbursement is queried for exactly this reason, and an unexplained one can stall a sanction that was otherwise complete. Some lenders permit part of the margin to come from a related party's funds. The relationship has to be evidenced and the money has to be a gift rather than a loan. Where it is a loan it becomes a liability, which changes the assessment it was meant to strengthen.</p></div>
      </section>
      <section id="proving-a-margin-contribution-through-a-certifie" class="gl-sec">
        <h2>Proving a Margin Contribution Through a Certified Statement of Assets</h2>
        <p>A certified statement of assets is how a margin contribution is most often evidenced, particularly for the self-employed. The statement shows the holdings the contribution will come from and separates what is liquid from what is not. A margin existing only as property equity cannot be paid on the disbursement date. Where the funds come from family, the source is documented and the relationship evidenced. A gift and a loan look identical in a bank statement and are treated very differently by an appraiser. The statement is prepared to a date close to disbursement rather than the last financial year end. A lender wants to see the funds now, not as they stood months ago. A stale certificate is one of the more common reasons a file is returned for an update.</p>
      </section>
      <section id="own-contribution-norms-indian-banks-apply-to-hom" class="gl-sec">
        <h2>Own-Contribution Norms Indian Banks Apply to Home, Vehicle and Education Loans</h2>
        <p>Indian own-contribution norms differ sharply by product. Housing carries the lowest, with the proportion rising as the loan grows. Vehicle finance sits higher and varies between new and used. Education loans have historically required nothing below a threshold and a contribution above it, with the proportion depending on whether the study is in India or abroad. Business loans are negotiated case by case against the appraisal. In every case the figure appears in the sanction letter and is a condition of disbursement rather than a suggestion. Where a subsidy or a scheme contributes toward the cost, whether it counts as the borrower's margin depends on the scheme's own terms and on the lender's policy. That is a question to settle at appraisal rather than at disbursement.</p>
      </section>
      <section id="funding-terms-that-interact-with-margin-money" class="gl-sec">
        <h2>Funding Terms That Interact With Margin Money</h2>
        <p>The terms interacting with margin money are the ones fixing how much of it is needed. One is the ratio setting the lender's maximum advance, whose complement is the margin. One is the security taken over the asset. One is the category of holdings that can actually be produced on the day. The last is the document stating the required contribution as a condition. <a href="/glossary/networth/loan-to-value-ratio-ltv">Loan-to-Value Ratio (LTV)</a>, <a href="/glossary/networth/collateral">Collateral</a>, <a href="/glossary/networth/liquid-assets">Liquid Assets</a>, <a href="/glossary/networth#sanction-letter">Sanction Letter</a>. Between them these describe how much the borrower funds, how much the lender advances and what secures the difference. Margin is also the part of a transaction most often underestimated at planning stage. Registration, stamp duty, insurance and processing fees sit outside the loan on most products, so the cash a borrower actually needs on the day exceeds the stated margin by a noticeable amount. Margin is finally what makes the lender and the borrower's interests point the same way. A borrower with nothing at stake has little reason to protect the asset, which is why the requirement survives even where a guarantee scheme would otherwise cover the lender. It is a discipline rather than a fee, and it is the one condition lenders are least willing to waive. Planning for the full amount rather than the stated proportion avoids a scramble at disbursement. Lenders rarely move on it, and asking usually costs credibility.</p>
