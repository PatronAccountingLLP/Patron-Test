<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What is a moratorium on a loan?</h3>
<div class="faq-expanded__a"><p>It is an agreed period at the start of a facility during which principal repayment is deferred. Education loans commonly carry one covering the course and a few months after; project loans carry one until construction is complete. The loan tenor runs from sanction, so the moratorium consumes part of it.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does interest stop during a moratorium?</h3>
<div class="faq-expanded__a"><p>Usually not. Interest continues to accrue and is either paid as it falls due or capitalised into the outstanding balance, which raises what is repaid later. Borrowers who assume the pause covers interest as well are the ones surprised by a larger instalment when repayment starts.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is the moratorium term the same as the repayment holiday under a resolution?</h3>
<div class="faq-expanded__a"><p>No. A structured moratorium is built into the sanction from the start. A repayment concession granted later, when a borrower is in difficulty, is a restructuring, and lenders classify and report it differently. The distinction shows up in the credit information report. The Reserve Bank&#x27;s directions set how a restructured account is classified and provisioned by the lender.</p></div>
