      <section id="what-a-moratorium-suspends-and-what-keeps-accrui" class="gl-sec">
        <h2>What a Moratorium Suspends and What Keeps Accruing</h2>
        <div class="definition-box" itemprop="description"><p>A moratorium suspends repayment for a stated period. What it does not suspend, in almost every case, is interest. Interest continues to accrue on the outstanding balance throughout, and where it is not serviced during the holiday it is added to the principal at the end of it. The borrower therefore emerges owing more than they borrowed, repaying a larger sum over the remaining term. Borrowers regularly understand a moratorium as a pause in the loan rather than a pause in payment, and the difference shows up as an instalment noticeably larger than the one originally quoted. A moratorium granted as relief after a facility has run into difficulty is a different thing again from one built into the sanction. The first is a restructuring and may be reported as such; the second is simply the agreed repayment structure. The distinction matters a great deal to a bureau record.</p></div>
      </section>
      <section id="how-unserviced-interest-surfaces-in-a-later-cert" class="gl-sec">
        <h2>How Unserviced Interest Surfaces in a Later Certified Liability Figure</h2>
        <p>Unserviced interest surfaces in a later certified liability figure as a balance higher than the borrower expects. A certificate prepared after a moratorium states the outstanding as the lender's records show it, which includes capitalised interest, rather than as the original sanction less repayments made. This is worth explaining in the statement where the difference is material, because a reader comparing the certificate to the sanction letter will otherwise see a discrepancy and ask about it. Where a borrower is being certified during a moratorium the position is stated as at the certificate date with the accrued interest included, and a note explains that repayment has not yet begun. Leaving that unexplained invites a reader to assume the loan is current in a way it is not.</p>
      </section>
      <section id="course-periods-on-education-loans-and-gestation" class="gl-sec">
        <h2>Course Periods on Education Loans and Gestation on Project Loans in India</h2>
        <p>Two moratoriums are common in India. Education loans carry a course period covering the duration of study plus a further interval before repayment begins, and whether interest is serviced during it materially changes the eventual instalment. Project loans carry a gestation period matched to when the plant is expected to generate cash, and the structure is set at sanction against the projections. In both cases the sanction letter states the length, whether interest is to be serviced, and what happens to it if it is not. Servicing interest during the holiday, where the borrower can afford to, materially reduces the eventual instalment and is worth modelling before the option is declined. Many borrowers are never told it is available. The length is negotiable at sanction and almost never afterwards.</p>
      </section>
      <section id="repayment-structures-related-to-a-moratorium" class="gl-sec">
        <h2>Repayment Structures Related to a Moratorium</h2>
        <p>The related structures are the ones that shape or record repayment. One is the ratio testing coverage, which reads very differently during a holiday than after it. One is the document setting the terms. One is the category of obligations that have not yet crystallised. The last is the bureau record, where a properly sanctioned moratorium should not read as a default, and occasionally does. <a href="/glossary/networth/debt-service-coverage-ratio-dscr">Debt Service Coverage Ratio (DSCR)</a>, <a href="/glossary/networth#sanction-letter">Sanction Letter</a>, <a href="/glossary/networth/contingent-liability">Contingent Liability</a>, <a href="/glossary/networth/credit-information-report-cibil">Credit Information Report (CIBIL)</a>. Read together they explain both what a moratorium does to the arithmetic and how it appears to anybody assessing the borrower afterwards. For anybody being certified, the practical lesson is that a moratorium does not make a liability smaller. It moves when the liability is paid and usually increases what is eventually owed, and a statement that presents the original sanction figure rather than the current outstanding understates the position. The structure is also worth revisiting rather than accepting as offered. Where a borrower can service interest during the holiday the eventual instalment falls materially, and where they cannot, knowing the capitalised figure in advance prevents the shock that arrives with the first full demand. Either way the number should be modelled at sanction and not discovered afterwards. Understanding that before signing is worth more than any renegotiation afterwards. Both are worth reading before a facility is signed rather than after. The arithmetic does not soften with time.</p>
