      <section id="equitable-and-registered-mortgages-the-practical" class="gl-sec">
        <h2>Equitable and Registered Mortgages: The Practical Difference</h2>
        <div class="definition-box" itemprop="description"><p>A mortgage is a transfer of an interest in immovable property to secure a debt. Indian practice relies on two forms most of the time. An equitable mortgage is created by depositing title deeds with the lender. It is quick and attracts lower stamp duty, and most housing and business loans rest on it. A registered mortgage is executed and registered like any other instrument, costs more in duty and time, and gives the lender a clearer and more readily enforceable position. The practical difference for a borrower being certified is visibility rather than legal effect. A registered mortgage appears in the sub-registrar's records and on an encumbrance certificate. An equitable mortgage may leave no public trace, which makes disclosure the borrower's responsibility. Both forms secure the same debt and both are enforceable. What differs is how visible the security is to somebody who was not party to it.</p></div>
      </section>
      <section id="netting-a-mortgaged-property-against-its-outstan" class="gl-sec">
        <h2>Netting a Mortgaged Property Against Its Outstanding Loan During Certification</h2>
        <p>During certification a mortgaged property is netted against the loan it secures rather than removed from the statement. The property is stated at its own value, the outstanding balance is shown as a liability, and the net position follows from the two. Removing the property understates assets and leaves an unexplained liability on the other side. Ignoring the loan overstates the position, and is the more serious error. Where the outstanding balance exceeds the value of the property, the negative equity is shown rather than floored at zero. A reader needs to know the asset will not clear its own debt. Presenting that situation as a nil contribution rather than a negative one is a material misstatement dressed as a rounding convention. The netting is shown rather than performed silently. A reader who disagrees with the property valuation can then substitute their own figure without re-deriving the liability side as well. Where a property secures more than one facility, each charge is listed separately. A single combined figure hides which lender ranks first, and ranking is what decides recovery.</p>
      </section>
      <section id="title-deeds-sub-registrar-records-and-sanction-l" class="gl-sec">
        <h2>Title Deeds, Sub-Registrar Records and Sanction Letters a CA Asks to See</h2>
        <p>The documents a chartered accountant asks to see establish title and encumbrance separately, because one does not imply the other. The registered title deed evidences ownership and is the starting point. The encumbrance certificate from the sub-registrar shows what has been registered against the property over a stated period. That is what reveals a registered mortgage. The sanction letter and the latest loan statement establish the outstanding amount and describe the security the lender believes it holds. Where an equitable mortgage was created by deposit of deeds, the lender's own confirmation is what evidences it, since the sub-registrar's record may show nothing whatsoever. A clean encumbrance certificate is therefore not proof that a property is unencumbered, and treating it as such is a recurring error. For that reason the lender's own confirmation is sought wherever a facility exists against property. Its absence is treated as a gap in the evidence rather than as proof that no charge exists. The period the encumbrance certificate covers is stated as well. A thirteen-year search and a thirty-year search answer different questions about the same property.</p>
      </section>
      <section id="security-terms-commonly-confused-with-a-mortgage" class="gl-sec">
        <h2>Security Terms Commonly Confused With a Mortgage</h2>
        <p>Mortgage is regularly confused with the security forms that apply to movable property, and the terms most worth reading alongside it are the ones that establish the property position rather than the loan position. One is the instrument that proves ownership in the first place. One is the certificate that shows what has been registered against the property, with the limitation described above. One is the asset class itself, which carries its own valuation and evidence conventions that differ from those applied to movable holdings. The last is the ratio a lender uses to decide how much it will advance against a property. It turns a valuation into a credit decision, which is why the basis matters so much. <a href="/glossary/networth#title-deed">Title Deed</a>, <a href="/glossary/networth/encumbrance-certificate">Encumbrance Certificate</a>, <a href="/glossary/networth#immovable-property">Immovable Property</a>, <a href="/glossary/networth/loan-to-value-ratio-ltv">Loan-to-Value Ratio (LTV)</a>. Read together they explain why two properties of identical market value can support very different borrowings. The valuation is only the starting point of that calculation, not the end of it.</p>
      </section>
