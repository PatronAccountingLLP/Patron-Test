<h3 class="faq-expanded__q">What are the main forms of mortgage in India?</h3>
<div class="faq-expanded__a"><p>Section 58 of the Transfer of Property Act 1882 sets out six, of which two dominate lending. A simple or English mortgage is created by a registered deed. A mortgage by deposit of title deeds, commonly called an equitable mortgage, is created by handing over the documents of title with intent to secure.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does an equitable mortgage need registration?</h3>
<div class="faq-expanded__a"><p>It is created by deposit of title deeds rather than by a registered instrument, which is why lenders use it. Several states require the memorandum recording the deposit to be stamped, and practice varies on registration. A chartered accountant checks the encumbrance record rather than assuming an unregistered charge does not exist.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does a mortgage affect the value carried in a certificate?</h3>
<div class="faq-expanded__a"><p>The property stays in the asset schedule at its value, and the outstanding loan is deducted as a liability. Net of the two, only the free equity contributes. A solvency opinion goes further and looks at realisable value, since a fully charged property supports nothing the reader could actually reach.</p></div>
