      <section id="how-accumulated-losses-erode-and-then-wipe-out-n" class="gl-sec">
        <h2>How Accumulated Losses Erode and Then Wipe Out Net Worth</h2>
        <div class="definition-box" itemprop="description"><p>Net worth erodes when accumulated losses consume the reserves and then the capital itself. The sequence is orderly. Losses first absorb retained earnings, so reserves fall while capital stays intact and the certified figure declines without alarming anybody. Once reserves are exhausted, further losses reduce the figure below paid-up capital, which is the point at which erosion becomes visible on the face of the balance sheet. Continue and the position turns negative: liabilities exceed assets and the company is worth less than nothing on the measure. Each stage is a different conversation with a lender, and a company that reaches the third without having had the first two has usually not been reading its own accounts. Erosion is a direction rather than a level, and that is what makes it informative. Accumulated losses are set against the capital and reserves, so the position falls steadily as they build, and passes through zero rather than arriving there suddenly.</p></div>
      </section>
      <section id="reporting-a-negative-or-eroded-position-honestly" class="gl-sec">
        <h2>Reporting a Negative or Eroded Position Honestly in a Certificate</h2>
        <p>Reporting an eroded or negative position honestly is the only defensible course, and it is where certification is genuinely tested. A certificate cannot floor the figure at zero because zero looks better, and it cannot omit accumulated losses because they are inconvenient. The statutory definition deducts them and the audited accounts show them. What a certificate can properly do is present the position with its components visible, so a reader sees capital, reserves and the deficit separately rather than a single negative total. Where the position has improved since the balance sheet date, that is worth stating as a fact about a later period rather than folding into the certified figure. A negative position is reported as it stands, with the figure on the face of the document. Softening it by omitting the comparative, or by presenting components without the total, misleads by arrangement rather than by statement. The recipient will usually find it anyway, and having found it will discount everything else on the page.</p>
      </section>
      <section id="erosion-triggers-that-pull-in-indian-lenders-aud" class="gl-sec">
        <h2>Erosion Triggers That Pull In Indian Lenders, Auditors and IBC Scrutiny</h2>
        <p>Erosion triggers attention from several directions at once. Lenders monitor it through covenants and frequently have the right to recall or reprice a facility when net worth falls below a stated level. Auditors consider whether it casts doubt on the company continuing as a going concern, and a modification on that basis is visible to everybody who reads the accounts. Where erosion is accompanied by default, the insolvency framework becomes relevant and a creditor may initiate proceedings. None of these follows automatically from erosion alone, but all of them become materially more likely, which is why the direction of travel matters as much as the level. What follows differs by who is reading. A lender responds through the covenants already in the facility rather than through anything new. An auditor is drawn towards whether the entity remains a going concern. A creditor may see it as supporting evidence of inability to pay, though the statutory tests turn on default rather than on the position itself.</p>
      </section>
      <section id="distress-indicators-related-to-eroded-net-worth" class="gl-sec">
        <h2>Distress Indicators Related to Eroded Net Worth</h2>
        <p>The distress indicators related to an eroded position each show a different symptom. One is the accumulated deficit that causes the erosion. One is the reserve category it consumes first. One is gearing, which usually deteriorates alongside as borrowing replaces equity. The last is the class of obligations that have not yet crystallised, and which turn a difficult position into an unrecoverable one when they do. The indicators grouped with this one describe distress at different stages. <a href="/glossary/networth#accumulated-losses">Accumulated Losses</a>, <a href="/glossary/networth/free-reserves">Free Reserves</a>, <a href="/glossary/networth/debt-to-equity-ratio">Debt-to-Equity Ratio</a>, <a href="/glossary/networth/contingent-liability">Contingent Liability</a>. One concerns the ability to meet obligations as they fall due. One concerns the relationship between borrowings and owned funds. One concerns the assumption on which the accounts themselves are prepared. An eroded position with obligations still being met is a different situation from an eroded position with payments missed, and readers who conflate them reach the wrong conclusion in both directions.</p>
      </section>
