<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does net worth erosion mean?</h3>
<div class="faq-expanded__a"><p>It means accumulated losses have consumed part or all of the capital and reserves, so the section 2(57) figure falls or turns negative. It is a balance sheet condition, not a cash flow one, and a company can erode its net worth while still meeting its payments.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does erosion trigger?</h3>
<div class="faq-expanded__a"><p>Contractually, covenant breaches: sanction letters commonly set a minimum net worth, and breach can accelerate repayment or trigger a review. Regulated entities face floors set by their regulator. Boards also face disclosure and governance consequences, since the position has to be reported to shareholders. Section 2(57) supplies the figure the covenant is tested against, so the definition matters commercially.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is an eroded company insolvent?</h3>
<div class="faq-expanded__a"><p>Not automatically. Insolvency under the Insolvency and Bankruptcy Code 2016 turns on default in payment, not on the balance sheet position. A company with negative net worth that services its debts is not in default, though lenders will treat it as a heightened risk. The Code fixes a minimum default threshold, and erosion on its own does not meet it.</p></div>
