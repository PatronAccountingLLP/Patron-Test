<h3 class="faq-expanded__q">What is a performance guarantee?</h3>
<div class="faq-expanded__a"><p>It is security furnished after a contract is awarded, covering the contractor&#x27;s obligation to perform. It is usually a bank guarantee for a stated percentage of the contract value, valid through the contract period and often a defect liability period beyond it. The employer invokes it if performance fails.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does a performance guarantee differ from the deposit lodged with the bid?</h3>
<div class="faq-expanded__a"><p>Timing and purpose. The bid deposit secures the offer before award and is refunded when the process ends. The performance security is furnished after award and secures execution. A contractor moving from bid to contract therefore replaces one instrument with a larger, longer one. Percentages in the range of five to ten per cent of contract value are frequently seen.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Why does furnishing a performance guarantee depend on financial standing?</h3>
<div class="faq-expanded__a"><p>Because a bank issues the guarantee only against margin and security it is comfortable with. A contractor with thin net worth may win a bid and then be unable to furnish the instrument, which forfeits the award. That is why financial capacity is tested before the award rather than after it.</p></div>
