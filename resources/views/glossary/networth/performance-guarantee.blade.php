      <section id="what-a-performance-guarantee-covers-once-work-is" class="gl-sec">
        <h2>What a Performance Guarantee Covers Once Work Is Awarded</h2>
        <div class="definition-box" itemprop="description"><p>A performance guarantee secures the contractor's obligations once work has been awarded. Where the earnest money deposit protected the authority during bidding, this protects it during delivery. If the contractor abandons the work, performs it defectively or misses the specification, the authority invokes the guarantee and recovers. It is furnished after award and before the contract is signed. It stays in force through the contract period and usually beyond. That covers the defect liability period, during which later faults remain the contractor's responsibility. That tail is what makes the instrument long-lived and what makes its cost material to a contractor holding several at once. Because it is issued against a bank limit rather than paid in cash, a contractor's capacity to hold several at once is finite. Each one consumes limit that cannot then be used for working capital, and a contractor winning three contracts in a quarter can find the third unfundable for that reason alone.</p></div>
      </section>
      <section id="why-awarding-authorities-recheck-financial-stand" class="gl-sec">
        <h2>Why Awarding Authorities Recheck Financial Standing at the PBG Stage</h2>
        <p>Awarding authorities recheck financial standing at this stage even though they assessed it at bidding, and there is a sound reason. The bid assessment established that the contractor could take the work on. The performance stage establishes that they can furnish a much larger guarantee. That requires their bank to extend a limit against their own standing. A contractor who bids successfully and then cannot obtain the guarantee loses the contract. The deposit usually goes with it. This is where a certified position does real work: the issuing bank reads it before agreeing the limit. The authority may ask for it again to satisfy itself that nothing has changed since the bid. The recheck is also where a gap between the bid and the award becomes visible. Months frequently pass between the two, and a contractor whose position has weakened in that interval may find the bank unwilling to issue on the terms assumed at bidding.</p>
      </section>
      <section id="percentages-and-validity-periods-typical-of-indi" class="gl-sec">
        <h2>Percentages and Validity Periods Typical of Indian Government Contracts</h2>
        <p>Indian government contracts commonly set the guarantee as a percentage of the contract value, with the exact proportion varying by department and by the nature of the work. Validity covers the contract period, the defect liability period and a claim period beyond it. A two-year contract can therefore carry a guarantee running well past three. Extensions are frequently required where the work overruns, and an authority will usually treat failure to extend as a default in itself. The wording is almost always prescribed by the department, and banks issue it as drafted rather than negotiating the terms. Release is rarely automatic. The authority usually requires a written request supported by a completion certificate, and guarantees sit unreleased for months after the obligation has ended simply because nobody asked. That is a cost the contractor continues to carry. Contractors who track release dates actively recover that capacity months earlier than those who wait to be told, and on a busy order book the difference is material.</p>
      </section>
      <section id="contract-securities-related-to-the-performance-g" class="gl-sec">
        <h2>Contract Securities Related to the Performance Guarantee</h2>
        <p>The contract securities related to this one form a sequence across the life of a procurement. One is lodged at bidding and released on award. One is the declaration most portals now accept instead. One is the bank instrument through which either is commonly furnished. The last is the individual who accepts liability for another's obligation, which is the personal equivalent of what a bank does when it issues a guarantee. A contractor moving through a tender meets all four in order. <a href="/glossary/networth/bank-guarantee-bg">Bank Guarantee (BG)</a>, <a href="/glossary/networth/earnest-money-deposit-emd">Earnest Money Deposit (EMD)</a>, <a href="/glossary/networth#bid-security">Bid Security</a>, <a href="/glossary/networth/surety">Surety</a>. Reading them as a sequence rather than as separate requirements is what lets a contractor plan the banking capacity a contract will actually consume. A contractor who plans for all four from the outset knows what banking capacity a tender will consume before bidding, rather than discovering it after the award. Planning it early is what keeps a growing order book fundable.</p>
      </section>
