<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What makes a pledge different from other security over movables?</h3>
<div class="faq-expanded__a"><p>Delivery of possession. Section 172 of the Indian Contract Act 1872 defines a pledge as the bailment of goods as security for a debt. So the creditor holds the goods or their equivalent. Shares are pledged by a depository marking, which performs the same function electronically.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Can the pledgee sell the pledged asset?</h3>
<div class="faq-expanded__a"><p>On default, and after notice. The Contract Act allows a pledgee to sue for the debt and retain the goods, or to sell them after giving the pledgor reasonable notice of sale. Because that power exists, a pledged holding is disclosed on a certificate rather than presented as freely available.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Do pledged shares still belong to the borrower?</h3>
<div class="faq-expanded__a"><p>Yes, until the pledge is invoked. The shares remain in the pledgor&#x27;s demat account with a pledge marking in favour of the lender, and dividends and voting rights ordinarily stay with the owner. On invocation the shares move to the pledgee, and only then does ownership change.</p></div>
