        <h2>What a Pledge Is and What Possession Has to Do With It</h2>
        <div class="definition-box" itemprop="description"><p>A pledge is a security interest over movable property where possession passes to the creditor while ownership remains with the borrower. Possession is the defining element and the one that separates a pledge from every other form of security over movables. Gold handed to a lender against a loan is pledged. Shares held in a pledged demat position are pledged, with the depository entry standing in for physical delivery of certificates. Stock held in a warehouse under the lender's lock and key is pledged. Where the borrower keeps the goods and carries on using, selling or replacing them, the arrangement is not a pledge. The label in the documents does not change that. A certifying accountant reads the arrangement rather than the heading on the agreement. The treatment on the statement follows what actually happened to the goods. Possession can also be constructive rather than physical, as it is with a demat pledge. What matters is that the borrower can no longer deal with the asset freely. The distinction is not academic. It decides who bears the risk of the goods being lost or damaged while the loan is outstanding.</p></div>
      </section>
      <section id="treating-pledged-securities-when-certifying-an-a" class="gl-sec">
        <h2>Treating Pledged Securities When Certifying an Asset Position</h2>
        <p>In certification the pledged asset stays on the statement at its own value. The pledge and the amount it secures are disclosed against it, so the reader sees both. Pledged shares carry an additional caution, because the value moves daily. A fall can trigger a margin call that changes the position without anything being sold. The certificate therefore states the price used and the date it was taken, and does not imply that the figure holds beyond that date. A pledged holding shown without its pledge is the commonest overstatement in a share portfolio. It is also among the easiest to detect, since the pledge sits in the same statement. Where a pledge has already been invoked the position changes completely. The shares are gone and the loan has reduced, and the statement records both rather than either.</p>
      </section>
      <section id="demat-pledge-entries-nsdl-and-cdsl-records-and-l" class="gl-sec">
        <h2>Demat Pledge Entries, NSDL and CDSL Records and Loan-Against-Shares Practice</h2>
        <p>Indian practice leaves a clear record for pledged securities. A demat pledge is created through the depository, and both NSDL and CDSL show the pledged quantity separately. That holding statement is what a chartered accountant reads, not a broker's summary. Loan-against-shares facilities carry a sanction letter setting out the margin required and the lender's right to invoke the pledge if it is breached. Invocation transfers the shares outright, at which point they leave the statement altogether and the loan reduces instead. These entries are visible to anybody who reads the depository statement. A pledge omitted from a certificate is found rather than missed, usually by the intended reader. The holding statement is therefore obtained directly rather than accepted as a summary. A portfolio screenshot shows quantity and value, but it rarely shows what has been pledged against a facility.</p>
      </section>
      <section id="how-a-pledge-sits-against-other-forms-of-securit" class="gl-sec">
        <h2>How a Pledge Sits Against Other Forms of Security</h2>
        <p>A pledge is best understood against the other security forms, because the differences between them are practical rather than technical. One covers movable assets where the borrower keeps possession and carries on trading, which is how stock and vehicles are financed. One covers immovable property and works through an interest in the property itself. One is the general term for anything given as security, which is the word a sanction letter is most likely to use without specifying which mechanism applies. The last is the borrower's own contribution to a secured facility, which determines how much of the asset the lender is exposed to in the first place. Reading a sanction letter accurately usually means knowing all four. <a href="/glossary/networth/hypothecation">Hypothecation</a>, <a href="/glossary/networth/mortgage">Mortgage</a>, <a href="/glossary/networth/collateral">Collateral</a>, <a href="/glossary/networth/margin-money">Margin Money</a>. The distinction matters because the same asset can be secured in more than one way over its life. What was pledged last year may be hypothecated this year under a different facility altogether. Reading a sanction letter accurately usually means knowing all four terms rather than assuming the one that appears is the one that applies.</p>
