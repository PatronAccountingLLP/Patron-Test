      <section id="what-qualifies-as-proof-of-funds-and-what-gets-r" class="gl-sec">
        <h2>What Qualifies as Proof of Funds and What Gets Rejected Outright</h2>
        <div class="definition-box" itemprop="description"><p>Proof of funds is evidence that an applicant has money available for a stated purpose. What qualifies is narrower than applicants expect. Bank statements covering a period qualify, because they show a balance held rather than a balance on one day. Fixed deposit receipts qualify, with the bank's confirmation of the balance and any lien. A bank's balance certificate qualifies. What is rejected outright is a screenshot of a banking app. So is a statement without the bank's stamp or digital signature where one is expected, and so is a balance shown for a single day with no history behind it. Money sitting in an account belonging to somebody who has not been identified as a sponsor is refused on the same reasoning. Property valuations are sometimes accepted as supporting evidence and almost never as proof of funds, because property cannot be spent.</p></div>
      </section>
      <section id="where-a-ca-certified-net-worth-statement-fits-in" class="gl-sec">
        <h2>Where a CA-Certified Net Worth Statement Fits Inside a Funds Pack</h2>
        <p>A chartered accountant's certified net worth statement sits inside a funds pack as corroboration rather than as the primary document. It does something the bank statements cannot. It presents the whole position, states a basis for anything without a market price, and separates what is liquid from what is not. It also carries a professional's responsibility for the figures. What it cannot do is replace evidence of the balances themselves, and a pack resting on the certificate alone is weak at every destination. The sensible construction puts the statements and deposit receipts first, the certificate alongside them, and the source documents for any large recent credit behind both. The arithmetic is the part applicants underestimate. Statements and receipts each evidence a holding in isolation; the certificate states the position they add up to, after debts, on a named date and over a signature that can be traced. A pack of documents without it leaves the reader to do the arithmetic, and to decide for themselves what was left out.</p>
      </section>
      <section id="bank-statements-fd-receipts-and-balance-confirma" class="gl-sec">
        <h2>Bank Statements, FD Receipts and Balance Confirmations Indian Applicants Rely On</h2>
        <p>Indian applicants rely most on three documents and each has a failure mode worth knowing. Bank statements are strongest over six months and weakest when they start a fortnight before the application. Fixed deposit receipts are strong until the reader notices a lien marking, which is why the bank's confirmation is obtained rather than the receipt alone. Balance confirmations are strong because they come on the bank's letterhead, and weak when they state a balance without saying whether any part of it is encumbered. Asking the bank to address encumbrance in the confirmation costs nothing and closes the gap before anybody else finds it. Seasoning is the requirement applicants most often discover too late. A balance that appeared shortly before the application invites the question of where it came from, and several readers apply an explicit holding period before they will count it. Assembling the pack early is therefore not only about processing time, since the age of the balance is itself part of what is being assessed.</p>
      </section>
      <section id="funding-evidence-terms-related-to-pof" class="gl-sec">
        <h2>Funding-Evidence Terms Related to POF</h2>
        <p>The funding-evidence terms related to this one describe the questions a reader asks in sequence. One is where the money came from, which is asked as soon as a balance looks recent. One is the bank's own statement of what is held. One is the requirement that a balance be seasoned rather than gathered for the occasion. The last is the amount a destination requires in the first place. The terms grouped with this one describe evidence at different depths. <a href="/glossary/networth/source-of-funds">Source of Funds</a>, <a href="/glossary/networth#bank-balance-certificate">Bank Balance Certificate</a>, <a href="/glossary/networth#fund-seasoning">Fund Seasoning</a>, <a href="/glossary/networth#maintenance-funds">Maintenance Funds</a>. One establishes the balance on a date. One establishes where that balance came from. One establishes that a third party has undertaken to provide it. A reader asking for funding evidence usually wants more than one of these, and supplying the shallowest of them against a request for the deepest is the commonest reason a pack comes back. Asking the recipient which of the three they want, in those terms, saves the round trip that guessing costs.</p>
      </section>
