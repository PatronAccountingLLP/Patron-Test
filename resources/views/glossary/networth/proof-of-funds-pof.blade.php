<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Which documents fall into the proof of funds class?</h3>
<div class="faq-expanded__a"><p>Bank statements and balance confirmations, fixed deposit receipts, and where a country requires it, a blocked account confirmation. A chartered accountant&#x27;s net worth certificate sits alongside them as a consolidated statement of position. Which combination is acceptable is set by the receiving institution. Banks verify customer identity under the Prevention of Money Laundering Act 2002 before issuing any confirmation.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is proof of funds the same as proof of income?</h3>
<div class="faq-expanded__a"><p>No. Proof of funds shows what is held at a point in time; proof of income shows what is earned over a period. Salary slips and tax returns answer the second question. Institutions usually ask for both, because a healthy income with no accumulated balance answers only half of what they need.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does a higher balance always strengthen a proof of funds file?</h3>
<div class="faq-expanded__a"><p>Not if it appeared suddenly. A large deposit shortly before an application raises the question of where it came from, so the trail behind the balance matters as much as its size. Funds held steadily over months read very differently from the same amount credited in the final week.</p></div>
