<h3 class="faq-expanded__q">How does a revaluation reserve arise?</h3>
<div class="faq-expanded__a"><p>It arises when an asset is restated upward to a revalued amount and the increase is credited to a reserve rather than to profit. Land and buildings are the usual candidates. No cash enters the business; only the carrying value of the asset and the reserve change.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Why do statutory definitions exclude the revaluation reserve?</h3>
<div class="faq-expanded__a"><p>Because it represents an unrealised gain. Section 2(57) of the Companies Act 2013 excludes reserves created out of revaluation of assets from the net worth computation. Section 2(43) keeps unrealised and notional gains out of free reserves. Lenders and regulators apply the same logic. Lenders computing tangible net worth strip it out for the same reason the statute does.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Can a company revalue assets to improve its certified position?</h3>
<div class="faq-expanded__a"><p>It can revalue, but the effect on a certificate is limited. Where the certificate follows a statutory or regulatory definition that excludes revaluation reserves, the uplift drops out of the computation. Where a market value basis is used, the certificate says so and a registered valuer&#x27;s report supports it.</p></div>
