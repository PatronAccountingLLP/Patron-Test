      <section id="how-a-revaluation-reserve-arises-on-an-asset-wri" class="gl-sec">
        <h2>How a Revaluation Reserve Arises on an Asset Write-Up</h2>
        <div class="definition-box" itemprop="description"><p>A revaluation reserve arises when a company writes an asset up to a higher value without selling it. The asset's carrying amount increases and the corresponding credit goes to a reserve rather than to profit, because nothing has been earned. Land and buildings are the usual subjects, since they are the assets most likely to be carried well below what they would now fetch. The exercise is legitimate and the accounting is correct. What the reserve is not is money, and it is not distributable. A company can revalue its way to a much larger balance sheet without acquiring a rupee it can spend, which is precisely why readers of a net worth figure treat the reserve with suspicion. Nothing enters or leaves the business when the reserve arises. The asset is restated upward and a reserve is credited by the same amount, so the balance sheet grows on both sides without a transaction having occurred.</p></div>
      </section>
      <section id="why-revaluation-gains-are-stripped-out-of-the-ce" class="gl-sec">
        <h2>Why Revaluation Gains Are Stripped Out of the Certified Net Worth Figure</h2>
        <p>The statutory definition strips it out for that reason. Section 2(57) adds reserves created out of profits and excludes those created out of revaluation of assets, so a certified figure that included the reserve would be wrong rather than merely generous. The exclusion has to be applied to both sides of the entry: the uplift comes out of the reserve. Where the asset is carried at the revalued amount that has to be visible in the working. A reserve schedule identifying how each reserve arose is what makes the exclusion checkable, and its absence is the commonest reason a company's own computation cannot be verified. The exclusion is about realisation rather than about honesty. A revaluation can be professionally performed, properly supported and entirely defensible, and the gain is still stripped out, because it reflects a judgement about worth rather than a transaction. A certified figure that included it would move with opinion. The figure a recipient relies on has to be stable enough to act on.</p>
      </section>
      <section id="the-section-2-57-exclusion-and-what-ind-as-reval" class="gl-sec">
        <h2>The Section 2(57) Exclusion and What Ind AS Revaluation Models Permit</h2>
        <p>Under Ind AS the revaluation model is permitted for classes of property, plant and equipment, with the requirement that a whole class be revalued rather than selected assets, and with revaluations kept sufficiently current. Increases go through other comprehensive income to the reserve; decreases reverse them and then go to profit. Where a revalued asset is later sold, the reserve is transferred to retained earnings rather than through profit. Companies applying the cost model carry no such reserve at all, which is worth establishing early, because a client who says they have revalued has sometimes only obtained a valuation. The accounting framework permits the write-up and the statutory definition declines to count it. Both positions can hold at once, because they answer different questions. The practical consequence is that a figure lifted from the audited balance sheet needs the reserve removed before it can be certified, and the removal is shown rather than absorbed silently into the total.</p>
      </section>
      <section id="reserve-movements-confused-with-revaluation" class="gl-sec">
        <h2>Reserve Movements Confused With Revaluation</h2>
        <p>The reserve movements confused with revaluation share the feature of increasing equity without earning. One is the category of reserves that genuinely qualify and count. One is the market price the revaluation was based on. One is the professional whose report supports it where the amount is material. The last strips out intangible items on top of the unrealised ones, and a cautious tender committee will ask for it by name. The movements confused with this one also sit in reserves and are excluded or included for reasons of their own. <a href="/glossary/networth/free-reserves">Free Reserves</a>, <a href="/glossary/networth/fair-market-value-fmv">Fair Market Value (FMV)</a>, <a href="/glossary/networth#registered-valuer">Registered Valuer</a>, <a href="/glossary/networth/tangible-net-worth">Tangible Net Worth</a>. One is credited when shares are issued above their face value. Another appears when two entities are combined. One is the write-back of a charge taken in an earlier period. Each increases reserves without profit having been earned in the period, which is precisely why the definition names them rather than relying on a general principle.</p>
