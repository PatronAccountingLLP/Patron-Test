      <section id="what-securities-premium-represents-on-a-share-is" class="gl-sec">
        <h2>What Securities Premium Represents on a Share Issue</h2>
        <div class="definition-box" itemprop="description"><p>Securities premium is the amount a company receives on issuing shares above their face value. A company issuing a ten-rupee share for a hundred records ten as capital and ninety as premium. The money is real, received in full, and is the company's own. What distinguishes it from retained earnings is that it was contributed by shareholders rather than earned by trading. For a company that has raised funding at a valuation, the premium account is frequently far larger than the paid-up capital. That is why a startup's capital line tells a reader almost nothing about how much money went in. Its size is a function of the price agreed rather than of anything in the accounts. The amount above the face value of the share is credited here, and the face value alone goes to capital.</p></div>
      </section>
      <section id="why-the-premium-counts-towards-net-worth-but-not" class="gl-sec">
        <h2>Why the Premium Counts Towards Net Worth but Not Towards Distributable Profit</h2>
        <p>The premium counts towards net worth and does not count towards distributable profit, and both halves of that follow from what it is. It counts because the money was received and belongs to the company, so section 2(57) includes it among the additions. It is not distributable because it was not earned: paying it out as dividend would return capital to shareholders under the guise of profit, which company law prevents. The account is therefore a permanent part of the capital base for most purposes while being unavailable for the one purpose shareholders most often assume. Counting towards one and not the other is not an inconsistency. It is capital contributed by shareholders, so it forms part of what the owners have put in and belongs in the certified position. It was never profit earned by the company, so it is not available to be paid back out as though it were. Readers who expect the two to move together misread both.</p>
      </section>
      <section id="section-52-end-uses-and-the-return-of-allotment" class="gl-sec">
        <h2>Section 52 End-Uses and the Return of Allotment Filed With the ROC</h2>
        <p>Section 52 restricts what the premium may be used for, and the permitted applications are narrow. Issuing fully paid bonus shares to members is the main one. Writing off preliminary expenses, or the expenses, commission or discount on an issue of shares or debentures, is permitted. Providing for the premium payable on redemption of redeemable preference shares or debentures is permitted. Buy-back under section 68 is permitted. Anything else is not. Every issue at a premium is also reported to the Registrar in the return of allotment, which is where the balance can be corroborated independently of the company's own accounts. The permitted uses are a closed list and the restriction is the point of it. The account may be applied to specified purposes and not to others, which is what protects it from being distributed under another name. The filing made on allotment is where the amount first becomes visible to anyone outside the company, and it is the document a reader traces the figure back to.</p>
      </section>
      <section id="share-capital-accounts-related-to-securities-pre" class="gl-sec">
        <h2>Share Capital Accounts Related to Securities Premium</h2>
        <p>The share capital accounts related to securities premium are the ones a reader has to distinguish when assessing a company's base. One is the category of reserves genuinely available for distribution. One is the regulatory capital measure that also counts the premium, applied to financial institutions. One is the accumulated deficit that reduces the total. The last is the reserve created without any money being received at all, which is the one the premium is most often confused with. The accounts related to this one all record what shareholders contributed and differ in what may be done with it. <a href="/glossary/networth/free-reserves">Free Reserves</a>, <a href="/glossary/networth/tier-i-capital">Tier I Capital</a>, <a href="/glossary/networth#accumulated-losses">Accumulated Losses</a>, <a href="/glossary/networth/revaluation-reserve">Revaluation Reserve</a>. One is the amount at face value. One is the maximum the company is authorised to issue. One is the portion actually called and received. Reading the capital line without this account beside it understates funding in almost every company that has raised money at a valuation. The distinction between authorised and issued capital catches readers out just as often.</p>
      </section>
