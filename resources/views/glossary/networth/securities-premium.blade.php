<h3 class="faq-expanded__q">What is securities premium?</h3>
<div class="faq-expanded__a"><p>It is the amount received on issue of shares over and above their face value. A share of ten rupees face value issued at one hundred generates ninety of premium. Section 52 of the Companies Act 2013 requires it to be credited to a separate account and restricts how it may be applied.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What can the premium account be used for?</h3>
<div class="faq-expanded__a"><p>Section 52 lists the permitted applications, which include issuing fully paid bonus shares, writing off preliminary expenses and share issue expenses, and buy-back under section 68. It cannot simply be distributed as dividend, which is what distinguishes it from accumulated profits. Section 52 also allows premium on redemption of redeemable preference shares or debentures to be written off.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does it appear in an NBFC&#x27;s regulatory capital?</h3>
<div class="faq-expanded__a"><p>Yes. The Reserve Bank&#x27;s computation of owned fund includes the premium account, and net owned fund is then derived after the prescribed deductions. So a premium-heavy capital structure can satisfy a regulatory floor that paid-up capital alone would not. Section 45-IA of the Reserve Bank of India Act 1934 is where that computation originates. Its treatment there is settled.</p></div>
