      <section id="what-makes-a-transfer-a-slump-sale-rather-than-a" class="gl-sec">
        <h2>What Makes a Transfer a Slump Sale Rather Than an Itemised Sale</h2>
        <div class="definition-box" itemprop="description"><p>A slump sale is the transfer of an undertaking as a going concern for a lump sum consideration, without values being assigned to individual assets and liabilities. That last element is what makes it a slump sale rather than an itemised sale. Parties may record an allocation for stamp duty or registration purposes without disturbing the character of the transaction, but a sale that prices each asset separately is an itemised sale and is taxed accordingly. The undertaking transferred has to be a business activity capable of being carried on independently, which excludes the sale of a collection of assets that never functioned as a business. The transfer is of the undertaking as a going concern for a single consideration, with no value assigned to individual assets. Assigning values asset by asset takes the transaction outside the definition, whatever the parties have called it.</p></div>
      </section>
      <section id="computing-an-undertaking-s-net-worth-the-way-sec" class="gl-sec">
        <h2>Computing an Undertaking&#x27;s Net Worth the Way Section 50B Prescribes</h2>
        <p>Section 50B prescribes how the undertaking's net worth is computed for the purpose, and the method departs from ordinary accounting in ways that surprise people. Net worth is the aggregate value of total assets less the value of liabilities as appearing in the books. For depreciable assets the written-down value under the Income-tax Act is taken rather than the book value. For assets on which the whole cost was allowed as a deduction, the value is taken as nil. For everything else the book value applies. Revaluation is ignored entirely. The resulting figure is the cost of acquisition against which the consideration is measured, and the difference is the capital gain. The prescribed computation departs from the accounts deliberately and in stated ways. Depreciable assets enter at their written-down value rather than at book value. Any revaluation is ignored entirely. The result is a figure that exists for this computation alone and will not match the net worth reported anywhere else, which is expected rather than a discrepancy to be reconciled.</p>
      </section>
      <section id="form-3cea-written-down-value-rules-and-the-fair" class="gl-sec">
        <h2>Form 3CEA, Written-Down Value Rules and the Fair Value Test in Indian Practice</h2>
        <p>In practice three things govern the compliance. A chartered accountant's report in Form 3CEA certifying the net worth computation accompanies the return. The written-down value rules mean the tax computation of net worth almost never matches the accounting one, so both are prepared and reconciled. And the consideration is tested against fair market value under the provisions introduced for this purpose, so a transfer at an agreed price below fair value does not simply reduce the gain. Valuation support is therefore part of the file rather than an afterthought, particularly where the parties are related. The valuation test added later changed the planning more than the arithmetic. Consideration is measured against a prescribed fair value, so a price set below it does not reduce the charge in the way it once might have. The accompanying report is filed with the return, and preparing it after the transaction has closed is considerably harder than preparing it alongside.</p>
      </section>
      <section id="restructuring-routes-compared-with-a-slump-sale" class="gl-sec">
        <h2>Restructuring Routes Compared With a Slump Sale</h2>
        <p>The restructuring routes compared with a slump sale differ in what moves and how it is taxed. One is the tangible measure, which is what a buyer assessing the undertaking usually wants alongside the statutory computation. One is the fair value standard the consideration is tested against. One is the reserve category that survives or does not survive the transfer depending on its form. The last is the professional whose valuation supports the price. The routes compared with this one achieve overlapping commercial ends under different regimes. <a href="/glossary/networth/tangible-net-worth">Tangible Net Worth</a>, <a href="/glossary/networth/fair-market-value-fmv">Fair Market Value (FMV)</a>, <a href="/glossary/networth/free-reserves">Free Reserves</a>, <a href="/glossary/networth#registered-valuer">Registered Valuer</a>. One transfers assets individually at assigned values. One moves a business under a court or tribunal approved scheme. One transfers the entity itself by moving its shares. They differ in the approvals required, in the time they take and in how the gain is computed, and the choice between them is made on those grounds rather than on the commercial result.</p>
