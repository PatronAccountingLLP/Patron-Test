<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What is a slump sale?</h3>
<div class="faq-expanded__a"><p>It is the transfer of one or more undertakings for a lump sum consideration, without assigning values to individual assets and liabilities. Section 2(42C) of the Income-tax Act defines it. The whole business moves as a going concern, which is what separates it from an itemised sale of assets.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How is net worth used in the tax computation?</h3>
<div class="faq-expanded__a"><p>Section 50B treats the net worth of the undertaking as its cost of acquisition and cost of improvement. Capital gain is the consideration less that net worth. The computation follows the section&#x27;s own rules, including how depreciable assets are taken, so it is not simply the book figure.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does the computation require a certificate?</h3>
<div class="faq-expanded__a"><p>Section 50B requires the net worth computation to be reported by an accountant in the prescribed form, filed with the return. That is a specific statutory reporting requirement, separate from any commercial net worth certificate the parties may obtain for the transaction. The report is filed electronically before the due date for furnishing the return of income.</p></div>
