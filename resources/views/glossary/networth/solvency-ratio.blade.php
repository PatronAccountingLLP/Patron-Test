      <section id="the-ratios-grouped-under-the-solvency-label" class="gl-sec">
        <h2>The Ratios Grouped Under the Solvency Label</h2>
        <div class="definition-box" itemprop="description"><p>Several different ratios travel under the solvency label, which is why the word alone rarely tells a reader what was computed. The broadest divides total assets by total liabilities, and anything above one means assets cover what is owed. A second divides net worth by total liabilities. That expresses the owners' stake against the creditors'. A third, used mainly in insurance regulation, compares available capital against a required solvency margin and has nothing to do with the tender usage. These produce different numbers from the same accounts. A condition requiring a solvency ratio of a stated level is therefore ambiguous until somebody asks which one. The label is used loosely in ordinary speech as well, where solvency simply means being able to pay. That everyday sense is close to the tender usage and some distance from the regulatory one, which is another reason a condition citing a ratio without defining it creates work rather than clarity.</p></div>
      </section>
      <section id="which-ratio-a-ca-computes-when-certifying-solven" class="gl-sec">
        <h2>Which Ratio a CA Computes When Certifying Solvency</h2>
        <p>When a chartered accountant certifies solvency the computation is usually narrower than any of these. The question posed is whether a stated sum can be met on a stated date. The working establishes what is owned, deducts what is owed, sets aside what is already charged to somebody else, and compares what remains against the figure named. That is a test rather than a ratio, and the certificate says so. Where a tender genuinely asks for a ratio, it is computed from the audited accounts and the basis is stated, because a ratio presented without its definition is a number the recipient cannot use. The certificate also names the date the test was applied to, because solvency on one day says nothing about the next. Where a tender requires the position to hold at submission rather than at the certificate date, that is a different question and is answered by timing the engagement rather than by adjusting the arithmetic. Stating the test rather than a ratio also makes the certificate reusable: a reader who wanted a different threshold can apply it to the same working.</p>
      </section>
      <section id="levels-indian-tender-conditions-and-court-filing" class="gl-sec">
        <h2>Levels Indian Tender Conditions and Court Filings Commonly Reference</h2>
        <p>Indian tender conditions most often reference a solvency amount rather than a ratio: a certificate for a sum equal to some proportion of the contract value. Where a ratio does appear it is usually the assets-to-liabilities form, with a threshold modestly above one. Court filings work the same way, asking whether a proposed surety is good for a stated amount rather than for a ratio. In both settings the practical requirement is a figure and a date, and reading the document for those two before computing anything is what prevents a certificate answering the wrong question. Where a bidder holds a certificate prepared for another tender, it is read for its workings rather than reused. The evidence usually transfers even where the sum and the date do not, which makes a fresh certificate faster to produce than the first one was.</p>
      </section>
      <section id="financial-health-metrics-near-the-solvency-ratio" class="gl-sec">
        <h2>Financial Health Metrics Near the Solvency Ratio</h2>
        <p>The metrics near the solvency ratio each measure financial health from a different angle. One is gearing, which looks at how the capital was assembled rather than whether it covers the debts. One is liquidity, which asks about timing rather than total. One is net worth after intangibles are removed, which is the base several of these ratios are properly computed on. The last is the certificate itself, which answers the narrow question a tender or a court actually asked. <a href="/glossary/networth/debt-to-equity-ratio">Debt-to-Equity Ratio</a>, <a href="/glossary/networth/liquidity">Liquidity</a>, <a href="/glossary/networth/tangible-net-worth">Tangible Net Worth</a>, <a href="/glossary/networth#realisable-value">Realisable Value</a>. A reader who knows which of the four a condition means can usually get the right document first time, which is most of what this vocabulary is for. Between them these four describe capital structure, timing, quality of assets and the specific question a recipient asked, which is the full set of things a solvency condition can mean. Getting that right first time is most of the value.</p>
      </section>
