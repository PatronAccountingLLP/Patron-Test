<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does a solvency ratio measure?</h3>
<div class="faq-expanded__a"><p>It measures capacity to meet long-term obligations from the resources a business holds. Several ratios sit in the family, comparing net worth or total assets against total liabilities, or comparing income after tax and depreciation against total debt. Each answers the same question from a different angle. Regulated sectors such as insurance carry a prescribed minimum set by IRDAI.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does a solvency ratio differ from a liquidity ratio?</h3>
<div class="faq-expanded__a"><p>By time horizon. Liquidity ratios test whether near-term payments can be met from current assets. Solvency ratios test whether the whole structure can carry its debt over years. A business can be solvent yet short of cash this month. Lenders test both, since Schedule III presents current and non-current items separately for exactly that reason.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is there a benchmark figure?</h3>
<div class="faq-expanded__a"><p>Not a universal one. Acceptable levels vary with the industry, the asset mix and the reader&#x27;s purpose, and regulated sectors set their own prescribed minimums. Comparing a ratio across unlike businesses without adjusting for those differences produces a number that looks precise and means very little.</p></div>
