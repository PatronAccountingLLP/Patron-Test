      <section id="source-of-funds-and-proof-of-balance-answer-diff" class="gl-sec">
        <h2>Source of Funds and Proof of Balance Answer Different Questions</h2>
        <div class="definition-box" itemprop="description"><p>Source of funds and proof of balance answer different questions, and files fail on the difference more often than on the amount. Proof of balance says the money is there. Source of funds says where it came from and why it is the applicant's. A statement showing a substantial balance satisfies the first entirely and the second not at all, which is why a strong-looking file can be refused. The question is asked because a balance that arrived recently might be borrowed, might belong to somebody else, or might have been assembled from several people specifically for the application. None of those makes the applicant able to fund what they say they will fund, which is the thing being assessed. One asks how much is there on a date. The other asks how it came to be there.</p></div>
      </section>
      <section id="how-a-ca-traces-where-an-asset-came-from-before" class="gl-sec">
        <h2>How a CA Traces Where an Asset Came From Before Certifying It</h2>
        <p>Tracing an asset before certifying it means following it back to a document rather than accepting an explanation. A credit is matched to the transaction that produced it: a sale agreement, a maturity, a salary, a gift. Where the trail runs through several accounts the intermediate movements are followed rather than skipped, because a reader looking for a gap will find it there. Where an asset has been held for many years the trail is shorter and the question rarely arises, which is why long-held holdings are easier to certify than recent ones. Where a document genuinely cannot be produced the certificate says so, because a stated limitation is far less damaging than a gap somebody else discovers. Tracing stops where the record stops, and a competent statement says where that is. An asset acquired decades ago from savings that predate any retrievable record cannot be traced to an instrument, and claiming otherwise is worse than disclosing the limit. Origin established for the substantial and recent entries, with the older ones described honestly, reads as diligence; uniform confidence across everything reads as assertion.</p>
      </section>
      <section id="gift-deeds-sale-agreements-salary-credits-and-it" class="gl-sec">
        <h2>Gift Deeds, Sale Agreements, Salary Credits and ITRs That Establish Origin in India</h2>
        <p>In India four documents carry most of this work. A registered gift deed establishes money or property received from a relative and is the cleanest evidence of a family transfer. A sale agreement establishes proceeds from disposing of an asset, with the registered instrument behind it. Salary credits establish employment income and are corroborated by Form 16 and the return. The income tax return itself establishes what was declared and is the document a reader is most likely to obtain independently. That is why a position inconsistent with it is the hardest kind to defend. The instruments differ in how much they settle on their own. A registered instrument carrying stamp duty and a date is difficult to reconstruct after the event and is correspondingly persuasive. A private writing between family members, unregistered and unstamped, evidences intention but establishes very little about timing. Where the underlying transaction was genuine, the weaker document is usually supported by the banking trail rather than relied on by itself.</p>
      </section>
      <section id="compliance-concepts-that-follow-source-of-funds" class="gl-sec">
        <h2>Compliance Concepts That Follow Source of Funds</h2>
        <p>The compliance concepts that follow from establishing origin are the ones a bank or a mission applies next. One is the evidence that the money is currently there. One is the expectation that it has been there for a period. One is the certificate evidencing money received from abroad. The last is the instrument by which a family transfer is documented. The concepts that follow this one are what a reader does with the answer once they have it. <a href="/glossary/networth/proof-of-funds-pof">Proof of Funds (POF)</a>, <a href="/glossary/networth#fund-seasoning">Fund Seasoning</a>, <a href="/glossary/networth/foreign-inward-remittance-certificate-firc">Foreign Inward Remittance Certificate (FIRC)</a>, <a href="/glossary/networth#gift-deed">Gift Deed</a>. One is the standing obligation on institutions to know who they are dealing with. One is the reporting that follows a transaction of size. One is the evidence pack the answer is delivered inside. Establishing origin is not an end in itself: it exists because someone downstream carries a duty they cannot discharge without it.</p>
