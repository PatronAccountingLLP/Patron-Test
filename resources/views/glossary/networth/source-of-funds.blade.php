<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does source of funds mean in practice?</h3>
<div class="faq-expanded__a"><p>It means the origin of the money, traced to an identifiable event. Salary credited over time, sale proceeds of a property, a matured deposit, a documented gift or an inheritance all qualify. The test is whether each credit can be tied to a transaction with paperwork behind it.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Why do banks and consulates ask for it separately from the balance?</h3>
<div class="faq-expanded__a"><p>Because a balance alone proves nothing about legitimacy. Obligations under the Prevention of Money Laundering Act 2002 require regulated entities to know their customer and the origin of funds. A consulate applies the same logic when it questions a deposit that appeared shortly before an application.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How is a gift from a relative evidenced?</h3>
<div class="faq-expanded__a"><p>By a gift deed or a written declaration, the donor&#x27;s own bank statement showing the debit, and the recipient&#x27;s credit. Gifts from specified relatives are outside the scope of taxation as income, which makes the relationship worth documenting. An undocumented transfer between accounts explains nothing on its own.</p></div>
