      <section id="what-stamp-duty-attaches-to-under-indian-stamp-l" class="gl-sec">
        <h2>What Stamp Duty Attaches To Under Indian Stamp Law</h2>
        <div class="definition-box" itemprop="description"><p>Stamp duty is a tax on instruments rather than on transactions. That distinction governs everything about it: duty attaches to the document that records a transaction, and an unstamped or under-stamped document is inadmissible in evidence until the duty and any penalty are paid. It is levied under the Indian Stamp Act as adapted by each state, and several states have their own Act entirely, so both the rates and the list of chargeable instruments vary. Conveyances, leases, mortgages, gift deeds, powers of attorney, affidavits, indemnity bonds and share transfer forms are all chargeable, at rates ranging from a nominal fixed amount to a substantial percentage of value. It attaches to the instrument rather than to the transaction it records, which is a distinction with consequences. The same bargain can attract duty or not depending on whether it was reduced to writing, and on the form the writing took.</p></div>
      </section>
      <section id="which-papers-in-a-certification-file-need-stampi" class="gl-sec">
        <h2>Which Papers in a Certification File Need Stamping: Affidavits, Undertakings, Indemnities</h2>
        <p>Within a certification file the papers that need stamping are usually the ancillary ones rather than the certificate itself. A chartered accountant's certificate is not a chargeable instrument. An affidavit sworn by the client is, at a nominal rate. An indemnity bond given to a bank or a company before an asset is released is, and the rate can be material where the amount is large. A power of attorney authorising somebody to act is. Getting these wrong rarely stops an engagement but frequently stops the institution acting on it, which amounts to the same delay from the client's point of view. The consequence of getting this wrong is delayed rather than immediate, which is why it is underestimated. An insufficiently stamped instrument does not become void, but it cannot be received in evidence until the deficiency and the penalty are made good. The document sits in the file looking complete and fails at the moment it is finally needed. Where the certification file crosses state lines, each instrument is stamped under the law of the state where it is executed.</p>
      </section>
      <section id="state-stamp-acts-e-stamping-through-shcil-and-pe" class="gl-sec">
        <h2>State Stamp Acts, e-Stamping Through SHCIL and Penalties for Under-Stamping</h2>
        <p>Payment has moved substantially to electronic stamping, operated through a central record keeping agency and its authorised collection centres, and most states now accept or require it for instruments above a threshold. Physical stamp paper survives for small amounts in several states. Under-stamping is penalised at a multiple of the deficient duty rather than at the shortfall alone, which makes guessing expensive. Where an instrument is executed in one state and used in another, the difference in duty may be payable in the second, which parties regularly overlook when a document travels. Electronic stamping has made the position easier to verify and no easier to get right. The certificate can be checked online against its unique number, which defeats the forgeries that once circulated. The rate and the classification of the instrument remain state subjects, so the same undertaking can be stamped correctly in one state and short in another.</p>
      </section>
      <section id="other-levies-confused-with-stamp-duty" class="gl-sec">
        <h2>Other Levies Confused With Stamp Duty</h2>
        <p>The levies confused with stamp duty are the ones that appear on the same transaction. One is the notified rate from which duty on property is computed. One is the instrument most often stamped in a certification file. One is the registered document by which property passes. The last is the separate act of having a signature witnessed, which is not a tax at all and is frequently assumed to substitute for stamping. The levies confused with this one are collected at the same counter and are otherwise unrelated. <a href="/glossary/networth/circle-rate">Circle Rate</a>, <a href="/glossary/networth#indemnity-bond">Indemnity Bond</a>, <a href="/glossary/networth#title-deed">Title Deed</a>, <a href="/glossary/networth#notarisation">Notarisation</a>. One is the charge for entering the instrument in the public register. One is the local body's recurring levy on the property itself. One is the tax on the supply rather than on the document. They are separate charges under separate statutes, and a cost estimate that merges them will be wrong in both directions depending on the state.</p>
      </section>
