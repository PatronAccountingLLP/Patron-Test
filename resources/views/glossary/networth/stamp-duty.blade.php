<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What attracts stamp duty?</h3>
<div class="faq-expanded__a"><p>Instruments, not transactions. Duty is charged on documents such as conveyances, mortgages, leases, gift deeds and certain agreements, under the Indian Stamp Act 1899 and the corresponding state legislation. Rates and the list of chargeable instruments vary between states, so the place of execution matters.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What happens if an instrument is insufficiently stamped?</h3>
<div class="faq-expanded__a"><p>It can be impounded and is generally not admissible in evidence until the deficit duty and penalty are paid. That is why an unstamped or under-stamped deed is a live problem in a certification file. The document may be unusable at the moment the client most needs it.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does a net worth or solvency certificate attract stamp duty?</h3>
<div class="faq-expanded__a"><p>The certificate itself is not a chargeable instrument. The documents it relies on frequently are, including the sale deed, the mortgage and the partnership deed. An affidavit sworn alongside a court filing attracts its own duty in several states. The duty question follows those documents, not the certificate.</p></div>
