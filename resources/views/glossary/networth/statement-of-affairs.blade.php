      <section id="what-a-statement-of-affairs-sets-out-for-a-non-c" class="gl-sec">
        <h2>What a Statement of Affairs Sets Out for a Non-Company Entity</h2>
        <div class="definition-box" itemprop="description"><p>A statement of affairs sets out everything an entity owns and owes at a single date, in a form that does not depend on a statutory balance sheet existing. Companies produce balance sheets under the Companies Act; proprietors, partnership firms and Hindu undivided families frequently do not, or produce them only for tax purposes and only covering the business side of their affairs. The statement of affairs fills that gap. It lists assets by class with the basis on which each is stated, lists liabilities by creditor, and arrives at the difference between them. It is a presentation rather than a set of accounts, and it says so on its face. That distinction protects everybody: the reader knows what they are being given, and the preparer has not implied that a statutory audit stands behind figures that were never audited. It is also the document most often prepared badly, because nothing external forces a format on it. Discipline has to come from the preparer rather than from a schedule in an Act.</p></div>
      </section>
      <section id="why-it-is-attached-to-the-certificate-rather-tha" class="gl-sec">
        <h2>Why It Is Attached to the Certificate Rather Than Summarised Into It</h2>
        <p>It is attached to the certificate rather than summarised into it because the detail is the entire point. A certificate stating a single figure asks the reader to trust it. A certificate with the statement attached lets them examine whichever line concerns them and disregard the rest. Recipients very rarely dispute a total. What they dispute is a particular property valuation, or the treatment of a loan given to a relative, or whether a vehicle used by the family should have been included at all. Attaching the statement means those questions are answered before they are asked, and answered in writing where the answer can be checked, rather than during a telephone call where it cannot. It also means the preparer has committed to a basis for each line rather than to a number alone. Attaching it also fixes the position in a form that can be revisited. A total remembered from a conversation is not something either side can rely on a year later.</p>
      </section>
      <section id="how-proprietors-firms-and-hufs-compile-one-from" class="gl-sec">
        <h2>How Proprietors, Firms and HUFs Compile One From Indian Books and Bank Records</h2>
        <p>For non-company entities it is compiled from whatever genuinely exists rather than from an idealised set of records. Bank statements establish balances. Title deeds and registration records establish immovable property. Depository statements establish securities. The books, where maintained under the Income-tax Act, establish stock, debtors and creditors. Where they are not maintained, the position is rebuilt from primary records and the limitation stated. Household assets are included where they belong to the individual being certified. For a proprietor that means the same statement as the business, since in law there is one person. Separating them would describe an entity that does not exist. Where a limitation exists it is stated on the statement itself rather than in a covering email. A limitation the reader never sees is not a limitation at all, and it offers no protection to anybody. The date is chosen and stated rather than left to imply the day of signing. A statement that does not say what date it speaks to has left out the most important thing on it.</p>
      </section>
      <section id="schedules-usually-prepared-alongside-a-statement" class="gl-sec">
        <h2>Schedules Usually Prepared Alongside a Statement of Affairs</h2>
        <p>The schedules usually prepared alongside a statement of affairs correspond to the groups it has to distinguish. Two are asset classes with different evidence conventions. The movable holdings are varied and easy to under-record; the immovable ones carry the most value and paperwork. One covers obligations that may never crystallise and therefore sit below the line rather than inside the totals. The last is the written confirmation the client signs, stating that what has been presented is complete. It matters more here than in a company engagement, because so little of the record has been examined externally. <a href="/glossary/networth#movable-assets">Movable Assets</a>, <a href="/glossary/networth#immovable-property">Immovable Property</a>, <a href="/glossary/networth/contingent-liability">Contingent Liability</a>, <a href="/glossary/networth/management-representation-letter">Management Representation Letter</a>. These four schedules between them account for most of what a reader questions. Preparing them alongside the statement is what turns a total into something that can be defended line by line. Preparing them alongside the statement is what turns a total into something defensible line by line.</p>
