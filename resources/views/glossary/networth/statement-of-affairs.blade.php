<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What does a statement of affairs contain?</h3>
<div class="faq-expanded__a"><p>A dated list of every asset at a stated valuation basis, every liability at its outstanding amount, and the resulting surplus. Contingent items appear as notes beneath. Schedule III of the Companies Act 2013 does not govern it, because no company reporting format applies. It is signed by the person whose affairs it describes, which is what makes it a representation rather than an assertion by the chartered accountant.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does a statement of affairs differ from a balance sheet?</h3>
<div class="faq-expanded__a"><p>A balance sheet is prepared from double-entry books under a reporting framework, with prescribed heads and comparatives. A statement of affairs is a single-date schedule used where no such books exist, which is why individuals, proprietors and firms rely on it. It carries no comparatives and no prescribed format.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Who signs a statement of affairs?</h3>
<div class="faq-expanded__a"><p>The individual, the proprietor, a partner authorised by the deed, or a director for a company. The signature owns the completeness of the disclosure. The chartered accountant then verifies it against evidence and certifies separately, so the two signatures on the file answer two different questions.</p></div>
