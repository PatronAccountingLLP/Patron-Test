<h3 class="faq-expanded__q">What does a succession certificate authorise?</h3>
<div class="faq-expanded__a"><p>It authorises the holder to collect debts and securities owed to a deceased person, and to give a valid discharge for them. Part X of the Indian Succession Act 1925 governs it, and a civil court grants it after publication and hearing objections. It does not decide title to immovable property.</p></div>
