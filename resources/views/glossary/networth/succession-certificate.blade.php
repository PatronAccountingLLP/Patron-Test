<div class="faq-expanded__a"><p>It is a court proceeding with notice and a publication period, so it runs into months rather than weeks, and longer where objections are filed. Court fees are charged on the value of the assets covered. Families often apply only after a bank refuses to release the funds, which adds to the delay.</p></div>
