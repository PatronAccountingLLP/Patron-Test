<h3 class="faq-expanded__q">Who can stand as a surety?</h3>
<div class="faq-expanded__a"><p>A person who undertakes to answer for another&#x27;s obligation, described in section 126 of the Indian Contract Act 1872 as the surety in a contract of guarantee. Courts accepting a surety for bail look for an identifiable individual with property they can reach, ordinarily within the court&#x27;s jurisdiction.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What financial proof does a court ask a surety for?</h3>
<div class="faq-expanded__a"><p>Evidence of means to the amount fixed, supported by title to property free of charge. Registered title documents, the revenue or municipal record and an encumbrance position are typically produced, along with the surety&#x27;s own affidavit. A stated total without traceable property behind it is not accepted.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What is the surety&#x27;s exposure if the obligation fails?</h3>
<div class="faq-expanded__a"><p>The liability of the surety is co-extensive with that of the principal debtor unless the contract provides otherwise. In a bail context the amount of the bond can be forfeited and recovery pursued against the surety&#x27;s property. It is a real financial commitment, not a formality.</p></div>
