<div class="faq-expanded__item">
<h3 class="faq-expanded__q">What is excluded to arrive at tangible net worth?</h3>
<div class="faq-expanded__a"><p>Intangible assets are removed from the asset side. That means goodwill, patents, trademarks, brand value, and deferred revenue expenditure not yet written off. Preliminary expenses and accumulated losses carried in the balance sheet go the same way. What remains is the asset base a lender believes it could realise.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Why do lenders ask for tangible net worth rather than net worth?</h3>
<div class="faq-expanded__a"><p>Because intangibles rarely convert to cash on enforcement. A brand carried at a large book value may be worth nothing to a creditor recovering a debt. Loan covenants are therefore written against the tangible figure, and appraisal notes state the deductions applied so the covenant can be tested each year.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Does tangible net worth appear in any statute?</h3>
<div class="faq-expanded__a"><p>Not as a defined statutory term for general use. Section 2(57) of the Companies Act 2013 defines net worth, and the tangible variant is a lending and tender convention layered on top of it. Because it is contractual rather than statutory, the exact deductions are set by the lender or the bid document.</p></div>
