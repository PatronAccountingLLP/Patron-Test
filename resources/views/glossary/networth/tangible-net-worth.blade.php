      <section id="what-tangible-net-worth-excludes-and-why" class="gl-sec">
        <h2>What Tangible Net Worth Excludes and Why</h2>
        <div class="definition-box" itemprop="description"><p>Tangible net worth is what remains after every intangible item is removed from the balance sheet total. Goodwill goes first, because it records what somebody once paid above the value of identifiable assets rather than anything that could be sold today. Patents, trademarks, capitalised software and brand valuations follow. So do preliminary expenses and any deferred revenue expenditure still sitting unwritten off. The reasoning is not that these items are worthless. Many are genuinely valuable and some are the most valuable thing a business owns. It is that a lender assessing recovery wants a number backed by something identifiable. It has to be valuable to an outsider and, if necessary, sellable to a third party. An intangible usually fails at least two of those three tests. Goodwill in particular cannot be sold separately from the business that generated it. That makes it worthless in precisely the situation a lender is imagining. A figure leaning on intangibles is discounted the moment somebody reads the schedule behind it. That is why the tangible measure exists as a separate concept.</p></div>
      </section>
      <section id="how-a-ca-arrives-at-the-tangible-figure-on-a-cer" class="gl-sec">
        <h2>How a CA Arrives at the Tangible Figure on a Certificate</h2>
        <p>The computation starts from the audited or certified position and works downward. The chartered accountant identifies each intangible head in the accounts, traces it to the schedule that supports it, and deducts it. Where an intangible has been revalued upward, both the original carrying amount and the uplift come out. Leaving the uplift behind would reintroduce through the reserve what was just removed. The working is annexed rather than summarised, so a reader who disputes one deduction can examine it in isolation instead of re-deriving the whole figure from scratch. Where the accounts do not separate intangibles clearly, and in smaller sets of accounts they frequently do not, that becomes a question back to the client rather than an estimate. A tangible figure produced by guessing which items were intangible is not a tangible figure, and a certificate that presents one as though it were has misdescribed the work behind it. Where the position cannot be established, the certificate says so rather than reaching for a number that looks complete.</p>
      </section>
      <section id="where-indian-tender-notices-and-bank-sanction-le" class="gl-sec">
        <h2>Where Indian Tender Notices and Bank Sanction Letters Demand a Tangible Number</h2>
        <p>Indian tender notices frequently specify tangible net worth rather than net worth, and the distinction is deliberate rather than careless drafting. A bidder whose balance sheet is carried by goodwill from an acquisition may look substantial while holding very little that could answer a claim if the contract went wrong. Public works tenders, empanelment applications and pre-qualification criteria therefore tend to use the tangible measure, and some spell out the exclusions in the bid document itself. Bank sanction letters do the same for working capital limits, where the security is current assets and the comfort behind it has to be real rather than accounting. Reading the requirement precisely matters more here than almost anywhere else in certification. A certificate stating net worth where the notice asked for tangible net worth answers a different question. It is returned for that reason, not for any error in the arithmetic. The safest course is to take the phrase from the document that used it and certify to that phrase exactly.</p>
      </section>
      <section id="terms-that-sit-next-to-tangible-net-worth" class="gl-sec">
        <h2>Terms That Sit Next to Tangible Net Worth</h2>
        <p>The terms sitting closest to this one are about how a figure is measured rather than what it contains. Each answers a question a reader tends to ask next. Two concern valuation. One is the price an asset would fetch between willing parties; the other is what would be recovered if it had to be sold under pressure, which is usually lower. One concerns the same figure after a particular reader's own additions and subtractions, which is what a regulator or a tender authority may specify instead. The last concerns the part of a company's reserves that is genuinely available rather than earmarked, which is where a great deal of apparent net worth turns out not to be. Read together they explain why two certificates for the same business can carry different figures. Prepared on the same day, neither is wrong. <a href="/glossary/networth/fair-market-value-fmv">Fair Market Value (FMV)</a>, <a href="/glossary/networth#realisable-value">Realisable Value</a>, <a href="/glossary/networth/adjusted-net-worth">Adjusted Net Worth</a>, <a href="/glossary/networth/free-reserves">Free Reserves</a>. Knowing which of the four a recipient has in mind is most of the work of reading a requirement correctly.</p>
      </section>
