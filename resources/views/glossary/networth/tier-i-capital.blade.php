<div class="faq-expanded__item">
<h3 class="faq-expanded__q">How does Tier I capital differ from net owned fund?</h3>
<div class="faq-expanded__a"><p>They start from the same place and diverge. Both build on owned fund and deduct group investments beyond the threshold. Tier I is a capital adequacy component measured against risk weighted assets; net owned fund is an entry-level and continuing registration condition under section 45-IA.</p></div>
</div>
<div class="faq-expanded__item">
<h3 class="faq-expanded__q">Is Tier II capital counted the same way?</h3>
<div class="faq-expanded__a"><p>No. Tier II includes items such as preference shares other than compulsorily convertible ones, revaluation reserves at a discount, general provisions within a limit, and subordinated debt. The Reserve Bank caps Tier II at a proportion of Tier I, so it cannot substitute for core capital.</p></div>
