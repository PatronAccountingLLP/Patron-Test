      <section id="what-rbi-counts-inside-tier-i-capital" class="gl-sec">
        <h2>What RBI Counts Inside Tier I Capital</h2>
        <div class="definition-box" itemprop="description"><p>Tier I capital is the core capital a regulator treats as genuinely loss-absorbing. For a non-banking financial company it comprises paid-up equity capital, preference shares compulsorily convertible into equity, free reserves and the securities premium account, less accumulated losses, deferred revenue expenditure and other intangible assets. Perpetual debt instruments count within limits. What is common to everything included is that it is permanently available to absorb losses without the company having to be wound up. What is excluded is anything that has to be repaid, anything unrealised, and anything that would disappear on a bad day. The layer is defined by permanence and by loss absorption rather than by label. Capital that is available to absorb losses while the firm continues to operate belongs here; capital that only ranks ahead of shareholders in a wind-up does not. Label alone settles nothing here, and the regulator looks past it.</p></div>
      </section>
      <section id="how-tier-i-feeds-the-net-owned-fund-a-ca-certifi" class="gl-sec">
        <h2>How Tier I Feeds the Net Owned Fund a CA Certifies</h2>
        <p>Tier I feeds directly into the net owned fund a chartered accountant certifies, and the overlap is close enough that the two are frequently confused. Owned funds are built from substantially the same components: paid-up capital, free reserves and premium, less the same deductions. Net owned fund then departs by deducting investment in and lending to group and subsidiary companies above ten per cent of owned funds, which the capital measure handles differently. So the certified figure and the reported tier I are related but not equal, and a computation that assumes they are will be wrong by exactly the group exposure. The feed is a subtraction rather than a transfer. Owned funds are reduced by specified investments in and exposures to group entities, and what survives that deduction is what the certificate reports. A firm with a substantial owned-fund figure and heavy intra-group exposure can certify a great deal less than its balance sheet suggests.</p>
      </section>
      <section id="perpetual-debt-instruments-and-scale-based-regul" class="gl-sec">
        <h2>Perpetual Debt Instruments and Scale Based Regulation Reporting for NBFCs</h2>
        <p>Perpetual debt instruments occupy an unusual position and are worth understanding separately. They are borrowings in form and capital in effect, carrying no maturity and permitting the issuer to defer payment in defined circumstances. That is why the regulator allows them into the core tier, subject to a ceiling expressed against the rest of tier I. Under scale-based regulation the reporting expectations differ across layers, with larger companies subject to more detailed disclosure, and a company moving between layers finds its obligations change with it. Where a firm sits in the regulatory hierarchy now determines a good deal of what it must report. The framework applies requirements in ascending order by size and activity, so two firms with identical ratios can face materially different reporting. Establishing the applicable layer before computing anything saves the recomputation that otherwise follows the first query.</p>
      </section>
      <section id="capital-layers-read-with-tier-i" class="gl-sec">
        <h2>Capital Layers Read With Tier I</h2>
        <p>The capital layers read with tier I are the ones a regulatory filing sets out together. One is the ratio in which tier I is the numerator's core. One is the supplementary tier, capped by reference to tier I. One is the reserve category that forms much of it in a profitable company. The last is the premium account, which contributes without ever having been earned. The layers read with this one make up the capital structure the regulator measures. <a href="/glossary/networth/capital-to-risk-weighted-assets-ratio-crar">Capital to Risk-weighted Assets Ratio (CRAR)</a>, <a href="/glossary/networth#tier-ii-capital">Tier II Capital</a>, <a href="/glossary/networth/free-reserves">Free Reserves</a>, <a href="/glossary/networth/securities-premium">Securities Premium</a>. One is the supplementary layer, admitted subject to a ceiling set against this one. One is the aggregate of both. One is the certified figure that this layer feeds. Following the sequence from the balance sheet through the deductions to the certified amount is what makes the final number checkable rather than asserted. Each layer answers a different question about the same capital, which is why the regulator asks for all of them rather than settling on one. A firm that reports only the aggregate has told the reader least about the quality of what stands behind it.</p>
      </section>
