<h3 class="faq-expanded__q">What makes up Tier I capital for an NBFC?</h3>
<div class="faq-expanded__a"><p>Core capital: owned fund reduced by investments in shares of subsidiaries, group companies and other non-banking financial companies beyond prescribed limits. Book value of certain intangible assets is also deducted. Perpetual debt instruments are permitted within a ceiling set by the Reserve Bank. The Reserve Bank&#x27;s master directions set the ceiling on perpetual debt instruments within Tier I.</p></div>
